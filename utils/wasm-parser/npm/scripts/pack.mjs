/// Assemble `@clickhouse/wasm-parser` in a staging directory (never in this source tree: CI
/// asserts `utils/wasm-parser` is clean) and run `npm pack`. The two `.wasm` files come from
/// `Build (wasm_parser)`; they are not committed.
import { spawnSync } from 'node:child_process';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const npmRoot = dirname(here);
const repoRoot = resolve(npmRoot, '../../..');

function argValue(name)
{
    const i = process.argv.indexOf(name);
    if (i < 0 || process.argv[i + 1] === undefined)
        throw new Error(`missing ${name}`);
    return process.argv[i + 1];
}

function optionalArg(name)
{
    const i = process.argv.indexOf(name);
    return i >= 0 ? process.argv[i + 1] : undefined;
}

function gitSha7()
{
    // Same `-c safe.directory=*` as ci/jobs/build_wasm_parser.py: the wasm-builder
    // image runs as root on a checkout owned by another user.
    const git = spawnSync(
        'git',
        ['-c', 'safe.directory=*', '-C', repoRoot, 'rev-parse', '--short=7', 'HEAD'],
        { encoding: 'utf8' },
    );
    if (git.status !== 0)
        throw new Error(`git rev-parse failed: ${git.stderr}`);
    return git.stdout.trim();
}

async function versionFromTree()
{
    const text = await readFile(join(repoRoot, 'cmake/autogenerated_versions.txt'), 'utf8');
    const major = text.match(/SET\(VERSION_MAJOR (\d+)\)/)[1];
    const minor = text.match(/SET\(VERSION_MINOR (\d+)\)/)[1];
    const patch = text.match(/SET\(VERSION_PATCH (\d+)\)/)[1];
    return `${major}.${minor}.${patch}-dev.${gitSha7()}`;
}

const wasmDir = resolve(argValue('--wasm-dir'));
const outDir = resolve(argValue('--out-dir'));
const sourceDir = resolve(optionalArg('--source-dir') ?? npmRoot);
const version = optionalArg('--version') ?? await versionFromTree();
const stageDir = resolve(optionalArg('--stage-dir') ?? join(outDir, 'npm-pack'));

const fullWasm = join(wasmDir, 'parser.wasm');
const slimWasm = join(wasmDir, 'parser-no-formatting-no-dcl.wasm');
await readFile(fullWasm);
await readFile(slimWasm);

await rm(stageDir, { recursive: true, force: true });
await mkdir(stageDir, { recursive: true });
await mkdir(outDir, { recursive: true });

const pkg = JSON.parse(await readFile(join(sourceDir, 'package.json'), 'utf8'));
pkg.version = version;
// Local DX scripts (`setup` / `build`) are not part of the published package.
delete pkg.scripts;
await writeFile(join(stageDir, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
await cp(join(sourceDir, 'README.md'), join(stageDir, 'README.md'));
await cp(join(sourceDir, 'src'), join(stageDir, 'src'), { recursive: true });
await cp(fullWasm, join(stageDir, 'parser.wasm'));
await cp(slimWasm, join(stageDir, 'parser-no-formatting-no-dcl.wasm'));

const pack = spawnSync('npm', ['pack', '--pack-destination', outDir], {
    cwd: stageDir,
    encoding: 'utf8',
});
if (pack.status !== 0)
{
    process.stderr.write(pack.stdout + pack.stderr);
    process.exit(pack.status ?? 1);
}

const tarballName = pack.stdout.trim().split('\n').filter(Boolean).at(-1);
const tarballPath = join(outDir, tarballName);
await cp(tarballPath, join(outDir, 'clickhouse-wasm-parser.tgz'));
process.stdout.write(tarballPath + '\n');

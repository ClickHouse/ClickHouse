#!/usr/bin/env node

import { spawn } from 'node:child_process';
import { cp, mkdir, readFile, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.resolve(scriptDirectory, '..');
const repositoryDirectory = path.resolve(projectDirectory, '..');
const artifactsDirectory = path.join(projectDirectory, '.artifacts');
const generatedDirectory = path.join(projectDirectory, 'src/generated');
const buildRoot = path.join(repositoryDirectory, 'tmp/docs-autogenerated-version-builds');
const outputDirectory = path.join(projectDirectory, 'dist');
const astroBinary = path.join(projectDirectory, 'node_modules/astro/bin/astro.mjs');

function runNode(argumentsList) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, argumentsList, {
      cwd: projectDirectory,
      stdio: 'inherit',
    });
    child.once('error', reject);
    child.once('exit', (code, signal) => {
      if (code === 0) resolve();
      else reject(new Error(`Command failed with ${signal ? `signal ${signal}` : `exit code ${code}`}`));
    });
  });
}

async function bundleDirectories() {
  const entries = await readdir(artifactsDirectory, { withFileTypes: true });
  const bundles = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.endsWith('.next')) continue;
    const directory = path.join(artifactsDirectory, entry.name);
    const manifest = JSON.parse(await readFile(path.join(directory, 'manifest.json'), 'utf8'));
    if (manifest.channel !== entry.name) {
      throw new Error(`Bundle directory ${entry.name} contains channel ${manifest.channel}`);
    }
    bundles.push({ id: manifest.channel, directory });
  }
  if (!bundles.some(({ id }) => id === 'latest')) {
    throw new Error('The latest reference bundle is missing');
  }
  return bundles.sort((left, right) => {
    if (left.id === 'latest') return 1;
    if (right.id === 'latest') return -1;
    return right.id.localeCompare(left.id, undefined, { numeric: true });
  });
}

async function copyVersionOutput(buildDirectory, version) {
  const versionSource = path.join(buildDirectory, 'docs/reference/versions', version);
  const versionDestination = path.join(outputDirectory, 'docs/reference/versions', version);
  await mkdir(path.dirname(versionDestination), { recursive: true });
  await cp(versionSource, versionDestination, { recursive: true, force: true });

  const assetsSource = path.join(buildDirectory, '_astro');
  await cp(assetsSource, path.join(outputDirectory, '_astro'), { recursive: true, force: true });

  const searchFile = `${version}.json`;
  await cp(
    path.join(buildDirectory, 'docs/reference/_search', searchFile),
    path.join(outputDirectory, 'docs/reference/_search', searchFile),
    { force: true },
  );
}

async function main() {
  const bundles = await bundleDirectories();
  await rm(buildRoot, { recursive: true, force: true });
  await mkdir(buildRoot, { recursive: true });

  const outputs = new Map();
  for (const bundle of bundles) {
    console.log(`\nBuilding reference bundle ${bundle.id}`);
    await runNode([
      path.join(scriptDirectory, 'prepare-content.mjs'),
      '--artifact', bundle.directory,
      '--artifacts', artifactsDirectory,
      '--generated', generatedDirectory,
    ]);
    await rm(path.join(projectDirectory, '.astro'), { recursive: true, force: true });
    await rm(path.join(projectDirectory, '.mintlify'), { recursive: true, force: true });
    const bundleOutput = path.join(buildRoot, bundle.id);
    await runNode([
      '--max-old-space-size=8192',
      astroBinary,
      'build',
      '--outDir', bundleOutput,
    ]);
    outputs.set(bundle.id, bundleOutput);
  }

  await rm(outputDirectory, { recursive: true, force: true });
  await cp(outputs.get('latest'), outputDirectory, { recursive: true });
  for (const bundle of bundles) {
    if (bundle.id !== 'latest') await copyVersionOutput(outputs.get(bundle.id), bundle.id);
  }
  console.log(`\nAssembled ${bundles.length} independently built reference bundles in dist`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});

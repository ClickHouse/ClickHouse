function splitSystemStatementSections(content, relativePath, route) {
  const headings = [];
  let offset = 0;
  let fence = null;
  let parent = null;

  for (const line of content.split(/(?<=\n)/)) {
    const lineWithoutNewline = line.replace(/\r?\n$/, '');
    const fenceMatch = lineWithoutNewline.match(/^\s*(`{3,}|~{3,})/);
    if (fenceMatch) {
      if (!fence) fence = fenceMatch[1];
      else if (fence[0] === fenceMatch[1][0] && fenceMatch[1].length >= fence.length) fence = null;
    } else if (!fence) {
      const heading = lineWithoutNewline.match(/^(#{2,4})\s+(.+?)\s+\{#([^}\n]+)\}\s*$/);
      if (heading) {
        const depth = heading[1].length;
        const record = {
          depth,
          title: heading[2],
          anchor: heading[3],
          start: offset,
          bodyStart: offset + line.length,
          parent,
          isStatement: depth <= 3 && (
            heading[2].startsWith('SYSTEM ')
            || heading[3] === 'sync-database-replica'
          ),
        };
        headings.push(record);
        if (depth === 2) parent = record;
      }
    }
    offset += line.length;
  }

  const statements = headings.filter((heading) => heading.isStatement);
  if (statements.length < 2) return [];

  const prefix = content.slice(0, statements[0].start).trim();
  const statementRoutes = new Map(statements.map(({ anchor }) => [
    anchor,
    `${route}/${splitRouteSegment(anchor, relativePath)}`,
  ]));
  const localRoutes = new Map(headings.map(({ anchor }) => [anchor, `${route}#${anchor}`]));
  for (const [anchor, statementRoute] of statementRoutes) localRoutes.set(anchor, statementRoute);

  const parentsWithStatementChildren = new Set(
    statements
      .filter((heading) => heading.depth === 3 && heading.parent)
      .map((heading) => heading.parent.anchor),
  );

  function rewriteLocalStatementLinks(sectionContent) {
    return sectionContent
      .replace(/\]\(#([^)]+)\)/g, (match, anchor) => (
        localRoutes.has(anchor) ? `](${localRoutes.get(anchor)})` : match
      ))
      .replace(/href=(['"])#([^'"]+)\1/g, (match, quote, anchor) => (
        localRoutes.has(anchor) ? `href=${quote}${localRoutes.get(anchor)}${quote}` : match
      ));
  }

  return statements.map((heading) => {
    const headingIndex = headings.indexOf(heading);
    const nextBoundary = headings.slice(headingIndex + 1).find((candidate) => (
      candidate.isStatement || candidate.depth <= heading.depth
    ));
    const body = content.slice(heading.bodyStart, nextBoundary?.start ?? content.length).trim();
    const sectionContent = [
      prefix,
      promoteNestedHeadings(body, heading.depth - 1),
    ].filter(Boolean).join('\n\n');

    let group = { anchor: 'general', title: 'General' };
    if (heading.depth === 3 && heading.parent) group = heading.parent;
    else if (parentsWithStatementChildren.has(heading.anchor)) group = heading;

    return {
      ...heading,
      route: statementRoutes.get(heading.anchor),
      descriptionContent: body,
      navigationGroup: {
        id: `reference.source.statements.system.${splitRouteSegment(group.anchor, relativePath)}`,
        label: navigationLabel(group.title),
      },
      content: rewriteLocalStatementLinks(sectionContent),
    };
  });
}

function splitEntitySections(content, entityKind, relativePath, route) {
  if (entityKind === 'statement' && relativePath === 'statements/system.mdx') {
    return splitSystemStatementSections(content, relativePath, route);
  }
  if (!['aggregate-function', 'function', 'setting'].includes(entityKind)) return [];
  if (relativePath === 'settings/beta-and-experimental-features.mdx') return [];

  function isEntityHeading(title, anchor) {
    if (title === anchor) return true;
    if (headingAnchor(title) !== headingAnchor(anchor)) return false;

    const plainTitle = title.replace(/[`*_]/g, '').trim();
    return /[a-z][A-Z]|[._]/.test(plainTitle) || /^[A-Z0-9 _-]+$/.test(plainTitle);
  }

  const headings = [];
  let offset = 0;
  let fence = null;
  for (const line of content.split(/(?<=\n)/)) {
    const lineWithoutNewline = line.replace(/\r?\n$/, '');
    const fenceMatch = lineWithoutNewline.match(/^\s*(`{3,}|~{3,})/);
    if (fenceMatch) {
      if (!fence) fence = fenceMatch[1];
      else if (fence[0] === fenceMatch[1][0] && fenceMatch[1].length >= fence.length) fence = null;
    } else if (!fence) {
      const heading = lineWithoutNewline.match(/^##\s+(.+?)\s+\{#([^}\n]+)\}\s*$/);
      if (heading && isEntityHeading(heading[1], heading[2])) {
        headings.push({
          title: heading[1],
          anchor: heading[2],
          start: offset,
          bodyStart: offset + line.length,
        });
      }
    }
    offset += line.length;
  }

  if (headings.length < 2) return [];

  const prefix = content.slice(0, headings[0].start).trim();
  const entityRoutes = new Map(headings.map(({ anchor }) => [
    anchor,
    `${route}/${splitRouteSegment(anchor, relativePath)}`,
  ]));

  function rewriteLocalEntityLinks(sectionContent) {
    return sectionContent
      .replace(/\]\(#([^)]+)\)/g, (match, anchor) => (
        entityRoutes.has(anchor) ? `](${entityRoutes.get(anchor)})` : match
      ))
      .replace(/href=(['"])#([^'"]+)\1/g, (match, quote, anchor) => (
        entityRoutes.has(anchor) ? `href=${quote}${entityRoutes.get(anchor)}${quote}` : match
      ));
  }

  return headings.map((heading, index) => {
    const body = content.slice(heading.bodyStart, headings[index + 1]?.start ?? content.length).trim();
    const sectionContent = [prefix, promoteNestedHeadings(body)].filter(Boolean).join('\n\n');
    return {
      ...heading,
      route: entityRoutes.get(heading.anchor),
      descriptionContent: body,
      content: rewriteLocalEntityLinks(sectionContent),
    };
  });
}

function normalizeLegacyRoute(slug) {
  if (typeof slug !== 'string' || !slug.startsWith('/')) {
    return null;
  }

  return slug.startsWith('/docs/') ? slug : `/docs${slug}`;
}

function plainDescription(value) {
  return value
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[`*_]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function navigationLabel(value) {
  return value.replace(/`/g, '').trim();
}

function entityAliases(content, title) {
  const aliases = new Set();
  for (const match of content.matchAll(/^\*{0,2}Alias(?:es)?\*{0,2}:?\s*(.+)$/gmi)) {
    const codeAliases = [...match[1].matchAll(/`([^`]+)`/g)].map((alias) => alias[1]);
    const candidates = codeAliases.length > 0
      ? codeAliases
      : match[1].split(',').map((alias) => alias.replace(/[`*_]/g, '').trim());
    for (const alias of candidates) {
      if (alias && alias !== title) aliases.add(alias);
    }
  }

  for (const section of content.matchAll(
    /^##\s+Aliases\s+\{#[^}\n]+\}\s*\r?\n([\s\S]*?)(?=^#{1,2}\s|(?![\s\S]))/gmi,
  )) {
    for (const match of section[1].matchAll(/`([^`\n]+)`/g)) {
      const alias = match[1].trim();
      if (
        alias
        && alias !== title
        && alias.toLocaleLowerCase().startsWith(title.toLocaleLowerCase())
      ) {
        aliases.add(alias);
      }
    }
  }
  return [...aliases];
}

function entityDescription(content, fallback) {
  const candidates = content
    .replace(/```[\s\S]*?```/g, '')
    .replace(/~~~[\s\S]*?~~~/g, '')
    .replace(/^import\s+.+$/gm, '')
    .replace(/<([A-Z][A-Za-z0-9]*)\b[^>]*>[\s\S]*?<\/\1>/g, '')
    .replace(/<[^>]+\/?\s*>/g, '')
    .split(/\n\s*\n/)
    .map((candidate) => plainDescription(candidate))
    .filter((candidate) => (
      candidate.length >= 20
      && !candidate.startsWith('Introduced in:')
      && !/^(Syntax|Arguments|Returned value|Examples|Aliases):?$/i.test(candidate)
    ));
  return candidates[0] ?? fallback;
}

function navigationGroupMatches(document, group) {
  const explicitlyIncluded = group.documentIds?.includes(document.id) ?? false;
  if (!group.match) return explicitlyIncluded;

  const prefixMatches = group.match.sourcePrefix === undefined
    || document.sourcePath.startsWith(group.match.sourcePrefix);
  const kindMatches = group.match.entityKinds === undefined
    || group.match.entityKinds.includes(document.entityKind);
  return explicitlyIncluded || (prefixMatches && kindMatches);
}

function excludedSourcePathSet(definition) {
  if (definition.excludedSourcePaths === undefined) return new Set();
  if (!Array.isArray(definition.excludedSourcePaths)) {
    throw new Error('Reference navigation excludedSourcePaths must be an array');
  }

  const excludedSourcePaths = new Set();
  for (const sourcePath of definition.excludedSourcePaths) {
    if (
      typeof sourcePath !== 'string'
      || path.isAbsolute(sourcePath)
      || sourcePath.includes('\\')
      || path.posix.normalize(sourcePath) !== sourcePath
      || !/\.mdx?$/.test(sourcePath)
    ) {
      throw new Error(`Invalid excluded reference source path: ${sourcePath}`);
    }
    if (excludedSourcePaths.has(sourcePath)) {
      throw new Error(`Duplicate excluded reference source path: ${sourcePath}`);
    }
    excludedSourcePaths.add(sourcePath);
  }
  return excludedSourcePaths;
}

function resolveNavigation(definition, documents) {
  if (definition.schemaVersion !== 1 || definition.id !== 'reference') {
    throw new Error('Unsupported reference navigation definition');
  }
  if (!Array.isArray(definition.groups) || definition.groups.length === 0) {
    throw new Error('Reference navigation must define at least one group');
  }

  const groupIds = new Set();

  function validateGroup(group) {
    if (!group || typeof group.id !== 'string' || typeof group.label !== 'string') {
      throw new Error('Every reference navigation group needs an id and label');
    }
    if (groupIds.has(group.id)) throw new Error(`Duplicate reference navigation group: ${group.id}`);
    groupIds.add(group.id);
    if (!group.match && !Array.isArray(group.documentIds)) {
      throw new Error(`Reference navigation group ${group.id} has no membership rule`);
    }
    if (group.match?.sourcePrefix !== undefined && typeof group.match.sourcePrefix !== 'string') {
      throw new Error(`Invalid sourcePrefix in reference navigation group ${group.id}`);
    }
    if (group.match?.entityKinds !== undefined && !Array.isArray(group.match.entityKinds)) {
      throw new Error(`Invalid entityKinds in reference navigation group ${group.id}`);
    }
    if (group.documentIds !== undefined && !Array.isArray(group.documentIds)) {
      throw new Error(`Invalid documentIds in reference navigation group ${group.id}`);
    }
    if (group.groupBySourcePage !== undefined && typeof group.groupBySourcePage !== 'boolean') {
      throw new Error(`Invalid groupBySourcePage in reference navigation group ${group.id}`);
    }
    for (const child of group.groups ?? []) validateGroup(child);
  }

  for (const group of definition.groups) validateGroup(group);

  function resolveGroups(groups, candidates, parentId) {
    const claimed = new Map();
    const resolved = [];

    for (const group of groups) {
      const matched = candidates.filter((document) => navigationGroupMatches(document, group));
      for (const document of matched) {
        const previousGroup = claimed.get(document.id);
        if (previousGroup) {
          throw new Error(
            `Document ${document.id} belongs to both ${previousGroup} and ${group.id} under ${parentId}`,
          );
        }
        claimed.set(document.id, group.id);
      }

      const nested = resolveGroups(group.groups ?? [], matched, group.id);
      const nestedDocumentIds = new Set(nested.flatMap((node) => node.allDocumentIds));
      const configuredOrder = new Map(
        (group.documentIds ?? []).map((documentId, index) => [documentId, index]),
      );
      const directDocuments = matched
        .filter((document) => !nestedDocumentIds.has(document.id))
        .sort((left, right) => {
          const leftOrder = configuredOrder.get(left.id);
          const rightOrder = configuredOrder.get(right.id);
          if (leftOrder !== undefined || rightOrder !== undefined) {
            if (leftOrder === undefined) return 1;
            if (rightOrder === undefined) return -1;
            return leftOrder - rightOrder;
          }
          return left.name.localeCompare(right.name);
        });
      const groupedDocuments = new Map();
      const ungroupedDocuments = [];
      for (const document of directDocuments) {
        if (!group.groupBySourcePage || !document.navigationGroup) {
          ungroupedDocuments.push(document);
          continue;
        }
        const existing = groupedDocuments.get(document.navigationGroup.id);
        if (existing && existing.label !== document.navigationGroup.label) {
          throw new Error(`Conflicting labels for generated navigation group ${document.navigationGroup.id}`);
        }
        if (existing) existing.documents.push(document);
        else groupedDocuments.set(document.navigationGroup.id, {
          id: document.navigationGroup.id,
          label: document.navigationGroup.label,
          documents: [document],
        });
      }

      const documentNodes = ungroupedDocuments.map((document) => ({
        type: 'document',
        documentId: document.id,
        label: document.name,
        route: document.route,
      }));
      const generatedGroupNodes = [...groupedDocuments.values()]
        .sort((left, right) => left.label.localeCompare(right.label))
        .map((generatedGroup) => ({
          type: 'group',
          id: generatedGroup.id,
          label: generatedGroup.label,
          expanded: false,
          children: generatedGroup.documents.map((document) => ({
            type: 'document',
            documentId: document.id,
            label: document.name,
            route: document.route,
          })),
          firstDocumentId: generatedGroup.documents[0].id,
          allDocumentIds: generatedGroup.documents.map((document) => document.id),
        }));
      const resolvedGroupNodes = [...nested, ...generatedGroupNodes];
      const groupNodes = resolvedGroupNodes.map(({ allDocumentIds: _allDocumentIds, ...node }) => node);
      const children = group.documentsPosition === 'after'
        ? [...groupNodes, ...documentNodes]
        : [...documentNodes, ...groupNodes];
      const allDocumentIds = [
        ...ungroupedDocuments.map((document) => document.id),
        ...resolvedGroupNodes.flatMap((node) => node.allDocumentIds),
      ];

      if (children.length > 0) {
        resolved.push({
          type: 'group',
          id: group.id,
          label: group.label,
          expanded: group.expanded === true,
          children,
          firstDocumentId: allDocumentIds[0],
          allDocumentIds,
        });
      }
    }

    return resolved;
  }

  const resolvedGroups = resolveGroups(definition.groups, documents, definition.id);
  const assignedDocumentIds = new Set(resolvedGroups.flatMap((group) => group.allDocumentIds));
  const unassigned = documents.filter((document) => !assignedDocumentIds.has(document.id));
  if (unassigned.length > 0) {
    throw new Error(
      `Reference navigation does not assign ${unassigned.length} documents, beginning with ${unassigned[0].id}`,
    );
  }

  for (const group of resolvedGroups) delete group.allDocumentIds;

  return {
    schemaVersion: 2,
    root: {
      type: 'group',
      id: definition.id,
      label: definition.label ?? 'Reference',
      children: resolvedGroups,
      firstDocumentId: resolvedGroups[0]?.firstDocumentId ?? null,
    },
  };
}

function readGitValue(argumentsList) {
  return execFileSync('git', argumentsList, {
    cwd: repositoryDirectory,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim();
}

async function writeJson(destination, value) {
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const [navigationDefinition, runtimeRegistries, componentSourcePaths] = await Promise.all([
    readFile(options.navigation, 'utf8').then(JSON.parse),
    loadRuntimeRegistries(options.sourceRoot),
    Promise.all([
      collectResourceFiles(path.join(options.snippetsDir, 'components')),
      collectResourceFiles(path.join(options.snippetsDir, 'lib')),
    ]).then((groups) => groups.flat()),
  ]);
  const documents = [];
  const entitySearchRecords = [];
  const snippets = new Map();
  const routes = new Set();
  const excludedSourcePaths = excludedSourcePathSet(navigationDefinition);

  const registryPages = new Map([
    ['system-tables/metrics.mdx', {
      title: 'Metric descriptions',
      anchor: 'metric-descriptions',
      entityKind: 'current-metric',
      idPrefix: 'reference:current-metric:',
      entries: runtimeRegistries.currentMetrics,
    }],
    ['system-tables/events.mdx', {
      title: 'Event descriptions',
      anchor: 'event-descriptions',
      entityKind: 'profile-event',
      idPrefix: 'reference:profile-event:',
      entries: runtimeRegistries.profileEvents,
    }],
  ]);

  for (const sourcePath of await collectFiles(options.docsDir)) {
    const relativePath = path.relative(options.docsDir, sourcePath).split(path.sep).join('/');
    if (excludedSourcePaths.has(relativePath)) continue;

    const source = await readFile(sourcePath, 'utf8');
    const regions = extractGeneratedContent(source, sourcePath);
    if (regions.length === 0) continue;

    const frontmatter = readFrontmatter(source, relativePath);
    let content = regions.filter(Boolean).join('\n\n');
    const route = routeFromRelativePath(relativePath);
    const entityKind = inferEntityKind(relativePath);
    if (entityKind === 'setting') content = removeSettingProvenance(content);
    let registryPage = registryPages.get(relativePath);
    if (relativePath === 'system-tables/asynchronous_metrics.mdx') {
      const generatedRegistry = extractSingleGeneratedRegion(
        source,
        relativePath,
        ASYNC_METRICS_START_MARKER,
        ASYNC_METRICS_END_MARKER,
      );
      registryPage = {
        title: 'Metric descriptions',
        anchor: 'metric-descriptions',
        entityKind: 'asynchronous-metric',
        idPrefix: 'reference:asynchronous-metric:',
        entries: parseMarkdownRegistry(generatedRegistry, relativePath),
      };
    }
    if (registryPage) {
      content = [
        content,
        renderRegistrySections(registryPage.title, registryPage.anchor, registryPage.entries),
      ].filter(Boolean).join('\n\n');

      for (const entry of registryPage.entries) {
        entitySearchRecords.push({
          id: `${registryPage.idPrefix}${entry.stableName ?? entry.name}`,
          title: entry.name,
          description: plainDescription(entry.description),
          aliases: [],
          route: `${route}#${entry.anchor ?? headingAnchor(entry.name)}`,
          entityKind: registryPage.entityKind,
          headings: [],
        });
      }
    }
    if (!content) continue;

    const title = String(frontmatter.title ?? humanize(path.basename(relativePath, path.extname(relativePath))));
    const description = plainDescription(String(
      frontmatter.description ?? `Autogenerated ClickHouse reference for ${title}.`,
    ));
    const aliases = Array.isArray(frontmatter.keywords)
      ? frontmatter.keywords.map(String)
      : [];
    const documentName = String(frontmatter.sidebarTitle ?? title);
    for (const alias of entityAliases(content, documentName)) {
      if (!aliases.includes(alias)) aliases.push(alias);
    }
    const legacyRoute = normalizeLegacyRoute(frontmatter.slug);

    for (const match of content.matchAll(
      /^import\s+\w+\s+from\s+['"]\/snippets\/(?!components\/)([^'"]+\.mdx)['"];?\s*$/gm,
    )) {
      const snippetPath = match[1];
      if (!snippets.has(snippetPath)) {
        const snippetSource = await readFile(path.join(options.snippetsDir, snippetPath), 'utf8');
        snippets.set(snippetPath, {
          path: snippetPath,
          content: snippetSource,
          contentHash: hash(snippetSource),
        });
      }
    }

    const sourceId = `reference:${relativePath.replace(/\.mdx?$/, '')}`;
    const splitSections = splitEntitySections(content, entityKind, relativePath, route);
    const keepSourceDocument = relativePath === 'statements/system.mdx' && splitSections.length > 0;
    const sourceDocumentRecord = {
      id: sourceId,
      entityKind,
      name: keepSourceDocument ? 'Overview' : documentName,
      title,
      description,
      aliases,
      route,
      legacyRoutes: legacyRoute && legacyRoute !== route ? [legacyRoute] : [],
      sourcePath: relativePath,
      featureState: entityKind === 'setting'
        && relativePath !== 'settings/beta-and-experimental-features.mdx'
        ? settingFeatureState(content)
        : null,
      content,
    };
    const documentRecords = splitSections.length > 0
      ? [
        ...(keepSourceDocument ? [sourceDocumentRecord] : []),
        ...splitSections.map((section, index) => ({
          id: `${sourceId}/${section.anchor}`,
          entityKind,
          name: section.title,
          title: section.title,
          description: entityDescription(section.descriptionContent, description),
          aliases: entityAliases(section.descriptionContent, section.title),
          route: section.route,
          legacyRoutes: [
            `${route}#${section.anchor}`,
            ...(legacyRoute && legacyRoute !== route ? [`${legacyRoute}#${section.anchor}`] : []),
            ...(!keepSourceDocument && index === 0 ? [
              route,
              ...(legacyRoute && legacyRoute !== route ? [legacyRoute] : []),
            ] : []),
          ],
          sourcePath: relativePath,
          featureState: entityKind === 'setting' ? settingFeatureState(section.content) : null,
          navigationGroup: section.navigationGroup ?? {
            id: `reference.source.${relativePath.replace(/\.mdx?$/, '').replace(/[^A-Za-z0-9_-]+/g, '.')}`,
            label: navigationLabel(String(
              entityKind === 'function' ? title : (frontmatter.sidebarTitle ?? title),
            )),
          },
          content: section.content,
        })),
      ]
      : [sourceDocumentRecord];

    for (const document of documentRecords) {
      if (routes.has(document.route)) {
        throw new Error(`Duplicate generated route: ${document.route}`);
      }
      routes.add(document.route);
      document.sections = extractSections(document.content);
      document.contentHash = hash(document.content);
      documents.push(document);
      for (const alias of document.aliases) {
        entitySearchRecords.push({
          id: `${document.id}:alias:${alias}`,
          title: alias,
          description: `Alias of ${document.title}`,
          aliases: [document.title],
          route: document.route,
          entityKind: document.entityKind,
          headings: [],
        });
      }
    }
  }

  documents.sort((left, right) => left.route.localeCompare(right.route));
  const snippetRecords = [...snippets.values()].sort((left, right) => left.path.localeCompare(right.path));
  const componentResources = await Promise.all(
    componentSourcePaths.map(async (sourcePath) => {
      const content = await readFile(sourcePath, 'utf8');
      return {
        path: path.relative(options.snippetsDir, sourcePath).split(path.sep).join('/'),
        content,
        contentHash: hash(content),
      };
    }),
  );
  componentResources.sort((left, right) => left.path.localeCompare(right.path));
  const documentPayload = { schemaVersion: SCHEMA_VERSION, documents };
  const navigation = resolveNavigation(navigationDefinition, documents);
  const routeManifest = {
    schemaVersion: SCHEMA_VERSION,
    routes: documents.map(({ id, route, legacyRoutes }) => ({ id, route, legacyRoutes })),
  };
  const search = {
    schemaVersion: SCHEMA_VERSION,
    records: [
      ...documents.map(({ id, title, description, aliases, route, entityKind, sections }) => ({
        id,
        title,
        description,
        aliases,
        route,
        entityKind,
        headings: sections.map(({ title: sectionTitle }) => sectionTitle),
      })),
      ...entitySearchRecords,
    ],
  };
  const serializedDocuments = JSON.stringify(documentPayload);
  const serializedSnippets = JSON.stringify(snippetRecords);
  const serializedComponentResources = JSON.stringify(componentResources);
  const serializedNavigation = JSON.stringify(navigation);
  const serializedRoutes = JSON.stringify(routeManifest);
  const serializedSearch = JSON.stringify(search);
  const sourceRevision = readGitValue(['rev-parse', 'HEAD']);
  const sourceVersion = readGitValue(['describe', '--tags', '--always']);
  const bundleHash = hash(
    `${serializedDocuments}\n${serializedSnippets}\n${serializedComponentResources}\n${serializedNavigation}\n${serializedRoutes}\n${serializedSearch}`,
  );
  const manifest = {
    schemaVersion: ARTIFACT_SCHEMA_VERSION,
    channel: options.channel,
    locale: options.locale,
    sourceRevision,
    sourceVersion,
    generatedAt: new Date().toISOString(),
    bundleHash,
    documentCount: documents.length,
    searchRecordCount: search.records.length,
    snippetCount: snippetRecords.length,
    componentResourceCount: componentResources.length,
    contentBytes: documents.reduce(
      (total, document) => total + Buffer.byteLength(document.content, 'utf8'),
      0,
    ),
    navigationSourceHash: hash(JSON.stringify(navigationDefinition)),
    excludedSourcePaths: [...excludedSourcePaths].sort(),
    files: {
      documents: 'documents.json',
      navigation: 'navigation.json',
      routes: 'routes.json',
      search: 'search.json',
      snippets: 'snippets.json',
    },
  };

  await mkdir(options.output, { recursive: true });
  await Promise.all([
    writeJson(path.join(options.output, 'manifest.json'), manifest),
    writeJson(path.join(options.output, 'documents.json'), documentPayload),
    writeJson(path.join(options.output, 'navigation.json'), navigation),
    writeJson(path.join(options.output, 'routes.json'), routeManifest),
    writeJson(path.join(options.output, 'search.json'), search),
    writeJson(path.join(options.output, 'snippets.json'), {
      schemaVersion: ARTIFACT_SCHEMA_VERSION,
      snippets: snippetRecords,
      componentResources,
    }),
  ]);

  console.log(
    `Exported ${documents.length} generated documents, ${snippetRecords.length} snippets, and ${componentResources.length} component resources to ${path.relative(repositoryDirectory, options.output)}`,
  );
  console.log(`Bundle SHA-256: ${bundleHash}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}


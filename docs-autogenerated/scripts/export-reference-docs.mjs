function parseArguments(argv) {
  const options = {
    docsDir: path.join(repositoryDirectory, 'docs/reference'),
    snippetsDir: path.join(repositoryDirectory, 'docs/snippets'),
    sourceRoot: repositoryDirectory,
    navigation: path.join(projectDirectory, 'reference-navigation.json'),
    output: path.join(projectDirectory, '.artifacts/latest'),
    channel: 'latest',
    locale: 'en',
  };

  const names = {
    '--docs-dir': 'docsDir',
    '--snippets-dir': 'snippetsDir',
    '--source-root': 'sourceRoot',
    '--navigation': 'navigation',
    '--output': 'output',
    '--channel': 'channel',
    '--locale': 'locale',
  };

  for (let index = 0; index < argv.length; index += 1) {
    const option = names[argv[index]];
    if (!option || index + 1 >= argv.length) {
      throw new Error(`Unknown or incomplete argument: ${argv[index]}`);
    }

    options[option] = argv[index + 1];
    index += 1;
  }

  options.docsDir = path.resolve(options.docsDir);
  options.snippetsDir = path.resolve(options.snippetsDir);
  options.sourceRoot = path.resolve(options.sourceRoot);
  options.navigation = path.resolve(options.navigation);
  options.output = path.resolve(options.output);
  return options;
}

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(entryPath)));
    } else if (/\.mdx?$/.test(entry.name) && entry.name !== 'AGENTS.md') {
      files.push(entryPath);
    }
  }

  return files;
}

async function collectResourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectResourceFiles(entryPath)));
    } else if (/\.(?:css|jsx?)$/.test(entry.name)) {
      files.push(entryPath);
    }
  }

  return files;
}

function hash(value) {
  return createHash('sha256').update(value).digest('hex');
}

function readFrontmatter(source, sourcePath) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
  if (!match) {
    return {};
  }

  const lines = match[1].split(/\r?\n/);
  const frontmatter = {};
  const fields = new Set(['description', 'keywords', 'sidebarTitle', 'slug', 'title']);

  for (let index = 0; index < lines.length; index += 1) {
    const fieldMatch = lines[index].match(/^([A-Za-z][A-Za-z0-9_]*):\s*(.*)$/);
    if (!fieldMatch || !fields.has(fieldMatch[1])) continue;

    const key = fieldMatch[1];
    let value = fieldMatch[2].trim();
    if ((value.startsWith("'") && !value.endsWith("'")) || (value.startsWith('"') && !value.endsWith('"'))) {
      const quote = value[0];
      while (index + 1 < lines.length && !value.endsWith(quote)) {
        index += 1;
        value += ` ${lines[index].trim()}`;
      }
    }

    if (key === 'keywords') {
      frontmatter[key] = [...value.matchAll(/['"]([^'"]+)['"]/g)].map((keyword) => keyword[1]);
      continue;
    }

    if ((value.startsWith("'") && value.endsWith("'")) || (value.startsWith('"') && value.endsWith('"'))) {
      value = value.slice(1, -1);
    }
    frontmatter[key] = value.replace(/''/g, "'");
  }

  return frontmatter;
}

function extractGeneratedContent(source, sourcePath) {
  const regions = [];
  let cursor = 0;

  while (cursor < source.length) {
    const start = source.indexOf(START_MARKER, cursor);
    const endWithoutStart = source.indexOf(END_MARKER, cursor);

    if (start === -1) {
      if (endWithoutStart !== -1) {
        throw new Error(`Found ${END_MARKER} without a start marker in ${sourcePath}`);
      }
      break;
    }

    if (endWithoutStart !== -1 && endWithoutStart < start) {
      throw new Error(`Found ${END_MARKER} before ${START_MARKER} in ${sourcePath}`);
    }

    const end = source.indexOf(END_MARKER, start + START_MARKER.length);
    if (end === -1) {
      throw new Error(`Missing ${END_MARKER} in ${sourcePath}`);
    }

    regions.push(source.slice(start + START_MARKER.length, end).trim());
    cursor = end + END_MARKER.length;
  }

  return regions;
}

function extractSingleGeneratedRegion(source, sourcePath, startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start + startMarker.length);
  if (start === -1 || end === -1) {
    throw new Error(`Missing ${startMarker} / ${endMarker} in ${sourcePath}`);
  }
  if (source.indexOf(startMarker, start + startMarker.length) !== -1) {
    throw new Error(`Found more than one ${startMarker} region in ${sourcePath}`);
  }
  return source.slice(start + startMarker.length, end).trim();
}


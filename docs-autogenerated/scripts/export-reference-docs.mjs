function parseMarkdownRegistry(content, sourcePath) {
  const headingPattern = /^###\s+(.+?)\s+\{#([^}\n]+)\}\s*$/gm;
  const headings = [...content.matchAll(headingPattern)];
  if (headings.length === 0) throw new Error(`No generated registry entries found in ${sourcePath}`);

  const anchors = new Set();
  return headings.map((heading, index) => {
    const anchor = heading[2];
    if (anchors.has(anchor)) throw new Error(`Duplicate generated registry anchor in ${sourcePath}: ${anchor}`);
    anchors.add(anchor);

    const descriptionStart = heading.index + heading[0].length;
    const descriptionEnd = headings[index + 1]?.index ?? content.length;
    const description = content.slice(descriptionStart, descriptionEnd).trim();
    if (!description) throw new Error(`Missing generated registry description for ${heading[1]} in ${sourcePath}`);

    return {
      name: heading[1].replace(/`/g, ''),
      stableName: anchor,
      heading: heading[1],
      anchor,
      description,
    };
  });
}

function extractSections(content) {
  const sections = [];
  const headingPattern = /^(#{2,6})\s+(.+?)(?:\s+\{#([^}]+)\})?\s*$/gm;

  for (const match of content.matchAll(headingPattern)) {
    const title = match[2]
      .replace(/\s+\{#[^}]+\}\s*$/, '')
      .replace(/[`*_]/g, '')
      .trim();
    const anchor = match[3] ?? title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    sections.push({ depth: match[1].length, title, anchor });
  }

  return sections;
}

function splitRouteSegment(value, sourcePath) {
  const segment = value
    .replace(/[^A-Za-z0-9_-]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-|-$/g, '');
  if (!segment) throw new Error(`Cannot create an entity route from ${value} in ${sourcePath}`);
  return segment;
}

function promoteNestedHeadings(content, levels = 1) {
  let fence = null;

  return content
    .split('\n')
    .map((line) => {
      const fenceMatch = line.match(/^\s*(`{3,}|~{3,})/);
      if (fenceMatch) {
        if (!fence) fence = fenceMatch[1];
        else if (fence[0] === fenceMatch[1][0] && fenceMatch[1].length >= fence.length) fence = null;
        return line;
      }
      if (fence) return line;
      return line.replace(/^(#{2,6})(\s+)/, (_line, heading, whitespace) => {
        if (heading.length <= levels + 1) return _line;
        return `${heading.slice(levels)}${whitespace}`;
      });
    })
    .join('\n')
    .trim();
}


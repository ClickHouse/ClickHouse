#!/usr/bin/env bash
# Generate a header with the names of sensitive librdkafka configuration properties.
#
# Extracts the names of the properties marked with the _RK_SENSITIVE flag in the
# rd_kafka_properties table in librdkafka's rdkafka_conf.c. ClickHouse uses the
# list to hide the values of these properties in its logs, because the public
# rd_kafka_conf_dump (used via cppkafka::Configuration::get_all) does not
# redact them.
#
# Usage: generate-sensitive-properties.sh <path/to/rdkafka_conf.c> <output_header>

set -euo pipefail

if [ "$#" -ne 2 ]; then
    echo "Usage: $0 <path/to/rdkafka_conf.c> <output_header>" >&2
    exit 1
fi

src=$1
out=$2

# A property table entry starts with an initializer whose first field (the scope
# flags, which contain no quotes or braces) includes _RK_SENSITIVE, followed by
# the property name as the first string literal. Entries can span multiple
# lines, so flatten the file first.
names=$(tr '\n' ' ' < "$src" \
    | grep -oE '\{[^"{}]*_RK_SENSITIVE[^"{}]*,[[:space:]]*"[^"]+"' \
    | sed -E 's/.*"([^"]+)"$/\1/' \
    | sort -u \
    || true)

# Fail-close sanity guard: a parser break must not silently produce a smaller
# blacklist. Known properties of the vendored librdkafka must be present.
count=$(printf '%s' "$names" | grep -c . || true)
if ! grep -qx 'sasl.password' <<< "$names" \
    || ! grep -qx 'ssl.key.pem' <<< "$names" \
    || [ "$count" -lt 10 ]
then
    echo "Sanity check failed: extracted $count sensitive properties from $src." \
         "The parser in $0 is likely out of sync with the librdkafka source:" >&2
    printf '%s\n' "$names" >&2
    exit 1
fi

{
    echo "/// Autogenerated by contrib/librdkafka-cmake/generate-sensitive-properties.sh"
    echo "/// from the properties marked with the \`_RK_SENSITIVE\` flag in"
    echo "/// contrib/librdkafka/src/rdkafka_conf.c. Do not edit."
    echo "#pragma once"
    echo
    echo "#include <string_view>"
    echo
    echo "inline constexpr std::string_view LIBRDKAFKA_SENSITIVE_PROPERTIES[] ="
    echo "{"
    while IFS= read -r name; do
        echo "    \"$name\","
    done <<< "$names"
    echo "};"
} > "$out.tmp"
mv "$out.tmp" "$out"

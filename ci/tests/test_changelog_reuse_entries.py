"""
Tests for `--reuse-entries-from` of `ci/tools/changelog.py`: a pull request that
already has an entry in `CHANGELOG.md` is copied from it instead of being
requested from GitHub.

Requesting every pull request of a monthly release exhausted the hourly rate
limit of the token, the script slept until the limit was reset, and the
`Create Release` job of `v26.11.1.2942-stable` ran out of its two hours:
https://github.com/ClickHouse/ClickHouse/actions/runs/45450531725/job/138675365339
"""

import os
import sys
from types import SimpleNamespace
from unittest import mock

import pytest

# `changelog.py` runs in the style-test container, where these are installed.
for module in ("github", "rapidfuzz", "tqdm"):
    pytest.importorskip(module)

REPO_ROOT = os.path.join(os.path.dirname(__file__), "../..")
sys.path.insert(0, REPO_ROOT)
sys.path.insert(0, os.path.join(REPO_ROOT, "ci/tools"))

import changelog  # noqa: E402  pylint: disable=wrong-import-position

REPO = "ClickHouse/ClickHouse"
URL = f"https://github.com/{REPO}"
BUG_FIX = "Bug Fix (user-visible misbehavior in an official stable release)"


def _attribution(number, author="Author"):
    return f"[#{number}]({URL}/pull/{number}) ([{author}](https://github.com/{author}))."


FEATURE = f"* Added a thing. {_attribution(1001)}"
# Two entries merged into one bullet: both pull requests are attributed.
GROUPED = f"* Faster reads. {_attribution(1002)} {_attribution(1003, 'Other')}"
# `#1001` is only mentioned here, the entry belongs to `#1004`.
FIX = f"* Fixed the thing. Follow-up to [#1001]({URL}/pull/1001). {_attribution(1004)}"
OLD_FIX = f"* Fixed something long ago. {_attribution(900)}"

CHANGELOG = f"""### Table of Contents
**[ClickHouse release v26.11, 2026-11-24](#2611)**<br/>
* A bullet outside of a category. {_attribution(1)}

# 2026 Changelog

### <a id="2611"></a> ClickHouse release 26.11, 2026-11-24

#### New Feature
{FEATURE}

#### Performance Improvement
{GROUPED}

#### Bug Fix (user-visible misbehavior in an official stable release)

{FIX}
* An entry of another repository. [#1005](https://github.com/ClickHouse/other/pull/1005) ([Author](https://github.com/Author)).

### <a id="2610"></a> ClickHouse release 26.10, 2026-10-22

#### Bug Fix (user-visible misbehavior in an official stable release)
{OLD_FIX}
"""


@pytest.fixture(name="changelog_path")
def fixture_changelog_path(tmp_path):
    path = tmp_path / "CHANGELOG.md"
    path.write_text(CHANGELOG, encoding="utf-8")
    return path


def _copy(changelog_path, searched, merged):
    """The entries copied for the `searched` pull requests when git has the
    merge commits `merged` (number -> head branch) in the interval."""
    issues = [SimpleNamespace(number=number) for number in searched]
    with mock.patch.object(changelog, "get_merged_prs", return_value=merged):
        entries, reused = changelog.get_existing_entries(issues, changelog_path, REPO)
    return [(e.number, e.category, e.formatted_entry) for e in entries], reused


def test_an_entry_is_a_bullet_that_attributes_the_pull_request(changelog_path):
    entries = changelog.read_existing_entries(changelog_path, REPO)
    assert entries == {
        1001: [("New Feature", FEATURE)],
        1002: [("Performance Improvement", GROUPED)],
        1003: [("Performance Improvement", GROUPED)],
        1004: [(BUG_FIX, FIX)],
        900: [(BUG_FIX, OLD_FIX)],
    }


def test_only_pull_requests_merged_in_the_interval_are_copied(changelog_path):
    # `#900` is found by the search, because its merge date is in the range,
    # but it was merged before the interval; `#1004` is merged in the interval,
    # but the search did not return it; `#2000` has no entry.
    entries, reused = _copy(
        changelog_path,
        searched=[900, 1001, 2000],
        merged={1001: "feature", 1004: "fix", 2000: "untold"},
    )
    assert entries == [(1001, "New Feature", FEATURE)]
    assert reused == {1001}


def test_a_shared_bullet_is_written_once(changelog_path):
    entries, reused = _copy(
        changelog_path, searched=[1003, 1002], merged={1002: "a", 1003: "b"}
    )
    assert entries == [(1002, "Performance Improvement", GROUPED)]
    assert reused == {1002, 1003}


def test_a_backport_copies_the_entry_of_the_original(changelog_path):
    entries, reused = _copy(
        changelog_path, searched=[5000, 5001], merged={5000: "backport/26.10/1004"}
    )
    expected = (
        f"* Backported in [#5000]({URL}/issues/5000): " + FIX.removeprefix("* ")
    )
    # Sorted by the original pull request, like a generated backport entry.
    assert entries == [(1004, BUG_FIX, expected)]
    assert reused == {5000}


def test_merge_commits_of_the_interval():
    subjects = "\n".join(
        [
            "Merge pull request #1001 from someone/feature",
            "Merge pull request #5000 from ClickHouse/backport/26.10/1004",
            'Revert "Merge pull request #1002 from someone/reads"',
            "Update autogenerated version to 26.10.2.1 and contributors",
            "",
        ]
    )
    runner = mock.Mock()
    runner.run.return_value = subjects
    with mock.patch.object(changelog, "runner", runner), mock.patch.object(
        changelog, "FROM_REF", "v1"
    ), mock.patch.object(changelog, "TO_REF", "v2"):
        merged = changelog.get_merged_prs()
    assert merged == {1001: "feature", 5000: "backport/26.10/1004"}
    assert runner.run.call_args.args[0].endswith(" v1..v2")
    assert changelog.get_backported_number(merged[5000]) == 1004
    assert changelog.get_backported_number(merged[1001]) is None

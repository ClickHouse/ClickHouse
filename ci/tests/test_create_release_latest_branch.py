"""
Tests for `is_latest_release_branch` of `ci/jobs/scripts/create_release.py`,
which decides whether a release moves the `latest` docker tag.

The branch `30.12` of ClickHouse/ClickHouse is not a release branch: it was
pushed to test the branch rules, and its version file says `26.7`. It sorted
above every release branch, so no release was the latest one, and `latest`
stayed at `26.10.4.207` while `26.11.1.2942` was released:
https://github.com/ClickHouse/ClickHouse/issues/134282
"""

import os
import sys
from types import SimpleNamespace
from unittest import mock

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../.."))

from ci.jobs.scripts import create_release  # noqa: E402  pylint: disable=wrong-import-position

# What `git for-each-ref --sort=-version:refname` prints, and the version in
# `cmake/autogenerated_versions.txt` of each of these branches.
BRANCHES = "30.12\n26.11\n26.10\n"
VERSIONS = {"30.12": (26, 7), "26.11": (26, 11), "26.10": (26, 10)}


def _version_at_commit(commit):
    major, minor = VERSIONS[commit.removeprefix("origin/")]
    return SimpleNamespace(major=major, minor=minor)


def _is_latest(branch):
    with mock.patch.object(
        create_release.Shell, "get_output", return_value=BRANCHES
    ), mock.patch.object(
        create_release.CHVersion, "get_version_at_commit", side_effect=_version_at_commit
    ):
        return create_release.is_latest_release_branch(branch)


def test_a_branch_named_like_a_release_branch_is_not_the_latest_release():
    assert _is_latest("26.11")
    assert not _is_latest("26.10")
    assert not _is_latest("30.12")

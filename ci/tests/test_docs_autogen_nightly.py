def test_protected_docs_guard_fetches_only_endpoint_revisions(monkeypatch):
    checks = []
    info = SimpleNamespace(
        pr_labels=[],
        git_branch="feature",
        fork_name="ClickHouse/ClickHouse",
        user_name="contributor",
        pr_number=12345,
        sha="head123",
        get_changed_files=lambda: ["docs/example.md"],
        get_kv_data=lambda key: "base123"
        if key == "merge_base_commit_sha"
        else None,
    )
    monkeypatch.setattr(docs_job_mintlify, "Info", lambda: info)
    monkeypatch.setattr(
        docs_job_mintlify, "check_readonly_copies", lambda _files: True
    )
    monkeypatch.setattr(
        docs_job_mintlify.Shell,
        "check",
        lambda command, **kwargs: checks.append((command, kwargs)) or True,
    )
    monkeypatch.setattr(
        docs_job_mintlify,
        "check_autogenerated_regions",
        lambda base, head: (base, head) == ("base123", "head123"),
    )

    assert docs_job_mintlify._protected_docs_guard()
    assert checks == [
        (
            "git fetch --no-tags --depth=1 --filter=blob:none origin "
            "base123 head123",
            {"verbose": True},
        )
    ]


def test_clickhouse_connect_sync_exemption_is_scoped():
    trusted = {
        "pr_labels": [docs_job_mintlify.AUTOGENERATED_DOCS_LABEL],
        "git_branch": docs_job_mintlify.CLICKHOUSE_CONNECT_SYNC_BRANCH,
        "fork_name": docs_job_mintlify.CLICKHOUSE_CONNECT_SYNC_HEAD_REPOSITORY,
        "user_name": docs_job_mintlify.CLICKHOUSE_CONNECT_SYNC_PR_AUTHOR,
    }
    untrusted_values = {
        "pr_labels": [],
        "git_branch": "robot/docs-autogen",
        "fork_name": "contributor/ClickHouse",
        "user_name": "contributor",
    }

    for field, value in untrusted_values.items():
        candidate = trusted.copy()
        candidate[field] = value
        info = SimpleNamespace(**candidate)
        assert not docs_job_mintlify._is_trusted_clickhouse_connect_sync(info)



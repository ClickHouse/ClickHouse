def test_autogenerated_label_still_checks_readonly_copies(monkeypatch):
    changed_files = ["docs/integrations/language-clients/python/README.md"]
    info = SimpleNamespace(
        pr_labels=["pr-autogenerated-docs"],
        git_branch=docs_autogen_nightly.BRANCH,
        fork_name=docs_job_mintlify.CLICKHOUSE_CONNECT_SYNC_HEAD_REPOSITORY,
        user_name=docs_job_mintlify.CLICKHOUSE_CONNECT_SYNC_PR_AUTHOR,
        get_changed_files=lambda: changed_files,
    )
    checked = []
    monkeypatch.setattr(docs_job_mintlify, "Info", lambda: info)
    monkeypatch.setattr(
        docs_job_mintlify,
        "check_readonly_copies",
        lambda files: checked.append(files) or False,
    )

    def unexpected_call(*_args, **_kwargs):
        raise AssertionError("autogenerated-region guard was not skipped")

    monkeypatch.setattr(docs_job_mintlify.Shell, "check", unexpected_call)
    monkeypatch.setattr(
        docs_job_mintlify, "check_autogenerated_regions", unexpected_call
    )

    assert not docs_job_mintlify._protected_docs_guard()
    assert checked == [changed_files]



def test_client_sync_branch_may_only_edit_its_owned_copy():
    sync_branch = "robot/docs-sync-clickhouse-connect"
    python_file = "docs/integrations/language-clients/python/README.md"
    rust_file = "docs/integrations/language-clients/rust/index.mdx"

    assert check_readonly_copies(
        [python_file], allowed_sync_branch=sync_branch
    )
    assert not check_readonly_copies(
        [python_file, rust_file], allowed_sync_branch=sync_branch
    )


def test_current_base_branch_accepts_current_master(monkeypatch):
    checks = []
    outputs = {
        "git rev-parse HEAD": "abc123\n",
        "git rev-parse FETCH_HEAD": "abc123\n",
    }

    monkeypatch.setattr(
        docs_autogen_nightly,
        "Info",
        lambda: SimpleNamespace(git_branch=docs_autogen_nightly.BASE_BRANCH),
    )
    monkeypatch.setattr(
        docs_autogen_nightly.Shell,
        "check",
        lambda command, **kwargs: checks.append((command, kwargs)) or True,
    )
    monkeypatch.setattr(
        docs_autogen_nightly.Shell,
        "get_output",
        lambda command: outputs[command],
    )

    assert docs_autogen_nightly.on_current_base_branch()
    assert checks == [
        (
            "git fetch --no-tags origin master",
            {"verbose": True},
        )
    ]


def test_current_base_branch_rejects_stale_master(monkeypatch, capsys):
    outputs = {
        "git rev-parse HEAD": "old123\n",
        "git rev-parse FETCH_HEAD": "new456\n",
    }

    monkeypatch.setattr(
        docs_autogen_nightly,
        "Info",
        lambda: SimpleNamespace(git_branch=docs_autogen_nightly.BASE_BRANCH),
    )
    monkeypatch.setattr(
        docs_autogen_nightly.Shell,
        "check",
        lambda *_args, **_kwargs: True,
    )
    monkeypatch.setattr(
        docs_autogen_nightly.Shell,
        "get_output",
        lambda command: outputs[command],
    )

    assert not docs_autogen_nightly.on_current_base_branch()
    assert (
        "HEAD (old123) is not the current 'master' tip (new456)"
        in capsys.readouterr().err
    )



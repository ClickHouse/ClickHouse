def test_client_docs_sync_scopes_copy_exemption_and_checks_regions(monkeypatch):
    changed_files = ["docs/integrations/language-clients/python/README.md"]
    sync_branch = (
        f"{docs_job_mintlify.CLIENT_DOCS_SYNC_BRANCH_PREFIX}clickhouse-connect"
    )
    info = SimpleNamespace(
        pr_labels=["pr-autogenerated-docs"],
        git_branch=sync_branch,
        fork_name="ClickHouse/ClickHouse",
        repo_name="ClickHouse/ClickHouse",
        pr_number=123,
        sha="head",
        get_changed_files=lambda: changed_files,
        get_kv_data=lambda _key: "base",
    )
    monkeypatch.setattr(docs_job_mintlify, "Info", lambda: info)
    readonly_checks = []
    region_checks = []
    monkeypatch.setattr(
        docs_job_mintlify,
        "check_readonly_copies",
        lambda files, allowed_sync_branch=None: readonly_checks.append(
            (files, allowed_sync_branch)
        )
        or True,
    )
    monkeypatch.setattr(
        docs_job_mintlify.Shell, "check", lambda *_args, **_kwargs: True
    )
    monkeypatch.setattr(
        docs_job_mintlify,
        "check_autogenerated_regions",
        lambda base, head: region_checks.append((base, head)) or True,
    )

    assert docs_job_mintlify._protected_docs_guard()
    assert readonly_checks == [(changed_files, sync_branch)]
    assert region_checks == [("base", "head")]



"""
Tests for ClickHouse CI version handling.

This branch uses the release version from `cmake/autogenerated_versions.txt`
as-is instead of deriving CI-only version fields from the current checkout.
"""

import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "../.."))

from ci.jobs.scripts.clickhouse_version import CHVersion
from version_helper import check_tag_version

_RELEASE = {
    "major": 99,
    "minor": 88,
    "patch": 77,
    "revision": "12345",
    "githash": "release-file-sha",
    "tweak": "66",
    "flavour": "customflavour",
    "describe": "v99.88.77.66.customflavour",
    "string": "99.88.77.66.customflavour",
}


class _FakeInfo:
    def __init__(self, pr_number, sha="deadbeef", git_branch="some-branch"):
        self.pr_number = pr_number
        self.sha = sha
        self.git_branch = git_branch


def _patch(monkeypatch, pr_number, commit_count="123"):
    monkeypatch.setattr(
        CHVersion, "get_release_version_as_dict", classmethod(lambda cls: dict(_RELEASE))
    )
    monkeypatch.setattr(
        "ci.jobs.scripts.clickhouse_version.Info",
        lambda: _FakeInfo(pr_number),
    )
    calls = []

    def fake_get_output(command, verbose=False):
        calls.append(command)
        return commit_count

    monkeypatch.setattr(
        "ci.jobs.scripts.clickhouse_version.Shell.get_output", fake_get_output
    )
    return calls


def test_pr_uses_release_version_as_is(monkeypatch):
    calls = _patch(monkeypatch, pr_number=107138, commit_count="250")
    version = CHVersion.get_current_version_as_dict()
    assert version == _RELEASE
    assert calls == []


def test_pr_version_stable_across_reopen(monkeypatch):
    v1 = (
        _patch(monkeypatch, pr_number=107138, commit_count="185"),
        CHVersion.get_current_version_as_dict()["string"],
    )[1]
    v2 = (
        _patch(monkeypatch, pr_number=107138, commit_count="250"),
        CHVersion.get_current_version_as_dict()["string"],
    )[1]
    assert v1 == v2 == _RELEASE["string"]


def test_master_uses_release_version_as_is(monkeypatch):
    calls = _patch(monkeypatch, pr_number=0, commit_count="106")
    version = CHVersion.get_current_version_as_dict()
    assert version == _RELEASE
    assert calls == []


def test_master_shallow_checkout_uses_release_version_as_is(monkeypatch):
    monkeypatch.setattr(
        CHVersion, "get_release_version_as_dict", classmethod(lambda cls: dict(_RELEASE))
    )
    monkeypatch.setattr(
        "ci.jobs.scripts.clickhouse_version.Info", lambda: _FakeInfo(0)
    )
    monkeypatch.setattr(
        "ci.jobs.scripts.clickhouse_version.Shell.get_output",
        lambda command, verbose=False: "not-a-number",
    )
    version = CHVersion.get_current_version_as_dict()
    assert version == _RELEASE


def test_matching_tag(monkeypatch):
    monkeypatch.setattr(
        "version_helper.read_versions",
        lambda _: {"describe": "v1.2.3.4.altinitystable"},
    )

    check_tag_version("v1.2.3.4.altinitystable")


def test_mismatching_tag(monkeypatch):
    monkeypatch.setattr(
        "version_helper.read_versions",
        lambda _: {"describe": "v1.2.3.4.altinitystable"},
    )

    with pytest.raises(ValueError, match="does not match VERSION_DESCRIBE"):
        check_tag_version("v1.2.3.5.altinitystable")

"""Focused regression coverage for `check_clickhouse_spelling`."""

import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "ci"))

from ci.jobs import check_style


def test_clickhouse_spelling_reports_only_non_exempt_misspellings(monkeypatch, tmp_path):
    """Pin the exemptions and filename check without requiring a Git repository."""
    files = {
        "bad.md": "Clickhouse\n",
        "docs/fr/generated.mdx": "Clickhouse\n",
        "docs/changelogs/v26.1.md": "Clickhouse\n",
        "generated.mdx": "AUTOGENERATED_START\nClickhouse\nAUTOGENERATED_END\n",
        "links.mdx": "https://example.test/Clickhouse\n",
        "ignored.mdx": "Clickhouse\n",
        "Clickhouse-name.mdx": "ClickHouse\n",
    }
    for path, text in files.items():
        target = tmp_path / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)

    records = []
    for path, text in files.items():
        for line_number, line in enumerate(text.splitlines(), 1):
            if "Clickhouse" in line:
                records.append(f"{path}\0{line_number}\0{line}")

    def fake_shell(command, verbose=False):
        if "git grep" in command:
            return 0, "\n".join(records), ""
        assert "git ls-files" in command
        return 0, "\0".join(files) + "\0", ""

    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(check_style.Shell, "get_res_stdout_stderr", fake_shell)
    monkeypatch.setattr(
        check_style, "_clickhouse_spelling_generated_locale_prefixes", lambda: ["docs/fr/"]
    )
    monkeypatch.setattr(
        check_style, "_clickhouse_spelling_ignore_list", lambda: {"ignored.mdx": {"Clickhouse"}}
    )

    assert check_style.check_clickhouse_spelling() == (
        "The product name is spelled `ClickHouse`; `clickhouse` and `CLICKHOUSE` are the "
        "only accepted case variants. Fix the spellings below, or, if the text is not ours "
        "to spell, add an exception to ci/jobs/scripts/check_style/clickhouse_spelling_ignore.txt:\n"
        "bad.md:1: Clickhouse\n"
        "Clickhouse-name.mdx: in the file name: Clickhouse"
    )

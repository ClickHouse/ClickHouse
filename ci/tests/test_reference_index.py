import importlib.util
from pathlib import Path


SCRIPT_PATH = (
    Path(__file__).resolve().parents[2]
    / "docs"
    / "_site"
    / "scripts"
    / "update_reference_index.py"
)
SPEC = importlib.util.spec_from_file_location("update_reference_index", SCRIPT_PATH)
assert SPEC and SPEC.loader
update_reference_index = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(update_reference_index)


def test_autogenerated_entities_excludes_structural_headings():
    content = """
{/*AUTOGENERATED_START*/}
## arrayAvg {#arrayAvg}

Introduced in: v21.1.0

## Description {#description}

Description text.

## Syntax {#syntax}

Syntax text.

## Example usage {#example-usage}

Example text.

## Returned value {#returned-value}

Returned value text.
{/*AUTOGENERATED_END*/}
"""

    assert update_reference_index.autogenerated_entities(content, "Functions") == [
        ("arrayAvg", "arrayAvg")
    ]


def test_autogenerated_settings_require_settings_metadata():
    content = """
{/*AUTOGENERATED_START*/}
## max_threads {#max_threads}

<SettingsInfoBlock type="MaxThreads" default_value="auto(N)" />

The maximum number of query processing threads.

## Description {#description}

Description text.
{/*AUTOGENERATED_END*/}
"""

    assert update_reference_index.autogenerated_entities(content, "Settings") == [
        ("max_threads", "max_threads")
    ]


def test_other_surfaces_do_not_extract_anchors():
    content = """
{/*AUTOGENERATED_START*/}
## Description {#description}

Introduced in: v1.0.0
{/*AUTOGENERATED_END*/}
"""

    assert update_reference_index.autogenerated_entities(content, "Engines") == []


def test_first_page_finds_nested_navigation_page():
    assert update_reference_index.first_page([
        {"group": "Empty", "pages": []},
        {"group": "Nested", "pages": ["reference/functions/index"]},
    ]) == "reference/functions/index"

"""Nightly ClickHouse job: synchronize ClickStack schemas from upstream HyperDX.

The job refreshes the canonical English snippets and opens or updates one bot
pull request when the upstream schema changes. When a stale bot pull request
matches the upstream schema again, the job closes it. It fails closed: a failed
fetch, schema extraction failure, or GitHub operation never publishes a partial
sync.
"""

import shlex
import sys

from ci.defs.defs import BASE_BRANCH
from praktika.git import Git
from praktika.info import Info
from praktika.result import Result
from praktika.utils import Shell


GENERATOR = "ci/jobs/scripts/docs/sync_clickstack_schemas.py"
SNIPPETS_PATH = "docs/snippets/clickstack"
BOT_BRANCH = "robot/sync-clickstack-schemas"
REPOSITORY = "ClickHouse/ClickHouse"
PR_TITLE = "Docs: sync ClickStack OTel schemas from HyperDX"
PR_BODY = f"""\
Automated nightly sync of the ClickStack OpenTelemetry `CREATE TABLE` schema
snippets from [hyperdxio/hyperdx](https://github.com/hyperdxio/hyperdx/tree/main/docker/otel-collector/schema/seed).

The job updates only the canonical English snippets in `{SNIPPETS_PATH}`.
Localized copies remain translation-owned.

Generated by `{GENERATOR}`.

### Changelog category (leave one):
- Documentation (changelog entry is not required)

### Changelog entry (a [user-readable short description](https://github.com/ClickHouse/ClickHouse/blob/master/docs/changelog_entry_guidelines.md) of the changes that goes into CHANGELOG.md):
"""


def checkout_current_base_branch():
    """Run only on the current base branch tip, including scheduled re-runs."""
    branch = Info().git_branch
    if branch != BASE_BRANCH:
        print(
            f"Refusing to run: this workflow force-pushes '{BOT_BRANCH}' and manages a"
            f" pull request, so it must run against '{BASE_BRANCH}', not '{branch}'"
            " (for example, a manual workflow dispatch from another branch).",
            file=sys.stderr,
        )
        return False

    return Shell.check(
        f"git fetch --no-tags origin {shlex.quote(BASE_BRANCH)}"
        " && git checkout --detach FETCH_HEAD",
        verbose=True,
    )


def sync_schemas():
    return Shell.check(f"python3 {GENERATOR}", verbose=True)


def has_changes():
    return bool(
        Shell.get_output(
            f"git status --porcelain -- {SNIPPETS_PATH}", strict=True
        ).strip()
    )


def is_expected_repository() -> bool:
    repository = Info().repo_name
    if repository == REPOSITORY:
        return True

    print(
        "ERROR: the ClickStack schema sync workflow must run only in "
        f"{REPOSITORY}, got {repository or '(unset)'}"
    )
    return False


def open_bot_pull_request() -> str | None:
    """Return the bot's open base-branch PR, or ``None`` if none exists.

    A GitHub query error raises instead of being treated as an absent PR, so a
    transient failure cannot lead to a destructive bot-branch replacement.
    """
    command = (
        f"gh pr list --head {shlex.quote(BOT_BRANCH)} --base {shlex.quote(BASE_BRANCH)} "
        f"--state open --repo {shlex.quote(REPOSITORY)} "
        "--json number,isCrossRepository "
        "--jq 'map(select(.isCrossRepository == false)) | .[0].number // empty'"
    )
    return_code, stdout, stderr = Shell.get_res_stdout_stderr(command, verbose=True)
    if return_code != 0:
        raise RuntimeError(f"Failed to query the ClickStack schema bot PR: {stderr}")
    return stdout.strip() or None


def fetch_bot_branch() -> None:
    """Fetch the bot branch with the ancestry needed to merge it into the base."""
    commands = []
    if Shell.get_output("git rev-parse --is-shallow-repository", strict=True) == "true":
        commands.append(
            f"git fetch --no-tags --unshallow origin {shlex.quote(BASE_BRANCH)}"
        )
    commands.append(f"git fetch --no-tags origin {shlex.quote(BOT_BRANCH)}")

    if not Shell.check(" && ".join(commands), verbose=True):
        raise RuntimeError(f"Failed to fetch existing bot branch '{BOT_BRANCH}'")


def bot_branch_matches_generated_snippets() -> bool:
    """Check whether the already-open PR already contains this exact sync."""
    fetch_bot_branch()
    return Shell.check(
        f"git diff --quiet FETCH_HEAD -- {SNIPPETS_PATH}", verbose=False
    )


def bot_branch_merges_cleanly() -> bool:
    """Check whether the bot branch still merges into the checked-out base tip."""
    return_code, stdout, stderr = Shell.get_res_stdout_stderr(
        "git merge-tree --write-tree --quiet FETCH_HEAD HEAD", verbose=True
    )
    if return_code == 0:
        return True
    if return_code == 1:
        print("The existing ClickStack schema bot branch conflicts with the base branch.")
        return False
    raise RuntimeError(
        "Failed to check whether the ClickStack schema bot branch merges into "
        f"the base branch: {stderr or stdout}"
    )


def publish_sync(existing_pr: str | None):
    if not is_expected_repository():
        return False

    prepare = [
        'git config user.name "robot-clickhouse"',
        'git config user.email "robot-clickhouse@users.noreply.github.com"',
        f"git checkout -B {shlex.quote(BOT_BRANCH)}",
        f"git add -A -- {SNIPPETS_PATH}",
        f"git commit -m {shlex.quote(PR_TITLE)}",
    ]
    if not Shell.check(" && ".join(prepare), verbose=True):
        return False
    if not Git.push(REPOSITORY, f"HEAD:refs/heads/{BOT_BRANCH}", force=True):
        return False

    if existing_pr:
        print(f"PR #{existing_pr} already open; branch refreshed")
        return Shell.check(
            f"gh pr edit {existing_pr} --repo {shlex.quote(REPOSITORY)} "
            f"--body {shlex.quote(PR_BODY)}",
            verbose=True,
        )
    return Shell.check(
        f"gh pr create --base {shlex.quote(BASE_BRANCH)} --head {shlex.quote(BOT_BRANCH)} "
        f"--repo {shlex.quote(REPOSITORY)} --title {shlex.quote(PR_TITLE)} "
        f"--body {shlex.quote(PR_BODY)}",
        verbose=True,
    )


def close_stale_bot_pull_request(pull_request: str) -> bool:
    """Close the bot PR when the generated snippets already match ``master``."""
    return Shell.check(
        f"gh pr close {shlex.quote(pull_request)} --repo {shlex.quote(REPOSITORY)} "
        "--comment "
        + shlex.quote(
            "🕵 The ClickStack schemas are back in sync with upstream; closing this stale autogenerated pull request."
        ),
        verbose=True,
    )


def publish_if_needed():
    if not is_expected_repository():
        return False

    if not has_changes():
        print("ClickStack schemas are already in sync with upstream.")
        existing_pr = open_bot_pull_request()
        if not existing_pr:
            return True
        return close_stale_bot_pull_request(existing_pr)

    existing_pr = open_bot_pull_request()
    if (
        existing_pr
        and bot_branch_matches_generated_snippets()
        and bot_branch_merges_cleanly()
    ):
        print(f"PR #{existing_pr} already contains the generated schema changes.")
        return True
    return publish_sync(existing_pr)


if __name__ == "__main__":
    results = [
        Result.from_commands_run(
            name="Check out current master", command=checkout_current_base_branch
        )
    ]
    if results[-1].is_ok():
        results.append(Result.from_commands_run(name="Sync schemas", command=sync_schemas))
    if results[-1].is_ok():
        results.append(
            Result.from_commands_run(
                name="Open or refresh PR", command=publish_if_needed
            )
        )

    Result.create_from(results=results).complete_job()

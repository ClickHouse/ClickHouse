import shlex
import sys

from ci.defs.defs import BASE_BRANCH
from praktika.git import Git
from praktika.info import Info
from praktika.result import Result
from praktika.utils import Shell

# The self-extracting master binary from the CH_ARM_RELEASE artifact. Required artifacts are
# downloaded into the input dir under their basename, so it lands at ci/tmp/clickhouse, as a plain
# file that must be made executable before use.
BINARY = "ci/tmp/clickhouse"
GENERATOR = "utils/startup-symbol-order/generate.py"
ORDER_FILE = "programs/startup_symbol_order.txt"

# A stable branch, force-pushed each run, so the bot keeps a single open PR that always carries
# exactly one commit off the latest master.
BRANCH = "robot/startup-symbol-order"
TITLE = "Regenerate the startup symbol order"

BODY = """\
This pull request is opened automatically by the nightly `NightlyStartupSymbolOrder` workflow. It
regenerates `programs/startup_symbol_order.txt`, the functions that ClickHouse executes at startup
in the order of their first execution, by tracing the release build (ARM, ThinLTO) of the current
master. See `utils/startup-symbol-order/README.md`.

The `clickhouse` binary is linked with this list as `--symbol-ordering-file`, so that a start with
a cold page cache reads less of the executable. Do not edit the list by hand; the next nightly run
regenerates it. The order differs slightly between runs (the threads of the server interleave
differently), so this pull request is refreshed every night: merge it from time to time.

### Changelog category (leave one):
- Not for changelog (changelog entry is not required)

### Changelog entry (a [user-readable short description](https://github.com/ClickHouse/ClickHouse/blob/master/docs/changelog_entry_guidelines.md) of the changes that goes into CHANGELOG.md):
"""


def regenerate():
    """Regenerate the list in place from the master binary.

    The artifact downloader materializes a plain file, so make it executable. The first run of
    the self-extracting binary replaces it with the real executable, which has the symbol table
    that the tracer needs. The generator fails if any of the traced workloads fails, and writes
    the list only after all of them succeeded."""
    return Shell.check(
        f"chmod +x {BINARY}"
        f" && {BINARY} local --query 'SELECT 1'"
        f" && python3 {GENERATOR} {BINARY} {ORDER_FILE}",
        verbose=True,
    )


def _open_bot_pr():
    """Return the number of the open bot pull request for BRANCH in the base repository, or "" if
    none.

    `gh pr list --head` matches by bare branch name, so a fork PR opened from a branch also named
    BRANCH would show up too. Scope to the base branch and filter to non-cross-repository PRs so
    we only ever act on the bot's own PR to the intended base."""
    return Shell.get_output(
        f"gh pr list --head {BRANCH} --base {BASE_BRANCH} --state open"
        " --json number,isCrossRepository"
        " --jq 'map(select(.isCrossRepository == false)) | .[0].number // empty'"
    ).strip()


def _same_functions():
    """Whether the regenerated list has the same functions as the committed one, in any order.

    The order alone differs between any two runs, which is not worth a pull request."""
    committed = Shell.get_output(f"git show HEAD:{ORDER_FILE}", strict=True)
    with open(ORDER_FILE, encoding="utf-8") as f:
        regenerated = f.read()
    return set(committed.split()) == set(regenerated.split())


def open_or_refresh_pr():
    """Commit the regenerated list and open (or refresh) the bot's pull request.

    When the functions are the same as on master, any pull request the bot opened earlier is
    stale (it was merged in another way, or a later change made the lists match again), so it is
    closed and its branch deleted."""
    if _same_functions():
        print("The startup symbol order is up to date; no changes to publish.")
        pr = _open_bot_pr()
        if not pr:
            return True
        print(f"Closing stale bot pull request #{pr} and deleting branch {BRANCH}.")
        return Shell.check(
            f"gh pr close {pr} --delete-branch --comment "
            + shlex.quote(
                "The startup symbol order on the base branch is up to date; "
                "closing this stale autogenerated pull request."
            ),
            verbose=True,
        )

    commit = [
        "git config user.name 'robot-clickhouse'",
        "git config user.email 'robot-clickhouse@users.noreply.github.com'",
        f"git checkout -B {BRANCH}",
        f"git add -- {ORDER_FILE}",
        f"git commit -m {shlex.quote(TITLE)}",
    ]
    if not Shell.check(" && ".join(commit), verbose=True):
        return False

    # Force-push HEAD as the GitHub App so that the refreshed PR triggers CI.
    if not Git.push(Info().repo_name, f"HEAD:refs/heads/{BRANCH}", force=True):
        return False

    if _open_bot_pr():
        return True  # the force-push above already refreshed it
    return Shell.check(
        f"gh pr create --base {BASE_BRANCH} --head {BRANCH} "
        f"--title {shlex.quote(TITLE)} --body {shlex.quote(BODY)}",
        verbose=True,
    )


def on_base_branch():
    """Refuse to manage the shared bot pull request from a non-base branch."""
    branch = Info().git_branch
    if branch != BASE_BRANCH:
        print(
            f"Refusing to run: this workflow force-pushes '{BRANCH}' and manages a"
            f" pull request, so it must run against '{BASE_BRANCH}', not '{branch}'"
            " (e.g. a workflow_dispatch from another branch).",
            file=sys.stderr,
        )
        return False
    return True


if __name__ == "__main__":
    results = [
        Result.from_commands_run(name="Run against base branch", command=on_base_branch)
    ]
    # Fail closed: only regenerate and touch the pull request from the base branch.
    if results[-1].is_ok():
        results.append(
            Result.from_commands_run(name="Regenerate the order", command=regenerate)
        )
    if results[-1].is_ok():
        results.append(
            Result.from_commands_run(
                name="Open or refresh PR", command=open_or_refresh_pr
            )
        )
    Result.create_from(results=results).complete_job()

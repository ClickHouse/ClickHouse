def prepare_repo():
    # The CI checkout is shallow and single-ref, while the generation walks
    # master back to the cycle start tag, so the history has to be fetched.
    # Restricted to the master refspec: the default one pulled every branch
    # of the repository along with it.
    #
    # Not `--filter=tree:0`: fetching only the commit graph takes 12 seconds
    # instead of half an hour, but it turns the checkout into a partial clone,
    # and changelog.py runs its own `git fetch --tags` in the container, which
    # then hangs (observed in
    # https://github.com/ClickHouse/ClickHouse/actions/runs/32747225427: the
    # job sat in `Fetching all tags` for five hours until it was killed).
    master_refspec = "'+refs/heads/master:refs/remotes/origin/master'"
    if Shell.get_output("git rev-parse --is-shallow-repository").strip() == "true":
        Shell.check(
            f"git fetch --unshallow --no-recurse-submodules origin {master_refspec}",
            verbose=True,
            strict=True,
        )
    # Explicit refspec: the CI checkout restricts remote.origin.fetch to the
    # triggering ref, so a plain `git fetch origin master` would not be
    # guaranteed to update the remote-tracking ref.
    Shell.check(
        f"git fetch --tags --no-recurse-submodules origin {master_refspec}",
        verbose=True,
        strict=True,
    )
    Shell.check(
        'git config user.name "robot-clickhouse" && '
        'git config user.email "robot-clickhouse@users.noreply.github.com"',
        verbose=True,
        strict=True,
    )
    return "Fetched master and tags"


def checkout_branch(branch, exists_on_remote):
    if exists_on_remote:
        # Explicit refspec, see prepare_repo.
        Shell.check(
            f"git fetch origin "
            f"'+refs/heads/{branch}:refs/remotes/origin/{branch}'",
            verbose=True,
            strict=True,
        )
        Shell.check(
            f"git checkout -B {branch} origin/{branch}", verbose=True, strict=True
        )
    else:
        Shell.check(
            f"git checkout -B {branch} origin/master", verbose=True, strict=True
        )


def reconcile_with_master(version):
    """Merge origin/master into the branch when master's CHANGELOG.md changed
    since the branch base. A conflict in CHANGELOG.md is resolved structurally
    by re-inserting our additions on top of master's file; any other conflict
    fails the job for manual resolution."""
    base = Shell.get_output("git merge-base HEAD origin/master", strict=True).strip()
    if Shell.check(f"git diff --quiet {base} origin/master -- {CHANGELOG_FILE}"):
        return "No CHANGELOG.md changes on master to reconcile"
    ours = _read_changelog()
    if Shell.check("git merge --no-edit origin/master", verbose=True):
        return "Merged origin/master cleanly"
    conflicts = Shell.get_output(
        "git diff --name-only --diff-filter=U", strict=True
    ).split()
    if conflicts != [CHANGELOG_FILE]:
        Shell.check("git merge --abort", verbose=True)
        raise RuntimeError(
            f"Merge of origin/master conflicts outside {CHANGELOG_FILE}: "
            f"{conflicts}; manual reconciliation required"
        )
    try:
        rebuilt = compose_on_master(
            Shell.get_output(
                f"git show origin/master:{CHANGELOG_FILE}", strict=True
            ),
            version,
            extract_toc_line(ours, version),
            extract_raw_blocks(ours),
            extract_in_progress_section(ours, _anchor_id(version)),
        )
        _write_changelog(rebuilt)
        Shell.check(f"git add {CHANGELOG_FILE}", strict=True)
        Shell.check("git commit --no-edit", verbose=True, strict=True)
    except BaseException:
        # Never leave the repository mid-merge: it would break the checkout
        # of the next processed cycle in the same run.
        Shell.check("git merge --abort", verbose=True)
        raise
    return "Merged origin/master, re-inserted the in-progress section on top"


def generate_raw_entries(version, from_ref, to_sha):
    """Run changelog.py in the style-test container for from_ref..to_sha and
    commit the raw entries as a marker block."""
    from_sha = _sha(from_ref)
    if from_sha == to_sha:
        return "No new commits since the last generation"
    if not Shell.check(f"git merge-base --is-ancestor {from_sha} {to_sha}"):
        raise RuntimeError(
            f"Recorded generation point {from_ref} ({from_sha}) is not an "
            f"ancestor of {to_sha}; refusing to generate"
        )

    if os.path.exists(RAW_OUTPUT):
        os.unlink(RAW_OUTPUT)
    # changelog.py queries the GitHub API for minutes with the token it is
    # handed, so it must start with a fresh one.
    refresh_gh_token()
    Shell.check(f"docker pull {STYLE_TEST_IMAGE}", verbose=True, strict=True)
    # The token is passed through the environment (the command line, which
    # gets logged, only carries the unexpanded expressions): the host shell
    # exports it to the docker CLI and the in-container shell expands it for
    # changelog.py's --gh-user-or-token.
    cmd = (
        f"./tests/ci/changelog.py -v --jobs=5 "
        f'--gh-user-or-token "$GH_TOKEN" '
        f"--from {shlex.quote(from_ref)} --output {shlex.quote(RAW_OUTPUT)} {to_sha}"
    )
    if not Shell.check(
        f'GH_TOKEN="$(gh auth token)" '
        f'docker run --rm -u "$(id -u):$(id -g)" -e PYTHONUNBUFFERED=1 -e CI=1 '
        f"-e GH_TOKEN --network=host --volume=$(pwd):/wd --workdir=/wd "
        f"{STYLE_TEST_IMAGE} sh -c {shlex.quote(cmd)}",
        verbose=True,
        timeout=GENERATE_TIMEOUT_SEC,
    ):
        raise RuntimeError("changelog.py failed")

    with open(RAW_OUTPUT, encoding="utf-8") as fd:
        body = strip_generated_preamble(fd.read())
    entries = count_entries(body)
    from_short, to_short = from_sha[:11], to_sha[:11]
    if entries == 0:
        return f"No new changelog entries in {from_short}..{to_short}"

    _write_changelog(
        insert_before_first_release(_read_changelog(), make_raw_block(body))
    )
    message = (
        f"Update changelog for {version}: generate raw entries "
        f"({from_short}..{to_short})\n\n"
        f"{entries} raw entries generated with tests/ci/changelog.py "
        f"by the NightlyChangelog CI job.\n\n"
        f"{STATE_TRAILER} {to_sha}\n"
    )
    Shell.check(f"git add {CHANGELOG_FILE}", strict=True)
    Shell.check(f"git commit -m {shlex.quote(message)}", verbose=True, strict=True)
    return f"Generated {entries} raw entries for {from_short}..{to_short}"


def _pr_list(prs):
    return ", ".join(f"`#{pr}`" for pr in prs) or "an earlier revert"


def _edit_prompt(version, reverts, previous_error=None):
    anchor = _anchor_id(version)
    strict = "\n".join(f"   - {c}" for c in sorted(STRICT_RETENTION_CATEGORIES))
    restore = ""
    if reverts["missing"]:
        entries = "\n".join(
            f"   - {_pr_list(group['prs'])}, deleted when "
            f"{_pr_list(group['removed_by'])} reverted "
            f"{'them' if len(group['prs']) > 1 else 'it'}, re-applied by "
            f"{_pr_list(group['reapplied_by'])}. The bullet when it was "
            f"deleted, which sat under `#### {group['category']}`:"
            f"\n     {group['line']}"
            + (
                f"\n     That bullet also carries {_pr_list(group['siblings'])}, "
                f"which {'are' if len(group['siblings']) > 1 else 'is'} still in "
                f"{CHANGELOG_FILE}: the bullet is therefore still there, so put "
                f"the missing link back into it — do not paste the line above as "
                f"a second bullet, and do not repeat "
                f"{_pr_list(group['siblings'])}."
                if group["siblings"]
                else ""
            )
            for group in reverts["missing"]
        )
        restore = f"""
Entries to restore. Point 4 above, spread over several days: an earlier run of this job deleted these entries because a revert cancelled them, and that revert has now itself been reverted, so the changes do ship in {version}. They are no longer in {CHANGELOG_FILE} and the intervening reverts are no longer in the raw blocks, so the text they had is quoted here. Put each bullet below back into the in-progress section — once, even where it covers several pull requests — under the `#### <Category>` header named with it, with the link of the pull request that re-applied it appended, and do not add a bullet for the reverts themselves. Use that category as given: it is where the entry was when it was deleted, which is a decision of the earlier edit (an entry promoted out of `NOT FOR CHANGELOG` or moved between categories does not go back to the category of its pull request). No pull request may end up attributed twice in the section.
{entries}
"""
    retry = ""
    if previous_error:
        retry = f"""
A previous attempt at this task was rejected by the verification of this job:

    {previous_error}

The working tree has been reset to the raw blocks, so start over - but produce
an edit that does not repeat that rejection.
"""
    return f"""\
You are updating {CHANGELOG_FILE} for the upcoming ClickHouse release {version} as part of an automated daily CI job.

{CHANGELOG_FILE} contains one or more blocks delimited by marker lines starting with `{RAW_BEGIN_PREFIX}` and ending with `{RAW_END}`. Each block holds raw auto-generated changelog entries (the output of `utils/changelog/changelog.py`) for pull requests merged into master since the previous run of this job.

Task:
1. Read {EDIT_SKILL} and apply its editing rules to the raw entries inside the marker blocks.
2. Integrate the edited entries into the in-progress release section, the one with the header containing `<a id="{anchor}"></a>`:
   - If that section does not exist yet, create it directly above the first released section, with exactly this header: `### <a id="{anchor}"></a> ClickHouse release {version}, FIXME (in progress)`, and add this line at the top of the "Table of Contents" list: `**[ClickHouse release v{version}, FIXME](#{anchor})**<br/>`.
   - Place entries under the proper `#### <Category>` headers in the preferred category order from the skill; create missing category headers as needed; keep exactly one blank line before each `####` header.
   - Entries already present in the in-progress section were edited on previous days: do not rewrite or reorder them, except where the skill requires it — a revert arriving in a raw block may delete or amend a previously added entry (skill section 2), and a follow-up PR may be merged into an existing bullet (skill section 7).
3. Never delete an entry that the generator put under one of these categories:
{strict}
   Such an entry may be rewritten, merged into another bullet, or moved to a different category, but its `[#N](...)` pull request link has to be present in {CHANGELOG_FILE} when you are done. The entries you may delete are the ones under `NOT FOR CHANGELOG / INSIGNIFICANT` and `NO CL ENTRY` that carry no user-visible change (skill section 3), the `Build/Testing/Packaging Improvement` entries that are pure CI plumbing (skill section 4), and an entry that a revert in these raw blocks cancels out (skill section 2). Deleting anything else fails this job, and the entry is then lost for good: the generation point has already moved past it, so the next run will not offer it again.
4. A revert of a revert re-applies the change (skill section 2.5): keep the original entry, append the link of the pull request that re-applied it, and delete only the intervening revert. Check for this case before concluding that a change landed and was reverted — all three pull requests can sit in the same range, and when they do not, the entries to bring back are listed at the end of this task.
5. Delete the marker blocks, including the marker lines themselves, after integrating them.
6. Do not commit. Do not modify any file other than {CHANGELOG_FILE}. Do not touch the sections of already-released versions or anything below them. Keep the `FIXME` placeholders in the header and table of contents — the release manager fills in the date and links at release time.

The `gh` CLI is authenticated; use `gh pr view <N> --json title,body` when the skill requires consulting a pull request (reverts, unclear entries).
{restore}{retry}"""


def disappeared_entries(old_text, text, anchor):
    """Pull requests whose changelog entry the edit lost: an entry the previous
    runs had already accumulated in the in-progress section, or one of this
    run's raw entries from a strict-retention category.

    Membership is checked against the whole file rather than the section: an
    entry may legitimately sit in an already-released section (a pull request
    merged into the last release branch after the cycle start appears in the
    range but was already published), and it may have been moved to another
    category."""
    old_section = extract_in_progress_section(old_text, anchor) or ""
    section = extract_in_progress_section(text, anchor) or ""
    removed = extract_pr_links(old_section) - extract_pr_links(section)
    strict_prs, _ = raw_strict_prs_and_reverts(old_text)
    return removed | {pr for pr in strict_prs if f"/pull/{pr})" not in text}


def revert_licensed_deletions(base_sha, version):
    """The entries the verified edit deleted, each with the category and the
    bullet it had before, for the ledger: when the revert that licensed the
    deletion is itself reverted — possibly weeks later, when nothing in the
    file or in the raw blocks remembers the entry — it has to be restorable
    exactly, in the category the edit had put it in."""
    old_text = Shell.get_output(f"git show {base_sha}:{CHANGELOG_FILE}", strict=True)
    deletions = {}
    for pr in disappeared_entries(old_text, _read_changelog(), _anchor_id(version)):
        category, line = entry_placement(old_text, pr)
        if line:
            deletions[pr] = (category, line)
    return deletions


def verify_edit(version, base_sha, reverts, pre_untracked=frozenset()):
    """Fail-closed checks after the editing agent ran, all against the
    pre-edit generate commit `base_sha` rather than a mutable HEAD (the agent
    has git access, and an agent-made commit must not bypass the checks).
    `reverts` is the `analyze_reverts` verdict for the raw blocks of this run.
    Returns an error string or None."""
    if _sha("HEAD") != base_sha:
        return "The editing agent created commits instead of leaving the edit uncommitted"
    changed = Shell.get_output(f"git diff --name-only {base_sha}", strict=True).split()
    if changed != [CHANGELOG_FILE]:
        return f"Unexpected working tree changes after edit: {changed or 'none'}"
    created = _untracked_files() - pre_untracked
    if created:
        return f"The editing agent created files: {sorted(created)}"
    text = _read_changelog()
    anchor = _anchor_id(version)
    if RAW_BEGIN_PREFIX in text or RAW_END in text:
        return "Raw entry markers are still present after edit"
    if f'<a id="{anchor}"></a>' not in text:
        return f"In-progress section for {version} is missing after edit"
    if not extract_toc_line(text, version):
        return f"Table-of-contents line for {version} is missing after edit"
    old_text = Shell.get_output(f"git show {base_sha}:{CHANGELOG_FILE}", strict=True)
    section = extract_in_progress_section(text, anchor)
    if section is None:
        return "In-progress section disappeared after edit"
    # Entries must survive the edit: previously accumulated entries (the
    # skill only deletes one when a revert cancels it, section 2; merges keep
    # all PR links, section 7), and today's raw entries from the
    # strict-retention categories (the skill prunes only the junk sections;
    # real entries are edited, merged, or moved — their PR links stay,
    # otherwise the entry is silently lost forever because the state trailer
    # has already advanced past it). A revert usually names the original PR
    # only in its title, so the deletion it licenses is bound to a PR number
    # through `analyze_reverts`, not through the entry text.
    unmatched = disappeared_entries(old_text, text, anchor) - set(reverts["credits"])
    if unmatched:
        return (
            f"Entries disappeared in the edit without a matching revert "
            f"({sorted(unmatched)}); the reverts of this release resolve to "
            f"{sorted(reverts['credits']) or 'nothing'}"
            + (
                f", and reverts {reverts['unresolved']} could not be resolved "
                f"(no `Reverts owner/repo#N` marker or failed lookup)"
                if reverts["unresolved"]
                else ""
            )
        )
    # The mirror image of the check above, and the reason the ledger exists:
    # an entry an earlier run deleted for a revert that has since been
    # reverted itself has to be back in the file, as its own attribution and
    # not as a mention inside someone else's bullet. Nothing here disappeared
    # — the entry went away days ago — so only the ledger can tell.
    not_restored = sorted(
        pr for pr in reverts["restore"] if not is_attributed(section, pr)
    )
    if not_restored:
        return (
            f"Entries deleted by an earlier run for a revert that was itself "
            f"reverted are still missing from the in-progress section "
            f"({not_restored}); those changes ship in this release, so their "
            f"entries have to be restored"
        )
    # A restoration also has to land where the entry was, which the pull
    # request itself does not say: the editing rules promote entries out of
    # `NOT FOR CHANGELOG` and move them between categories, and re-deriving
    # the category from the pull request would undo that decision. Only this
    # run's restorations are checked - a later edit may legitimately move the
    # entry again, and the ledger keeps the record for the rest of the cycle.
    misplaced = []
    for group in reverts["missing"]:
        if not group["category"]:
            continue
        for pr in group["prs"]:
            found = entry_placement(section, pr)[0]
            if found != group["category"]:
                misplaced.append(
                    f"#{pr} under {found or 'no category'} "
                    f"instead of {group['category']}"
                )
    if misplaced:
        return (
            f"Restored entries were put under the wrong category "
            f"({sorted(misplaced)}); a restoration keeps the category the "
            f"entry had when it was deleted"
        )
    # A restored bullet may have been a merged one (skill section 7), carrying
    # pull requests that were never deleted and are still in the section.
    # Pasting the recorded line back wholesale duplicates them, and the check
    # above cannot see it - the link it looks for is present either way.
    # Duplicates that predate the edit are none of this run's business.
    duplicated = sorted(
        duplicate_attributions(section)
        - duplicate_attributions(extract_in_progress_section(old_text, anchor) or "")
    )
    if duplicated:
        return (
            f"The edit attributes pull requests twice in the in-progress "
            f"section ({duplicated}); an entry was written a second time "
            f"instead of being merged into the bullet that already carries it"
        )
    _, old_tail = split_at_first_released_section(old_text, anchor)
    _, new_tail = split_at_first_released_section(text, anchor)
    if old_tail.rstrip() != new_tail.rstrip():
        return "Sections of already-released versions were modified by the edit"
    return None


def edit_raw_entries(version):
    """Run the editing agent on the committed raw blocks and commit the result.
    Retries a few times; on failure resets to the generate commit and raises."""
    openai_key = Secret.Config(
        name=OPENAI_KEY_SECRET, type=Secret.Type.AWS_SSM_PARAMETER
    ).get_value()

    # The generate commit the edit must be based on; every verification and
    # cleanup is pinned to this SHA, not to HEAD, which the agent can move.
    base_sha = _sha("HEAD")
    pre_untracked = _untracked_files()
    # Resolving the reverts talks to GitHub, and every attempt starts from the
    # same raw blocks, so it is done once for all of them.
    refresh_gh_token()
    reverts = analyze_reverts(_read_changelog(), _anchor_id(version))
    last_error = None
    for attempt in range(1, MAX_EDIT_ATTEMPTS + 1):
        # `last_error` still holds the rejection of the previous attempt here:
        # tell the agent about it, otherwise a retry just reproduces the same
        # edit and the same rejection.
        prompt = _edit_prompt(version, reverts, last_error)
        # Full reset to the generate commit: a failed attempt may have left
        # changes beyond CHANGELOG.md, new files, or even commits (all are
        # verify_edit failure modes), and they must not leak into the next
        # attempt or the next processed version.
        _reset_worktree(base_sha, pre_untracked)
        # The GitHub App token expires after an hour and an editing attempt
        # can run long; refresh so the agent's `gh pr view` calls work.
        refresh_gh_token()
        try:
            with tempfile.TemporaryDirectory(dir="./ci/tmp") as codex_home:
                subprocess.run(
                    ["codex", "login", "--with-api-key"],
                    input=openai_key,
                    text=True,
                    check=True,
                    env={**os.environ, "CODEX_HOME": codex_home},
                )
                # Same invocation as the Code Review job (proven on these
                # runners): writable workspace, network for `gh pr view`.
                ok = Shell.check(
                    f"CODEX_HOME={shlex.quote(codex_home)} codex exec "
                    f"-m gpt-5.4 -c 'model_reasoning_effort=xhigh' "
                    f"-s workspace-write "
                    f"-c sandbox_workspace_write.network_access=true "
                    f"-c approval_policy=never "
                    f"--color never "
                    f"{shlex.quote(prompt)}",
                    verbose=True,
                )
            last_error = None if ok else "codex exited with non-zero status"
        except Exception as e:
            last_error = f"{type(e).__name__}: {e}"
            traceback.print_exc()
        if not last_error:
            # The attempt itself can outlive the token; the verification
            # resolves reverts through `gh pr view`.
            refresh_gh_token()
            last_error = verify_edit(version, base_sha, reverts, pre_untracked)
        if not last_error:
            break
        print(
            f"WARNING: edit attempt {attempt}/{MAX_EDIT_ATTEMPTS} failed: {last_error}"
        )
        if attempt < MAX_EDIT_ATTEMPTS:
            time.sleep(min(2**attempt, 60))

    if last_error:
        _reset_worktree(base_sha, pre_untracked)
        raise RuntimeError(
            f"Editing failed after {MAX_EDIT_ATTEMPTS} attempts: {last_error}. "
            f"The raw entries stay committed and will be edited by the next run."
        )

    # Record the revert bookkeeping of this run on the edit commit, so that a
    # revert of one of today's reverts, whenever it arrives, still finds the
    # relation and the text of the entry it has to bring back.
    trailers = reverts["ledger"] + [
        f"{DELETED_TRAILER} {pr} [{category}] {line}"
        for pr, (category, line) in sorted(
            revert_licensed_deletions(base_sha, version).items(),
            key=lambda kv: int(kv[0]),
        )
    ]
    message = (
        f"Update changelog for {version}: edit new entries\n\n"
        f"Edited by the NightlyChangelog CI job following {EDIT_SKILL}.\n"
        + ("\n" + "\n".join(trailers) + "\n" if trailers else "")
    )
    Shell.check(f"git add {CHANGELOG_FILE}", strict=True)
    Shell.check(f"git commit -m {shlex.quote(message)}", verbose=True, strict=True)
    return "Edited the raw entries and committed the result"


def push_branch(branch, exists_on_remote):
    ahead_of = f"origin/{branch}" if exists_on_remote else "origin/master"
    if not Shell.get_output(f"git log --oneline {ahead_of}..HEAD").strip():
        return "Nothing to push"
    # The push authenticates with this token, and the preceding editing step
    # takes long enough to expire it.
    refresh_gh_token()
    # Push with the App token rather than the GITHUB_TOKEN that the checkout
    # action persists in the http extraheader: GITHUB_TOKEN pushes do not
    # trigger workflow runs, so the PR would get no CI on refreshes. Same
    # pattern as the workflow-regeneration push in praktika's native_jobs.
    # The token expands at run time and is kept out of the logs
    # (verbose=False); the inherited extraheader is cleared so the tokenized
    # URL is the one that authenticates.
    repo_url = (
        "https://x-access-token:${token}@github.com/"
        + shlex.quote(Info().repo_name)
        + ".git"
    )
    refspec = shlex.quote(f"HEAD:refs/heads/{branch}")
    if not Shell.check(
        'token="$(gh auth token)" && '
        "git -c http.https://github.com/.extraheader= push "
        f"{repo_url} {refspec}",
        verbose=False,
    ):
        raise RuntimeError(f"Failed to push {branch}")
    return f"Pushed {branch}"


def ensure_pr(branch, version):
    # Refresh the App token: the preceding editing step may have outlived it.
    refresh_gh_token()
    states = get_pr_states(branch)
    open_prs = [num for num, state in states if state == "OPEN"]
    if open_prs:
        return f"PR #{open_prs[0]} already open"
    if states:
        return f"PR was closed or merged ({states}); not creating a new one"
    body = f"""\
Automated daily preparation of `CHANGELOG.md` for the upcoming {version} release.

Every day the `NightlyChangelog` CI job appends the raw changelog entries for the pull requests newly merged into `master` (generated with `utils/changelog/changelog.py`) as one commit, and edits them following `.claude/skills/edit-changelog/SKILL.md` as a separate commit, so both the raw and the edited state stay reviewable. The point up to which entries were generated is recorded as a `{STATE_TRAILER}` trailer in the generate commits.

This pull request stays a draft until the release. The release manager finalizes it manually: fills in the release date and the presentation/video links (the `FIXME` placeholders), reviews the entries, and marks it ready.

### Changelog category (leave one):
- Not for changelog (changelog entry is not required)
"""
    with tempfile.NamedTemporaryFile(
        "w", dir="./ci/tmp", suffix=".md", delete=False
    ) as fd:
        fd.write(body)
        body_file = fd.name
    try:
        Shell.check(
            f"gh pr create --draft --base master --head {branch} "
            f"--repo {shlex.quote(Info().repo_name)} "
            f'--title {shlex.quote(f"Prepare changelog for {version}")} '
            f'--label "do not test" --body-file {shlex.quote(body_file)}',
            verbose=True,
            strict=True,
        )
    finally:
        os.unlink(body_file)
    return "Created a draft PR"


def cycle_skip_reason(branch, is_current, branch_exists, pr_states):
    """Decide whether a release cycle must not be processed: a finished cycle
    without a branch, a cycle whose PRs were all closed or merged by a human,
    or a branch that was deleted while its PRs exist (deleting the branch
    auto-closes the PR; silently recreating the branch from the cycle start
    would override that deliberate action)."""
    if not branch_exists and not is_current:
        return f"No branch {branch} for a finished cycle"
    if pr_states and not any(state == "OPEN" for _, state in pr_states):
        return f"PR for {branch} was closed or merged ({pr_states})"
    if not branch_exists and pr_states:
        return (
            f"Branch {branch} does not exist but its PRs do ({pr_states}); "
            f"refusing to recreate the branch, manual investigation required"
        )
    return None


def _step(results, name, fn):
    """Run `fn` as a praktika sub-result: `fn` returns an info string on
    success and raises on failure (stdout/traceback become the info then)."""
    holder = {}

    def _run():
        holder["info"] = fn()
        return True

    result = Result.from_commands_run(name=name, command=_run)
    if result.is_ok() and holder.get("info"):
        result.set_info(holder["info"])
        print(f"[{name}] {holder['info']}")
    results.append(result)
    return result.is_ok()


def process_version(version, master_version, results):
    """Run the full generate/edit/push/PR pipeline for one release cycle.
    Appends step Results to `results`; returns False if something failed."""
    branch = _branch(version)
    is_current = version == master_version
    # The processing of the previous version can have outlived the token.
    refresh_gh_token()

    def _skip(info):
        print(f"[{version}] {info}")
        results.append(
            Result(name=f"{version}: prepare", status=Result.Status.SKIPPED, info=info)
        )
        return True

    end_ref = get_cycle_end_ref(version, master_version)
    if end_ref is None:
        return _skip(f"No cycle end tag for finished cycle {version} yet")
    to_sha = _sha(end_ref)

    exists = remote_branch_exists(branch)
    skip_reason = cycle_skip_reason(
        branch, is_current, exists, get_pr_states(branch)
    )
    if skip_reason:
        return _skip(skip_reason)

    checkout_branch(branch, exists)
    from_ref = determine_from_ref(version, branch, exists)

    ok = True
    if exists:
        ok = _step(
            results,
            f"{version}: reconcile with master",
            lambda: reconcile_with_master(version),
        )

    if ok:
        ok = _step(
            results,
            f"{version}: generate raw entries",
            lambda: generate_raw_entries(version, from_ref, to_sha),
        )

    edit_ok = True
    if ok and RAW_BEGIN_PREFIX in _read_changelog():
        # A failed edit is reported, but the generate commit is still pushed
        # below so the raw entries are visible in the PR and picked up by the
        # next run.
        edit_ok = _step(
            results, f"{version}: edit entries", lambda: edit_raw_entries(version)
        )

    if ok:
        ok = _step(
            results, f"{version}: push", lambda: push_branch(branch, exists)
        )

    if ok and remote_branch_exists(branch):
        ok = _step(results, f"{version}: ensure PR", lambda: ensure_pr(branch, version))

    return ok and edit_ok


def main():
    # The GitHub App token from enable_gh_auth expires; re-issue it at job
    # start, and again in every step that talks to GitHub (refresh_gh_token):
    # a single run outlives the one-hour lifetime of a token many times over.
    refresh_gh_token()
    os.makedirs("./ci/tmp", exist_ok=True)

    results = []
    ok = _step(results, "prepare repository", prepare_repo)

    if ok:
        master_version = get_master_version()
        print(f"Upcoming release on master: {master_version}")

        # Older cycles first (their final catch-up after the version bump),
        # then the current one.
        versions = []
        for ref in Shell.get_output(
            f"git ls-remote --heads origin '{BRANCH_PREFIX}*'"
        ).splitlines():
            m = re.search(rf"refs/heads/{re.escape(BRANCH_PREFIX)}(\d+\.\d+)$", ref)
            if m and m.group(1) != master_version:
                versions.append(m.group(1))
        versions = sorted(versions, key=lambda v: tuple(int(x) for x in v.split(".")))
        versions.append(master_version)

        for version in versions:
            try:
                process_version(version, master_version, results)
            except Exception as e:
                traceback.print_exc()
                results.append(
                    Result(
                        name=f"{version}: processing",
                        status=Result.Status.FAIL,
                        info=f"ERROR: {e}",
                    )
                )

    Result.create_from(results=results).complete_job()


if __name__ == "__main__":
    main()

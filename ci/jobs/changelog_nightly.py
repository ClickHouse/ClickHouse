def _anchor_id(version):
    """'26.7' -> '267', the anchor used in CHANGELOG.md section headers."""
    return version.replace(".", "")


def _branch(version):
    return f"{BRANCH_PREFIX}{version}"


def _start_tag(version):
    return f"v{version}.1.1-new"


def _sha(ref):
    return Shell.get_output(f"git rev-parse '{ref}^{{}}'", strict=True).strip()


def refresh_gh_token():
    """Mint a fresh GitHub App token.

    Installation tokens are valid for an hour, and the steps of this job
    routinely run longer than that (the editing agent alone takes tens of
    minutes), so every step that talks to GitHub - `gh`, `changelog.py` and
    the `git push` - starts with a fresh token instead of inheriting one that
    may be about to expire. `GHAuth.auth` mints at most once per process, so
    the refresh has to be forced.
    """
    GHAuth.auth(force=True, no_strict=True)


def get_master_version():
    """Version 'X.Y' currently developed on master = the upcoming release."""
    text = Shell.get_output(f"git show origin/master:{VERSIONS_FILE}", strict=True)
    major = re.search(r"SET\(VERSION_MAJOR (\d+)\)", text)
    minor = re.search(r"SET\(VERSION_MINOR (\d+)\)", text)
    assert major and minor, f"Cannot parse version from {VERSIONS_FILE}"
    return f"{major.group(1)}.{minor.group(1)}"


def get_cycle_start_tags():
    """All vX.Y.1.1-new tags (each marks the start of a development cycle)."""
    tags = {}
    for tag in Shell.get_output("git tag --list 'v*-new'").splitlines():
        m = re.fullmatch(r"v(\d+)\.(\d+)\.1\.1-new", tag.strip())
        if m:
            tags[(int(m.group(1)), int(m.group(2)))] = tag.strip()
    return tags


def get_cycle_end_ref(version, master_version):
    """The ref up to which the changelog of `version` should be generated.

    For the version currently developed on master it is the master head.
    For a past version it is the tag that started the next cycle, i.e. the
    point where master moved on to the next version.
    """
    if version == master_version:
        return "origin/master"
    tags = get_cycle_start_tags()
    key = tuple(int(x) for x in version.split("."))
    later = sorted(k for k in tags if k > key)
    if not later:
        return None
    return tags[later[0]]


def get_last_generated_sha(branch):
    """Read the state trailer from the branch-only commits, newest first.
    Requires origin/{branch} to be fetched (checkout_branch does that)."""
    log = Shell.get_output(
        f"git log --format=%B origin/master..origin/{branch}", strict=True
    )
    for line in log.splitlines():
        m = re.fullmatch(rf"{STATE_TRAILER}\s*([0-9a-f]{{40}})", line.strip())
        if m:
            return m.group(1)
    return None


def determine_from_ref(version, branch, exists_on_remote):
    """The point to continue the generation from: the last state trailer of
    the branch, or the cycle start tag for a fresh branch. Must run after
    checkout_branch. Refuses the tag fallback when the branch already carries
    changelog content: regenerating from the cycle start would duplicate the
    entries that were already integrated."""
    if exists_on_remote:
        from_ref = get_last_generated_sha(branch)
        if from_ref:
            return from_ref
        text = _read_changelog()
        if (
            RAW_BEGIN_PREFIX in text
            or extract_in_progress_section(text, _anchor_id(version)) is not None
        ):
            raise RuntimeError(
                f"Branch {branch} contains changelog content for {version} but "
                f"no '{STATE_TRAILER}' trailer in "
                f"origin/master..origin/{branch}; refusing to regenerate from "
                f"the cycle start, manual investigation required"
            )
    return _start_tag(version)


def remote_branch_exists(branch):
    return bool(Shell.get_output(f"git ls-remote --heads origin {branch}").strip())


def get_pr_states(branch):
    """States of the PRs from the repository's own branch `branch`. Fork PRs
    that happen to use the same head branch name are excluded: they must not
    make the job think its own PR already exists or was closed."""
    out = Shell.get_output(
        f"gh pr list --head {branch} --base master --state all "
        f"--repo {shlex.quote(Info().repo_name)} "
        "--json number,state,isCrossRepository "
        "--jq '.[] | select(.isCrossRepository | not) | \"\\(.number) \\(.state)\"'",
        strict=True,
    )
    return [tuple(line.split()) for line in out.splitlines() if line.strip()]


# --- CHANGELOG.md text manipulation ----------------------------------------

RELEASE_HEADING_RE = re.compile(r'^### <a id="(\d+)"></a>')


def strip_generated_preamble(raw_text):
    """Drop the docs frontmatter and the year header emitted by changelog.py,
    keeping from the '### ClickHouse release ...' line on."""
    lines = raw_text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("### "):
            return "\n".join(lines[i:]).strip()
    raise ValueError("No '### ' release header in the generated changelog")


def count_entries(text):
    return len(re.findall(r"^\* ", text, flags=re.MULTILINE))


def make_raw_block(body):
    return f"{RAW_BEGIN}\n{body}\n{RAW_END}"


def insert_before_first_release(text, block):
    """Insert `block` right above the first release section heading."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if RELEASE_HEADING_RE.match(line):
            return "\n".join(lines[:i] + block.splitlines() + [""] + lines[i:]) + "\n"
    raise ValueError(f"No release section heading found in {CHANGELOG_FILE}")


def split_at_first_released_section(text, anchor):
    """Split into (head, tail) where tail starts at the first release heading
    that is not the in-progress section `anchor`. The tail must never be
    touched by the edit step."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = RELEASE_HEADING_RE.match(line)
        if m and m.group(1) != anchor:
            return "\n".join(lines[:i]), "\n".join(lines[i:])
    return text, ""


def extract_in_progress_section(text, anchor):
    lines = text.splitlines()
    start = None
    for i, line in enumerate(lines):
        m = RELEASE_HEADING_RE.match(line)
        if m and m.group(1) == anchor and start is None:
            start = i
        elif m and start is not None:
            return "\n".join(lines[start:i]).rstrip()
    if start is not None:
        return "\n".join(lines[start:]).rstrip()
    return None


def extract_raw_blocks(text):
    blocks = []
    lines = text.splitlines()
    begin = None
    for i, line in enumerate(lines):
        if line.startswith(RAW_BEGIN_PREFIX):
            begin = i
        elif line.strip() == RAW_END and begin is not None:
            blocks.append("\n".join(lines[begin : i + 1]))
            begin = None
    return blocks


def extract_toc_line(text, version):
    for line in text.splitlines():
        if line.startswith(f"**[ClickHouse release v{version},"):
            return line
    return None


def extract_pr_links(text):
    """PR numbers referenced as changelog entry links in `text`."""
    return set(
        re.findall(
            r"\[#(\d+)\]\(https://github\.com/[^/)]+/[^/)]+/pull/\d+\)", text
        )
    )


# The attribution form the generator emits at the end of every entry:
# `[#N](.../pull/N) ([Author](...))`. Inline mentions of other PRs inside the
# entry text lack the author parenthesis.
PR_ATTRIBUTION_RE = re.compile(
    r"\[#(\d+)\]\(https://github\.com/[^/)]+/[^/)]+/pull/\d+\) \(\["
)

# Categories whose raw entries the editing agent must carry into the edited
# section (possibly rewritten, merged, or under another category — the PR
# link must survive). The skill legitimately prunes the other sections
# (NOT FOR CHANGELOG, NO CL ENTRY, Build/Testing/Packaging).
STRICT_RETENTION_CATEGORIES = {
    "Backward Incompatible Change",
    "New Feature",
    "Experimental Feature",
    "Performance Improvement",
    "Improvement",
    "Bug Fix (user-visible misbehavior in an official stable release)",
}


# A bullet that IS a revert: the entry text (the generator uses the PR title
# for entries without a changelog description) starts with "Revert"/"Reverts"
# — possibly wrapped in the NO CL ENTRY prefix — or quotes a git revert
# commit message. A bullet merely mentioning reverts ("Improve revert
# logic ...") earns no deletion credit.
_REVERT_ENTRY_RE = re.compile(
    r"""(?ix)^\*\s* (?:NO\ CL\ ENTRY:\s*'?\s*)? revert(s|ed)?\b"""
)


def raw_strict_prs_and_reverts(text):
    """From the raw marker blocks in `text`: the attribution PR numbers of
    entries under the strict-retention categories, and the PR numbers of the
    revert entries (each licenses the deletion of the entry it reverts)."""
    strict_prs = set()
    revert_prs = []
    for block in extract_raw_blocks(text):
        category = None
        for line in block.splitlines():
            if line.startswith("#### "):
                category = line[5:].strip()
            elif line.startswith("* "):
                if _REVERT_ENTRY_RE.match(line) or "this reverts commit" in line.lower():
                    revert_prs.extend(PR_ATTRIBUTION_RE.findall(line))
                if category in STRICT_RETENTION_CATEGORIES:
                    strict_prs.update(PR_ATTRIBUTION_RE.findall(line))
    return strict_prs, revert_prs


def _older_than(prs, pr):
    """The pull requests of `prs` merged before `pr`, by number."""
    return {p for p in prs if int(p) < int(pr)}


# The revert bookkeeping the job carries on its own branch. A release cycle is
# edited in ~30 nightly increments and a revert chain routinely spans them: the
# change lands on one day, the revert arrives on another, the revert of the
# revert on a third. By then the deleted entry is gone from CHANGELOG.md and
# the intervening revert is gone from the raw blocks, so neither the editing
# agent nor the verification can reconstruct the chain from the current state
# of the file. These trailers on the edit commits are that memory — like
# `Changelog-generated-up-to:`, the branch carries its own state and the pull
# request diff stays clean:
#   `Changelog-revert: <revert> <reverted> <title of the revert>`
#   `Changelog-deleted-entry: <pull request> [<category>] <bullet as deleted>`
# The category is the `#### <Category>` the bullet sat under, which is not
# derivable from the pull request: the editing rules promote entries out of
# `NOT FOR CHANGELOG` (skill section 3) and move them between real categories
# (section 6), so the category an entry ends up in is a decision of the edit,
# and a restoration has to reproduce it rather than start over.
REVERT_TRAILER = "Changelog-revert:"
DELETED_TRAILER = "Changelog-deleted-entry:"
REVERT_TRAILER_RE = re.compile(rf"^{REVERT_TRAILER}\s+(\d+)\s+(\d+)\s*(.*)$")
DELETED_TRAILER_RE = re.compile(
    rf"^{DELETED_TRAILER}\s+(\d+)\s+(?:\[([^\]]*)\]\s+)?(.*)$"
)


# `Revert #NNNNN` / `Reverts #NNNNN` / `Revert of PR #NNNNN`: the title names
# the reverted pull request outright. Anchored on the whole title, so that a
# `Revert "Fix #12345"` — a quoted original title that happens to mention an
# issue — is not mistaken for it and goes to the nested-title form instead.
_REVERT_NUMBER_TITLE_RE = re.compile(
    r"(?is)^\s*revert(?:s|ed)?\s+(?:of\s+)?(?:pr\s*)?#(\d+)\.?\s*$"
)


def resolve_revert_targets(revert_prs, known_titles=None):
    """Bind every pull request of `revert_prs` to the pull request it reverts,
    via the `Reverts owner/repo#N` line GitHub puts into revert pull request
    bodies. `known_titles` supplies the titles of the reverts earlier runs of
    the job already resolved, so a revert of a revert binds to its target even
    when that target is not in the current raw block. Returns (targets, titles,
    unresolved): `targets` maps a revert to the pull requests it reverts,
    `titles` holds the titles looked up here, and `unresolved` lists the
    reverts whose target stayed unknown (a manual revert without the marker, a
    failed lookup, or a nested title that fits several earlier reverts equally
    well) — those grant no deletion credit, and the caller fails closed on any
    disappearance it cannot bind to a resolved, uncancelled revert."""
    targets = {}
    titles = {}
    for pr in revert_prs:
        out = Shell.get_output(
            f"gh pr view {pr} --repo {shlex.quote(Info().repo_name)} "
            "--json title,body"
        )
        data = json.loads(out) if out else {}
        titles[pr] = " ".join(data.get("title", "").split())
        found = re.findall(r"(?i)reverts\s+[\w.-]+/[\w.-]+#(\d+)", data.get("body", ""))
        # A revert is always merged after what it reverts, so it always has the
        # higher number. That is the invariant `revert_net_effect` settles
        # whole chains in a single descending pass with, so a relation that
        # breaks it is not one: drop it and let the other forms try.
        older = _older_than(found, pr)
        if older:
            targets[pr] = older
    # A revert of a revert made with the web UI carries no `Reverts ...#N`
    # marker in its body (the button restores the change, GitHub words the
    # body differently), but its title nests the reverted title: the target
    # of `Revert "Revert "X""` is the revert titled `Revert "X"` — which this
    # job may have processed days ago, hence `known_titles`.
    candidates = {**(known_titles or {}), **titles}
    unresolved = []
    for pr in revert_prs:
        if pr in targets:
            continue
        # The skill's other common form, and an exact one: no title matching
        # needed, and nothing to be ambiguous about.
        numbered = _REVERT_NUMBER_TITLE_RE.match(titles[pr])
        if numbered:
            older = _older_than([numbered.group(1)], pr)
            if older:
                targets[pr] = older
                continue
        nested = re.match(r'(?is)revert(?:s|ed)?\s+"(.+)"\s*$', titles[pr])
        matched = (
            {
                p
                for p, t in candidates.items()
                if t == nested.group(1) and int(p) < int(pr)
            }
            if nested
            else set()
        )
        # Revert titles are not unique — the same change can be reverted more
        # than once in a cycle, and every one of those reverts is titled
        # `Revert "X"` — so a title matching several earlier reverts
        # identifies none of them. Bind only an unambiguous match; anything
        # else stays unresolved, which grants no credit at all.
        if len(matched) == 1:
            targets[pr] = matched
        else:
            unresolved.append(pr)
    return targets, titles, unresolved


def revert_net_effect(targets):
    """Reduce revert chains to their net effect: a revert that is itself
    reverted grants no deletion credit for its target, because the target
    ships in the release (`#109946` ← `#114911` ← `#114912`: the fix
    `#109946` stays, only the entry of the cancelled revert `#114911` may go).
    A revert always has a higher pull request number than what it reverts, so
    walking the reverts in descending order settles every chain in one pass, at
    any depth. Returns (credits, cancelled): `credits` maps a pull request whose
    entry may be deleted to the uncancelled revert that licenses it, `cancelled`
    is the set of reverts a later revert took back."""
    cancelled = set()
    credits = {}
    for pr in sorted(targets, key=int, reverse=True):
        if pr in cancelled:
            continue
        for target in targets[pr]:
            if target in targets:
                cancelled.add(target)
            credits.setdefault(target, pr)
    return credits, cancelled


def read_revert_ledger():
    """The revert relations and the revert-licensed deletions that previous
    runs recorded in the trailers of their own edit commits on this branch.
    Returns (targets, titles, deleted): `targets` maps a revert to what it
    reverts, `titles` gives those reverts' titles (for nested-title matching
    of a later revert of a revert), `deleted` maps a pull request whose entry
    a revert licensed us to delete to the (category, bullet) it had at that
    moment.

    All three are empty on a branch whose edit commits predate the trailers,
    which degrades to the previous behaviour: chains are then only seen inside
    a single raw block."""
    log = Shell.get_output(
        "git log origin/master..HEAD --format=%B", strict=True
    )
    targets, titles, deleted = {}, {}, {}
    for line in log.splitlines():
        m = REVERT_TRAILER_RE.match(line)
        if m:
            targets.setdefault(m.group(1), set()).add(m.group(2))
            if m.group(3):
                titles.setdefault(m.group(1), m.group(3))
            continue
        m = DELETED_TRAILER_RE.match(line)
        if m:
            # `setdefault`, because `git log` walks newest first and one entry
            # can be deleted, restored and deleted again, gaining a re-apply
            # link each time it comes back: the newest record holds the text
            # to restore, the older ones are superseded.
            deleted.setdefault(m.group(1), (m.group(2) or "", m.group(3)))
    return targets, titles, deleted


def _attribution_re(pr):
    return re.compile(
        rf"\[#{pr}\]\(https://github\.com/[^/)]+/[^/)]+/pull/{pr}\) \(\["
    )


def is_attributed(text, pr):
    """Whether `text` carries the changelog entry of `pr`, i.e. its attribution
    `[#N](.../pull/N) ([Author](...))` — the form the generator emits at the
    end of every entry and a merge (skill section 7) appends for each pull
    request it merges in.

    A bare `[#N](...)` link inside another entry — a `This closes` reference, a
    follow-up named in prose — is not the entry of `pr` and does not stand in
    for it. The current `CHANGELOG.md` has 17 pull requests linked that way and
    never attributed, so the distinction is not theoretical: without it a
    restoration is satisfied by someone else's bullet merely mentioning the
    pull request."""
    return bool(_attribution_re(pr).search(text))


def entry_placement(text, pr):
    """Where the changelog entry of `pr` sits in `text`: the (category, bullet)
    of the bullet `pr` is attributed to, ("", "") when it has none. Only the
    attribution counts, see `is_attributed`."""
    attributed = _attribution_re(pr)
    category = ""
    for line in text.splitlines():
        if line.startswith("#### "):
            category = line[5:].strip()
        elif line.startswith("* ") and attributed.search(line):
            return category, line
    return "", ""


def group_restorations(restore, section):
    """Group the entries to restore by the bullet they were recorded from.

    A merge (skill section 7) puts several pull requests on one bullet, so one
    recorded line can be the record of more than one of them: it has to be
    restored once, not once per pull request. `siblings` are the other pull
    requests attributed on that line which are still in `section` — the bullet
    is therefore still there, and the restoration has to put the missing links
    back into it instead of pasting a copy of the line and duplicating them.

    `section` is the in-progress section, not the whole file: the same pull
    request legitimately appears in an already-released section further down
    (published in the last release, or backported), and a sibling that
    survives only there is no bullet to merge into."""
    groups = {}
    for pr, (category, line) in restore.items():
        groups.setdefault((category, line), []).append(pr)
    out = []
    for (category, line), prs in groups.items():
        siblings = set(PR_ATTRIBUTION_RE.findall(line)) - set(prs)
        out.append(
            {
                "prs": sorted(prs, key=int),
                "siblings": sorted(
                    (p for p in siblings if is_attributed(section, p)), key=int
                ),
                "category": category,
                "line": line,
            }
        )
    return sorted(out, key=lambda group: int(group["prs"][0]))


def duplicate_attributions(text):
    """Pull requests attributed more than once in `text`. The generator emits
    one attribution per entry and a merge appends the merged pull requests'
    links to a single bullet, so a repetition means the same entry was written
    twice — which is what restoring a merged bullet by pasting the recorded
    line next to the one that already carries its siblings produces."""
    counts = {}
    for pr in PR_ATTRIBUTION_RE.findall(text):
        counts[pr] = counts.get(pr, 0) + 1
    return {pr for pr, count in counts.items() if count > 1}


def analyze_reverts(text, anchor):
    """Everything the editing step needs to know about reverts, resolved
    against the branch's ledger so that a chain spread over several nightly
    runs is handled exactly like one arriving inside a single raw block.
    Returns a dict:

    `credits`    - pull request -> the uncancelled revert that licenses the
                   deletion of its entry;
    `restore`    - pull request -> the (category, bullet) an earlier run
                   deleted whose revert has since been reverted, so the change
                   ships after all and the entry has to be in the in-progress
                   section;
    `missing`    - the work the editing agent has to do: the part of `restore`
                   that is not in `text` yet, grouped by the bullet it was
                   recorded from (one merged bullet covers several pull
                   requests) and annotated with the reverts that removed and
                   re-applied it;
    `unresolved` - the reverts of this raw block whose target stayed unknown;
    `ledger`     - the trailer lines to record on the edit commit.
    """
    ledger_targets, ledger_titles, deleted = read_revert_ledger()
    _, revert_prs = raw_strict_prs_and_reverts(text)
    new_targets, titles, unresolved = resolve_revert_targets(revert_prs, ledger_titles)
    targets = {pr: set(reverted) for pr, reverted in ledger_targets.items()}
    for pr, reverted in new_targets.items():
        targets.setdefault(pr, set()).update(reverted)
    credits, cancelled = revert_net_effect(targets)
    reverted_by = {}
    for pr, reverted in targets.items():
        for target in reverted:
            reverted_by.setdefault(target, set()).add(pr)
    # An entry deleted on an earlier run stays deleted only as long as the
    # revert that licensed it stands. Once that revert is itself reverted, the
    # pull request drops out of `credits` and its entry has to come back.
    # Neither the current CHANGELOG.md (the entry is gone from it) nor the
    # current raw blocks (they hold only the newest revert) could tell the
    # agent that, which is why the ledger keeps the text.
    section = extract_in_progress_section(text, anchor) or ""
    restore = {
        pr: record for pr, record in deleted.items() if pr not in credits
    }

    def removed_by(prs):
        return sorted({r for pr in prs for r in reverted_by.get(pr, ())}, key=int)

    def reapplied_by(prs):
        return sorted(
            {
                reapply
                for remover in removed_by(prs)
                for reapply in reverted_by.get(remover, ())
                if reapply not in cancelled
            },
            key=int,
        )

    # Everything about a restoration is asked of the in-progress section, not
    # of the whole file. A recorded entry was in that section before it was
    # deleted, so that is where it has to come back; the same pull request
    # appearing in an already-released section further down (published in the
    # last release, or backported) is neither the entry nor a bullet to merge
    # into. This is not the question `disappeared_entries` asks of a raw entry
    # that never made it in, where a released copy is a legitimate reason for
    # it not to be in this section at all.
    missing = group_restorations(
        {
            pr: record
            for pr, record in restore.items()
            if not is_attributed(section, pr)
        },
        section,
    )
    for group in missing:
        group["removed_by"] = removed_by(group["prs"])
        group["reapplied_by"] = reapplied_by(group["prs"])
    return {
        "credits": credits,
        "restore": restore,
        "missing": missing,
        "unresolved": unresolved,
        "ledger": [
            f"{REVERT_TRAILER} {pr} {target} {titles[pr]}".rstrip()
            for pr in sorted(new_targets, key=int)
            for target in sorted(new_targets[pr], key=int)
        ],
    }


def compose_on_master(master_text, version, toc_line, raw_blocks, section):
    """Rebuild our additions on top of master's CHANGELOG.md. Used to resolve
    the merge conflict that appears when master's CHANGELOG.md changed (e.g.
    the previous release section landed while this branch was open)."""
    anchor = _anchor_id(version)
    if f'<a id="{anchor}"></a>' in master_text:
        raise ValueError(
            f"Master already contains a section for {version}; "
            "manual reconciliation required"
        )
    text = master_text
    if toc_line:
        lines = text.splitlines()
        for i, line in enumerate(lines):
            if line.startswith("**[ClickHouse release v"):
                lines.insert(i, toc_line)
                break
        else:
            raise ValueError("No table-of-contents entries found on master")
        text = "\n".join(lines) + ("\n" if text.endswith("\n") else "")
    for part in [section] + raw_blocks:
        if part:
            text = insert_before_first_release(text, part)
    return text


def _untracked_files():
    """Untracked, not-ignored files (the gitignored ci/tmp scratch space is
    excluded, so the job's own temporary files never show up here).
    NUL-delimited so file names with spaces survive."""
    out = Shell.get_output(
        "git ls-files -z --others --exclude-standard", strict=True
    )
    return {path for path in out.split("\0") if path}


def _reset_worktree(base_sha, pre_untracked=None):
    """Restore the branch and all tracked files to the given commit, and
    remove untracked files that appeared since `pre_untracked` was snapshot
    (fail-closed cleanup after a bad edit attempt, including one where the
    editing agent created commits or new files of its own)."""
    Shell.check(f"git reset --hard {base_sha}", verbose=True, strict=True)
    if pre_untracked is not None:
        for path in sorted(_untracked_files() - pre_untracked):
            print(f"Removing file left behind by the editing agent: {path}")
            os.unlink(path)


def _read_changelog():
    with open(CHANGELOG_FILE, encoding="utf-8") as fd:
        return fd.read()


def _write_changelog(text):
    with open(CHANGELOG_FILE, "w", encoding="utf-8") as fd:
        fd.write(text)



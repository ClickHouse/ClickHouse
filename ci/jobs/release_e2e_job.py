"""End-to-end check for the release pipeline's `--release-type new` path.

Runs `ci/jobs/release_job.py` for real -- deliberately not `--dry-run` -- against
a throwaway local bare repo, and asserts the git state the run leaves there. The
release runner's outside world is reduced to two `PATH` stubs (`aws` for the SSM
robot token, `gh` for the GitHub API) plus git `insteadOf`, which redirects the
tokenized `github.com` push URL to the bare repo; a push that escaped the
redirect fails closed on authentication rather than mutating anything.

A `--dry-run` rehearsal cannot observe this path. `Shell.run` only prints under
`dry_run`, so no bump commit exists and the push is already-up-to-date;
`Git.push` skips its non-fast-forward rebase loop when `dry_run`; and the
release-PR reuse lookup is hardcoded to `""` under `dry_run`.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from ci.praktika._environment import _Environment
from ci.praktika.result import Result
from ci.praktika.utils import Utils

REPO_ROOT = Utils.cwd()
RELEASE_INFO = "/tmp/release_info.json"
VERSIONS_FILE = "cmake/autogenerated_versions.txt"
CONTRIBUTORS_FILE = "src/Storages/System/StorageSystemContributors.generated.cpp"
REPO = "test/clickhouse"
TOKEN = "faketoken"
ROBOT_TOKEN_PARAM = "/github-tokens/robot-1"
PUSH_URL = f"https://x-access-token:{TOKEN}@github.com/{REPO}.git"
ROBOT_NAME = "robot-clickhouse"
ROBOT_EMAIL = "robot-clickhouse@users.noreply.github.com"
BUMP_SUBJECT = "Update autogenerated version to 26.9.1.1 and contributors"
INTERLOPER_SUBJECT = "A backport landed during the release"
IDENTITY = (
    ("user.name", "A Developer"),
    ("user.email", "dev@clickhouse.com"),
    ("commit.gpgsign", "false"),
    ("tag.gpgsign", "false"),
)

# Minor 8 releases as `v26.8.1.1-new`, so the bump under test lands 26.9.1.1 on
# master and `26.8.1.1-lts` on the cut branch. 8 % 5 == 3 makes only the cut branch
# an LTS line, so the release PR's `release-lts` label names the version it read.
VERSIONS_CONTENT = """\
# This variables autochanged by ci/jobs/scripts/create_release.py:

SET(VERSION_REVISION 54500)
SET(VERSION_MAJOR 26)
SET(VERSION_MINOR 8)
SET(VERSION_PATCH 1)
SET(VERSION_GITHASH 0000000000000000000000000000000000000000)
SET(VERSION_DESCRIBE v26.8.1.1-new)
SET(VERSION_STRING 26.8.1.1)
# end of autochange
"""


def git(*args, cwd, check=True):
    res = subprocess.run(
        ["git", *args], cwd=str(cwd), capture_output=True, text=True, timeout=60
    )
    if check and res.returncode != 0:
        raise RuntimeError(f"git {args} rc={res.returncode}\n{res.stdout}{res.stderr}")
    return res.stdout.strip()


def git_ok(*args, cwd):
    """For the git predicates that answer through the exit code, not stdout."""
    return (
        subprocess.run(
            ["git", *args], cwd=str(cwd), capture_output=True, timeout=60
        ).returncode
        == 0
    )


def flag_value(command, flag):
    """The token following `flag` in a logged command line, or ''."""
    tokens = command.split()
    for i, token in enumerate(tokens[:-1]):
        if token == flag:
            return tokens[i + 1]
    return ""


def flag_values(command, flag):
    """Every value `flag` is given, '' for a trailing one that `gh` would reject."""
    tokens = command.split()
    return [
        tokens[i + 1] if i + 1 < len(tokens) else ""
        for i, token in enumerate(tokens)
        if token == flag
    ]


def api_fields(command):
    """The payload fields `gh api` will send, in the spellings pflag accepts. A bare
    `key=value` is not one: `gh` reads it as a second positional and refuses the call
    with "accepts 1 arg(s), received 2"."""
    fields = {}
    tokens = command.split()
    for i, token in enumerate(tokens):
        if token in ("-f", "--raw-field", "-F", "--field"):
            pair = tokens[i + 1] if i + 1 < len(tokens) else ""
        elif token.startswith(("--raw-field=", "--field=")):
            pair = token.split("=", 1)[1]
        elif len(token) > 2 and token[0] == "-" and token[1] in "fF":
            pair = token[2:]
        else:
            continue
        key, _, value = pair.partition("=")
        fields[key] = value
    return fields


def api_method(command):
    """The method `gh api` will use: an explicit override in any of the spellings
    pflag accepts, else POST because the command adds parameters (`gh api --help`).
    A `GET` merely reads the endpoint."""
    tokens = command.split()
    for i, token in enumerate(tokens):
        if token in ("--method", "-X"):
            return tokens[i + 1] if i + 1 < len(tokens) else ""
        if token.startswith("--method="):
            return token.split("=", 1)[1]
        if token.startswith("-X") and len(token) > 2:
            return token[2:]
    return "POST" if api_fields(command) else "GET"


class ReleaseE2E:
    def __init__(self, root, log):
        self.root = root
        self.log = log
        self.results = []
        self.master = None
        self.branch = None

    # --- fixture ------------------------------------------------------------

    def build_origin(self):
        """Bare origin whose `master` is base -> released (annotated
        `v26.8.1.1-new`) -> advanced, plus the `aws`/`gh` stubs.

        `advanced` is what lets the `VERSION_GITHASH` oracle discriminate: the run
        is dispatched with `released` while the bump resyncs master to the later
        tip, so the two shas differ. It touches only `README.md`, since a
        version-file change would flip the skip-when-already-bumped comparison.
        """
        seed = self.seed = self.root / "seed"
        seed.mkdir()
        self.home = self.root / "home"
        self.home.mkdir()
        git("init", "-q", "-b", "master", ".", cwd=seed)
        for key, value in IDENTITY:
            git("config", key, value, cwd=seed)
        (seed / "cmake").mkdir()
        (seed / "src/Storages/System").mkdir(parents=True)
        (seed / VERSIONS_FILE).write_text(VERSIONS_CONTENT, encoding="utf-8")
        (seed / CONTRIBUTORS_FILE).write_text(
            "const char * auto_contributors[] {\n    nullptr};\n", encoding="utf-8"
        )
        (seed / "README.md").write_text("clickhouse\n", encoding="utf-8")
        git("add", "-A", cwd=seed)
        git("commit", "-q", "-m", "Base commit", cwd=seed)
        anchor = git("rev-parse", "HEAD", cwd=seed)

        # `VERSION_GITHASH` must name a real earlier commit: the tweak is the
        # commit count since it, and counting from an unknown hash raises. Authored
        # by the release robot so `git shortlog` already lists it -- otherwise the
        # bump commit would add a contributor, and a rerun would rewrite the
        # contributors file and push again.
        (seed / VERSIONS_FILE).write_text(
            VERSIONS_CONTENT.replace("0" * 40, anchor), encoding="utf-8"
        )
        git("add", "-A", cwd=seed)
        git("-c", f"user.name={ROBOT_NAME}", "-c", f"user.email={ROBOT_EMAIL}",
            "commit", "-q", "-m", "Anchor version githash", cwd=seed)
        git("tag", "-a", "v26.8.1.1-new", "-m", "Release v26.8.1.1-new", cwd=seed)
        self.released = git("rev-parse", "HEAD", cwd=seed)
        (seed / "README.md").write_text("clickhouse\nmoved on\n", encoding="utf-8")
        git("add", "-A", cwd=seed)
        git("commit", "-q", "-m", "Post-release commit on master", cwd=seed)
        self.advanced = git("rev-parse", "HEAD", cwd=seed)

        self.origin = self.root / "origin.git"
        # `-b master`: a bare HEAD left on the ambient `init.defaultBranch` gives the
        # shallow `file://` clone no branch to resolve.
        git("init", "-q", "--bare", "-b", "master", str(self.origin), cwd=self.root)
        # Serve the treeless partial fetch the release job's first step performs.
        git("config", "uploadpack.allowFilter", "true", cwd=self.origin)
        git("remote", "add", "origin", str(self.origin), cwd=seed)
        git("push", "-q", "origin", "master", "--tags", cwd=seed)

        # `post-receive` gets one `<old> <new> <ref>` line per updated ref on stdin, so the
        # branch cut and the later bump are distinguishable events rather than one end state.
        self.reflog = self.root / "origin-refs.log"
        git("config", "core.hooksPath", str(self.origin / "hooks"), cwd=self.origin)
        hook = Path(self.origin, "hooks/post-receive")
        hook.write_text(f'#!/bin/sh\ncat >> "{self.reflog}"\n', encoding="utf-8")
        hook.chmod(0o755)

        # `aws` answers the one SSM parameter the `new` path may read and fails
        # closed on anything else, so a credential read added to this path shows up
        # as a loud failure rather than a silently satisfied one.
        self.bindir = self.root / "bin"
        self.bindir.mkdir()
        (self.bindir / "aws").write_text(
            f'#!/bin/sh\nprintf "%s\\n" "$*" >> "{self.root}/aws.log"\n'
            'name=""; output=""; query=""; decrypt=""; prev=""\n'
            'for a in "$@"; do\n'
            '  case "$prev" in\n'
            '    --name)   name="$a" ;;\n'
            '    --output) output="$a" ;;\n'
            '    --query)  query="$a" ;;\n'
            "  esac\n"
            '  [ "$a" = "--with-decryption" ] && decrypt=yes\n'
            '  prev="$a"\n'
            "done\n"
            f'if [ "$1 $2" != "ssm get-parameter" ] || [ "$name" != "{ROBOT_TOKEN_PARAM}" ]\n'
            "then\n"
            '  echo "release-e2e stub: unexpected aws call [$*]" >&2; exit 1\n'
            "fi\n"
            # Each flag's value decides what real SSM returns: without it, or with an
            # extension of it, the caller gets ciphertext or a JSON document rather than
            # the token. Compared individually, so reordering the command stays acceptable.
            '[ "$decrypt" = yes ] || {\n'
            '  echo "release-e2e stub: aws ssm read lacks [--with-decryption]: [$*]" >&2\n'
            "  exit 1; }\n"
            '[ "$output" = text ] || {\n'
            '  echo "release-e2e stub: aws ssm read has --output [$output], want [text]: [$*]" >&2\n'
            "  exit 1; }\n"
            '[ "$query" = Parameter.Value ] || {\n'
            '  echo "release-e2e stub: aws ssm read has --query [$query], want [Parameter.Value]: [$*]" >&2\n'
            "  exit 1; }\n"
            f"echo '{TOKEN}'\n",
            encoding="utf-8",
        )
        # The sentinel a `pr create` writes is keyed on repository, head and the states
        # under which the resulting open PR is visible -- the three inputs
        # `get_pr_url_by_branch` varies. An unmatched `pr list` gets `[]`, the answer a
        # successful `gh pr list --json` prints when nothing matches, so the retried
        # strict reads succeed and report "no PR".
        (self.bindir / "gh").write_text(
            f'#!/bin/sh\nprintf "%s\\n" "$*" >> "{self.root}/gh.log"\n'
            'sub="$1 $2"\n'
            'head=""; repo=""; state=""; json=""; prev=""\n'
            'for a in "$@"; do\n'
            '  case "$prev" in\n'
            '    --head)  head="$a" ;;\n'
            '    --repo)  repo="$a" ;;\n'
            '    --state) state="$a" ;;\n'
            '    --json)  json="$a" ;;\n'
            "  esac\n"
            '  prev="$a"\n'
            "done\n"
            # `gh pr list` prints only the fields `--json` asks for, so a lookup that
            # does not request the one it dereferences is neither answered nor handed it.
            'if [ "$sub" = "pr list" ]; then\n'
            '  case ",$json," in\n'
            "    *,url,*) ;;\n"
            '    *) echo "release-e2e stub: gh pr list lacks [--json url]: [$*]" >&2\n'
            "       exit 1 ;;\n"
            "  esac\n"
            "fi\n"
            # A repository name contains a slash: unsanitized, the marker path names a
            # directory that does not exist, and the failed redirect would leave the
            # reuse arm permanently answered `[]` with every phase still green.
            'key=""\n'
            'if [ -n "$repo" ] && [ -n "$head" ]; then\n'
            f'  key="{self.root}/gh.created.$(printf "%s" "$repo:$head" | tr / _)"\n'
            "fi\n"
            'if [ "$sub" = "pr create" ] && [ -n "$key" ]; then : > "$key"; fi\n'
            'if [ "$sub" = "pr list" ] && [ -n "$key" ] && [ -e "$key" ]\n'
            "then\n"
            # `gh pr list` defaults to open and `all` includes it; closed and merged miss.
            '  case "$state" in\n'
            f"""    ""|open|all) printf '[{{"url":"https://github.com/{REPO}/pull/1"}}]\\n'\n"""
            "      exit 0 ;;\n"
            "  esac\n"
            "fi\n"
            # Like the `aws` stub, an unknown call fails rather than succeeds: a
            # catch-all success answers every `gh` path no assertion covers, which
            # makes not issuing one indistinguishable from issuing it. The listed
            # subcommands are what the `new` path issues.
            'case "$sub" in\n'
            "  \"pr list\") echo '[]' ;;\n"
            '  "pr create"|"auth setup-git") ;;\n'
            f'  "api repos/{REPO}/labels") ;;\n'
            f'  *) printf "%s\\n" "$*" >> "{self.root}/gh.unexpected"\n'
            '     echo "release-e2e stub: unexpected gh call [$*]" >&2\n'
            "     exit 1 ;;\n"
            "esac\n",
            encoding="utf-8",
        )
        for name in ("aws", "gh"):
            (self.bindir / name).chmod(0o755)

    def clone(self, name, shallow):
        """A working clone shaped like the release runner's checkout.

        Shallow for the phase that runs the orchestrator, whose first step
        unshallows, because `git fetch --unshallow` fails on a complete repository;
        a plain path clone is `--local` and ignores `--depth`, hence the `file://`
        URL. Complete for the phases that call the subcommand directly, since
        nothing unshallows them and `update_contributors` refuses a shallow
        repository.
        """
        clone = self.root / name
        depth = ["--depth", "1"] if shallow else []
        src = f"file://{self.origin}" if shallow else str(self.origin)
        git("clone", "-q", *depth, src, str(clone), cwd=self.root)
        for key, value in IDENTITY:
            git("config", key, value, cwd=clone)
        git("config", f"url.{self.origin}.insteadOf", PUSH_URL, cwd=clone)
        # An ambient `core.hooksPath` would disarm the phase-3 interloper hook.
        git("config", "core.hooksPath", str(clone / ".git/hooks"), cwd=clone)

        # `create_release.py` resolves `s3_helper`/`ssh` relative to itself and names
        # the contributors "executer" by its own path relative to cwd, so it must run
        # from inside the repo it operates on. `ci` is a real directory of per-entry
        # symlinks with its own `ci/tmp`: `Settings.TEMP_DIR` is cwd-relative and the
        # release job's cleanup step unlinks `ci/tmp/praktika_setup_env.sh`, which
        # through a whole-`ci` symlink would delete this job's own env script.
        (clone / "ci").mkdir()
        for entry in os.listdir(f"{REPO_ROOT}/ci"):
            if entry != "tmp":
                os.symlink(f"{REPO_ROOT}/ci/{entry}", clone / "ci" / entry)
        (clone / "ci/tmp").mkdir()
        os.symlink(f"{REPO_ROOT}/tests", clone / "tests")

        # The inner run builds its job `Result` from `_Environment`, whose file is
        # also cwd-relative. A distinct job name keeps its result JSON out of ours, and
        # `REPOSITORY` is the fallback repo for the `GH` helpers, so it must not name
        # the real one.
        inner = json.loads(
            Path(_Environment.file_name_static()).read_text(encoding="utf-8")
        )
        inner["JOB_NAME"] = "Release Workflow E2E (inner)"
        inner["REPOSITORY"] = REPO
        Path(clone, "ci/tmp/environment.json").write_text(
            json.dumps(inner), encoding="utf-8"
        )
        return clone

    def complete_clone(self, name, check):
        if self.master is None:
            raise RuntimeError("the release job phase did not complete")
        clone = self.clone(name, shallow=False)
        check(
            git("rev-parse", "--is-shallow-repository", cwd=clone) == "false",
            f"{name} is shallow, so update_contributors would refuse it",
        )
        return clone

    def run_release(self, clone, *argv, gh_token=True):
        """Invoke a release script in `clone` with the stubs first on `PATH`.

        `gh_token=False` denies the run the token it is itself responsible for
        establishing from SSM, so every push it makes authenticates through that
        production path. An ambient token has to be scrubbed rather than left
        unset, because the environment is inherited from this process.
        """
        drop = {"ROBOT_CLICKHOUSE_SSH_KEY"}
        if not gh_token:
            drop.add("GH_TOKEN")
        env = {k: v for k, v in os.environ.items() if k not in drop}
        env.update(
            # `<repo>:<repo>/ci`, the import path praktika gives a dockerized job.
            PYTHONPATH=f"{clone}{os.pathsep}{clone}/ci",
            PATH=f"{self.bindir}{os.pathsep}{env['PATH']}",
            # The release job's credential cleanup unmounts `~/mountpoint` and removes
            # `~/.r2_auth*`, so the inner run must not inherit a real home.
            HOME=str(self.home),
            GITHUB_REPOSITORY=REPO,
        )
        if gh_token:
            env["GH_TOKEN"] = TOKEN
        res = subprocess.run(
            [sys.executable, *argv], cwd=str(clone), env=env,
            capture_output=True, text=True, timeout=240,
        )
        with open(self.log, "a", encoding="utf-8") as f:
            f.write(f"$ {' '.join(argv)}\nrc={res.returncode}\n{res.stdout}{res.stderr}\n")
        # A call the stubs do not model was not tested, whatever the run's own rc says:
        # the release code reads some `gh` failures as warnings.
        unexpected = Path(self.root, "gh.unexpected")
        if unexpected.is_file():
            raise RuntimeError(
                f"gh calls this harness does not model: "
                f"{unexpected.read_text(encoding='utf-8').splitlines()}"
            )
        return res.returncode, res.stdout + res.stderr

    def stub_log(self, name):
        return Path(self.root, f"{name}.log").read_text(encoding="utf-8")

    def show(self, ref, path):
        return git("show", f"{ref}:{path}", cwd=self.origin)

    def rev(self, ref):
        return git("rev-parse", ref, cwd=self.origin)

    def phase(self, name, body):
        """One CIDB row. A harness failure is an ERROR rather than a skip: nothing
        here declines to test the release flow, so a broken environment or a
        missing dependency can never be read as a pass."""
        stopwatch = Utils.Stopwatch()
        failures = []
        status = Result.Status.FAIL
        try:
            body(lambda ok, what: None if ok else failures.append(what))
        except Exception as exc:
            status = Result.Status.ERROR
            failures.append(f"harness error: {exc}")
        self.results.append(
            Result.create_from(
                name=name,
                status=status if failures else Result.Status.OK,
                stopwatch=stopwatch,
                info="\n".join(failures),
            )
        )

    # --- phases -------------------------------------------------------------

    def preconditions(self, check):
        check(self.released != self.advanced, "released and advanced shas are equal")
        check(
            ROBOT_NAME in git("shortlog", "master", "--summary", cwd=self.seed),
            f"no {ROBOT_NAME} commit in the fixture, so a rerun would add a contributor",
        )

    def bump_is_pushed(self, check):
        """The orchestrator, end to end: one bump commit on master anchored at
        master's head, one on the cut branch, the tag, and the release PR."""
        clone = self.clone("run1", shallow=True)
        Path(RELEASE_INFO).unlink(missing_ok=True)
        rc, _ = self.run_release(
            clone, "ci/jobs/release_job.py",
            "--ref", self.released, "--release-type", "new",
            gh_token=False,
        )
        check(rc == 0, f"release_job.py rc={rc}")
        if rc != 0:
            # Everything below reads state this run was supposed to produce, so
            # reporting it too would bury the failure that explains it.
            return

        # A ref the run failed to push is the regression, so name it: the reads below
        # would instead raise out of the phase and be reported as a broken harness.
        for ref in ("v26.9.1.1-new", "26.8", "master"):
            if not git_ok("rev-parse", "--verify", ref, cwd=self.origin):
                check(False, f"origin has no {ref} after the release run")
                return

        updates = [
            line.split()
            for line in self.reflog.read_text(encoding="utf-8").splitlines()
        ]

        # `release_job.py` stops at the first failing step, so pushing the tag first is
        # what keeps a run that dies there from having published a branch or a bump.
        tags = [i for i, u in enumerate(updates) if u[2].startswith("refs/tags/")]
        heads = [i for i, u in enumerate(updates) if u[2].startswith("refs/heads/")]
        check(
            bool(tags) and bool(heads) and max(tags) < min(heads),
            f"the tag did not precede every branch update: {[u[2] for u in updates]}",
        )

        # The cut and the bump both land on `26.8`, and the bump alone would CREATE the ref:
        # only the update history distinguishes a real cut from a bump that stood in for it.
        cut = [u for u in updates if u[2:3] == ["refs/heads/26.8"]]
        check(len(cut) == 2, f"want 2 pushes to 26.8 (cut, then bump), got {len(cut)}")
        if len(cut) == 2:
            check(cut[0][0] == "0" * 40, "the first 26.8 push did not create the ref")
            check(cut[0][1] == self.released, "the branch was not cut at the released commit")
            check(cut[1][0] == self.released, "the bump did not build on the cut branch")

        info = json.loads(Path(RELEASE_INFO).read_text(encoding="utf-8"))
        for key, want in (
            ("release_branch", "26.8"),
            ("release_tag", "v26.9.1.1-new"),
            ("version", "26.9.1.1"),
            ("commit_sha", self.released),
            ("is_tag_pushed", False),
        ):
            check(info.get(key) == want, f"release info {key}={info.get(key)!r}")

        check(
            git("rev-list", "--count", f"{self.advanced}..master", cwd=self.origin) == "1",
            "origin master did not advance by exactly one commit",
        )
        subject = git("log", "-1", "--format=%s", "master", cwd=self.origin)
        check(subject == BUMP_SUBJECT, f"unexpected bump subject [{subject}]")
        versions = self.show("master", VERSIONS_FILE)
        check(
            "SET(VERSION_DESCRIBE v26.9.1.1-testing)" in versions,
            "master version file does not describe 26.9.1.1-testing",
        )
        # The bump on master must anchor VERSION_GITHASH at master's head at resync
        # time, not back at the released commit.
        check(
            f"SET(VERSION_GITHASH {self.advanced})" in versions,
            "master VERSION_GITHASH is not the advanced master tip",
        )

        check(
            self.rev("v26.9.1.1-new^{commit}") == self.released,
            "the release tag is not at the released commit",
        )
        # The branch is cut from the released commit rather than master's tip, so
        # the tag and the branch cannot end up on different commits.
        check(
            self.rev("26.8^") == self.released,
            "the 26.8 bump is not a child of the released commit",
        )
        check(
            "SET(VERSION_DESCRIBE v26.8.1.1-lts)" in self.show("26.8", VERSIONS_FILE),
            "the 26.8 version file does not describe 26.8.1.1-lts",
        )
        for ref in ("master", "26.8"):
            names = self.show(ref, CONTRIBUTORS_FILE).count('",')
            check(names > 1, f"{ref} contributors list has {names} names, want > 1")
        # A bump authored by the runner rather than the release robot adds a contributor
        # per release, so the next rerun rewrites the contributors file and pushes again.
        for ref in ("master", "26.8"):
            author = git("log", "-1", "--format=%an", ref, cwd=self.origin)
            check(author == ROBOT_NAME, f"{ref} bump is authored by [{author}], not {ROBOT_NAME}")

        gh_log = self.stub_log("gh")
        # The target has to be read off the create itself. The reuse lookup that
        # precedes it names the same branch, so a whole-log match for a flag would
        # hold even with no create at all.
        creates = [line for line in gh_log.splitlines() if "pr create" in line]
        check(len(creates) == 1, f"want exactly one `pr create`, got {len(creates)}")
        create = creates[0] if creates else ""
        # Only the cut branch is an LTS line, so its label is there exactly when the
        # release type was read from it rather than from the bumped master. An absent
        # `--base` is the repository default branch, which is master.
        for flag, want in (
            ("--repo", ([REPO],)),
            ("--head", (["26.8"],)),
            ("--label", (["release", "release-lts"],)),
            ("--base", ([], ["master"])),
        ):
            got = sorted(flag_values(create, flag))
            check(
                got in want,
                f"the release PR was created with {flag} {got}, want one of {list(want)}",
            )
        # The backport labels the cut branch needs before anything can be backported
        # to it. A request creates a label only if endpoint, method, name and color
        # all hold, so all four are matched; compared as a list, so a duplicate of one
        # call is not a match for the other.
        labels = []
        for line in gh_log.splitlines():
            tokens = line.split()
            if tokens[:1] == ["api"]:
                fields = api_fields(line)
                labels.append((
                    tokens[1],
                    api_method(line),
                    fields.get("name", ""),
                    fields.get("color", ""),
                ))
        want_labels = [
            (f"repos/{REPO}/labels", "POST", "v26.8-affected", "c2bfff"),
            (f"repos/{REPO}/labels", "POST", "v26.8-must-backport", "10dbed"),
        ]
        check(
            sorted(labels) == want_labels,
            f"the backport labels created were {sorted(labels)}, want {want_labels}",
        )
        reads = [line for line in self.stub_log("aws").splitlines() if "get-parameter" in line]
        check(
            len(reads) == 1 and flag_value(reads[0], "--name") == ROBOT_TOKEN_PARAM,
            f"want exactly one SSM read, of {ROBOT_TOKEN_PARAM}, got {reads}",
        )
        self.master = self.rev("master")
        self.branch = self.rev("26.8")

    def rerun_is_noop(self, check):
        """Rerunning the bump changes nothing, on master and on the cut branch."""
        clone = self.complete_clone("run2", check)
        rc, out = self.run_release(
            clone, "ci/jobs/scripts/create_release.py", "--create-bump-version-pr"
        )
        check(rc == 0, f"rerun rc={rc}")
        check(self.rev("master") == self.master, "the rerun moved origin master")
        check(
            "master already at version [26.9.1.1]" in out,
            "the rerun did not report master as already bumped",
        )
        check(self.rev("26.8") == self.branch, "the rerun moved origin 26.8")
        check(
            "Version files already up to date on 26.8" in out,
            "the rerun did not report 26.8 as already bumped",
        )
        check(
            "Release PR already exists" in out,
            "the rerun did not reuse the existing release PR",
        )
        check(
            self.stub_log("gh").count("pr create") == 1,
            "the rerun created a second release PR",
        )

    def heal_non_fast_forward(self, check):
        """A push rejected because master moved is healed by a rebase and retry, and
        the replayed bump keeps the githash of the tip it resynchronized to."""
        git("update-ref", "refs/heads/master", self.advanced, cwd=self.origin)
        clone = self.complete_clone("run3", check)

        # Advance origin between the bump commit and its push, which is the race the
        # rebase loop exists for. Restricted to a commit made on `master` and fired
        # once, so it lands in the window of the push under test and the retry that
        # follows is not rejected in turn.
        interloper_repo = self.root / "interloper"
        git("clone", "-q", str(self.origin), str(interloper_repo), cwd=self.root)
        for key, value in IDENTITY:
            git("config", key, value, cwd=interloper_repo)
        git("config", "core.hooksPath", str(interloper_repo / ".git/hooks"),
            cwd=interloper_repo)
        marker = self.root / "interloper.done"
        hook = Path(clone, ".git/hooks/post-commit")
        hook.write_text(
            f'#!/bin/sh\n[ -e "{marker}" ] && exit 0\n'
            '[ "$(git rev-parse --abbrev-ref HEAD)" = master ] || exit 0\n'
            f'touch "{marker}"\n'
            # githooks(5): a hook inherits GIT_DIR, so clear it before running git elsewhere.
            "unset $(git rev-parse --local-env-vars)\n"
            f'cd "{interloper_repo}" || exit 0\n'
            'printf "a backport landed\\n" >> README.md\n'
            f'git commit -q -a -m "{INTERLOPER_SUBJECT}"\n'
            "git push -q origin HEAD:refs/heads/master\n",
            encoding="utf-8",
        )
        hook.chmod(0o755)

        rc, out = self.run_release(
            clone, "ci/jobs/scripts/create_release.py", "--create-bump-version-pr"
        )
        check(rc == 0, f"heal rc={rc}")
        check(
            "Push to master rejected; re-syncing and retrying 1/" in out,
            "the push was never rejected, so the rebase loop was not exercised",
        )
        interloper = git("rev-parse", "HEAD", cwd=interloper_repo)
        check(interloper != self.advanced, "the interloper hook never committed")
        check(
            git_ok("merge-base", "--is-ancestor", interloper, "master", cwd=self.origin),
            "the interloping commit is not an ancestor of origin master",
        )
        check(
            git("log", "-1", "--format=%s", "master^", cwd=self.origin) == INTERLOPER_SUBJECT,
            "the bump was not rebased on top of the interloping commit",
        )
        check(
            "a backport landed" in self.show("master", "README.md"),
            "the interloping commit's content did not survive the push",
        )
        check(self.rev("26.8") == self.branch, "the heal moved origin 26.8")
        # The rebase replays the bump commit unchanged, so the githash stays the tip
        # it resynchronized to, neither the released commit nor the interloper.
        check(
            f"SET(VERSION_GITHASH {self.advanced})" in self.show("master", VERSIONS_FILE),
            "the healed bump does not carry the resynchronized master tip as githash",
        )


def main():
    stopwatch = Utils.Stopwatch()
    Path(REPO_ROOT, "ci/tmp").mkdir(parents=True, exist_ok=True)
    env_file = Path(_Environment.file_name_static())
    if not env_file.is_file():
        _Environment.get()
    env_before = env_file.read_text(encoding="utf-8")
    setup_env = Path(REPO_ROOT, "ci/tmp/praktika_setup_env.sh")
    setup_env_before = setup_env.is_file()

    log = f"{REPO_ROOT}/ci/tmp/release_e2e.log"
    Path(log).write_text("", encoding="utf-8")
    root = Path(tempfile.mkdtemp(prefix="release-e2e-"))
    e2e = ReleaseE2E(root, log)
    try:
        e2e.phase("new: build the throwaway origin", lambda check: e2e.build_origin())
        e2e.phase("new: fixture preconditions", e2e.preconditions)
        e2e.phase("new: release job pushes the bump to master", e2e.bump_is_pushed)
        e2e.phase("new: rerunning the bump is a no-op", e2e.rerun_is_noop)
        e2e.phase("new: non-fast-forward heal", e2e.heal_non_fast_forward)
    finally:
        shutil.rmtree(root, ignore_errors=True)

    def isolation_held(check):
        check(
            env_file.read_text(encoding="utf-8") == env_before,
            "an inner run rewrote this job's environment file",
        )
        check(
            setup_env.is_file() or not setup_env_before,
            "an inner run's cleanup step deleted this job's env script",
        )

    e2e.phase("new: the inner runs left this job's state alone", isolation_held)
    Result.create_from(
        results=e2e.results, stopwatch=stopwatch, files=[log]
    ).complete_job()


if __name__ == "__main__":
    main()

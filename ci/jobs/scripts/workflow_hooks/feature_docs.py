import sys

from praktika.info import Info

from ci.jobs.scripts.workflow_hooks.pr_labels_and_category import Labels

# Files that contain embedded documentation as part of their definitions
embedded_doc_files = [
    "src/Common/ProfileEvents.cpp",
    "src/Common/CurrentMetrics.cpp",
]

# Directories where source files may contain inline documentation
# (e.g. FunctionDocumentation structs registered with function factories)
inline_doc_paths = [
    "src/Functions/",
    "src/AggregateFunctions/",
    "src/TableFunctions/",
]

# File name suffixes that indicate embedded documentation
# (e.g. settings files with DECLARE macros containing description strings)
# Settings.cpp files declare the per-setting DECLARE(...) macros for Settings/ServerSettings,
# whereas the format settings put DECLARE(...) blocks in FormatFactorySettings.h.
embedded_doc_suffixes = [
    "Settings.cpp",
    "Settings.h",
]

# Source paths that feed autogenerated Mintlify reference pages. Keep this list
# shared with the docs job digest so a source-only documentation change cannot
# reuse a cached docs result.
source_owned_doc_files = embedded_doc_files + [
    "src/Common/AsynchronousMetrics.cpp",
    "src/Interpreters/ServerAsynchronousMetrics.cpp",
    "src/Coordination/KeeperAsynchronousMetrics.cpp",
]

source_owned_doc_paths = inline_doc_paths + [
    "src/Databases/",
    "src/DataTypes/",
    "src/Processors/Formats/",
    "src/Storages/",
]

source_owned_doc_globs = [
    f"src/**/*{suffix}" for suffix in embedded_doc_suffixes
]

SOURCE_OWNED_DOC_DIGEST_PATHS = [
    *(f"./{file}" for file in source_owned_doc_files),
    *(f"./{path.rstrip('/')}" for path in source_owned_doc_paths),
    *(f"./{glob}" for glob in source_owned_doc_globs),
]


def file_contains_marker(file_path, marker):
    """Check if a file contains the given marker string."""
    try:
        with open(file_path) as f:
            content = f.read()
        return marker in content
    except OSError:
        return False


def check_docs():
    info = Info()
    if Labels.PR_FEATURE in info.pr_labels:
        changed_files = info.get_kv_data("changed_files")
        assert changed_files is not None, (
            "changed_files is not populated in JOB_KV_DATA: the store_data pre-hook "
            "most likely failed to fetch the PR file list from the GitHub API. "
            "See the Config Workflow logs for the underlying error."
        )
        has_doc_changes = any(
            file.startswith("docs/")
            or file in embedded_doc_files
            or (
                any(file.startswith(path) for path in inline_doc_paths)
                and file_contains_marker(file, "FunctionDocumentation")
            )
            or (
                any(file.endswith(suffix) for suffix in embedded_doc_suffixes)
                and (
                    file_contains_marker(file, "DECLARE_SETTING")
                    or file_contains_marker(file, "DECLARE(")
                )
            )
            for file in changed_files
        )
        if not has_doc_changes:
            print(
                "No documentation changes found, please update the documentation"
            )
            return False
    return True


if __name__ == "__main__":
    if not check_docs():
        sys.exit(1)

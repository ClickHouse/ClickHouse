"""The settings-history check: what a diff of the settings declaration files does to the change history of the
settings, and whether it records the changes made now under the current version.

The history records are trailing arguments of the setting declarations:

    DECLARE(Bool, x, true, R"(...)", 0,
        {"26.5", false, true, "Enable by default"},
        {"25.12", false, false, "New setting"})

Rules, for the current version from cmake/autogenerated_versions.txt:

A. A declaration (`DECLARE`, `DECLARE_WITH_ALIAS`, `MAKE_OBSOLETE*`) that is added, or whose default text changed,
   must have a record with the current version. Reverting a default changes the default text too.
B. A record that was removed, or whose values were edited, requires the setting to have a record with the current
   version, unless the setting itself is removed. Reason-only edits are exempt. This keeps a default change from
   being hidden by deleting or editing the record that announced it.
C. Adding a record under an older version is always allowed (backports, corrections of what an older release
   recorded).

A default that moves through a constant defined elsewhere is caught at runtime by 03999_stateless_settings_history,
which requires the newest recorded new_value of every setting to equal its default.

The result depends only on the diff, the final files and the current version, so it is the same in CI, where the
diff comes from the PR, and locally:

    python3 -m ci.jobs.scripts.settings_history [--base blessed/master]

checks `git diff <base>` of the declaration files, uncommitted changes included, against the working tree.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

# The files that declare the settings, and the namespace (`system.settings_changes.type`) of each.
SETTINGS_DECLARATION_FILES = {
    "src/Core/Settings.cpp": "Session",
    "src/Core/FormatFactorySettings.h": "Session",
    "src/Storages/MergeTree/MergeTreeSettings.cpp": "MergeTree",
}

_HUNK_RE = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")
_DECLARATION_RE = re.compile(
    r"^\s*(DECLARE_WITH_ALIAS|DECLARE|MAKE_OBSOLETE_MERGE_TREE_SETTING|MAKE_OBSOLETE"
    r"|MAKE_DEPRECATED_BY_SERVER_CONFIG)\((.*)$"
)
# `{"26.5", false, true, "reason"}, \` - a trailing argument of a setting declaration.
_RECORD_RE = re.compile(r'^\s*(\{\s*"(\d+(?:\.\d+)+)"\s*,.*\})\s*[,)]?\s*\\?\s*$')


def parse_declaration_header(line):
    """`(name, default)` of the line that opens a setting declaration, or None.

    `DECLARE(Type, name, default, R"(...` and `DECLARE_WITH_ALIAS` name the setting in the second argument,
    `MAKE_OBSOLETE(M, Type, name, default)` and friends in the third. The arguments are read up to the default."""
    m = _DECLARATION_RE.match(line)
    if not m:
        return None
    macro, rest = m.group(1), m.group(2)
    name_index = 2 if macro.startswith("MAKE_") else 1
    args, current, depth, i = [], "", 0, 0
    while i < len(rest) and len(args) < name_index + 2:
        c = rest[i]
        if c == '"':
            end = i + 1
            while end < len(rest) and rest[end] != '"':
                end += 2 if rest[end] == "\\" else 1
            current += rest[i : end + 1]
            i = end + 1
            continue
        if c in "({":
            depth += 1
        elif c in ")}":
            if depth == 0:
                break
            depth -= 1
        if c == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += c
        i += 1
    if current.strip() and len(args) < name_index + 2:
        args.append(current.strip())
    if len(args) <= name_index:
        return None
    return args[name_index], args[name_index + 1] if len(args) > name_index + 1 else ""


def parse_record(line):
    """`(version, signature)` of a history record line, or None. The signature is the record with its reason
    blanked, so a reason-only edit keeps it."""
    m = _RECORD_RE.match(line)
    if not m:
        return None
    signature = re.sub(r'"(?:[^"\\]|\\.)*"(?=[^"]*\}$)', '""', m.group(1))
    return m.group(2), re.sub(r"\s+", "", signature)


def _declaration_before(file_lines, lineno):
    """Name of the declaration that the 1-based `lineno` of `file_lines` belongs to, or None."""
    for i in range(min(lineno, len(file_lines)) - 1, -1, -1):
        header = parse_declaration_header(file_lines[i])
        if header:
            return header[0]
    return None


def _record_versions(file_lines, name):
    versions, inside = [], False
    for line in file_lines:
        header = parse_declaration_header(line)
        if header:
            inside = header[0] == name
            continue
        record = parse_record(line) if inside else None
        if record:
            versions.append(record[0])
    return versions


def parse_declaration_changes(files):
    """What a change does to the settings history, given `{path: (patch, final_file_lines)}` for every changed file
    of `SETTINGS_DECLARATION_FILES`. Only names and versions are returned, never free text from the diff:

    - "declarations": `{"namespace", "name", "record_versions"}` of every declaration added or whose default text
      changed (rule A).
    - "records": `{"namespace", "name", "record_versions"}` of every setting with a record removed or value-edited
      (rule B), unless the setting itself was removed.

    `record_versions` are the versions of the records the setting has in the final files.

    A record line is attributed to the declaration it sits in: an added line through the final file, a removed line
    through the pre-change side of the hunk, starting from the final file at the line before the hunk, which the
    hunk does not change. A declaration moved within a file or between the files of one namespace is not a change."""
    added_records, removed_records = [], []
    added_headers, removed_headers = {}, {}  # (namespace, name) -> default text
    final_files = {}
    for path, (patch, file_lines) in files.items():
        namespace = SETTINGS_DECLARATION_FILES[path]
        final_files.setdefault(namespace, []).append(file_lines)
        new_lineno, old_owner, new_owner = None, None, None
        for line in patch.splitlines():
            hunk = _HUNK_RE.match(line)
            if hunk:
                new_lineno = int(hunk.group(1))
                old_owner = new_owner = _declaration_before(file_lines, new_lineno - 1)
                continue
            # File headers (`---`, `+++`) precede the first hunk; `\ No newline at end of file` has no content.
            if new_lineno is None or line.startswith("\\"):
                continue
            sign, text = line[:1], line[1:]
            header = parse_declaration_header(text)
            if sign in "+-":
                if header:
                    (added_headers if sign == "+" else removed_headers)[(namespace, header[0])] = header[1]
                record = parse_record(text)
                owner = new_owner if sign == "+" else old_owner
                if record and owner:
                    (added_records if sign == "+" else removed_records).append(
                        (namespace, owner, record[0], record[1])
                    )
            if header:
                if sign != "+":
                    old_owner = header[0]
                if sign != "-":
                    new_owner = header[0]
            if sign != "-":
                new_lineno += 1

    def with_versions(namespace, name):
        versions = []
        for file_lines in final_files[namespace]:
            versions += _record_versions(file_lines, name)
        return {"namespace": namespace, "name": name, "record_versions": versions}

    declarations = [
        with_versions(namespace, name)
        for (namespace, name), default in added_headers.items()
        if removed_headers.get((namespace, name), object()) != default
    ]
    deleted = {key for key in removed_headers if key not in added_headers}
    # A removed record re-added with the same values and version is a reason-only edit or a move.
    added_keys = set(added_records)
    edited = []
    for namespace, name, version, signature in removed_records:
        if (namespace, name, version, signature) in added_keys or (namespace, name) in deleted:
            continue
        if (namespace, name) not in edited:
            edited.append((namespace, name))
    return {
        "declarations": declarations,
        "records": [with_versions(namespace, name) for namespace, name in edited],
    }


def violations(changes, current_version):
    """The rule violations of `changes` (see `parse_declaration_changes`), one line each."""
    result = []
    for rule, what in (
        ("declarations", "was added or its default changed"),
        ("records", "had a record removed or its values edited"),
    ):
        for item in changes[rule]:
            if current_version not in item["record_versions"]:
                result.append(
                    f"  {item['namespace']} setting '{item['name']}' {what}, but it has no '{current_version}' record"
                )
    return sorted(set(result))


def violation_message(found, current_version):
    return (
        f"The settings history must record the changes made now under the current version ('{current_version}'): "
        f"add a record `{{\"{current_version}\", previous_value, new_value, \"reason\"}}` as the first trailing "
        f"argument of the setting's declaration. Records under older versions may be added freely (backports, "
        f"corrections):\n" + "\n".join(found)
    )


def current_version(root="."):
    text = (Path(root) / "cmake/autogenerated_versions.txt").read_text(encoding="utf-8")
    return "{}.{}".format(
        re.search(r"SET\(VERSION_MAJOR (\d+)\)", text).group(1),
        re.search(r"SET\(VERSION_MINOR (\d+)\)", text).group(1),
    )


def main():
    parser = argparse.ArgumentParser(description="Check the settings history of the working tree against a base.")
    parser.add_argument("--base", default="blessed/master", help="Revision to diff against (default: blessed/master)")
    args = parser.parse_args()
    # Diff from the merge base, as the PR patch in CI does: a two-endpoint diff against a base that moved
    # on would report the base's own changes as reversions made here.
    merge_base = subprocess.run(
        ["git", "merge-base", args.base, "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()
    files = {}
    for path in SETTINGS_DECLARATION_FILES:
        patch = subprocess.run(
            ["git", "diff", "--no-ext-diff", "-U3", merge_base, "--", path],
            check=True, capture_output=True, text=True,
        ).stdout
        if patch:
            files[path] = (patch, Path(path).read_text(encoding="utf-8").splitlines())
    version = current_version()
    found = violations(parse_declaration_changes(files), version)
    if found:
        print(violation_message(found, version))
        return 1
    print(f"OK: the settings history records every change made against {args.base} under '{version}'.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

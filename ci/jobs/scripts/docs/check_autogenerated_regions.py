#!/usr/bin/env python3
"""
Guard for the autogenerated regions of docs pages.

Reference pages under ``docs/`` embed machine-generated content between
``{/*AUTOGENERATED_START*/}`` and ``{/*AUTOGENERATED_END*/}`` markers (the MDX
comment form; the generators also emit prefixed variants such as
``AUTOGENERATED_METRICS_START``). That region is produced from the
documentation embedded in the ClickHouse source (``system.documentation``) by
``autogenerate/autogenerate_docs.py`` and is overwritten on every run -- so a
hand-edit to it is silently lost at the next regeneration.

This check fails a pull request that changes any line inside those markers.
Everything else stays editable: adding or removing whole pages, changing
frontmatter, and editing prose outside the markers are all allowed.

For each changed ``.mdx`` page it locates the marker regions (line ranges) in
the page at HEAD and asks whether any line the pull request touched falls
inside one. A newly added page is left alone -- its whole body is "new", and
adding pages is allowed; only an edit to an existing page's region is a
violation.

The docs-autogen bot, which commits regenerated regions, is exempted by the
``pr-autogenerated-docs`` label (handled by the CI wrapper, not here).
"""

import argparse
import json
import re
import subprocess
import sys

# MDX comment markers only. Legacy Markdown pages used the HTML-comment form
# (``<!--AUTOGENERATED_START-->``); those pages are being removed, so this guard
# matches the MDX form exclusively. ``AUTOGENERATED[A-Z_]*_START`` also covers
# prefixed variants like ``AUTOGENERATED_METRICS_START``.
START_RE = re.compile(r"\{/\*\s*AUTOGENERATED[A-Z_]*_START\s*\*/\}")
END_RE = re.compile(r"\{/\*\s*AUTOGENERATED[A-Z_]*_END\s*\*/\}")

_HUNK_RE = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")


def find_marker_regions(text):
    """Return marker regions as inclusive 1-based ``(start_line, end_line)``.

    ``start_line`` is the line holding the START marker and ``end_line`` the
    line holding the matching END marker, so the range covers both the markers
    and everything between them. An unbalanced trailing START (no following
    END) is ignored.
    """
    regions = []
    start_line = None
    for lineno, line in enumerate(text.splitlines(), start=1):
        if start_line is None:
            if START_RE.search(line):
                start_line = lineno
        elif END_RE.search(line):
            regions.append((start_line, lineno))
            start_line = None
    return regions


def parse_changed_lines(diff_text):
    """Return ``(changed, deleted_gaps)`` for a ``git diff --unified=0``.

    ``changed`` holds the new-file line numbers of added/modified runs: a run
    of ``n`` lines starting at ``s`` contributes ``s .. s+n-1``. ``deleted_gaps``
    holds pure deletions as gap positions: a deletion hunk anchored at new-file
    line ``s`` (git reports the surviving line before the gap) contributes
    ``s``, meaning "lines were removed between new lines ``s`` and ``s+1``".
    """
    changed = set()
    deleted_gaps = set()
    for line in diff_text.splitlines():
        m = _HUNK_RE.match(line)
        if not m:
            continue
        new_start = int(m.group(1))
        new_count = 1 if m.group(2) is None else int(m.group(2))
        if new_count == 0:
            deleted_gaps.add(new_start)
        else:
            changed.update(range(new_start, new_start + new_count))
    return changed, deleted_gaps


def region_touched(regions, changed_lines, deleted_gaps=()):
    """True if any changed line falls within any (inclusive) region range, or
    lines were deleted from a region's interior.

    A deletion gap after new line ``g`` touched a region only when the gap is
    interior (``start <= g < end``): deleting the line just above the START
    marker leaves a gap at ``start - 1`` and deleting the line just below the
    END marker leaves one at ``end``, and neither changes region content --
    anchoring deletions to the neighbouring line in either direction would
    misreport exactly those edits."""
    return any(
        start <= line <= end for start, end in regions for line in changed_lines
    ) or any(
        start <= gap < end for start, end in regions for gap in deleted_gaps
    )


def find_violations(changed_files, read_head, changed_lines, exists_at_base):
    """Return the sorted list of pages whose autogenerated region was edited.

    ``read_head(path)`` returns the page contents at HEAD (or ``None`` if it was
    deleted), ``changed_lines(path)`` the set of new-file line numbers the pull
    request touched, and ``exists_at_base(path)`` whether the page already
    existed at the base (so newly added pages are skipped).
    """
    violations = []
    for path in changed_files:
        path = path.strip().removeprefix("./")
        if not path.endswith(".mdx"):
            continue
        head_text = read_head(path)
        if head_text is None:
            continue  # Deleted page: removing a whole page is allowed.
        if not exists_at_base(path):
            continue  # Newly added page: adding pages is allowed.
        regions = find_marker_regions(head_text)
        if not regions:
            continue
        changed, deleted_gaps = changed_lines(path)
        if region_touched(regions, changed, deleted_gaps):
            violations.append(path)
    return sorted(violations)


def format_message(violations):
    lines = [
        "The content between the {/*AUTOGENERATED_START*/} and",
        "{/*AUTOGENERATED_END*/} markers is generated from the ClickHouse",
        "source (system.documentation) and is overwritten on every",
        "regeneration -- edits made to it here are lost.",
        "",
        "Edit the documentation in the defining C++ source instead; the",
        "docs-autogen bot regenerates these regions.",
        "",
        "Pages with edited autogenerated regions:",
    ]
    lines.extend(f"    {f}" for f in violations)
    return "\n".join(lines)


def check_autogenerated_regions(
    changed_files, read_head, changed_lines, exists_at_base
):
    """Return True if no autogenerated region was edited, else False."""
    violations = find_violations(
        changed_files, read_head, changed_lines, exists_at_base
    )
    if not violations:
        print("OK: no edits to autogenerated regions.")
        return True
    print("Edits to autogenerated regions detected:\n")
    print(format_message(violations))
    return False


def parse_file_patch(patch):
    """From one file's unified-diff ``patch`` (as the GitHub pulls/files API
    returns it), return ``(changed_lines, deleted_gaps, removed_marker)``: the
    new-file line numbers the patch touches, the gap positions of removed
    lines ("after new line ``g``", same convention as ``parse_changed_lines``),
    and whether it removes an AUTOGENERATED marker line -- deleting the markers
    and replacing the region with prose must not be a way to bypass the
    guard."""
    changed = set()
    deleted_gaps = set()
    removed_marker = False
    new_lineno = None
    for line in (patch or "").splitlines():
        if line.startswith("@@"):
            m = _HUNK_RE.match(line)
            if not m:
                new_lineno = None
                continue
            new_start = int(m.group(1))
            new_count = 1 if m.group(2) is None else int(m.group(2))
            # A deletion-only hunk is anchored at the surviving line BEFORE the
            # gap, while a hunk with content starts at its first new line.
            # Normalize so ``gap = new_lineno - 1`` holds for every '-' line.
            new_lineno = new_start + (1 if new_count == 0 else 0)
        elif new_lineno is None:
            continue
        elif line.startswith("+"):
            changed.add(new_lineno)
            new_lineno += 1
        elif line.startswith("-"):
            # A removed line has no new-file line; record the gap between the
            # surrounding surviving lines and note marker removals.
            if START_RE.search(line) or END_RE.search(line):
                removed_marker = True
            deleted_gaps.add(new_lineno - 1)
        elif line.startswith("\\"):
            continue  # "\ No newline at end of file"
        else:
            new_lineno += 1  # context line
    return changed, deleted_gaps, removed_marker


def pr_file_diffs(repo, pr):
    """Return ``{path: {...}}`` for every file in the pull request, from the
    GitHub pulls/files API. Paginated, so unlike ``gh pr diff`` (which GitHub
    rejects with HTTP 406 once a PR touches >300 files) it scales to large docs
    PRs. Returns None if the API call fails (the caller then fails closed)."""
    result = subprocess.run(
        ["gh", "api", "--paginate", "--slurp", f"repos/{repo}/pulls/{pr}/files"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stderr.strip(), file=sys.stderr)
        return None
    files = {}
    # --slurp wraps each response page in an outer list, so the output is
    # list[list[dict]]; flatten the pages before iterating the file objects.
    for obj in (o for page in json.loads(result.stdout) for o in page):
        status = obj.get("status")
        patch = obj.get("patch")
        entry = {
            "added": status == "added",
            "deleted": status == "removed",
            "changed": set(),
            "deleted_gaps": set(),
            "removed_marker": False,
            # GitHub omits ``patch`` when a diff is too large to inline. Without
            # it the line-level check cannot run, so a modified file with
            # content changes but no patch is "cannot verify" and must fail
            # closed. A pure rename also has no patch but changes == 0.
            "unverifiable": (status not in ("added", "removed")
                             and patch is None
                             and obj.get("changes", 0) != 0),
        }
        if not entry["added"] and not entry["deleted"] and patch is not None:
            (entry["changed"], entry["deleted_gaps"],
             entry["removed_marker"]) = parse_file_patch(patch)
        files[obj["filename"]] = entry
    return files


# The tree autogenerate_docs.py owns: every generator writes only under
# docs/reference/. Marker regions elsewhere have other sources of truth --
# locale copies (docs/<locale>/reference/...) belong to the translation
# pipeline and quickstart pages to their own sync script -- so the guard,
# whose remediation is "edit the defining C++ source", must not block them.
GUARDED_PREFIX = "docs/reference/"


def find_violations_in_diff(diff_files, read_head):
    """Return the sorted list of ``.mdx`` pages whose autogenerated region was
    edited -- content changed between the markers, or a marker line removed.
    Added/deleted pages are skipped (adding and removing whole pages is fine)."""
    violations = []
    for path, info in diff_files.items():
        if (not path.startswith(GUARDED_PREFIX) or not path.endswith(".mdx")
                or info["added"] or info["deleted"]):
            continue
        if info.get("unverifiable"):
            # No patch payload for this modified page (diff too large to
            # inline). If the page has protected regions, the edit may have
            # touched one and there is no way to tell, so fail closed; a page
            # without markers cannot violate the guard, and prose-only edits
            # stay allowed. (A patchless edit that also removed the markers is
            # indistinguishable from a page that never had them.)
            head_text = read_head(path)
            if head_text is None or find_marker_regions(head_text):
                print(f"cannot verify {path}: GitHub returned no patch for it"
                      " (diff too large); treating as a violation.")
                violations.append(path)
            continue
        if info["removed_marker"]:
            violations.append(path)
            continue
        head_text = read_head(path)
        if head_text is None:
            continue
        regions = find_marker_regions(head_text)
        if regions and region_touched(regions, info["changed"],
                                      info.get("deleted_gaps", ())):
            violations.append(path)
    return sorted(violations)


def check_pr(repo, pr, read_head):
    """Return True if the pull request edits no autogenerated region, else False
    (fail closed when the file list cannot be fetched)."""
    diff_files = pr_file_diffs(repo, pr)
    if diff_files is None:
        print("Error: could not fetch the PR file list, cannot run the check.")
        return False
    violations = find_violations_in_diff(diff_files, read_head)
    if not violations:
        print("OK: no edits to autogenerated regions.")
        return True
    print("Edits to autogenerated regions detected:\n")
    print(format_message(violations))
    return False


def _run_git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True)


def _resolve_base_ref(base_branch):
    """Return the merge-base of HEAD and ``origin/<base_branch>``.

    Raises if the base cannot be resolved so the caller can fail closed rather
    than silently pass a pull request whose base is unknown.
    """
    remote_ref = f"origin/{base_branch}"
    result = _run_git("merge-base", "HEAD", remote_ref)
    if result.returncode != 0:
        raise RuntimeError(
            f"cannot resolve the base ref '{remote_ref}': {result.stderr.strip()}"
        )
    return result.stdout.strip()


def git_readers(base_branch):
    """Build the (read_head, changed_lines, exists_at_base) git-backed callables.

    Diffs against the merge-base of HEAD and ``origin/<base_branch>``; raises
    ``RuntimeError`` if that base cannot be resolved so the caller can fail
    closed.
    """
    base_ref = _resolve_base_ref(base_branch)

    def read_head(path):
        try:
            with open(path, encoding="utf-8") as f:
                return f.read()
        except FileNotFoundError:
            return None

    def changed_lines(path):
        diff = _run_git("diff", "--unified=0", base_ref, "--", path)
        return parse_changed_lines(diff.stdout)

    def exists_at_base(path):
        return _run_git("cat-file", "-e", f"{base_ref}:{path}").returncode == 0

    return read_head, changed_lines, exists_at_base


def _read_changed_files(args):
    if args.changed_file:
        return args.changed_file
    return [line.strip() for line in sys.stdin.read().splitlines() if line.strip()]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--base-branch",
        required=True,
        help="Pull request base branch; the guard diffs against the merge-base "
        "of HEAD and origin/<base-branch>.",
    )
    p.add_argument(
        "--changed-file",
        action="append",
        default=[],
        help="A changed file path (repeatable). If omitted, newline-separated "
        "paths are read from stdin.",
    )
    args = p.parse_args(argv)
    read_head, changed_lines, exists_at_base = git_readers(args.base_branch)
    ok = check_autogenerated_regions(
        _read_changed_files(args), read_head, changed_lines, exists_at_base
    )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
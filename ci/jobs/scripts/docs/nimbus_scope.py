"""Build scope for Nimbus docs previews.

Derives which locale trees a preview build must include from the PR's changed
files. English-only edits build English only; a change under `docs/<locale>/`,
`docs/snippets/<locale>/` or to the translation lock adds that locale; a change
to the site's own sources or configuration builds every locale. The
autogenerated reference pages are never part of a preview (they need no
preview, and building them would need a `clickhouse` binary).
"""

import json

LOCALES = ["ar", "es", "fr", "ja", "ko", "pt-BR", "ru", "zh"]

# Paths whose change invalidates every locale.
ALL_LOCALES_TRIGGERS = (
    "docs/src/",
    "docs/bin/",
    "docs/astro.config.ts",
    "docs/package.json",
    "docs/pnpm-lock.yaml",
    "docs/snippets/components/",
    "docs/gt.config.json",
)


def compute_scope(changed_files):
    """Return the preview scope dict for `docs/.preview-scope.json`."""
    locales = set()
    if changed_files is None or any(f.startswith(ALL_LOCALES_TRIGGERS) for f in changed_files):
        locales.update(LOCALES)
    else:
        for f in changed_files:
            for locale in LOCALES:
                if f.startswith((f"docs/{locale}/", f"docs/snippets/{locale}/")):
                    locales.add(locale)
            if f == "docs/gt-lock.json":
                locales.update(LOCALES)
    return {
        "locales": ["en"] + sorted(locales),
        # Previews never carry the binary-derived reference pages.
        "reference": False,
    }


def scope_to_env(scope):
    """Environment variables the site's build reads (see docs/bin/scope.ts)."""
    non_english = [l for l in scope["locales"] if l != "en"]
    env = {"DOCS_LOCALES": ",".join(non_english)}
    if not scope.get("reference", True):
        env["DOCS_REFERENCE"] = "off"
    return env


if __name__ == "__main__":
    import sys

    files = [line.strip() for line in sys.stdin if line.strip()]
    print(json.dumps(compute_scope(files), indent=2))

#!/usr/bin/env python3
"""
Shared helpers for the catalog-domain generators (table engines, database
engines, data types, formats): frontmatter parsing/synthesis, matching system
catalog names to existing pages, and rendering the `| Page | Description |`
listing tables on index pages.
"""

import datetime
import os
import re
from pathlib import Path

FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n?", re.DOTALL)

BADGE_RE = re.compile(
    r'<Badge className="autogenerated-notice"[^>]*>'
    r'Auto-generated: (\d{4}-\d{2}-\d{2})</Badge>'
)


def badge(source, date=None):
    """The provenance badge shown at the bottom of generated pages.

    `source` is kept for call-site compatibility (and documents which system
    table a page is generated from) but is no longer rendered: the badge is
    the minimal, styleable `autogenerated-notice` marker."""
    date = date or datetime.date.today().isoformat()
    return (
        '<Badge className="autogenerated-notice" size="xs" icon="edit" '
        f'color="gray">Auto-generated: {date}</Badge>'
    )


# Inverse of `composeMarkdown` in src/Storages/System/StorageSystemDocumentation.cpp:
# the assembled `description` is the trimmed base description followed by
# machine-appended blocks in a fixed shape and order. Peel them off the end,
# last block first.
_RELATED_RE = re.compile(r"\n\n\*\*Related:\*\* (`[^`\n]+`(?:, `[^`\n]+`)*)\Z")
_INTRODUCED_RE = re.compile(r"\n\n\*\*Introduced in:\*\* ([^\n]+)\Z")
_EXAMPLES_TOKEN = "\n\n**Examples**\n\n"
_SYNTAX_TOKEN = "\n\n**Syntax**\n\n```sql\n"


def split_assembled(description, peel_examples=True):
    """Split a `system.documentation` description back into its structured
    parts: {body, syntax, examples, introduced_in, related}.

    An `**Examples**` block is textually ambiguous: authors also write one
    inline in the description itself (e.g. the `Date32` data type), which the
    peel cannot distinguish from a machine-appended `examples` field. Callers
    whose domain never registers a separate `examples` field pass
    `peel_examples=False` to keep such blocks in the body."""
    parts = {"syntax": "", "examples": "", "introduced_in": "", "related": []}
    text = description.rstrip("\n")
    m = _RELATED_RE.search(text)
    if m:
        parts["related"] = [x.strip("`") for x in m.group(1).split(", ")]
        text = text[: m.start()]
    m = _INTRODUCED_RE.search(text)
    if m:
        parts["introduced_in"] = m.group(1)
        text = text[: m.start()]
    if peel_examples:
        at = text.rfind(_EXAMPLES_TOKEN)
        if at != -1:
            parts["examples"] = text[at + len(_EXAMPLES_TOKEN):]
            text = text[:at]
    at = text.rfind(_SYNTAX_TOKEN)
    if at != -1 and text.endswith("\n```"):
        parts["syntax"] = text[at + len(_SYNTAX_TOKEN): -len("\n```")]
        text = text[:at]
    parts["body"] = text
    return parts


def reconcile_badge_date(current, new):
    """Keep the committed badge date when the regenerated content is otherwise
    identical, so the date only advances when the content actually changes
    (otherwise every run would churn all pages and --check would always
    drift)."""
    m_cur = BADGE_RE.search(current)
    m_new = BADGE_RE.search(new)
    if not m_cur or not m_new:
        return new
    candidate = new[: m_new.start(1)] + m_cur.group(1) + new[m_new.end(1):]
    return candidate if candidate == current else new


def full_transform(migrate, body, title, src_docu, dest, lk):
    """The Docusaurus->Mintlify body transform sequence migrate.py runs on a
    migrated page, applied to an embedded full-page description. Delegates to
    migrate.transform_body (the single source of truth) so generated pages are
    transformed identically to migrated ones. Verified to reproduce the
    migrated pages byte-for-byte (modulo genuine docs<->C++ content drift).

    `inject_imports=False`: the transformed body is embedded into synthesized
    frontmatter by the caller, so runnable/image imports (which must sit at the
    page top) are not injected here."""
    return migrate.transform_body(
        body, lk, [],
        title=title,
        source_docu_path=Path(src_docu),
        source_docu_file=src_docu,
        dest_path=Path(dest),
        inject_imports=False,
        # Apply the migrator's per-file override for this docusaurus source, so
        # patterns that don't map to a generic transform (e.g. the JSON page's
        # <Link><CardSecondary/></Link>, which uses the unmapped @docusaurus/Link)
        # are rewritten in the generated page exactly as in the migrated one.
        override_key=src_docu,
    )


def _quote_closed(value, quote):
    """Whether a quoted scalar is closed at the end of `value` (the text after
    the opening quote). In single-quoted scalars `''` is an escaped quote, not
    a close-and-reopen."""
    value = value.rstrip()
    if quote == "'":
        return value.replace("''", "").endswith("'")
    return value.endswith('"') and not value.endswith('\\"')


def parse_frontmatter(page):
    """Parse the frontmatter subset the migrated pages use: `key: value` with
    optional single/double quotes (a quoted scalar may continue over the
    following lines until the line that closes the quote), unquoted values
    folded onto indented continuation lines, and inline `[a, b]` arrays.
    Returns {} when there is none."""
    match = FRONTMATTER_RE.match(page)
    if not match:
        return {}
    lines = match.group(1).split("\n")
    fm = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if line[:1].isspace() or ":" not in line or line.startswith("#"):
            continue
        key, value = line.split(":", 1)
        key = key.strip()
        value = value.strip()
        if value[:1] in ("'", '"') and not _quote_closed(value[1:], value[0]):
            # A quoted scalar continues until the line that closes the quote.
            # YAML folds the line breaks: each becomes a space, except that a
            # run of blank lines becomes that many newlines.
            quote = value[0]
            parts = [value[1:]]
            while i < len(lines) and not _quote_closed("\n".join(parts), quote):
                parts.append(lines[i].strip())
                i += 1
            folded = parts[0]
            breaks = 0
            for part in parts[1:]:
                if part:
                    folded += ("\n" * breaks if breaks else " ") + part
                    breaks = 0
                else:
                    breaks += 1
            if _quote_closed("\n".join(parts), quote):
                folded = folded.rstrip()[:-1]
            fm[key] = folded.replace("''", "'") if quote == "'" else folded
            continue
        if value.startswith("[") and not value.endswith("]"):
            # An inline array may also continue over the following lines,
            # until the line that closes the bracket.
            while i < len(lines) and not value.endswith("]"):
                value += " " + lines[i].strip()
                value = value.rstrip()
                i += 1
        # Join folded continuation lines (indented) onto the value.
        while i < len(lines) and lines[i][:1].isspace() and lines[i].strip():
            value += " " + lines[i].strip()
            i += 1
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            items = [v.strip().strip("'\"") for v in value[1:-1].split(",")]
            fm[key] = [v for v in items if v]
        elif value.startswith("'") and value.endswith("'") and len(value) >= 2:
            fm[key] = value[1:-1].replace("''", "'")
        else:
            fm[key] = value.strip('"')
    return fm


def yaml_quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def first_sentence(text):
    """First sentence of a description, single-line, for frontmatter."""
    text = " ".join(text.split())
    match = re.match(r"(.+?[.!?])(?:\s|$)", text)
    return (match.group(1) if match else text)[:300]


def normalize_name(name):
    """Key for matching a catalog name against a page filename: lowercase
    alphanumerics only, so `EmbeddedRocksDB` matches `embedded-rocksdb` and
    `AzureQueue` matches `azure-queue`."""
    return re.sub(r"[^a-z0-9]", "", name.lower())


def scan_pages(docs_dir, rel_dirs, exclude_dirs=()):
    """Index the existing pages of a domain: {normalized_basename: rel_path}.
    `rel_dirs` are docs-relative directories, scanned recursively; index and
    overview pages are skipped, as are subdirectories named in
    `exclude_dirs` (e.g. fully-generated groups that belong to another
    domain)."""
    index = {}
    for rel_dir in rel_dirs:
        root = os.path.join(docs_dir, rel_dir)
        # Iterate the walk lazily: pruning (and ordering) via in-place
        # `dirnames` assignment only affects traversal before descent.
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in exclude_dirs)
            for filename in sorted(filenames):
                if not filename.endswith(".mdx"):
                    continue
                stem = filename[: -len(".mdx")]
                if stem in ("index", "overview"):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, filename), docs_dir)
                index.setdefault(normalize_name(stem), rel)
    return index


def render_listing(docs_dir, page_ids):
    """Render the `| Page | Description |` table for an index page from the
    frontmatter of the listed pages (same data the legacy
    autogenerate-table-of-contents script used), in the given order."""
    lines = ["| Page | Description |", "|-----|-----|"]
    for page_id in page_ids:
        path = os.path.join(docs_dir, page_id + ".mdx")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as f:
            fm = parse_frontmatter(f.read())
        title = fm.get("title") or os.path.basename(page_id)
        description = " ".join(str(fm.get("description", "")).split())
        # Escape characters that would break the markdown table.
        title = title.replace("|", "\\|")
        description = description.replace("|", "\\|")
        lines.append(f"| [{title}](/{page_id}) | {description} |")
    return "\n".join(lines) + "\n"

#!/usr/bin/env python3
"""
Per-item description listings that fill the `AUTOGENERATED_DESCRIPTIONS` region
of system-table pages, built from the one-line summaries embedded in the source
and exposed by `system.documentation`.

`system.events` and `system.metrics` have one row per profiling event / current
metric, each with a short description; the reference pages render those as a
sorted list of `### <name> {#anchor}` sections. There are ~1300 profile events
and ~500 current metrics, so this is a single generated region per page rather
than a page per item (mirrors the `asynchronous_metrics` listing).
"""

import re


def slugify(name):
    """Anchor id matching the existing docs convention (see async_metrics)."""
    return re.sub(r"[^a-z0-9_]+", "", name.lower())


def render_descriptions(rows):
    """Render `rows` (a `system.documentation` name -> row mapping) as a sorted
    list of `### <name> {#anchor}` / description entries."""
    lines = []
    for name in sorted(rows):
        desc = rows[name]["description"].strip()
        if not desc:
            continue
        lines += [f"### {name} {{#{slugify(name)}}}", "", desc, ""]
    return "\n".join(lines).rstrip("\n")


# entity type in system.documentation -> the page whose descriptions region it fills
DOMAINS = [
    {"entity_type": "Profile Event", "dest_rel": "reference/system-tables/events.mdx"},
    {"entity_type": "Current Metric", "dest_rel": "reference/system-tables/metrics.mdx"},
]


def build_generators(docs_map):
    gens = []
    for domain in DOMAINS:
        gens.append({
            "name": f"descriptions:{domain['entity_type']}",
            "content": render_descriptions(docs_map.get(domain["entity_type"], {})),
            "dest": "docs/" + domain["dest_rel"],  # unused (no_transform)
            "dest_rel": domain["dest_rel"],
            "markers": "AUTOGENERATED_DESCRIPTIONS",
            "no_transform": True,
        })
    return gens

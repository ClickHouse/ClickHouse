#!/usr/bin/env python3
"""Self-contained tests for full-page system-table documentation generation."""

import importlib.util
import re
import tempfile
from importlib.machinery import SourceFileLoader
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[4]
GENERATOR = REPO_ROOT / "utils" / "generate-system-tables-docs"
DOCUMENTATION = (
    REPO_ROOT / "src" / "Storages" / "System" / "SystemTableDocumentation.inc"
)

EXPECTED_TEMPLATE_COUNT = 169
PLACEHOLDERS = {
    "{{SYSTEM_TABLE_COLUMNS}}": EXPECTED_TEMPLATE_COUNT,
    "{{PROFILE_EVENTS}}": 1,
    "{{CURRENT_METRICS}}": 1,
    "{{ASYNCHRONOUS_METRICS}}": 1,
}


def load_generator():
    loader = SourceFileLoader("generate_system_tables_docs", str(GENERATOR))
    spec = importlib.util.spec_from_file_location(
        "generate_system_tables_docs", GENERATOR, loader=loader
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    generator = load_generator()

    registry = DOCUMENTATION.read_text(encoding="utf-8")
    table_names = re.findall(r'^    \{"([^"]+)",$', registry, re.MULTILINE)
    assert len(table_names) == EXPECTED_TEMPLATE_COUNT
    assert len(table_names) == len(set(table_names))
    assert registry.count(')DOCS_MD",') == EXPECTED_TEMPLATE_COUNT
    assert set(re.findall(r"\{\{[A-Z_]+\}\}", registry)) == set(PLACEHOLDERS)
    for placeholder, expected_count in PLACEHOLDERS.items():
        assert registry.count(placeholder) == expected_count

    assert generator.DOC_FILENAMES == {
        "delta_lake_metadata_log": "delta_metadata_log.mdx",
        "warnings": "system_warnings.mdx",
    }

    frontmatter = """---
description: 'A table.'
title: 'system.example'
---
"""
    old_body = """
## Description {#description}

Old prose.

## Columns {#columns}

{/*AUTOGENERATED_START*/}
- `old` (`UInt8`)
{/*AUTOGENERATED_END*/}
"""
    full_body = """import Widget from '/widget.mdx';

## Description {#description}

Complete embedded prose.

## Columns {#columns}

- `value` ([UInt8](/reference/data-types/int-uint))

{/*AUTOGENERATED_METRICS_START*/}
### Metric {#metric}

Description.
{/*AUTOGENERATED_METRICS_END*/}"""

    temporary_root = REPO_ROOT / "tmp"
    temporary_root.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=temporary_root) as directory:
        page = Path(directory) / "example.mdx"
        page.write_text(frontmatter + old_body, encoding="utf-8")

        assert generator.update_full_doc_file(page, full_body)
        expected = (
            frontmatter
            + "\n"
            + generator.AUTOGENERATED_START
            + "\n"
            + full_body
            + "\n"
            + generator.AUTOGENERATED_END
            + "\n"
        )
        assert page.read_text(encoding="utf-8") == expected
        assert not generator.update_full_doc_file(page, full_body)

        created = Path(directory) / "created.mdx"
        generator.create_doc_file(
            created,
            "created",
            "A newly documented table.",
            "- `value` (`UInt8`)\n",
            full_body,
        )
        created_text = created.read_text(encoding="utf-8")
        assert generator.AUTOGENERATED_START + "\n" + full_body in created_text
        assert created_text.endswith(generator.AUTOGENERATED_END + "\n")

    print(
        f"OK: {len(table_names)} system-table templates are complete; "
        "full bodies replace and create pages deterministically"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

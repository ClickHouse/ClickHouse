#!/usr/bin/env python3
"""Verify full-page system-table regions retain refreshable column regions."""

import importlib.util
import tempfile
from importlib.machinery import SourceFileLoader
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[4]
GENERATOR = REPO_ROOT / "utils" / "generate-system-tables-docs"
DOCS = REPO_ROOT / "docs" / "reference" / "system-tables"
EXCLUDED = {
    "delta_lake_metadata_log",
    "histogram_metric_log",
    "information_schema",
    "overview",
    "warnings",
}


def load_generator():
    loader = SourceFileLoader("generate_system_tables_docs", str(GENERATOR))
    spec = importlib.util.spec_from_file_location(
        "generate_system_tables_docs", GENERATOR, loader=loader
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    generator = load_generator()
    pages = sorted(path for path in DOCS.glob("*.mdx") if path.stem not in EXCLUDED)
    assert len(pages) == 169

    for page in pages:
        content = page.read_text(encoding="utf-8")
        assert content.count(generator.AUTOGENERATED_START) == 1, page
        assert content.count(generator.AUTOGENERATED_END) == 1, page
        assert content.count(generator.AUTOGENERATED_COLUMNS_START) == 1, page
        assert content.count(generator.AUTOGENERATED_COLUMNS_END) == 1, page
        assert generator.generated_region_covers_page_body(content), page

    for page_name in EXCLUDED:
        content = (DOCS / f"{page_name}.mdx").read_text(encoding="utf-8")
        assert not generator.generated_region_covers_page_body(content), page_name

    temporary_root = REPO_ROOT / "tmp"
    temporary_root.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=temporary_root) as directory:
        page = Path(directory) / "existing.mdx"
        content = """---
title: 'system.existing'
---

import SystemTableCloud from '/snippets/_system_table_cloud.mdx';

<SystemTableCloud/>

{/*AUTOGENERATED_START*/}
## Description {#description}

Existing description.

## Columns {#columns}

{/*AUTOGENERATED_COLUMNS_START*/}
- `old` ([UInt8](/reference/data-types/int-uint))
{/*AUTOGENERATED_COLUMNS_END*/}

## Example {#example}

```sql
SELECT old FROM system.existing;
```
{/*AUTOGENERATED_END*/}
"""
        page.write_text(content, encoding="utf-8")
        assert generator.update_doc_file(
            page,
            "- `new` ([String](/reference/data-types/string))\n",
        )
        updated_content = page.read_text(encoding="utf-8")
        assert "Existing description." in updated_content
        assert "SELECT old FROM system.existing;" in updated_content
        assert "- `old`" not in updated_content
        assert "- `new` ([String](/reference/data-types/string))" in updated_content

        created = Path(directory) / "created.mdx"
        generator.create_doc_file(
            created,
            "created",
            "Created description.",
            "- `value` ([UInt8](/reference/data-types/int-uint))\n",
        )
        created_content = created.read_text(encoding="utf-8")
        assert created_content.count(generator.AUTOGENERATED_START) == 1
        assert created_content.count(generator.AUTOGENERATED_END) == 1
        assert created_content.count(generator.AUTOGENERATED_COLUMNS_START) == 1
        assert created_content.count(generator.AUTOGENERATED_COLUMNS_END) == 1
        assert generator.generated_region_covers_page_body(created_content)

    print("OK: 169 full-page system-table regions contain refreshable column regions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

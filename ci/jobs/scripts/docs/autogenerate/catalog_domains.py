#!/usr/bin/env python3
"""
Catalog-domain generators: table engines, database engines, data types, and
I/O formats, generated from the documentation embedded in the C++ source as
exposed by `system.documentation` (the unified source for all embedded docs;
the per-domain tables are queried only for non-documentation metadata such as
format input/output flags and data-type aliases).

Policy (pre-cutover): existing pages are never overwritten -- differences
between a page and the embedded documentation are reported as `CONTENT-DRIFT`
(the embedded copy and the docs must be reconciled before flipping to
source-wins). Items that are documented in the source (a full-page
`description`) but have no page get one created, plus a navigation entry.
Items with only a short summary and no page are counted as coverage gaps for
upstream enrichment, not created.

Also provides the listing-table generators that refresh the
`| Page | Description |` tables on the index pages between their
`AUTOGENERATED` markers, ordered by the navigation fragment (so the sidebar
and the tables stay consistent and new pages appear in both).
"""

import os
import sys

import catalog
import introspect
import navigation

# A description longer than this is a full page (the embedded copies of the
# documented items are whole page bodies); anything shorter is a stub that is
# not worth a page of its own yet.
FULL_PAGE_MIN_LEN = 500

# Known name -> page filename mismatches that the alphanumeric normalization
# cannot bridge.
TABLE_ENGINE_PAGE_OVERRIDES = {
    "ReplicatedMergeTree": "reference/engines/table-engines/mergetree-family/replication.mdx",
    "GenerateRandom": "reference/engines/table-engines/special/generate.mdx",
    # Documented together with `Executable` on a shared page.
    "ExecutablePool": "reference/engines/table-engines/special/executable.mdx",
}

DATA_TYPE_PAGE_OVERRIDES = {
    "Bool": "reference/data-types/boolean.mdx",
    "JSON": "reference/data-types/newjson.mdx",
    "Point": "reference/data-types/geo.mdx",
    "Nested": "reference/data-types/nested-data-structures/index.mdx",
    # These pages document a whole family; the named type carries the full
    # embedded body.
    "Float64": "reference/data-types/float.mdx",
    "Int32": "reference/data-types/int-uint.mdx",
    "IntervalDay": "reference/data-types/special-data-types/interval.mdx",
}

TABLE_ENGINE_DIRS = [
    "reference/engines/table-engines/mergetree-family",
    "reference/engines/table-engines/log-family",
    "reference/engines/table-engines/special",
    "reference/engines/table-engines/integrations",
]

FAMILY_NAV_GROUPS = {
    "mergetree-family": ["Engines", "Table Engines", "MergeTree Family"],
    "log-family": ["Engines", "Table Engines", "Log Family"],
    "special": ["Engines", "Table Engines", "Special"],
    "integrations": ["Engines", "Table Engines", "Integrations"],
}


def _engine_family(name):
    if name.endswith("MergeTree"):
        return "mergetree-family"
    if name in ("Log", "StripeLog", "TinyLog"):
        return "log-family"
    # Most newly added engines connect ClickHouse to an external system.
    print(f"WARN: table engine {name!r} not categorized, defaulting to"
          f" 'integrations' -- adjust the page/navigation placement if wrong",
          file=sys.stderr)
    return "integrations"


def _frontmatter(pairs):
    lines = ["---"]
    for key, value in pairs:
        lines.append(f"{key}: {value}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def _description_fm(migrate, description):
    return catalog.yaml_quote(
        catalog.first_sentence(migrate._strip_inline_markdown(description))
    )


def _item_generators(domain, rows, docs_dir, migrate):
    """Common per-domain flow: match rows to existing pages (content-drift),
    create pages for full-page items without one, count coverage gaps."""
    index = catalog.scan_pages(docs_dir, domain["dirs"],
                               exclude_dirs=domain.get("exclude_dirs", ()))
    gens = []
    gaps = []
    for row in rows:
        name = row["name"]
        if domain.get("skip") and domain["skip"](row):
            continue
        page_rel = domain.get("overrides", {}).get(name)
        if not page_rel:
            page_rel = index.get(catalog.normalize_name(name))
        if page_rel:
            page_path = os.path.join(docs_dir, page_rel)
            with open(page_path, encoding="utf-8") as f:
                fm = catalog.parse_frontmatter(f.read())
            slug = fm.get("slug") or "/" + page_rel[: -len(".mdx")]
            gens.append({
                "name": f"{domain['family']}:{name}",
                "method": "content-drift",
                "content": row["description"],
                "dest": f"docs{slug}.md",
                "dest_rel": page_rel,
                "title": fm.get("title"),
                "full_transform": True,
                "source": row.get("source", ""),
            })
        elif len(row["description"]) > FULL_PAGE_MIN_LEN:
            page_rel, nav_group, fm_text, title = domain["new_item"](row)
            gens.append({
                "name": f"{domain['family']}:{name}",
                "method": "content-drift",  # unused: the page does not exist
                "content": row["description"],
                "dest": f"docs/{domain['legacy_prefix']}/{os.path.basename(page_rel)[:-len('.mdx')]}.md",
                "dest_rel": page_rel,
                "create_frontmatter": fm_text,
                "badge": catalog.badge("system.documentation"),
                "title": title,
                "full_transform": True,
                "nav": (nav_group, page_rel[: -len(".mdx")]),
            })
        else:
            gaps.append(name)
    if gaps:
        print(f"note: {len(gaps)} {domain['family']} item(s) have no page and"
              f" only a short embedded description (upstream enrichment"
              f" queue): {', '.join(gaps)}", file=sys.stderr)
    return gens


def build_generators(docs_map, binary, docs_dir, migrate):
    def doc_rows(entity_type):
        # The documentation body with the machine-assembled tail peeled off;
        # for full-page items the body IS the page. The catalog domains never
        # register a separate `examples` field, so an `**Examples**` block is
        # always author-written body content (peel_examples=False).
        return [
            {
                "name": name,
                "description": catalog.split_assembled(
                    row["description"], peel_examples=False
                )["body"],
                "source": row["source"],
            }
            for name, row in sorted(docs_map.get(entity_type, {}).items())
        ]

    gens = []

    # --- Table engines ---
    def engine_new_item(row):
        name = row["name"]
        family = _engine_family(name)
        page_rel = f"reference/engines/table-engines/{family}/{name.lower()}.mdx"
        title = f"{name} table engine"
        fm_text = _frontmatter([
            ("description", _description_fm(migrate, row["description"])),
            ("sidebarTitle", catalog.yaml_quote(name)),
            ("slug", f"/engines/table-engines/{family}/{name.lower()}"),
            ("title", catalog.yaml_quote(title)),
            ("doc_type", "'reference'"),
        ])
        return page_rel, FAMILY_NAV_GROUPS[family], fm_text, title

    gens += _item_generators(
        {
            "family": "table-engines",
            "dirs": TABLE_ENGINE_DIRS,
            # The generated skipping-indexes group lives inside the MergeTree
            # family directory but belongs to another domain.
            "exclude_dirs": ("skipping-indexes",),
            "overrides": TABLE_ENGINE_PAGE_OVERRIDES,
            "legacy_prefix": "engines/table-engines",
            "new_item": engine_new_item,
        },
        doc_rows("Table Engine"),
        docs_dir,
        migrate,
    )

    # --- Database engines ---
    def db_engine_new_item(row):
        name = row["name"]
        page_rel = f"reference/engines/database-engines/{name.lower()}.mdx"
        title = f"{name} database engine"
        fm_text = _frontmatter([
            ("description", _description_fm(migrate, row["description"])),
            ("sidebarTitle", catalog.yaml_quote(name)),
            ("slug", f"/engines/database-engines/{name.lower()}"),
            ("title", catalog.yaml_quote(title)),
            ("doc_type", "'reference'"),
        ])
        return page_rel, ["Engines", "Database Engines"], fm_text, title

    gens += _item_generators(
        {
            "family": "database-engines",
            "dirs": ["reference/engines/database-engines"],
            "legacy_prefix": "engines/database-engines",
            "new_item": db_engine_new_item,
        },
        doc_rows("Database Engine"),
        docs_dir,
        migrate,
    )

    # --- Data types ---
    # Alias-ness is catalog metadata, not documentation; aliases are
    # documented on their target's page.
    data_type_aliases = {
        r["name"]: r["alias_to"]
        for r in introspect.fetch_rows(
            binary, "SELECT name, alias_to FROM system.data_type_families"
        )
    }

    def data_type_new_item(row):
        name = row["name"]
        page_rel = f"reference/data-types/{name.lower()}.mdx"
        print(f"WARN: data type {name!r} gets a page at the end of the"
              f" 'Data Types' navigation group -- move it into the right"
              f" category subgroup", file=sys.stderr)
        fm_text = _frontmatter([
            ("description", _description_fm(migrate, row["description"])),
            ("sidebarTitle", catalog.yaml_quote(name)),
            ("slug", f"/sql-reference/data-types/{name.lower()}"),
            ("title", catalog.yaml_quote(name)),
            ("doc_type", "'reference'"),
        ])
        return page_rel, ["Data Types"], fm_text, name

    gens += _item_generators(
        {
            "family": "data-types",
            "dirs": ["reference/data-types"],
            "overrides": DATA_TYPE_PAGE_OVERRIDES,
            "legacy_prefix": "sql-reference/data-types",
            "new_item": data_type_new_item,
            "skip": lambda row: data_type_aliases.get(row["name"]),
        },
        doc_rows("Data Type"),
        docs_dir,
        migrate,
    )

    # --- Formats ---
    format_families = sorted(
        d for d in os.listdir(os.path.join(docs_dir, "reference/formats"))
        if os.path.isdir(os.path.join(docs_dir, "reference/formats", d))
    )
    # Input/output capability is catalog metadata, not documentation.
    format_flags = {
        r["name"]: r
        for r in introspect.fetch_rows(
            binary, "SELECT name, is_input, is_output FROM system.formats"
        )
    }

    def format_new_item(row):
        name = row["name"]
        # Formats with a family folder (JSON*, CSV*, ...) go inside it.
        family = next(
            (d for d in sorted(format_families, key=len, reverse=True)
             if name.startswith(d)),
            None,
        )
        rel_dir = f"reference/formats/{family}" if family else "reference/formats"
        page_rel = f"{rel_dir}/{name}.mdx"
        nav_group = ["Formats", family] if family else ["Formats"]
        flags = format_flags.get(name, {})
        fm_text = _frontmatter([
            ("alias", "[]"),
            ("description", _description_fm(migrate, row["description"])),
            ("input_format", "true" if flags.get("is_input") else "false"),
            ("keywords", f"['{name}']"),
            ("output_format", "true" if flags.get("is_output") else "false"),
            ("slug", f"/interfaces/formats/{name}"),
            ("title", catalog.yaml_quote(name)),
            ("doc_type", "'reference'"),
        ])
        return page_rel, nav_group, fm_text, name

    gens += _item_generators(
        {
            "family": "formats",
            "dirs": ["reference/formats"],
            "legacy_prefix": "interfaces/formats",
            "new_item": format_new_item,
        },
        doc_rows("Format"),
        docs_dir,
        migrate,
    )

    return gens


# Index pages whose `| Page | Description |` table is regenerated from the
# navigation fragment order + the listed pages' frontmatter.
LISTINGS = [
    ("reference/engines/table-engines/mergetree-family/index.mdx",
     ["Engines", "Table Engines", "MergeTree Family"]),
    ("reference/engines/table-engines/log-family/index.mdx",
     ["Engines", "Table Engines", "Log Family"]),
    ("reference/engines/table-engines/special/index.mdx",
     ["Engines", "Table Engines", "Special"]),
    ("reference/engines/table-engines/integrations/index.mdx",
     ["Engines", "Table Engines", "Integrations"]),
    ("reference/engines/database-engines/index.mdx",
     ["Engines", "Database Engines"]),
    ("reference/system-tables/index.mdx",
     ["System Tables"]),
]


def listing_generators(docs_dir):
    def render(group_path):
        # Evaluated at generation time, after page creation and navigation
        # insertion, so a single --write run converges.
        def _render():
            fragment = navigation.load_json(
                os.path.join(docs_dir, "reference", "navigation.json")
            )
            pages = [
                p for p in navigation._group_pages(fragment, group_path)
                if isinstance(p, str) and not p.endswith("/index")
            ]
            return catalog.render_listing(docs_dir, pages)
        return _render

    return [
        {
            "name": f"listing:{os.path.basename(os.path.dirname(rel))}",
            "content": render(group_path),
            "dest": "docs/" + rel,  # unused (no_transform)
            "dest_rel": rel,
            "method": "markers",
            "no_transform": True,
        }
        for rel, group_path in LISTINGS
    ]

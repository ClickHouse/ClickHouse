#!/usr/bin/env python3
"""Self-contained tests for aggregate-function documentation routing."""

import importlib.util
import tempfile
from pathlib import Path


HERE = Path(__file__).resolve().parent
DOCS_DIR = HERE.parents[4] / "docs"


def main():
    spec = importlib.util.spec_from_file_location(
        "autogenerate_docs", HERE / "autogenerate_docs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    migrate = mod.import_migrate(str(DOCS_DIR))
    lookup, _ = mod.build_file_map(
        migrate, DOCS_DIR / "_migration" / "slug-map.csv")

    with tempfile.TemporaryDirectory() as root:
        docs = Path(root) / "docs"
        page = docs / "reference/functions/aggregate-functions/newAggregate.mdx"
        page.parent.mkdir(parents=True)
        original = (
            "---\ntitle: 'newAggregate'\n---\n\n"
            "{/*AUTOGENERATED_START*/}\nold body\n"
            "{/*AUTOGENERATED_END*/}\n\nRetained content.\n"
        )
        page.write_text(original, encoding="utf-8")
        generators = mod.aggregate_generators(str(docs))
        assert len(generators) == 1
        generator = generators[0]
        assert generator["name"] == "aggregate:newAggregate"
        assert generator["params"] == {"function_name": "newAggregate"}

        generated_body = (
            "## newAggregate {#newAggregate}\n\n"
            "Returns a [Float64](/sql-reference/data-types/float) value.\n"
        )

        def fake_run_sql(_binary, _sql_path, cwd, params=None):
            assert params == {"function_name": "newAggregate"}
            (Path(cwd) / "temp-aggregate-function.md").write_text(
                generated_body, encoding="utf-8")

        mod.run_sql = fake_run_sql

        def generate(current):
            return mod.generate_artifacts(
                current,
                binary="unused",
                docs_dir=str(docs),
                repo_root=root,
                migrate=migrate,
                lk=lookup,
                file_map={},
            )

        # New pages have no legacy migration-map entry.
        artifacts = generate(generator)
        assert generator["dest_mintlify"] == (
            "reference/functions/aggregate-functions/newAggregate.mdx")
        assert len(artifacts) == 1
        assert artifacts[0].path == page
        assert "## newAggregate {#newAggregate}" in artifacts[0].content
        assert "[Float64](/reference/data-types/float)" in artifacts[0].content
        assert "old body" not in artifacts[0].content
        assert artifacts[0].content.startswith("---\ntitle: 'newAggregate'\n---\n")
        assert artifacts[0].content.endswith("Retained content.\n")
        assert page.read_text(encoding="utf-8") == original

        unrouted = dict(generator)
        del unrouted["dest_mintlify"]
        try:
            generate(unrouted)
        except ValueError as error:
            assert str(error) == (
                "no Mintlify destination for "
                "docs/sql-reference/aggregate-functions/reference/newAggregate.md")
        else:
            raise AssertionError("unrouted aggregate did not fail")

        # A marked page for an unregistered name still skips empty SQL output.
        generated_body = ""
        assert generate(unrouted) == []

    print("aggregate routing tests passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

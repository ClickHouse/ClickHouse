#!/usr/bin/env python3
"""Check that embedded dictionary-layout docs reproduce their marked MDX pages.

This test does not require a ClickHouse binary. It extracts each raw Markdown
description from its layout registration, runs the same Docusaurus-to-Mintlify
transform as the nightly generator, and compares it with the committed region.
"""

import importlib.util
import re
import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[4]
DOCS_DIR = REPO_ROOT / "docs"
GENERATOR = HERE / "autogenerate_docs.py"

LAYOUT_PAGES = {
    "cache": ("registerCacheDictionaries.cpp", "cache"),
    "direct": ("DirectDictionary.cpp", "direct"),
    "flat": ("FlatDictionary.cpp", "flat"),
    "hashed-array": ("HashedArrayDictionary.cpp", "hashed_array"),
    "hashed": ("registerHashedDictionary.cpp", "hashed"),
    "ip-trie": ("IPAddressDictionary.cpp", "ip_trie"),
    "naive-bayes": ("NaiveBayesDictionary.cpp", "naive_bayes"),
    "polygon": ("PolygonDictionaryImplementations.cpp", "polygon"),
    "range-hashed": ("registerRangeHashedDictionary.cpp", "range_hashed"),
    "regexp-tree": ("RegExpTreeDictionary.cpp", "regexp_tree"),
    "ssd-cache": ("registerCacheDictionaries.cpp", "ssd_cache"),
}

RAW_DESCRIPTION_RE = re.compile(
    r'\.description\s*=\s*R"DOCS_MD\(\n(?P<body>.*?)\n\)DOCS_MD"',
    re.DOTALL,
)


def load_generator():
    spec = importlib.util.spec_from_file_location("autogenerate_docs", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def embedded_description(source, layout):
    registration = re.search(
        rf'factory\.registerLayout\(\s*"{re.escape(layout)}"', source
    )
    if not registration:
        return None
    next_registration = source.find("factory.registerLayout(", registration.end())
    if next_registration == -1:
        next_registration = len(source)
    match = RAW_DESCRIPTION_RE.search(source, registration.end(), next_registration)
    return match.group("body") if match else None


def generated_region(module, page):
    start = module.START_RE.search(page)
    end = module.END_RE.search(page, start.end()) if start else None
    if not start or not end:
        raise AssertionError("page is missing AUTOGENERATED markers")
    return page[start.end():end.start()].strip("\n")


def main():
    module = load_generator()
    migrate = module.import_migrate(str(DOCS_DIR))
    lookup, file_map = module.build_file_map(
        migrate, DOCS_DIR / "_migration" / "slug-map.csv"
    )
    reverse_file_map = {mint: docu for docu, mint in file_map.items()}

    generators = module.dictionary_layout_generators(str(DOCS_DIR), file_map)
    generated_layouts = {}
    for generator in generators:
        basename = generator["name"].removeprefix("dictionary-layout:")
        generated_layouts[basename] = generator["params"]["layout"]
    expected_layouts = {
        basename: registered_name
        for basename, (_, registered_name) in LAYOUT_PAGES.items()
    }
    if generated_layouts != expected_layouts:
        print("dictionary-layout generator discovery or aliases differ", file=sys.stderr)
        return 1

    failures = []
    for basename, (source_name, layout) in LAYOUT_PAGES.items():
        source_path = REPO_ROOT / "src" / "Dictionaries" / source_name
        source = source_path.read_text(encoding="utf-8")
        description = embedded_description(source, layout)
        if description is None:
            failures.append(f"{source_name}: full-page documentation for {layout} not found")
            continue

        mint_rel = f"reference/statements/create/dictionary/layouts/{basename}.mdx"
        page_path = DOCS_DIR / mint_rel
        page = page_path.read_text(encoding="utf-8")
        if not module.is_fully_autogenerated_page(page):
            failures.append(f"{basename}: generated region does not cover the full page body")
            continue
        legacy_path = reverse_file_map[mint_rel]
        transformed = module.transform_full_body(
            migrate,
            description,
            legacy_path,
            str(page_path),
            lookup,
            module.frontmatter_title(page),
        ).strip("\n")
        expected = generated_region(module, page)
        if transformed != expected:
            failures.append(f"{basename}: embedded documentation differs from MDX")

    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 1
    print(f"OK: {len(LAYOUT_PAGES)} dictionary-layout pages match their embedded documentation")
    return 0


if __name__ == "__main__":
    sys.exit(main())

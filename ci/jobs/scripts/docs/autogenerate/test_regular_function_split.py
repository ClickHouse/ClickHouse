#!/usr/bin/env python3
"""Focused tests for generated regular-function category sharding."""

import importlib.util
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load_module():
    spec = importlib.util.spec_from_file_location(
        "autogenerate_docs", HERE / "autogenerate_docs.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def generated_array_page():
    return """---
description: 'Array functions.'
sidebarTitle: 'Arrays'
slug: /sql-reference/functions/array-functions
title: 'Array Functions'
doc_type: 'reference'
---

import { ExperimentalBadge } from "/snippets/components/ExperimentalBadge/ExperimentalBadge.jsx";

{/*AUTOGENERATED_START*/}
## arrayMap {#arrayMap}

Introduced in: v1.1.0

Maps an expression over an array. See [`hasAny`](#hasAny).

<ExperimentalBadge />

**Syntax**

```sql
arrayMap(func, arr)
```

### Example {#arrayMap-example}

```sql title=Query
SELECT arrayMap(x -> x + 1, [1, 2]);
```

## hasAny {#hasAny}

Introduced in: v1.1.0

Checks whether two arrays overlap.

**Syntax**

```sql
hasAny(arr_x, arr_y)
```
{/*AUTOGENERATED_END*/}

## Distance functions {#distance-functions}

See the distance functions reference.
"""


def main():
    mod = load_module()
    with tempfile.TemporaryDirectory() as temp:
        docs_dir = Path(temp)
        dest = (
            docs_dir
            / "reference/functions/regular-functions/array-functions.mdx"
        )
        artifacts = mod.split_regular_function_page(
            dest,
            generated_array_page(),
            docs_dir,
            "array-functions",
        )
        by_path = {artifact.path: artifact.content for artifact in artifacts}

        root = by_path[dest]
        assert "<ArrayFunctionsIndex />" in root
        assert "## arrayMap {#arrayMap}" not in root
        assert "## Distance functions {#distance-functions}" in root
        assert "Browse array functions" not in root
        assert "available in the navigation" in root

        array_map_path = (
            docs_dir
            / "reference/functions/regular-functions/array-functions/arrayMap.mdx"
        )
        array_map = by_path[array_map_path]
        for required in (
            "description:",
            "sidebar_label:",
            "sidebar_position:",
            "slug:",
            "title:",
            "doc_type:",
        ):
            assert required in array_map
        assert "## arrayMap {#arrayMap}" in array_map
        assert "## hasAny {#hasAny}" not in array_map
        assert "import { ExperimentalBadge }" in array_map
        assert (
            "[`hasAny`](/reference/functions/regular-functions/"
            "array-functions/hasAny)"
        ) in array_map
        assert mod.is_fully_autogenerated_page(array_map)

        shard_dir = dest.with_suffix("")
        navigation = json.loads(by_path[shard_dir / "navigation.json"])
        assert navigation["expandable"] is True
        assert navigation["expanded"] is False
        assert navigation["pages"] == [
            "reference/functions/regular-functions/array-functions/overview",
            "reference/functions/regular-functions/array-functions/arrayMap",
            "reference/functions/regular-functions/array-functions/hasAny",
        ]

        overview_path = shard_dir / "overview.mdx"
        overview = by_path[overview_path]
        assert "sidebar_label: 'Overview'" in overview
        assert "title: 'Array Functions Overview'" in overview
        assert "<ArrayFunctionsIndex />" in overview
        assert "## Distance functions {#distance-functions}" in overview

        manifest = json.loads(by_path[shard_dir / "manifest.json"])
        assert manifest["functions"] == 2
        assert manifest["anchorRoutes"]["arrayMap"] == (
            "/reference/functions/regular-functions/array-functions/arrayMap")
        assert manifest["anchorRoutes"]["arrayMap-example"] == (
            "/reference/functions/regular-functions/array-functions/arrayMap")

        component = by_path[
            docs_dir
            / "snippets/components/ArrayFunctionsIndex/ArrayFunctionsIndex.jsx"
        ]
        assert "redirectLegacyAnchor" in component
        assert "Search array functions" in component
        assert '"description":"Maps an expression over an array."' in component
        assert (
            '"href":"/reference/functions/regular-functions/'
            'array-functions/arrayMap"'
        ) in component
        assert "arrayMap#arrayMap" not in component
        assert '"group":' not in component
        assert "groupedFunctions" not in component
        assert "rounded-lg" not in component

    print("regular-function split tests passed")


if __name__ == "__main__":
    main()

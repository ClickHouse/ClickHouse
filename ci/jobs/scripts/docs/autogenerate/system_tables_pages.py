#!/usr/bin/env python3
"""
Generate the system-table reference pages (`docs/reference/system-tables/*.mdx`)
from a ClickHouse binary.

Port of `utils/generate-system-tables-docs` targeting the Mintlify tree:
queries `system.tables` / `system.columns` via `clickhouse local` (with a
config that eagerly creates the system log tables so their schemas are
visible), renders the per-table column list, and exposes the result as
autogenerate_docs.py generator entries -- one per system table. Existing pages
get the region between their `AUTOGENERATED` markers replaced; tables without
a page get a whole new page (plus a navigation entry in
`docs/reference/navigation.json`).

The rendered markdown uses Docusaurus-style type links; the driver's
`--remap-legacy` bridge rewrites them to the Mintlify equivalents, the same as
every other generator.
"""


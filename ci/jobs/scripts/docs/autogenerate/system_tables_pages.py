# Tables to skip in documentation generation (internal/helper tables).
SKIP_TABLES = {"transposed_metric_log"}


def unescape_tsv(value):
    """Unescape TSV escape sequences (\\n, \\t, \\', \\\\)."""
    result = []
    i = 0
    while i < len(value):
        if value[i] == "\\" and i + 1 < len(value):
            next_char = value[i + 1]
            if next_char == "n":
                result.append("\n")
                i += 2
                continue
            elif next_char == "t":
                result.append("\t")
                i += 2
                continue
            elif next_char == "\\":
                result.append("\\")
                i += 2
                continue
            elif next_char == "'":
                result.append("'")
                i += 2
                continue
        result.append(value[i])
        i += 1
    return "".join(result)


def run_query(binary, config, query):
    """Run a query via `clickhouse local` and return rows as dicts."""
    cmd = [binary, "local", "--query", query, "--format", "TSVWithNamesAndTypes"]
    if config:
        cmd.extend(["--config-file", config])
    # `clickhouse local` treats inherited stdin as input data; detach it.
    result = subprocess.run(
        cmd, capture_output=True, text=True, timeout=300, stdin=subprocess.DEVNULL
    )
    reader = csv.reader(io.StringIO(result.stdout), delimiter="\t")
    rows = list(reader)
    # `clickhouse local` can exit non-zero because of races between system log
    # teardown and `Poco::Application` destruction, even after the query has
    # produced complete output. Tolerate that specific case only: stdout must
    # parse as TSVWithNamesAndTypes (header + types row).
    if result.returncode != 0:
        if len(rows) >= 2:
            print(
                f"Warning: query exited with code {result.returncode} but"
                f" produced {len(rows)} rows of output, treating as success.",
                file=sys.stderr,
            )
        else:
            print(f"Error running query: {query}", file=sys.stderr)
            print(f"stderr: {result.stderr}", file=sys.stderr)
            sys.exit(1)
    if len(rows) < 2:
        return []
    headers = rows[0]
    # rows[1] is the types row, skip it
    return [
        {k: unescape_tsv(v) for k, v in zip(headers, row)}
        for row in rows[2:]
    ]


def format_type_link(type_str):
    """Format a ClickHouse type as a markdown link (outermost type)."""
    match = re.match(r"^(\w+)", type_str)
    if not match:
        return f"`{type_str}`"
    link = TYPE_LINKS.get(match.group(1))
    if link:
        return f"[{type_str}]({link})"
    return f"`{type_str}`"


def indent_continuation(text, indent="  "):
    """Indent continuation lines of a multi-line string for markdown list items."""
    lines = text.split("\n")
    if len(lines) <= 1:
        return text
    result = [lines[0]]
    for line in lines[1:]:
        result.append(indent + line if line.strip() else "")
    return "\n".join(result)


def generate_columns_markdown(columns, aliases=None):
    """Render the column bullet list, with an optional Aliases section."""
    lines = []
    for col in columns:
        name = col["name"]
        type_linked = format_type_link(col["type"])
        comment = col.get("comment", "").strip()
        if comment:
            lines.append(f"- `{name}` ({type_linked}) — {indent_continuation(comment)}")
        else:
            lines.append(f"- `{name}` ({type_linked})")

    if aliases:
        lines.append("")
        lines.append("**Aliases:**")
        lines.append("")
        for alias in aliases:
            lines.append(
                f"- `{alias['name']}` — Alias for `{alias.get('default_expression', '')}`."
            )

    return "\n".join(lines) + "\n" if lines else ""


MDX_START = "{/*AUTOGENERATED_START*/}"
MDX_END = "{/*AUTOGENERATED_END*/}"


def add_markers_to_page(page, columns_md):
    """Add the AUTOGENERATED markers to a hand-written page that lacks them:
    replace the column list following the `Columns` heading (up to the next
    section) with a marked autogenerated block, or append one at the end."""
    columns_pattern = re.compile(
        r"^(#{0,3}\s*Columns:?(?:\s*\{#[\w-]+\})?\s*)$", re.MULTILINE
    )
    match = columns_pattern.search(page)

    if match:
        rest = page[match.end():]
        # Find the next major section boundary after the column list.
        section_pattern = re.compile(
            r"^(?:#{1,3}\s|\*\*(?:See Also|Example|See also)\*\*)",
            re.MULTILINE,
        )
        section_match = section_pattern.search(rest)
        after_columns = rest[section_match.start():] if section_match else ""
        # `\s*$` in the columns header pattern can consume the trailing
        # newline; normalize before appending the separating blank line.
        before = page[:match.end()].rstrip("\n")
        new_page_content = (
            f"{before}\n\n{MDX_START}\n{columns_md}{MDX_END}\n"
        )
        if after_columns:
            new_page_content += "\n" + after_columns
        return new_page_content

    return (
        page.rstrip()
        + f"\n\n## Columns {{#columns}}\n\n{MDX_START}\n{columns_md}{MDX_END}\n"
    )


def new_page(table_name, table_comment, columns_md):
    """A whole new page for a table that has no documentation yet, following
    the structure of the existing reference/system-tables pages."""
    description = " ".join(table_comment.split()).replace("'", "''")
    return f"""---
description: '{description}'
keywords: ['system table', '{table_name}']
slug: /operations/system-tables/{table_name}
title: 'system.{table_name}'
doc_type: 'reference'
---

import SystemTableCloud from '/snippets/_system_table_cloud.mdx';

<SystemTableCloud/>

## Description {{#description}}

{table_comment}

## Columns {{#columns}}

{{/*AUTOGENERATED_START*/}}
{columns_md}{{/*AUTOGENERATED_END*/}}

{catalog.badge("system.tables")}
"""


def build_generators(binary, config=DEFAULT_CONFIG):
    """Query the binary once and return one generator entry per system table."""
    # Filter out rotated log tables (e.g. query_log_0) and user-created tables
    # by requiring a non-empty comment (all real system tables have comments
    # set during registration).
    tables = run_query(
        binary,
        config,
        "SELECT name, comment FROM system.tables"
        " WHERE database = 'system'"
        " AND comment != ''"
        " AND NOT match(name, '_\\\\d+$')"
        " ORDER BY name",
    )
    known_tables = {t["name"] for t in tables}

    columns = run_query(
        binary,
        config,
        "SELECT table, name, type, comment, default_kind, default_expression"
        " FROM system.columns WHERE database = 'system'"
        " AND default_kind NOT IN ('ALIAS')"
        " ORDER BY table, position",
    )
    aliases = run_query(
        binary,
        config,
        "SELECT table, name, type, default_expression"
        " FROM system.columns WHERE database = 'system'"
        " AND default_kind = 'ALIAS'"
        " ORDER BY table, position",
    )

    table_columns = {}
    for col in columns:
        if col["table"] in known_tables:
            table_columns.setdefault(col["table"], []).append(col)
    table_aliases = {}
    for alias in aliases:
        if alias["table"] in known_tables:
            table_aliases.setdefault(alias["table"], []).append(alias)
    table_comments = {t["name"]: t["comment"] for t in tables}

    gens = []
    for table in sorted(table_columns):
        if table in SKIP_TABLES:
            continue
        columns_md = generate_columns_markdown(
            table_columns[table], table_aliases.get(table)
        )
        gens.append({
            "name": f"system-tables:{table}",
            "content": columns_md,
            "dest": f"docs/operations/system-tables/{table}.md",
            # New tables are not in the slug map; place their page here.
            "dest_fallback": f"reference/system-tables/{table}.mdx",
            "method": "markers",
            "add_markers": add_markers_to_page,
            "create_page": new_page(table, table_comments.get(table, ""), columns_md),
            "nav": (["System Tables"], f"reference/system-tables/{table}"),
        })
    return gens

def _statement_page_candidates(docs_dir):
    statement_root = Path(docs_dir) / "reference/statements"
    if not statement_root.is_dir():
        raise ValueError(f"statement documentation directory is missing: {statement_root}")

    pages = []
    for page in sorted(statement_root.rglob("*.mdx")):
        relative = page.relative_to(statement_root).as_posix()
        if (
            relative.startswith("create/dictionary/sources/")
            or relative.startswith("create/dictionary/layouts/")
        ):
            continue
        content = page.read_text(encoding="utf-8")
        title = frontmatter_title(content)
        if (START_RE.search(content) or END_RE.search(content)) and not title:
            raise ValueError(
                f"marked statement page has no frontmatter title: {page}"
            )
        if title:
            pages.append((title, page, content))
    return pages



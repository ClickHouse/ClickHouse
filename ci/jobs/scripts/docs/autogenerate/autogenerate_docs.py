#!/usr/bin/env python3
"""
Autogenerate ClickHouse reference documentation (settings, functions, ...) from
a ClickHouse binary's introspection tables. Python port of clickhouse-docs's
`scripts/settings/autogenerate-settings.sh`, living under ci/jobs/scripts/docs
so it can run as an optional step of the docs check.

Each generator produces markdown from the source (a `.sql` file run through
`<binary> local`, or a pre-rendered `system.documentation` body) and places it
into the docs tree in one uniform shape: the page's human-owned frontmatter (and
any hand-written preamble) is preserved, and all generated markdown lives in a
single region between `{/*AUTOGENERATED_START*/}` / `{/*AUTOGENERATED_END*/}`
markers, with the provenance badge inside it. The source is authoritative -- the
region is replaced wholesale on every run; a net-new item gets a fresh page whose
frontmatter is synthesized once. The region markers are what the docs check's
edit guard protects, so contributors never hand-edit generated content.

Legacy-link bridge: the SQL emits Docusaurus-style paths (destination files and
in-content links, e.g. `/operations/settings/settings#x`). While `--remap-legacy`
is on (the default, for the migration period), both are translated to their
Mintlify equivalents via `_migration/slug-map.csv`. Once the generation source
is updated to emit Mintlify-native paths, run with `--no-remap-legacy`.

Modes: `--write` updates the docs tree in place (used by the nightly
regeneration workflow); `--check` regenerates in memory and diffs against the
committed docs, failing on drift (a local convenience, not a CI gate).
"""

import argparse
import os
import re
import shutil
import subprocess
import sys

def aggregate_generators(docs_dir):
    # Aggregate functions are driven by the existing doc pages (one per function)
    # rather than a fixed list: for each page that has the AUTOGENERATED markers,
    # regenerate its body via generate-aggregate-functions.sql. Pages whose name
    # is not an aggregate function produce empty SQL output and are skipped.
    agg_dir = os.path.join(docs_dir, "reference", "functions", "aggregate-functions")
    gens = []
    for name in sorted(os.listdir(agg_dir)) if os.path.isdir(agg_dir) else []:
        if not name.endswith(".mdx") or name == "index.mdx":
            continue
        fn = name[:-len(".mdx")]
        with open(os.path.join(agg_dir, name), encoding="utf-8") as f:
            if not START_RE.search(f.read()):
                continue
        gens.append({
            "name": f"aggregate:{fn}",
            "sql": ["generate-aggregate-functions.sql"],
            "params": {"function_name": fn},
            "outfile": "temp-aggregate-function.md",
            "dest": f"docs/sql-reference/aggregate-functions/reference/{fn}.md",
            "skip_if_empty": True,  # non-aggregate name -> empty output -> skip
        })
    return gens


ALL_GENERATORS = SETTINGS_GENERATORS + FUNCTION_GENERATORS


FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n?", re.DOTALL)


def import_migrate(docs_dir):
    # The Docusaurus->Mintlify body transforms (imports @theme->/snippets,
    # HTML->MDX comments, link rewriting) are reused from the migration script
    # so generated pages match migrated ones exactly -- a single source of truth.
    sys.path.insert(0, os.path.join(docs_dir, "_migration"))
    import migrate  # noqa: E402
    return migrate


def build_file_map(migrate, slug_map):
    # docusaurus_file -> mintlify_file, plus migrate's link/import Lookups.
    lk, rows = migrate.build_lookups(Path(slug_map))
    file_map = {}
    for r in rows:
        mfile = (r.get("mintlify_file") or "").split(" | ")[0].strip()
        if r.get("status") == "matched" and mfile:
            file_map[(r.get("docusaurus_file") or "").strip()] = mfile
    return lk, file_map


def transform_body(migrate, content, src_docu, dest_path, lk):
    # Run migrate.py's full body transform (the single source of truth) on
    # generated marker content -- aggregate functions, settings, functions --
    # so it is converted identically to a migrated page instead of only having
    # its imports/comments/links rewritten. This is what turns Docusaurus
    # admonitions (`:::warning`) embedded in the C++ source descriptions into
    # Mintlify `<Warning>`, `<Tabs>`, `<Accordion>`, etc. The content is a
    # fragment spliced between AUTOGENERATED markers, so there is no page title
    # (`drop_redundant_h1` stays a no-op) and imports are not injected -- they
    # would land inside the markers instead of at the page top.
    return migrate.transform_body(
        content, lk, [],
        title=None,
        source_docu_path=Path(src_docu),
        source_docu_file=src_docu,
        dest_path=Path(dest_path),
        inject_imports=False,
        override_key=src_docu,  # apply any per-file override, as the migrator does
    )


def run_sql(binary, sql_path, cwd, params=None):
    # Run the generator SQL; it writes its INTO OUTFILE markdown into `cwd`.
    cmd = [binary, "local", "--queries-file", sql_path]
    for k, v in (params or {}).items():
        cmd.append(f"--param_{k}={v}")
    subprocess.run(cmd, cwd=cwd, check=True)


def replace_between_markers(page, content, start_re=START_RE, end_re=END_RE, pad=False):
    start = start_re.search(page)
    end = end_re.search(page, start.end()) if start else None
    if not start or not end:
        raise ValueError("destination is missing the AUTOGENERATED markers")
    # Keep the marker lines themselves; replace only the region between them.
    sep = "\n\n" if pad else "\n"
    return page[:start.end()] + sep + content.strip("\n") + sep + page[end.start():]


def marker_tokens(prefix="AUTOGENERATED"):
    """The literal MDX marker strings for a given prefix."""
    return "{/*" + prefix + "_START*/}", "{/*" + prefix + "_END*/}"


def wrap_in_markers(region, prefix="AUTOGENERATED"):
    """Frame a region body between a fresh START/END marker pair."""
    start, end = marker_tokens(prefix)
    return f"{start}\n{region.strip(chr(10))}\n{end}\n"


def region_body(content, badge=None):
    """The text placed between the markers: the generated body, with the
    provenance badge (when the domain uses one) appended at the end so a reader
    sees the "autogenerated" cue and it regenerates in place with the content."""
    body = content.strip("\n")
    if badge:
        body = f"{body}\n\n{badge}"
    return body


def generate(gen, binary, docs_dir, repo_root, migrate, lk, file_map, remap):
    if "content" in gen:
        # Pre-rendered content (system tables, catalog domains, async
        # metrics) -- no SQL run. Callables are evaluated now, after earlier
        # generators' page creation and navigation insertion (listing tables).
        content = gen["content"]() if callable(gen["content"]) else gen["content"]
    else:
        with tempfile.TemporaryDirectory(prefix="autogen-") as scratch:
            # Stage the files the SQL reads via file() (C++ sources, etc.) into scratch.
            for staged, src in gen.get("deps", {}).items():
                shutil.copyfile(
                    os.path.join(repo_root, src), os.path.join(scratch, staged)
                )
            for sql in gen["sql"]:
                run_sql(binary, os.path.join(SQL_DIR, sql), scratch, gen.get("params"))
            with open(os.path.join(scratch, gen["outfile"]), encoding="utf-8") as f:
                content = f.read()
    if gen.get("skip_if_empty") and not content.strip():
        return None, None, None  # e.g. a page whose name is not an aggregate function

    if gen.get("dest_rel"):
        # The generator already knows its Mintlify file (catalog domains,
        # listing tables).
        dest_rel = gen["dest_rel"]
    elif remap:
        # Items newly documented in the source are not in the slug map; they
        # get a brand-new page at the generator's fallback location.
        dest_rel = file_map.get(gen["dest"]) or gen.get("dest_fallback")
    else:
        dest_rel = re.sub(r"^docs/", "", gen["dest"])
    if not dest_rel:
        raise ValueError(f"no Mintlify destination for {gen['dest']}")
    dest = os.path.join(docs_dir, dest_rel)

    if gen.get("fixups"):
        content = apply_fixups(content)
    if remap and not gen.get("no_transform"):
        if gen.get("full_transform"):
            content = catalog.full_transform(
                migrate, content, gen.get("title"), gen["dest"], dest, lk
            )
        else:
            content = transform_body(migrate, content, gen["dest"], dest, lk)

    # Generated content is a body fragment: drop any leading frontmatter the
    # source emitted (e.g. the settings SQL) so it does not land inside the
    # markers -- the page's own frontmatter, above the region, is authoritative.
    content = FRONTMATTER_RE.sub("", content, count=1).lstrip("\n")

    # Every generated page has the same shape: human-owned frontmatter, then a
    # single AUTOGENERATED region holding all generated markdown -- including any
    # MDX imports the source embeds, kept inside the region so the page mirrors
    # the source verbatim -- with the provenance badge at the end. The source of
    # truth is always the embedded documentation: the region is replaced
    # wholesale on every run; frontmatter is preserved.
    prefix = gen.get("markers", "AUTOGENERATED")
    start_re, end_re = marker_res(prefix)
    region = region_body(content, gen.get("badge"))

    if not os.path.isfile(dest):
        # A newly documented item: synthesize the page once. `create_page`
        # supplies a whole template (already carrying its markers and any
        # hand-written preamble, e.g. system tables); otherwise
        # `create_frontmatter` supplies just the frontmatter and the writer
        # frames the region below it.
        if gen.get("create_page") is not None:
            new = gen["create_page"]
            if remap:
                new = transform_body(migrate, new, gen["dest"], dest, lk)
            return dest, new, "create"
        if gen.get("create_frontmatter") is not None:
            new = gen["create_frontmatter"].rstrip("\n") + "\n\n" + wrap_in_markers(
                region, prefix
            )
            return dest, new, "create"
        raise ValueError(f"no create template for new page {dest_rel}")

    with open(dest, encoding="utf-8") as f:
        page = f.read()
    if start_re.search(page):
        # The region already exists: replace only what is between the markers,
        # preserving frontmatter, preamble, and anything after the region.
        new = replace_between_markers(
            page, region, start_re, end_re, pad=gen.get("pad", False)
        )
    elif gen.get("add_markers"):
        # A hand-written page gaining a generated sub-region for the first time
        # (e.g. a system table's Columns block).
        new = gen["add_markers"](page, region)
    else:
        # A fully generated page that predates the marker convention: keep its
        # frontmatter and replace the entire body with the marker-wrapped region.
        fm = FRONTMATTER_RE.match(page)
        prefix_fm = (fm.group(0).rstrip("\n") + "\n\n") if fm else ""
        new = prefix_fm + wrap_in_markers(region, prefix)
    return dest, new, "update"


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--binary", default="build/programs/clickhouse")
    p.add_argument("--docs-dir", default="docs")
    p.add_argument("--slug-map",
                   help="default: <docs-dir>/_migration/slug-map.csv")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update docs in place")
    mode.add_argument("--check", action="store_true",
                      help="fail if regenerated output differs from committed docs")
    p.add_argument("--no-remap-legacy", dest="remap", action="store_false",
                   help="emit paths/links as the SQL produces them (Mintlify-native)")
    p.add_argument("--only", help="only run generators whose name contains this substring")
    args = p.parse_args(argv)

    binary = os.path.abspath(args.binary)
    docs_dir = os.path.abspath(args.docs_dir)
    repo_root = os.path.dirname(docs_dir)
    slug_map = args.slug_map or os.path.join(docs_dir, "_migration", "slug-map.csv")

    migrate = lk = None
    file_map = {}
    if args.remap:
        migrate = import_migrate(docs_dir)
        lk, file_map = build_file_map(migrate, slug_map)

    # The navigation fragment with the generators' enqueued mutations applied
    # in memory. Shared between `flush_nav_inserts` and the listing
    # generators, so every mode -- including --check -- renders the listings
    # from the synthesized navigation state, not from whatever happens to be
    # committed (a stale but self-consistent navigation/listing pair must
    # still come back as drift).
    frag_path = os.path.join(docs_dir, "reference", "navigation.json")
    nav_state = {"fragment": None}

    def current_fragment():
        if nav_state["fragment"] is None:
            nav_state["fragment"] = navigation.load_json(frag_path)
        return nav_state["fragment"]

    def family_selected(family):
        # Building these generators has a cost (queries, C++ parsing), so skip
        # it when --only can't match them.
        return not args.only or args.only in family or family in args.only

    # `system.documentation` is the unified source for all embedded docs;
    # fetch it once for every family that consumes it.
    docs_map = None
    doc_families = ("table-engines", "database-engines", "data-types",
                    "formats", "skipping-indexes", "disk-types", "coverage",
                    "descriptions")
    if any(family_selected(f) for f in doc_families):
        docs_map = introspect.fetch_documentation(binary)

    all_generators = ALL_GENERATORS + aggregate_generators(docs_dir)
    if family_selected("system-tables"):
        all_generators += system_tables_pages.build_generators(binary)
    if family_selected("async-metrics"):
        all_generators.append(async_metrics.build_generator(repo_root))
    if any(family_selected(f) for f in
           ("table-engines", "database-engines", "data-types", "formats")):
        all_generators += catalog_domains.build_generators(
            docs_map, binary, docs_dir, migrate, lk
        )
    if any(family_selected(f) for f in ("skipping-indexes", "disk-types")):
        all_generators += generated_groups.build_generators(docs_map, docs_dir)
    if family_selected("descriptions"):
        all_generators += descriptions.build_generators(docs_map)
    if family_selected("listing"):
        # Last: listing tables render from the navigation fragment and the
        # pages' frontmatter, after any page creation and nav insertion.
        all_generators += catalog_domains.listing_generators(docs_dir, current_fragment)
    generators = [g for g in all_generators if not args.only or args.only in g["name"]]

    drift = 0
    nav_inserts = []  # (group_path, page_id) for pages created by --write
    nav_groups = []  # generator-owned groups (fully generated domains)

    def flush_nav_inserts():
        # Newly created pages are added to the navigation fragment; docs.json
        # includes the fragment via $ref, so no further compilation is needed.
        # Runs before the listing generators so their tables see the new pages.
        # The mutations are applied to the shared in-memory fragment in every
        # mode; --write persists them, --check reports unpersisted ones as
        # drift (the committed navigation.json is stale, and so may be the
        # listings rendered from it).
        nonlocal drift
        if not nav_inserts and not nav_groups:
            return
        fragment = current_fragment()
        changed = [
            page_id
            for group_path, page_id in nav_inserts
            if navigation.insert_page(fragment, group_path, page_id)
        ]
        changed += [
            spec["group"]
            for spec in nav_groups
            if navigation.ensure_group(
                fragment, spec["parent_path"], spec["group"], spec["pages"],
                root=spec.get("root"), after_group=spec.get("after_group"),
            )
        ]
        if changed:
            if args.write:
                with open(frag_path, "w", encoding="utf-8") as f:
                    f.write(navigation.dump_fragment(fragment))
                print(f"wrote: reference/navigation.json ({', '.join(changed)})")
            elif args.check:
                print("DRIFT: reference/navigation.json is stale"
                      f" ({', '.join(changed)})")
                drift += 1
            else:
                print("[dry-run] would write: reference/navigation.json"
                      f" ({', '.join(changed)})")
        nav_inserts.clear()
        nav_groups.clear()

    for gen in generators:
        if gen.get("no_transform"):
            flush_nav_inserts()  # listing generators come after all creations
        dest, new, kind = generate(
            gen, binary, docs_dir, repo_root, migrate, lk, file_map, args.remap
        )
        if new is None:  # skipped (e.g. a non-aggregate page)
            continue
        rel = os.path.relpath(dest, docs_dir)

        if kind == "update" and os.path.isfile(dest):
            # The provenance badge's date only advances when the generated
            # content actually changed.
            with open(dest, encoding="utf-8") as f:
                new = catalog.reconcile_badge_date(f.read(), new)

        # Enqueue the navigation mutations in every mode: --check must
        # synthesize the same navigation state --write would persist.
        if kind == "create" and gen.get("nav"):
            nav_inserts.append(gen["nav"])
        if gen.get("nav_group"):
            nav_groups.append(gen["nav_group"])

        if args.check:
            if kind == "create":
                print(f"MISSING: {rel} (newly documented, run --write to create)")
                drift += 1
                continue
            current = open(dest, encoding="utf-8").read() if os.path.isfile(dest) else ""
            if current != new:
                print(f"DRIFT: {rel} is stale")
                drift += 1
            else:
                print(f"ok: {rel}")
        elif args.write:
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"{'created' if kind == 'create' else 'wrote'}: {rel}")
        else:
            verb = "create" if kind == "create" else "update"
            print(f"[dry-run] would {verb}: {rel}")

    flush_nav_inserts()

    # Domains whose hand-written pages are richer than the embedded summaries
    # are checked for coverage instead of generated (see coverage.py).
    if family_selected("coverage"):
        for problem in coverage.run_checks(docs_map, docs_dir):
            print(f"COVERAGE: {problem}")
            drift += 1

    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())

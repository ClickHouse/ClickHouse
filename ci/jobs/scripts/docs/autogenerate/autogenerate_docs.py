#!/usr/bin/env python3
"""
Autogenerate ClickHouse reference documentation (settings, functions, ...) from
a ClickHouse binary's introspection tables. Python port of clickhouse-docs's
`scripts/settings/autogenerate-settings.sh`, living under ci/jobs/scripts/docs
so it can run as an optional step of the docs check.

Each generator runs a `.sql` file (in ./sql) through `<binary> local`, letting
it write its `INTO OUTFILE` markdown into a scratch dir, then places that output
into the docs tree -- either overwriting a page or replacing the region between
`<!--AUTOGENERATED_START-->` / `<!--AUTOGENERATED_END-->` markers.

Legacy-link bridge: the SQL emits Docusaurus-style paths (destination files and
in-content links, e.g. `/operations/settings/settings#x`). While `--remap-legacy`
is on (the default, for the migration period), both are translated to their
Mintlify equivalents via `_migration/slug-map.csv`. Once the generation source
is updated to emit Mintlify-native paths, run with `--no-remap-legacy`.

Modes: `--write` updates the docs tree in place; `--check` regenerates to a
scratch copy and diffs against the committed docs, failing on drift (so CI can
flag reference pages that are stale relative to the binary).
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import async_metrics  # noqa: E402
import catalog  # noqa: E402
import catalog_domains  # noqa: E402
import coverage  # noqa: E402
import generated_groups  # noqa: E402
import navigation  # noqa: E402
import system_tables_pages  # noqa: E402

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SQL_DIR = os.path.join(SCRIPT_DIR, "sql")

# The autogenerated region markers. Docusaurus source uses HTML comments
# (`<!--AUTOGENERATED_START-->`); migrated Mintlify pages use MDX comments
# (`{/*AUTOGENERATED_START*/}`), since MDX parses `<!-- -->` as JSX. Match either
# form and preserve whichever the page already uses. Some pages use a custom
# marker prefix (e.g. `AUTOGENERATED_METRICS` for the async metrics listing).
def marker_res(prefix="AUTOGENERATED"):
    start = re.compile(rf"<!--\s*{prefix}_START\s*-->|\{{/\*\s*{prefix}_START\s*\*/\}}")
    end = re.compile(rf"<!--\s*{prefix}_END\s*-->|\{{/\*\s*{prefix}_END\s*\*/\}}")
    return start, end


START_RE, END_RE = marker_res()

# A settings generator:
#   sql     -- the .sql file(s) run in order; their INTO OUTFILE lands in scratch
#   outfile -- the OUTFILE name the SQL writes
#   dest    -- Docusaurus destination path (the slug-map key -> Mintlify file)
#   method  -- how to place the content:
#                "markers" -> replace between the AUTOGENERATED markers
#                "body"    -> keep the Mintlify page's frontmatter, replace the
#                             rest with the generated body
#   deps    -- files the SQL reads via file() relative to CWD, staged into
#              scratch as {staged_name: repo-root-relative source path}

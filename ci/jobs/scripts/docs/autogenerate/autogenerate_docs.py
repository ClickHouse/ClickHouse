import navigation  # noqa: E402
import system_tables_pages  # noqa: E402

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SQL_DIR = os.path.join(SCRIPT_DIR, "sql")

# The autogenerated region markers. Docusaurus source uses HTML comments
# (`<!--AUTOGENERATED_START-->`); migrated Mintlify pages use MDX comments
# (`{/*AUTOGENERATED_START*/}`), since MDX parses `<!-- -->` as JSX. Match either
# form and preserve whichever the page already uses. Some pages use a custom
# marker prefix (e.g. `AUTOGENERATED_METRICS` for the async metrics listing).
def marker_res(prefix="AUTOGENERATED"):
    start = re.compile(rf"<!--\s*{prefix}_START\s*-->|\{{/\*\s*{prefix}_START\s*\*/\}}")
    end = re.compile(rf"<!--\s*{prefix}_END\s*-->|\{{/\*\s*{prefix}_END\s*\*/\}}")
    return start, end


START_RE, END_RE = marker_res()

# A settings generator:
#   sql     -- the .sql file(s) run in order; their INTO OUTFILE lands in scratch
#   outfile -- the OUTFILE name the SQL writes
#   dest    -- Docusaurus destination path (the slug-map key -> Mintlify file)
#   method  -- how to place the content:
#                "markers" -> replace between the AUTOGENERATED markers
#                "body"    -> keep the Mintlify page's frontmatter, replace the
#                             rest with the generated body
#   deps    -- files the SQL reads via file() relative to CWD, staged into
#              scratch as {staged_name: repo-root-relative source path}

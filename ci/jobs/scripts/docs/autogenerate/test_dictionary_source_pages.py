#!/usr/bin/env python3
"""Check that embedded dictionary-source docs reproduce their marked MDX pages.

This test does not require a ClickHouse binary. It extracts each raw Markdown
description from its source registration, runs the same Docusaurus-to-Mintlify
transform as the nightly generator, and compares it with the committed region.
"""

import importlib.util
import re
import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[4]
DOCS_DIR = REPO_ROOT / "docs"
GENERATOR = HERE / "autogenerate_docs.py"

SOURCE_PAGES = {
    "cassandra": ("CassandraDictionarySource.cpp", "cassandra"),
    "clickhouse": ("ClickHouseDictionarySource.cpp", "clickhouse"),
    "executable-file": ("ExecutableDictionarySource.cpp", "executable"),
    "executable-pool": ("ExecutablePoolDictionarySource.cpp", "executable_pool"),
    "http": ("HTTPDictionarySource.cpp", "http"),
    "local-file": ("FileDictionarySource.cpp", "file"),
    "mongodb": ("MongoDBDictionarySource.cpp", "mongodb"),
    "mysql": ("MySQLDictionarySource.cpp", "mysql"),
    "null": ("NullDictionarySource.cpp", "null"),
    "odbc": ("XDBCDictionarySource.cpp", "odbc"),
    "postgresql": ("PostgreSQLDictionarySource.cpp", "postgresql"),
    "redis": ("RedisDictionarySource.cpp", "redis"),
    "yamlregexptree": ("YAMLRegExpTreeDictionarySource.cpp", "yamlregexptree"),
    "ytsaurus": ("YTsaurusDictionarySource.cpp", "ytsaurus"),
}

RAW_DESCRIPTION_RE = re.compile(
    r'\.description\s*=\s*R"DOCS_MD\(\n(?P<body>.*?)\n\)DOCS_MD"',
    re.DOTALL,
)


def load_generator():
    spec = importlib.util.spec_from_file_location("autogenerate_docs", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generated_region(module, page):
    start = module.START_RE.search(page)
    end = module.END_RE.search(page, start.end()) if start else None
    if not start or not end:
        raise AssertionError("page is missing AUTOGENERATED markers")
    return page[start.end():end.start()].strip("\n")


def main():
    module = load_generator()
    migrate = module.import_migrate(str(DOCS_DIR))
    lookup, file_map = module.build_file_map(
        migrate, DOCS_DIR / "_migration" / "slug-map.csv"
    )
    reverse_file_map = {mint: docu for docu, mint in file_map.items()}

    generators = module.dictionary_source_generators(str(DOCS_DIR), file_map)
    generated_sources = {}
    for generator in generators:
        basename = generator["name"].removeprefix("dictionary-source:")
        generated_sources[basename] = generator["params"]["source"]
    expected_sources = {
        basename: registered_name
        for basename, (_, registered_name) in SOURCE_PAGES.items()
    }
    if generated_sources != expected_sources:
        print("dictionary-source generator discovery or aliases differ", file=sys.stderr)
        return 1

    failures = []
    for basename, (source_name, _) in SOURCE_PAGES.items():
        source_path = REPO_ROOT / "src" / "Dictionaries" / source_name
        source = source_path.read_text(encoding="utf-8")
        match = RAW_DESCRIPTION_RE.search(source)
        if not match:
            failures.append(f"{source_name}: full-page raw description not found")
            continue

        mint_rel = f"reference/statements/create/dictionary/sources/{basename}.mdx"
        page_path = DOCS_DIR / mint_rel
        page = page_path.read_text(encoding="utf-8")
        if not module.is_fully_autogenerated_page(page):
            failures.append(f"{basename}: generated region does not cover the full page body")
            continue
        legacy_path = reverse_file_map[mint_rel]
        transformed = module.transform_full_body(
            migrate,
            match.group("body"),
            legacy_path,
            str(page_path),
            lookup,
            module.frontmatter_title(page),
        ).strip("\n")
        expected = generated_region(module, page)
        if transformed != expected:
            failures.append(f"{basename}: embedded documentation differs from MDX")

    if failures:
        print("\n".join(failures), file=sys.stderr)
        return 1
    print(f"OK: {len(SOURCE_PAGES)} dictionary-source pages match their embedded documentation")
    return 0


if __name__ == "__main__":
    sys.exit(main())

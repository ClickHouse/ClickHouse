#!/usr/bin/env python3
"""Self-contained tests for SQL-statement documentation generation."""

import importlib.util
import os
import re
import sys
import tempfile
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[4]
REGISTERED_STATEMENT_PATTERN = re.compile(
    r'\.registerStatement\(\s*"([^"]+)"')


def load_module():
    spec = importlib.util.spec_from_file_location(
        "autogenerate_docs", HERE / "autogenerate_docs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def marked_page(body="old body"):
    return (
        "---\ntitle: 'FROM'\n---\n\n"
        "{/*AUTOGENERATED_START*/}\n"
        f"{body}\n"
        "{/*AUTOGENERATED_END*/}\n"
    )


def registered_statement_names():
    names = []
    for source in sorted((REPO_ROOT / "src/Parsers").rglob("*.cpp")):
        names.extend(REGISTERED_STATEMENT_PATTERN.findall(
            source.read_text(encoding="utf-8")))

    assert names, "no registered statements found in source"
    assert len(names) == len(set(names)), (
        "duplicate statement registrations found")
    return set(names)


def main():
    mod = load_module()
    manifest_names = list(mod.STATEMENT_PAGE_NAMES.values())
    assert len(manifest_names) == len(set(manifest_names)), (
        "duplicate statement names found in manifest")

    expected_names = registered_statement_names()
    actual_names = set(manifest_names)
    assert actual_names == expected_names, (
        "statement page manifest differs from source registrations: "
        f"missing={sorted(expected_names - actual_names)}, "
        f"extra={sorted(actual_names - expected_names)}"
    )

    with tempfile.TemporaryDirectory() as root:
        docs = Path(root) / "docs"
        page = docs / "reference/statements/select/from.mdx"
        page.parent.mkdir(parents=True)
        page.write_text(marked_page(), encoding="utf-8")

        # A hand-written supplemental page is intentionally outside the manifest.
        supplemental = docs / "reference/statements/index.mdx"
        supplemental.write_text(marked_page(), encoding="utf-8")

        generators = mod.statement_generators(str(docs))
        assert len(generators) == 1
        generator = generators[0]
        assert generator["name"] == "statement:FROM"
        assert generator["params"] == {"statement": "FROM"}
        assert generator["mintlify_native"] is True
        assert generator["require_nonempty"] is True

        generated_body = "Mintlify-native [link](/reference/statements/select/index)"

        def fake_run_sql(_binary, _sql_path, cwd, params=None):
            assert params == {"statement": "FROM"}
            Path(cwd, "temp-statement.md").write_text(
                generated_body + "\n", encoding="utf-8")

        mod.run_sql = fake_run_sql
        mod.transform_body = lambda *args: (_ for _ in ()).throw(
            AssertionError("Mintlify-native statement documentation was transformed"))
        dest, output = mod.generate(
            generator,
            binary="unused",
            docs_dir=str(docs),
            repo_root=root,
            migrate=object(),
            lk=object(),
            file_map={},
            remap=True,
        )
        assert dest == os.fspath(page)
        assert generated_body in output
        assert "old body" not in output

        def fake_empty_sql(_binary, _sql_path, cwd, params=None):
            Path(cwd, "temp-statement.md").write_text("", encoding="utf-8")

        mod.run_sql = fake_empty_sql
        try:
            mod.generate(
                generator,
                binary="unused",
                docs_dir=str(docs),
                repo_root=root,
                migrate=object(),
                lk=object(),
                file_map={},
                remap=True,
            )
        except ValueError as error:
            assert "produced empty documentation" in str(error)
        else:
            raise AssertionError("empty statement documentation did not fail")

    print("OK: statement pages are routed and emitted verbatim")
    return 0


if __name__ == "__main__":
    sys.exit(main())

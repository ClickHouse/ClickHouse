#!/usr/bin/env python3
"""Self-contained tests for SQL-statement documentation generation."""

import importlib.util
import json
import re
import sys
import tempfile
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[4]
REGISTERED_STATEMENT_RE = re.compile(
    r'factory\.registerStatement\("(?P<name>[^"]+)",'
)
SOURCE_STATEMENT_RE = re.compile(
    r'factory\.registerStatement\("(?P<name>[^"]+)",\s*\{\s*'
    r'\.description\s*=\s*R"DOCS_MD\(\n'
    r'(?P<description>.*?)\n\)DOCS_MD"',
    re.DOTALL,
)


def load_module():
    spec = importlib.util.spec_from_file_location(
        "autogenerate_docs", HERE / "autogenerate_docs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def marked_page(title, body="old body"):
    return (
        f"---\ntitle: '{title}'\n---\n\n"
        "{/*AUTOGENERATED_START*/}\n"
        f"{body}\n"
        "{/*AUTOGENERATED_END*/}\n"
    )


def write_generator_output(cwd, rows):
    output = Path(cwd) / "temp-statements.jsonl"
    output.write_text(
        "".join(json.dumps(row) + "\n" for row in rows),
        encoding="utf-8",
    )


def source_statement_documents():
    documents = {}
    registered_names = set()
    for source in sorted((REPO_ROOT / "src/Parsers").rglob("*.cpp")):
        source_text = source.read_text(encoding="utf-8")
        registered_names.update(
            match.group("name")
            for match in REGISTERED_STATEMENT_RE.finditer(source_text)
        )
        for match in SOURCE_STATEMENT_RE.finditer(source_text):
            name = match.group("name")
            assert name not in documents, f"duplicate statement {name!r}"
            documents[name] = match.group("description")
    assert documents, "no registered statement documents found"
    assert set(documents) == registered_names, (
        "registered statements without structured page metadata: "
        f"{sorted(registered_names - set(documents))}"
    )
    return documents


def main():
    mod = load_module()

    source_names = set(source_statement_documents())
    marked_names = {
        name
        for name, _page, content in mod._statement_page_candidates(
            REPO_ROOT / "docs"
        )
        if mod.START_RE.search(content) or mod.END_RE.search(content)
    }
    assert source_names == marked_names, (
        f"source/page name mismatch: missing={sorted(source_names - marked_names)}, "
        f"extra={sorted(marked_names - source_names)}"
    )

    with tempfile.TemporaryDirectory() as root:
        docs = Path(root) / "docs"
        page = docs / "reference/statements/select/from.mdx"
        page.parent.mkdir(parents=True)
        page.write_text(marked_page("FROM"), encoding="utf-8")

        # Marked dictionary subtopic pages are generated by another family and
        # must not be mistaken for registered SQL statements.
        supplemental = (
            docs
            / "reference/statements/create/dictionary/sources/local-file.mdx"
        )
        supplemental.parent.mkdir(parents=True)
        supplemental.write_text(
            marked_page("Local file dictionary source"), encoding="utf-8")

        page.write_text(
            "---\nsidebarTitle: 'FROM'\n---\n\n"
            "{/*AUTOGENERATED_START*/}\nold body\n"
            "{/*AUTOGENERATED_END*/}\n",
            encoding="utf-8",
        )
        try:
            mod._statement_page_candidates(docs)
        except ValueError as error:
            assert "marked statement page has no frontmatter title" in str(error)
        else:
            raise AssertionError("marked statement page without a title did not fail")
        page.write_text(marked_page("FROM"), encoding="utf-8")

        generators = mod.statement_generators(str(docs))
        assert len(generators) == 1
        generator = generators[0]
        assert generator["name"] == "statement:"

        generated_body = (
            "Mintlify-native [link](/reference/statements/select/index)"
        )

        def fake_run_sql(_binary, _sql_path, cwd, params=None):
            assert params is None
            write_generator_output(cwd, [{
                "name": "FROM",
                "description": generated_body,
            }])

        mod.run_sql = fake_run_sql
        artifacts = mod.generate_artifacts(
            generator,
            binary="unused",
            docs_dir=str(docs),
            repo_root=root,
            migrate=object(),
            lk=object(),
            file_map={},
        )
        assert len(artifacts) == 1
        assert artifacts[0].path == page
        assert generated_body in artifacts[0].content
        assert "old body" not in artifacts[0].content

        page.write_text(
            "---\ntitle: 'FROM'\n---\n\nold body\n",
            encoding="utf-8",
        )
        try:
            mod.generate_statement_artifacts(
                generator, binary="unused", docs_dir=str(docs))
        except ValueError as error:
            assert "missing the AUTOGENERATED markers" in str(error)
        else:
            raise AssertionError("unmarked statement page did not fail")

        page.write_text(marked_page("FROM"), encoding="utf-8")

        def fake_missing_page(_binary, _sql_path, cwd, params=None):
            write_generator_output(cwd, [{
                "name": "NEW STATEMENT",
                "description": "Body",
            }])

        mod.run_sql = fake_missing_page
        try:
            mod.generate_statement_artifacts(
                generator, binary="unused", docs_dir=str(docs))
        except ValueError as error:
            assert "no matching Mintlify page title" in str(error)
        else:
            raise AssertionError("unrouted registered statement did not fail")

        def fake_incomplete_doc(_binary, _sql_path, cwd, params=None):
            write_generator_output(cwd, [{
                "name": "FROM",
                "description": "",
            }])

        mod.run_sql = fake_incomplete_doc
        try:
            mod.generate_statement_artifacts(
                generator, binary="unused", docs_dir=str(docs))
        except ValueError as error:
            assert "documentation body is empty" in str(error)
        else:
            raise AssertionError("statement without documentation did not fail")

    print("OK: registered statement documents are routed and fail closed")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""
Maintain the Mintlify navigation.

Per-section `navigation.json` fragments (e.g. `docs/reference/navigation.json`)
are the editable source of truth. `docs/docs.json` (the Mintlify manifest)
inlines each fragment under the menu entry whose `item`/`group` name matches
the fragment's root, with `$ref` includes resolved and object keys sorted
alphabetically -- that is the convention the committed docs.json follows, and
compiling an unchanged fragment reproduces docs.json byte-for-byte.

This module provides

  * `insert_page` -- add a newly generated page to a fragment group, placed
    alphabetically among the existing string entries (additive only: existing
    entries are never removed or reordered, group objects are left in place);
  * `compile_docs_json` / `run` -- recompile fragments into docs.json, with a
    `--check` mode that reports `NAV-DRIFT` when docs.json is stale.

autogenerate_docs.py runs this as the final step after page generation; it can
also be run standalone:

    python3 navigation.py --docs-dir docs --check
    python3 navigation.py --docs-dir docs --write
"""

import argparse
import json
import os
import sys

# Fragments compiled into docs.json. Only sections whose pages are autogenerated
# are listed; the other sections' fragments are maintained by hand and synced by
# their own tooling.
DEFAULT_FRAGMENTS = ["reference/navigation.json"]

# docs.json keeps the redirects include on one line; json.dumps(indent=2)
# expands it. Swap it back after serialization so the compile is byte-stable.
_REDIRECTS_EXPANDED = '"redirects": {\n    "$ref": "./_site/redirects.json"\n  }'
_REDIRECTS_ONE_LINE = '"redirects": { "$ref": "./_site/redirects.json" }'


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def dump_fragment(data):
    # The committed fragments are exactly this serialization (2-space indent,
    # unescaped non-ASCII, trailing newline).
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def dump_docs_json(data):
    # docs.json has no trailing newline and the one-line redirects include.
    return json.dumps(data, indent=2, ensure_ascii=False).replace(
        _REDIRECTS_EXPANDED, _REDIRECTS_ONE_LINE
    )


def sort_keys(node):
    # docs.json stores navigation objects with alphabetically sorted keys;
    # fragments use a natural order (`group` first). Sort on the way in.
    if isinstance(node, dict):
        return {k: sort_keys(node[k]) for k in sorted(node)}
    if isinstance(node, list):
        return [sort_keys(v) for v in node]
    return node


def resolve_refs(node, base_dir):
    # Fragments may include sub-fragments as {"$ref": "relative/path"}.
    if isinstance(node, dict):
        if set(node) == {"$ref"}:
            path = os.path.join(base_dir, node["$ref"])
            return resolve_refs(load_json(path), os.path.dirname(path))
        return {k: resolve_refs(v, base_dir) for k, v in node.items()}
    if isinstance(node, list):
        return [resolve_refs(v, base_dir) for v in node]
    return node


def fragment_root_key(fragment):
    # Section fragments root on "item" (a menu entry); sub-fragments included
    # via $ref root on "group". Matching on the same key disambiguates a menu
    # item from same-named groups nested inside other sections.
    for key in ("item", "group"):
        if fragment.get(key):
            return key
    raise ValueError("fragment root has neither 'item' nor 'group'")


def _find_named_nodes(tree, key, name, found):
    if isinstance(tree, dict):
        if tree.get(key) == name:
            found.append(tree)
        for value in tree.values():
            _find_named_nodes(value, key, name, found)
    elif isinstance(tree, list):
        for value in tree:
            _find_named_nodes(value, key, name, found)


def compile_docs_json(docs, fragment, fragment_dir):
    # Replace the docs.json navigation node matching the fragment's root name
    # with the fragment's content (refs resolved, keys sorted). The locale
    # navigations are unresolved {"$ref": ...} entries, so only the `en`
    # navigation contains named nodes and can match.
    key = fragment_root_key(fragment)
    name = fragment[key]
    compiled = sort_keys(resolve_refs(fragment, fragment_dir))
    found = []
    _find_named_nodes(docs["navigation"], key, name, found)
    if len(found) != 1:
        raise ValueError(
            f"expected exactly one navigation entry with {key}={name!r} in "
            f"docs.json, found {len(found)}"
        )
    node = found[0]
    node.clear()
    node.update(compiled)


def _group_pages(node, group_path):
    # Walk `group_path` (e.g. ["Engines", "Table Engines", "MergeTree Family"])
    # down from the fragment root and return the group's `pages` list.
    for name in group_path:
        children = node.get("pages") or node.get("groups") or []
        for child in children:
            if isinstance(child, dict) and child.get("group") == name:
                node = child
                break
        else:
            raise ValueError(f"navigation group {name!r} not found "
                             f"(path: {' > '.join(group_path)})")
    if "pages" not in node:
        node["pages"] = []
    return node["pages"]


def insert_page(fragment, group_path, page_id):
    """Insert `page_id` into the group at `group_path`, before the first string
    sibling that sorts after it (case-insensitive, by path basename). Group
    objects are pinned in place and existing entries are never reordered, so a
    curated order stays intact and the new page lands in its alphabetical slot.
    Returns True if the fragment changed."""
    pages = _group_pages(fragment, group_path)
    if page_id in pages:
        return False
    key = os.path.basename(page_id).lower()
    at = len(pages)
    for i, entry in enumerate(pages):
        if isinstance(entry, str) and os.path.basename(entry).lower() > key:
            at = i
            break
    pages.insert(at, page_id)
    return True


def run(docs_dir, write=False, check=False, fragments=None):
    """Compile the fragments into docs.json. Returns the number of stale
    files (for --check exit status)."""
    docs_json_path = os.path.join(docs_dir, "docs.json")
    docs = load_json(docs_json_path)
    sources = []
    for rel in fragments or DEFAULT_FRAGMENTS:
        path = os.path.join(docs_dir, rel)
        compile_docs_json(docs, load_json(path), os.path.dirname(path))
        sources.append(rel)
    new = dump_docs_json(docs)
    with open(docs_json_path, encoding="utf-8") as f:
        current = f.read()

    if current == new:
        print("ok: docs.json (navigation)")
        return 0
    if check:
        print(f"NAV-DRIFT: docs.json is stale relative to {', '.join(sources)}")
        return 1
    if write:
        with open(docs_json_path, "w", encoding="utf-8") as f:
            f.write(new)
        print("wrote: docs.json (navigation)")
    else:
        print("[dry-run] would update: docs.json (navigation)")
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--docs-dir", default="docs")
    p.add_argument("--fragment", action="append", dest="fragments",
                   help="fragment path relative to the docs dir (repeatable); "
                        f"default: {', '.join(DEFAULT_FRAGMENTS)}")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update docs.json in place")
    mode.add_argument("--check", action="store_true",
                      help="fail if docs.json is stale relative to the fragments")
    args = p.parse_args(argv)
    return 1 if run(os.path.abspath(args.docs_dir), write=args.write,
                    check=args.check, fragments=args.fragments) else 0


if __name__ == "__main__":
    sys.exit(main())

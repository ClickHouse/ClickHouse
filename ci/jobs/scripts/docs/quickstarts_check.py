#!/usr/bin/env python3
"""
Validate the quickstart pages and the generated explorer data.

Run from the docs root (the directory containing docs.json):

    python3 ../ci/jobs/scripts/docs/quickstarts_check.py .

Six checks (see docs/get-started/quickstarts/README.md for the authoring
guide):

1. Frontmatter metadata and badge markers. Every English and localized
   quickstart page must declare `searchable: true`. Quickstart pages are not
   included in any locale's sidebar, so this keeps them discoverable through
   docs search. Every English quickstart must additionally declare `products`
   (one or more of ALLOWED_PRODUCTS) and `useCases` (one or more of
   ALLOWED_USE_CASES). The QuickStartsGrid explorer filters match on slugs
   derived from the tag values, so an unknown value produces a card that no
   filter can find. Every English page must also contain the
   `AUTOGENERATED_START`/`AUTOGENERATED_END` marker pair: the generator
   rewrites the badge block between them, so a page without markers keeps
   stale badges that the freshness check below cannot detect.

2. Generated data freshness. The explorer card data
   (snippets/[<locale>/]components/QuickStartsGrid/quickstarts-data.jsx) and
   the badge blocks on the English pages are produced by
   _site/scripts/update_quickstarts.py from the page frontmatter. This check
   runs the generator and fails if it changes anything — meaning the PR
   author edited a quickstart without re-running the generator and committing
   its output. The working tree is restored afterwards; the failure message
   names the exact command to run.

3. Homepage links. English and localized homepages must render the canonical
   `/docs` mount during server-side rendering. Localized links must also use the
   page's locale before hydration. This keeps middle-click, copied links, and
   no-JavaScript clients on the final published destination.

4. Install-page Cloud banner parity. The English and localized install pages
   must render the same recommended Cloud banner, attributed signup link, and
   locale-preserving quickstart link.

5. Cloud setup signup attribution. The English and localized Cloud setup
   guides must all use the same attributed signup URL.

6. Localized quickstart navigation. The group labels added for the quickstart
   explorer must use each locale's existing terminology instead of rendering
   English labels in translated sidebars.
"""


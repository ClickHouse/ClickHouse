def parse_args():
    parser = argparse.ArgumentParser(
        "Checks if enough days elapsed since the last release on each release "
        "branches and do a release in case for green builds."
    )
    parser.add_argument("--token", help="GitHub token, if not set, used from smm")
    parser.add_argument(
        "--post-status",
        action="store_true",
        help="Post release branch statuses",
    )
    parser.add_argument(
        "--post-auto-release-complete",
        action="store_true",
        help="Post autorelease completion status",
    )
    parser.add_argument(
        "--prepare",
        action="store_true",
        help="Prepare autorelease info",
    )
    parser.add_argument(
        "--wf-status",
        type=str,
        default="",
        help="overall workflow status [success|failure]",
    )
    return parser.parse_args(), parser


MAX_NUMBER_OF_COMMITS_TO_CONSIDER_FOR_RELEASE = 8
AUTORELEASE_INFO_FILE = "/tmp/autorelease_info.json"
AUTORELEASE_MATRIX_PARAMS = "/tmp/autorelease_params.json"


@dataclasses.dataclass
class ReleaseParams:
    ready: bool
    ci_status: str
    num_patches: int
    release_branch: str
    commit_sha: str
    commits_to_branch_head: int
    latest: bool
    description: str = ""

    def to_dict(self):
        return dataclasses.asdict(self)


@dataclasses.dataclass
class AutoReleaseInfo:
    releases: List[ReleaseParams]

    def add_release(self, release_params: ReleaseParams) -> None:
        self.releases.append(release_params)

    def dump(self):
        print(f"Dump release info into [{AUTORELEASE_INFO_FILE}]")
        with open(AUTORELEASE_INFO_FILE, "w", encoding="utf-8") as f:
            print(json.dumps(dataclasses.asdict(self), indent=2), file=f)

        # dump file for GH action matrix that is similar to the file above but with dropped not ready release branches
        params = dataclasses.asdict(self)
        params["releases"] = [
            release for release in params["releases"] if release["ready"]
        ]
        with open(AUTORELEASE_MATRIX_PARAMS, "w", encoding="utf-8") as f:
            print(json.dumps(params, indent=2), file=f)

    @staticmethod
    def from_file() -> "AutoReleaseInfo":
        with open(AUTORELEASE_INFO_FILE, "r", encoding="utf-8") as json_file:
            res = json.load(json_file)
        releases = [ReleaseParams(**release) for release in res["releases"]]
        return AutoReleaseInfo(releases=releases)


# The six packages CreateRelease's PackageDownloader downloads per arch. Kept in
# sync with `ci/jobs/scripts/create_release.py` `PackageDownloader.PACKAGES`.
_RELEASE_PACKAGES = (
    "clickhouse-client",
    "clickhouse-common-static",
    "clickhouse-common-static-dbg",
    "clickhouse-keeper",
    "clickhouse-keeper-dbg",
    "clickhouse-server",
)


def _release_version_for_commit(commit_sha: str) -> str:
    """The `major.minor.patch.tweak` version CreateRelease computes for a
    release-branch commit, derived here without checking it out.

    Matches the new release helper `ci/jobs/scripts/clickhouse_version.py`
    (`CHVersion.get_current_version`): `major.minor.patch` come from the commit's
    `cmake/autogenerated_versions.txt`, and the tweak is the first-parent commit
    count since the file's `VERSION_GITHASH` (no tags), i.e. `git rev-list
    --count --first-parent <githash>..<commit>`.
    """
    content = Shell.get_output_or_raise(
        f"git show {commit_sha}:cmake/autogenerated_versions.txt"
    )
    parts = {}
    for line in content.splitlines():
        line = line.strip()
        if line.startswith("SET(VERSION_"):
            name, value = line[4:-1].split(maxsplit=1)
            parts[name] = value
    tweak = Shell.get_output_or_raise(
        f"git rev-list --count --first-parent {parts['VERSION_GITHASH']}..{commit_sha}"
    )
    return (
        f"{parts['VERSION_MAJOR']}.{parts['VERSION_MINOR']}."
        f"{parts['VERSION_PATCH']}.{tweak}"
    )


def _release_build_artifacts_ready(release_branch: str, commit_sha: str) -> bool:
    """Whether every package CreateRelease will download for this commit is
    present in S3.

    A commit can pass the CI checks above (`check_wf_completed` + no
    `get_failed_statuses`) while its release build was deduplicated by the CI
    cache — reported as `skipped`, which is not a *failed* status — so nothing (or
    only part) was uploaded under this commit's own SHA. CreateRelease downloads
    each package strictly from `REFs/<branch>/<commit_sha>/<build_job>/<file>`
    (`ci/jobs/scripts/create_release.py` `PackageDownloader`), so it would 404 on
    such a commit.

    Enumerate the *exact* object keys CreateRelease asks for — deb/rpm/tgz/
    tgz.sha512 for the six packages on amd+arm, plus the per-arch macOS
    `clickhouse` binary under `build_<arch>_darwin/` — and require every one to
    exist. A directory-level check is too weak (a partial upload, or a build-vs-
    release version mismatch, leaves the dir non-empty yet the exact file
    absent). Fail closed: a missing object rejects the commit and the selector
    falls back to the previous one.
    """
    version = _release_version_for_commit(commit_sha)
    major, minor = (int(x) for x in release_branch.split(".")[:2])
    is_new_ci = (major >= 25 and minor >= 3) or major > 25
    s3_release_prefix = f"REFs/{release_branch}" if is_new_ci else release_branch

    expected_by_job = {}  # type: dict[str, set]
    for arch in ("amd", "arm"):
        if is_new_ci:
            job = f"build_{arch}_release"
            job_darwin = f"build_{arch}_darwin"
        else:
            job = "package_release" if arch == "amd" else "package_aarch64"
            job_darwin = "binary_darwin" if arch == "amd" else "binary_darwin_aarch64"
        deb_arch = "amd64" if arch == "amd" else "arm64"
        rpm_arch = "x86_64" if arch == "amd" else "aarch64"
        files = expected_by_job.setdefault(job, set())
        for package in _RELEASE_PACKAGES:
            files.add(f"{package}_{version}_{deb_arch}.deb")
            files.add(f"{package}-{version}.{rpm_arch}.rpm")
            files.add(f"{package}-{version}-{deb_arch}.tgz")
            files.add(f"{package}-{version}-{deb_arch}.tgz.sha512")
        expected_by_job.setdefault(job_darwin, set()).add("clickhouse")

    s3 = S3Helper()
    for job, expected_files in expected_by_job.items():
        prefix = f"{s3_release_prefix}/{commit_sha}/{job}/"
        present = {key.rsplit("/", 1)[-1] for key in s3.list_prefix(prefix)}
        missing = expected_files - present
        if missing:
            print(
                f"Missing release artifacts for [{version}] under "
                f"[s3://.../{prefix}]: {sorted(missing)} — the release build for "
                f"this commit was skipped/cached or uploaded partially; not "
                f"releasable"
            )
            return False
    return True


def _prepare(token):
    assert len(token) > 10
    os.environ["GH_TOKEN"] = token
    Shell.check("gh auth status")

    # Check all previous version bump prs were merged
    open_version_change_prs = Shell.get_output(
        'gh pr list  --state open --search "Update version_date.tsv" --json number,title'
    )
    if open_version_change_prs != "[]":
        CIBuddy(dry_run=False).post_critical(
            "Found not merged version bump PRs", body=open_version_change_prs
        )
        raise RuntimeError()

    gh = GitHub(token)
    prs = gh.get_release_pulls(GITHUB_REPOSITORY)
    prs.sort(key=lambda x: x.head.ref)
    branch_names = [pr.head.ref for pr in prs]
    print(f"Found release branches [{branch_names}]")

    repo = gh.get_repo(GITHUB_REPOSITORY)
    autoRelease_info = AutoReleaseInfo(releases=[])

    for pr in prs:
        print(f"\nChecking PR [{pr.head.ref}]")

        refs = list(repo.get_git_matching_refs(f"tags/v{pr.head.ref}"))
        assert refs

        latest_release_tag_ref = refs[-1]
        latest_release_tag = repo.get_git_tag(latest_release_tag_ref.object.sha)

        commits = Shell.get_output_or_raise(
            f"git rev-list --first-parent {latest_release_tag.tag}..origin/{pr.head.ref}",
        ).split("\n")
        commit_num = len(commits)
        if latest_release_tag.tag.endswith("new"):
            print("It's a new release branch - skip auto release for it")
            continue

        print(
            f"Previous release [{latest_release_tag.tag}] was [{commit_num}] commits ago, date [{latest_release_tag.tagger.date}]"
        )

        commits_to_check = commits[:-1]  # Exclude the version bump commit
        commit_sha = ""
        commit_ci_status = ""
        commits_to_branch_head = 0

        description = ""
        for idx, commit in enumerate(
            commits_to_check[:MAX_NUMBER_OF_COMMITS_TO_CONSIDER_FOR_RELEASE]
        ):
            print(
                f"Check commit [{commit}] [{pr.head.ref}~{idx+1}] as release candidate"
            )
            commit_num -= 1

            is_completed = GH.check_wf_completed(token=token, commit_sha=commit)
            if not is_completed:
                print(f"CI is in progress for [{commit}] - check previous commit")
                commits_to_branch_head += 1
                continue

            failed_jobs = GH.get_failed_statuses(token=token, commit_sha=commit)
            if failed_jobs:
                print(
                    f"CI failed for [{commit}]: {failed_jobs} - check previous commit"
                )
                # Save the description from the most recent failed commit
                if not description:
                    description = f"Failed jobs: {failed_jobs}"
                commits_to_branch_head += 1
                continue

            # CI is green, but "no failed jobs" also passes when the release
            # build was deduplicated by the CI cache (reported `skipped`, not
            # `failed`) and no packages were uploaded under this commit's SHA.
            # Releasing such a commit fails later in CreateRelease's package
            # download, so require the exact artifacts to actually be present.
            if not _release_build_artifacts_ready(pr.head.ref, commit):
                print(
                    f"CI green for [{commit}] but release build artifacts are "
                    f"missing - check previous commit"
                )
                if not description:
                    description = "Release build artifacts missing (build skipped/cached)"
                commits_to_branch_head += 1
                continue

            commit_sha = commit
            commit_ci_status = SUCCESS
            break

        ready = False
        if commit_ci_status == SUCCESS and commit_sha:
            print(
                f"Add release ready info for commit [{commit_sha}] and release branch [{pr.head.ref}]"
            )
            ready = True
        else:
            print(f"WARNING: No ready commits found for release branch [{pr.head.ref}]")

        autoRelease_info.add_release(
            ReleaseParams(
                release_branch=pr.head.ref,
                commit_sha=commit_sha,
                ready=ready,
                ci_status=commit_ci_status,
                num_patches=commit_num,
                commits_to_branch_head=commits_to_branch_head,
                latest=False,
                description=description if not ready else "",
            )
        )

    if autoRelease_info.releases:
        autoRelease_info.releases[-1].latest = True

    autoRelease_info.dump()


def main():
    args, parser = parse_args()

    if args.post_status:
        info = AutoReleaseInfo.from_file()
        for release_info in info.releases:
            if release_info.ready:
                CIBuddy(dry_run=False).post_info(
                    title=f"Auto Release Status for {release_info.release_branch}",
                    body=release_info.to_dict(),
                )
            else:
                CIBuddy(dry_run=False).post_warning(
                    title=f"Auto Release Status for {release_info.release_branch}",
                    body=release_info.to_dict(),
                )
    elif args.post_auto_release_complete:
        assert args.wf_status, "--wf-status Required with --post-auto-release-complete"
        if args.wf_status != SUCCESS:
            CIBuddy(dry_run=False).post_job_error(
                error_description="Autorelease workflow failed",
                job_name="Autorelease",
                with_instance_info=False,
                with_wf_link=True,
                critical=True,
            )
        else:
            CIBuddy(dry_run=False).post_info(
                title="Autorelease completed",
                body="",
                with_wf_link=True,
            )
    elif args.prepare:
        _prepare(token=args.token or get_best_robot_token())
    else:
        parser.print_help()
        sys.exit(2)


if __name__ == "__main__":
    main()

"""Enabling the union system log tables must not drop a user's table that sits on one of the names.

The union tables are proxies over a table function and hold no data, so the creation path replaces an
outdated one. `system.all_query_log` is also exactly the name a hand-rolled union of the rotated logs
takes, and such a table can be a `MergeTree` holding history - replacing that loses its data silently.
A user's own proxy `AS merge(...)` or `AS clusterAllReplicas(...)` on such a name is kept as well: a
generated table is recognized only by reading from this very log table through one of the shapes the
feature generates, and by carrying the comment those definitions have always carried.
"""

import os
import threading

import pytest

from helpers.cluster import ClickHouseCluster

SCRIPT_DIR = os.path.dirname(os.path.realpath(__file__))

cluster = ClickHouseCluster(__file__)
# The union section is added later, which is what an upgrade or a configuration change looks like.
node = cluster.add_instance(
    "node", main_configs=["configs/clusters.xml"], stay_alive=True
)

MARKER = (
    "It is safe to drop this table at any time: it will be recreated automatically."
)


@pytest.fixture(scope="module")
def started_cluster():
    try:
        cluster.start()
        yield cluster
    finally:
        cluster.shutdown()


def show_create(table):
    return node.query(f"SHOW CREATE TABLE system.{table} FORMAT TSVRaw")


def test_user_tables_on_union_names_survive(started_cluster):
    # A history table with data.
    node.query(
        "CREATE TABLE system.all_query_log (d Date, note String) ENGINE = MergeTree ORDER BY d"
    )
    node.query(
        "INSERT INTO system.all_query_log SELECT '2026-01-01', 'precious' FROM numbers(10)"
    )
    assert (
        node.query("SELECT count() FROM system.all_query_log WHERE note = 'precious'")
        == "10\n"
    )

    # The user's own proxies over the same table functions the feature uses. They differ from the
    # generated definitions only in the arguments and in the absence of the comment. The log tables
    # have to exist for the structure of the proxies to be derived from them.
    node.query("SYSTEM FLUSH LOGS")
    node.query("CREATE TABLE system.all_trace_log AS merge('system', '^trace_log')")
    node.query(
        "CREATE TABLE system.all_part_log AS clusterAllReplicas('system_logs_cluster', 'system', 'part_log')"
    )

    # A definition generated by an older server, when no cluster was configured: it reads from this
    # very log table through one of the generated shapes and carries the marker, so it is ours and is
    # brought up to date. The column list is stale as well, which is what pins the recreation.
    node.query(
        f"CREATE TABLE system.all_text_log (dummy UInt8) AS merge('system', '^text_log(_[0-9]+)?$')"
        f" COMMENT 'Union of the `text_log` table and its rotated versions.\\n\\n{MARKER}'"
    )

    # A user's proxy that copied the generated comment but reads from something else. The comment is
    # not an ownership transfer: the table is the user's and is kept.
    node.query(
        f"CREATE TABLE system.all_query_views_log (dummy UInt8) AS merge('system', '^query_views_log_stale$')"
        f" COMMENT 'Union of the `query_views_log` table and its rotated versions.\\n\\n{MARKER}'"
    )

    node.copy_file_to_container(
        os.path.join(SCRIPT_DIR, "configs/union_system_logs.xml"),
        "/etc/clickhouse-server/config.d/union_system_logs.xml",
    )
    node.restart_clickhouse()

    # The flush is what runs the union-table preparation for every log.
    node.query("SELECT 42")
    node.query("SYSTEM FLUSH LOGS")

    assert (
        node.query("SELECT count() FROM system.all_query_log WHERE note = 'precious'")
        == "10\n"
    )
    assert (
        node.query(
            "SELECT engine FROM system.tables WHERE database = 'system' AND name = 'all_query_log'"
        )
        == "MergeTree\n"
    )
    assert node.contains_in_log("Not creating system.all_query_log")

    trace_log_create = show_create("all_trace_log")
    assert "AS merge('system', '^trace_log')" in trace_log_create
    assert MARKER not in trace_log_create
    assert node.contains_in_log("Not creating system.all_trace_log")

    part_log_create = show_create("all_part_log")
    assert (
        "AS clusterAllReplicas('system_logs_cluster', 'system', 'part_log')"
        in part_log_create
    )
    assert MARKER not in part_log_create
    assert node.contains_in_log("Not creating system.all_part_log")

    text_log_create = show_create("all_text_log")
    assert "dummy" not in text_log_create
    assert (
        "AS clusterAllReplicas('system_logs_cluster', merge('system', '^text_log(_[0-9]+)?$')"
        in text_log_create
    )
    assert MARKER in text_log_create
    assert not node.contains_in_log("Not creating system.all_text_log")

    views_log_create = show_create("all_query_views_log")
    assert "query_views_log_stale" in views_log_create
    assert "dummy" in views_log_create
    assert node.contains_in_log("Not creating system.all_query_views_log")

    # Once the user's tables are gone, the union tables take their names, so the feature itself keeps
    # working. A log is only prepared again on a flush that has something to write, so every one of
    # them gets an entry first.
    tables = ["all_query_log", "all_trace_log", "all_part_log", "all_query_views_log"]
    for table in tables:
        node.query(f"DROP TABLE system.{table} SYNC")
    node.query("CREATE TABLE some_parts (x UInt8) ENGINE = MergeTree ORDER BY x")
    node.query(
        "CREATE MATERIALIZED VIEW some_parts_mv ENGINE = MergeTree ORDER BY x AS SELECT x FROM some_parts"
    )
    node.query("INSERT INTO some_parts VALUES (1)")
    node.query("SYSTEM FLUSH LOGS")
    for table in tables:
        create = show_create(table)
        assert "AS clusterAllReplicas('system_logs_cluster', merge('system'," in create
        assert MARKER in create


def test_user_table_created_during_the_replacement_survives(started_cluster):
    """A user table created while the union table is being created must not be replaced.

    The union table's owner is classified outside any `DDLGuard`, so between that decision and the
    exchange that publishes the new table another session can put a table of its own on the name.
    `CREATE OR REPLACE` of a generated union table definition re-applies the ownership rule itself, under
    the target name's `DDLGuard` immediately before the exchange, so that table is left alone.
    """
    # Start from the state the previous test leaves: the union tables exist and are up to date.
    node.query("SELECT 42")
    node.query("SYSTEM FLUSH LOGS")
    assert MARKER in show_create("all_query_log")

    # Dropping it is what makes the next flush create it again - the creation this test races with.
    node.query("DROP TABLE system.all_query_log SYNC")

    node.query("SYSTEM ENABLE FAILPOINT create_or_replace_before_rename")
    # The flush prepares the union table and parks before the exchange that publishes it. It only
    # runs the preparation when the log has something to write, hence the query before it.
    node.query("SELECT 'racing the union table creation'")
    flush = threading.Thread(target=lambda: node.query("SYSTEM FLUSH LOGS query_log"))
    flush.start()
    try:
        node.query("SYSTEM WAIT FAILPOINT create_or_replace_before_rename PAUSE")

        # The window: a user takes the name and puts data in it.
        node.query(
            "CREATE TABLE system.all_query_log (d Date, note String) ENGINE = MergeTree ORDER BY d"
        )
        node.query(
            "INSERT INTO system.all_query_log SELECT '2026-01-01', 'precious' FROM numbers(10)"
        )
    finally:
        node.query("SYSTEM NOTIFY FAILPOINT create_or_replace_before_rename")
        node.query("SYSTEM DISABLE FAILPOINT create_or_replace_before_rename")
    flush.join()

    # The exchange saw the user's table under the guard and refused to replace it.
    assert (
        node.query("SELECT count() FROM system.all_query_log WHERE note = 'precious'")
        == "10\n"
    )
    assert (
        node.query(
            "SELECT engine FROM system.tables WHERE database = 'system' AND name = 'all_query_log'"
        )
        == "MergeTree\n"
    )
    # The message of the refusal under the `DDLGuard`, not the one of the up-front check.
    assert node.contains_in_log(
        "the name was taken by a table that this server did not generate for it while the"
    )
    # The aborted replacement left no filled temporary table behind.
    assert (
        node.query(
            "SELECT count() FROM system.tables WHERE database = 'system' AND name LIKE '%tmp_replace%'"
        )
        == "0\n"
    )

    # Once the user's table is gone, the union table takes the name again.
    node.query("DROP TABLE system.all_query_log SYNC")
    node.query("SELECT 'after the collision is resolved'")
    node.query("SYSTEM FLUSH LOGS query_log")
    assert MARKER in show_create("all_query_log")

-- CTE column aliases must work with INTERSECT/EXCEPT (issue #104770)
SET enable_analyzer = 1;

WITH t (a, b) AS (SELECT 1, 2 INTERSECT SELECT 1, 2) SELECT a, b FROM t ORDER BY a;
WITH t (a, b) AS (SELECT 1, 2 INTERSECT DISTINCT SELECT 1, 2) SELECT a, b FROM t ORDER BY a;
WITH t (a, b) AS (SELECT 1, 2 EXCEPT SELECT 3, 4) SELECT a, b FROM t ORDER BY a;
WITH t (a, b) AS (SELECT 1, 2 EXCEPT DISTINCT SELECT 3, 4) SELECT a, b FROM t ORDER BY a;
WITH t (a, b) AS (SELECT 1, 2 INTERSECT SELECT 1, 2 UNION ALL SELECT 3, 4) SELECT a, b FROM t ORDER BY a;
WITH t (a) AS (SELECT number FROM numbers(5) INTERSECT SELECT number + 2 FROM numbers(5)) SELECT a FROM t ORDER BY a;
WITH t (a) AS (SELECT number FROM numbers(5) EXCEPT SELECT number + 2 FROM numbers(5)) SELECT a FROM t ORDER BY a;

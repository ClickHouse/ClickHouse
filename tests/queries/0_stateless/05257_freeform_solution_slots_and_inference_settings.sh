#!/usr/bin/env bash
# Tags: no-fasttest

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CUR_DIR"/../shell_config.sh

FILE_NAME=${CLICKHOUSE_TEST_UNIQUE_NAME}.data
DATA_FILE=${USER_FILES_PATH:?}/$FILE_NAME

trap 'rm -f "$DATA_FILE"' EXIT
touch "$DATA_FILE"

echo "A JSON key named like the autogenerated name of a later field does not stand in for that field"

for i in $(seq 1 150); do echo "{\"a\":$i} $i"; done > $DATA_FILE
echo '{"c1":0,"a":1} 2' >> $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select count() from file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "CANNOT_READ_ALL_DATA" | head -1

for i in $(seq 1 150); do echo "{\"a\":$i} $i"; done > $DATA_FILE
echo '{"c1":0,"a":1}' >> $DATA_FILE

$CLICKHOUSE_CLIENT -q "select count() from file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "CANNOT_READ_ALL_DATA" | head -1

echo "A separator character that the escaping rule made part of the field is data"

printf 'a,",",b\nc,",",d\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all"

printf "' ' 1\n" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all format JSONEachRow"

echo "input_format_try_infer_integers"

echo "1 2" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings input_format_try_infer_integers = 1"
$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings input_format_try_infer_integers = 0"

echo "The schema cache is keyed by the inference settings"

echo "2022-01-01 00:00:00" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings input_format_try_infer_dates = 1, input_format_try_infer_datetimes = 1"
$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings input_format_try_infer_dates = 0, input_format_try_infer_datetimes = 0"

echo "schema_inference_hints"

printf '\\N\t1\n\\N\t2\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings schema_inference_hints = 'c0 Nullable(UInt64)'"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all settings schema_inference_hints = 'c0 Nullable(UInt64)'"

echo "schema_inference_make_columns_nullable"

printf 'a\\tb\t\\N\t\\:\nc\\td\t2\t\\:\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings schema_inference_make_columns_nullable = 0"
$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings schema_inference_make_columns_nullable = 1"

echo "column_names_for_schema_inference"

echo "1 2" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings column_names_for_schema_inference = 'x,y'"
$CLICKHOUSE_CLIENT -q "select y, x from file('$FILE_NAME', 'Freeform') settings column_names_for_schema_inference = 'x,y'"
$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings column_names_for_schema_inference = 'x'" 2>&1 | grep -oF "CANNOT_EXTRACT_TABLE_STRUCTURE" | head -1

echo '{"b":1,"a":2}' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "select q, p from file('$FILE_NAME', 'Freeform') settings column_names_for_schema_inference = 'p,q'"

echo "input_format_max_bytes_to_read_for_schema_inference"

(for i in $(seq 1 20); do echo "$i"; done; echo "abc") > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "CANNOT_EXTRACT_TABLE_STRUCTURE" | head -1
$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform') settings input_format_max_bytes_to_read_for_schema_inference = 10"

echo "INSERT SELECT reorders the columns named by the data to the columns of the table"

echo '{"b":1,"a":2}' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "drop table if exists t_freeform_order"
$CLICKHOUSE_CLIENT -q "create table t_freeform_order (a UInt64, b UInt64) engine = Memory"
$CLICKHOUSE_CLIENT -q "insert into t_freeform_order select * from file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from t_freeform_order"
$CLICKHOUSE_CLIENT -q "drop table t_freeform_order"

#!/usr/bin/env bash
# Tags: no-fasttest

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CUR_DIR"/../shell_config.sh

FILE_NAME=${CLICKHOUSE_TEST_UNIQUE_NAME}.data
DATA_FILE=${USER_FILES_PATH:?}/$FILE_NAME

trap 'rm -f "$DATA_FILE"' EXIT
touch "$DATA_FILE"

echo "A one-character punctuation token is data, not a separator"

echo -e "a - 1
b - 2" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all"

echo "A row after the inference sample that stops matching the solution fails instead of reusing the previous row"

for i in $(seq 1 150); do echo "abc $i"; done > $DATA_FILE
echo "short" >> $DATA_FILE

$CLICKHOUSE_CLIENT -q "select count() from file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "CANNOT_READ_ALL_DATA" | head -1

echo "A JSON row after the inference sample that omits a key fails instead of reusing the previous row"

for i in $(seq 1 150); do echo "{\"msg\":$i,\"type\":\"log\"}"; done > $DATA_FILE
echo "{\"type\":\"log2\"}" >> $DATA_FILE

$CLICKHOUSE_CLIENT -q "select count() from file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "CANNOT_READ_ALL_DATA" | head -1

echo "An explicit structure narrower than the inferred solution fails instead of reading out of bounds"

echo -e "1 2 3
4 5 6" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'c0 Int64')" 2>&1 | grep -oF "INCORRECT_NUMBER_OF_COLUMNS" | head -1

echo "An explicit structure of the right width works"

$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'c0 Int64, c1 Int64, c2 Int64') order by all"

echo "A row that ends with a trailing delimiter ends there instead of continuing on the next line"

echo -e "a,
b" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all"

echo "An empty input with an explicit structure is zero rows, not an error"

truncate -s 0 $DATA_FILE

$CLICKHOUSE_CLIENT -q "select count() from file('$FILE_NAME', 'Freeform', 'c0 String')"

echo "A root JSON key colliding with an autogenerated column name is rejected instead of merging two columns"

echo -e "{\"c1\":1} 2" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "CANNOT_EXTRACT_TABLE_STRUCTURE" | head -1

echo "An Escaped field keeps its escape sequences until the final deserialization"

printf 'a\\tb\t\\N\t\\:\nc\\td\t2\t\\:\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all"

echo "A column that is null in every row has no type"

printf '\\N\t1\n\\N\t2\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')" 2>&1 | grep -oF "ONLY_NULLS_WHILE_READING_SCHEMA" | head -1

echo "Fields named by the data are read into the columns of the same name, in any order"

echo '{"b":1,"a":2}' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'a UInt64, b UInt64')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'b String, a UInt64')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'a UInt64, c UInt64')" 2>&1 | grep -oF "INCORRECT_DATA" | head -1

echo "Autogenerated names are read by position unless the structure names them"

echo "1 2" > $DATA_FILE

$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'a UInt64, b UInt64')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'c1 UInt64, c0 UInt64')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform', 'x UInt64, c0 UInt64')" 2>&1 | grep -oF "INCORRECT_DATA" | head -1

echo "Fields are deserialized as the column of the provided structure, not as the inferred type"

echo '{"type":"log","msg":1}' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "drop table if exists t_freeform_insert"
$CLICKHOUSE_CLIENT -q "create table t_freeform_insert (msg Nullable(UInt64), type String) engine = Memory"
$CLICKHOUSE_CLIENT -q "insert into t_freeform_insert format Freeform" < $DATA_FILE
$CLICKHOUSE_CLIENT -q "select * from t_freeform_insert"
$CLICKHOUSE_CLIENT -q "drop table t_freeform_insert"

echo "Blank lines are not rows, for inference as well as for reading"

printf '\na b\n\nc d\n\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all"

echo "A JSON key not seen in the first row is skipped wherever it is, also in the inference sample"

printf '{"msg":1,"type":"log"} 7\n{"skipped":0,"msg":2,"type":"log"} 8\n' > $DATA_FILE

$CLICKHOUSE_CLIENT -q "desc file('$FILE_NAME', 'Freeform')"
$CLICKHOUSE_CLIENT -q "select * from file('$FILE_NAME', 'Freeform') order by all"

echo "The format may be reused for several streams of an asynchronous insert"

$CLICKHOUSE_CLIENT -q "drop table if exists t_freeform_async"
$CLICKHOUSE_CLIENT -q "create table t_freeform_async (a UInt64, b String) engine = Memory"
echo "1 x" | $CLICKHOUSE_CLIENT --async_insert 1 --wait_for_async_insert 1 --async_insert_busy_timeout_min_ms 1000 --async_insert_busy_timeout_max_ms 1000 -q "insert into t_freeform_async format Freeform" &
echo '{"b":"y","a":2}' | $CLICKHOUSE_CLIENT --async_insert 1 --wait_for_async_insert 1 --async_insert_busy_timeout_min_ms 1000 --async_insert_busy_timeout_max_ms 1000 -q "insert into t_freeform_async format Freeform" &
wait
$CLICKHOUSE_CLIENT -q "select * from t_freeform_async order by all"
$CLICKHOUSE_CLIENT -q "drop table t_freeform_async"

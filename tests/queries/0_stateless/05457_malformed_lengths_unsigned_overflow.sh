#!/usr/bin/env bash
# Tags: no-fasttest
# Lengths and offsets read from malformed input are rejected with an error before they are added to or
# subtracted from a position, instead of wrapping around (which UBSan reports as an unsigned overflow).

CURDIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CURDIR"/../shell_config.sh

# A Protobuf length of `UINT64_MAX`: for the root message and for a length-delimited field.
$CLICKHOUSE_LOCAL -q "
    SELECT * FROM format(Protobuf, 'x UInt64', unhex('ffffffffffffffffff01'))
    SETTINGS format_protobuf_use_autogenerated_schema = 1" 2>&1 | grep -o -m1 'UNKNOWN_PROTOBUF_FORMAT'
$CLICKHOUSE_LOCAL -q "
    SELECT * FROM format(ProtobufSingle, 'x String', unhex('0affffffffffffffffff01'))
    SETTINGS format_protobuf_use_autogenerated_schema = 1" 2>&1 | grep -o -m1 'UNKNOWN_PROTOBUF_FORMAT'

# A Parquet column chunk whose dictionary page offset (93) is after its data page offset (92).
BAD_FILE="${CLICKHOUSE_TMP}/${CLICKHOUSE_TEST_UNIQUE_NAME}.parquet"
cp "$CURDIR/data_parquet/05318_parquet_dictionary_bit_width_0.parquet" "$BAD_FILE"
printf '\xba' | dd of="$BAD_FILE" bs=1 seek=220 conv=notrunc status=none
for q in "SELECT sum(c) FROM file('$BAD_FILE')" "SELECT count() FROM file('$BAD_FILE') WHERE c = 1"; do
    $CLICKHOUSE_LOCAL -q "$q SETTINGS input_format_parquet_use_native_reader_v3 = 1" 2>&1 | grep -o -m1 'INCORRECT_DATA'
done
rm -f "$BAD_FILE"

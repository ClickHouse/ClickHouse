#!/usr/bin/env bash
# Tags: no-fasttest
#       ^ no Parquet support in fasttest

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CUR_DIR"/../shell_config.sh

# Regression test: `extractSpatialFilters`'s `accept_input` (src/Processors/Formats/Impl/Parquet/GeoFilter.cpp)
# used to accept ANY column referenced by a spatial predicate as long as it was present in the
# sample block, regardless of its type. `MergeTree`'s `spatial_bbox` index can never face a
# `Variant`-typed indexed column: `spatialBboxIndexValidator` requires the column to structurally
# reduce to `Tuple(Float64,Float64)`, which rejects `Geometry` (`Variant`) at index-creation time.
# GeoParquet has no equivalent guard -- a mixed/unknown-kind GeoParquet column is exposed as
# `Geometry` (`Variant` over `Point`/`Ring`/`Polygon`/...), and different row groups can genuinely
# store different geometry kinds. Accepting such a column derives a pruning bbox from the row
# group's `covering.bbox` statistics and can prune away the very row group whose real geometry kind
# `polygonsIntersectCartesian`/`polygonsWithinCartesian`/`pointInPolygon` is guaranteed to reject
# (e.g. `Point` for `polygonsIntersectCartesian`, `Polygon` for `pointInPolygon`) -- silently
# returning a result instead of raising `ILLEGAL_TYPE_OF_ARGUMENT`.
#
# The fixture (generated by a throwaway pyarrow script, not checked into the repo) has 2 row
# groups on column `geometry` (Geometry/Variant, geometry_types = ["Point", "Polygon"]), with
# `covering.bbox` statistics columns `bbox_xmin`/`bbox_ymin`/`bbox_xmax`/`bbox_ymax`:
#   - row group 1: 2 `Point` rows near (-100, -100)
#   - row group 2: 2 `Polygon` rows, the square (0,0)-(2,2)

FILE="$CUR_DIR/data_parquet/04886_geo_variant_column_pruning.parquet"

echo "=== toTypeName(geometry) is Geometry (Variant) -- mixed-kind GeoParquet column ==="
$CLICKHOUSE_LOCAL -q "SELECT DISTINCT toTypeName(geometry) FROM file('$FILE', Parquet)"

# polygonsIntersectCartesian rejects Point. Row group 1 (Point, far from the query polygon near
# the origin) must not be pruned away using only the query bbox: it must still be evaluated and
# raise, not be silently skipped in favor of only row group 2 (Polygon, which the predicate
# accepts and which does overlap the query polygon).
echo "=== polygonsIntersectCartesian: row group 1 (Point) must still raise, not be pruned away ==="
$CLICKHOUSE_LOCAL -q "
SELECT count() FROM file('$FILE', Parquet)
WHERE polygonsIntersectCartesian(geometry, [[(0., 0.), (2., 0.), (2., 2.), (0., 2.), (0., 0.)]])
" 2>&1 | grep -o "must not be Point"

# pointInPolygon requires its first argument to be a Point. Row group 2 (Polygon, far from the
# query polygon near (-100, -100)) must not be pruned away either: it must still be evaluated and
# raise, not be silently skipped in favor of only row group 1 (Point, which pointInPolygon accepts).
echo "=== pointInPolygon: row group 2 (Polygon) must still raise, not be pruned away ==="
$CLICKHOUSE_LOCAL -q "
SELECT count() FROM file('$FILE', Parquet)
WHERE pointInPolygon(geometry, [(-102., -102.), (-98., -102.), (-98., -98.), (-102., -98.), (-102., -102.)])
" 2>&1 | grep -o "must contain a tuple"

# Sanity: a predicate accepting every kind actually stored in the column (here, both Point and
# Polygon columns queried without any spatial predicate at all) must still read every row -- this
# fix must not regress ordinary reads of a mixed-kind Geometry column.
echo "=== sanity: reading the mixed-kind column without a spatial predicate is unaffected ==="
$CLICKHOUSE_LOCAL -q "SELECT count() FROM file('$FILE', Parquet)"

-- A `STEP` below the unit in the last place of the cursor cannot advance it (`1e17 + 0.25 == 1e17`),
-- so the fill stops instead of generating the same row forever.

SELECT count() FROM
(
    SELECT 100000000000000000. AS x ORDER BY x WITH FILL FROM 100000000000000000. TO 100000000000000010. STEP 0.25
);

SELECT x FROM
(
    SELECT 100000000000000000. AS x ORDER BY x WITH FILL FROM 100000000000000000. TO 100000000000000010. STEP 0.25
);

-- A step at or above the precision of the values still fills the whole range.

SELECT x FROM
(
    SELECT 100000000000000000. AS x ORDER BY x WITH FILL FROM 100000000000000000. TO 100000000000000100. STEP 32
);

SELECT x FROM (SELECT 1. AS x ORDER BY x WITH FILL FROM 1. TO 3. STEP 0.5);

-- The same for a descending order and for the second `WITH FILL` key.

SELECT x FROM
(
    SELECT 100000000000000000. AS x ORDER BY x DESC WITH FILL FROM 100000000000000000. TO 99999999999999990. STEP -0.25
);

SELECT y, x FROM
(
    SELECT 1 AS y, 100000000000000000. AS x
    ORDER BY y WITH FILL FROM 1 TO 3 STEP 1, x WITH FILL FROM 100000000000000000. TO 100000000000000010. STEP 0.25
);

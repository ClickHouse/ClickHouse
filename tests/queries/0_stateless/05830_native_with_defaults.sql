-- `NativeWithDefaults` is `Native` with a marker byte after the type of each column and, if the marker is 1, a defaults mask
-- with a byte per row. The rows that the mask marks take the default of the column and have no value in the column data.

SELECT 'documentation example';
SELECT * FROM format(NativeWithDefaults, 'x UInt32 DEFAULT 42, y String', x'020301780655496e743332010001000100000003000000017906537472696e6700016101620163');

SELECT 'without a DEFAULT expression, the default of the type';
SELECT * FROM format(NativeWithDefaults, 'x UInt32, e Enum8(\'a\' = 1, \'b\' = 2), s String, n Nullable(UInt32)', x'040301780655496e7433320101000105000000016517456e756d3828276127203d20312c20276227203d203229010001000201017306537472696e6701010100017a016e104e756c6c61626c652855496e743332290100010000000400000006000000');

SELECT 'DEFAULT and NULL in a Nullable column';
SELECT * FROM format(NativeWithDefaults, 'x Nullable(UInt32) DEFAULT 42', x'01030178104e756c6c61626c652855496e743332290101000001000000000007000000');

SELECT 'DEFAULT expressions of other columns';
SELECT * FROM format(NativeWithDefaults, 'x UInt32, y UInt32 DEFAULT x * 10', x'020301780655496e7433320001000000020000000300000001790655496e7433320101000105000000');
SELECT * FROM format(NativeWithDefaults, 'x UInt32 DEFAULT 5, y UInt32 DEFAULT x * 10', x'020201780655496e7433320101000200000001790655496e743332010101');


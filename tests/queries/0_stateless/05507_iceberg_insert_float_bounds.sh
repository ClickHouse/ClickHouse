#!/usr/bin/env bash
# Tags: no-fasttest

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CUR_DIR"/../shell_config.sh

PREFIX="t_${CLICKHOUSE_DATABASE}_${RANDOM}"
ROOT="${USER_FILES_PATH}/${PREFIX}"
CREATED_TABLES=()

cleanup()
{
    for table in "${CREATED_TABLES[@]}"; do
        ${CLICKHOUSE_CLIENT} --query "DROP TABLE IF EXISTS ${table}"
    done
    rm -rf "${ROOT}"
}
trap cleanup EXIT

# Creates a two-column `(f32 Float32, f64 Float64)` table, inserts `values` (each row sets both
# columns to the same value, so one INSERT exercises both widths at once), and prints which field
# ids got bounds plus the decoded f32 (field id 1) / f64 (field id 2) bounds.
# With `split`, every row is written as its own chunk, so the per-chunk ranges are merged by
# `uniteRanges`. `INSERT ... VALUES` always arrives as one chunk whatever `max_block_size` is, so the
# rows are generated by `numbers`, which emits blocks of exactly `max_block_size` rows. The format is
# pinned to Parquet: for a format that prefers large blocks (e.g. ORC), insert squashing would merge
# the blocks back up to `min_insert_block_size_rows` instead of `max_block_size`.
run_case()
{
    local suffix="$1" values="$2" split="${3:-}"
    local table="${PREFIX}_${suffix}"
    CREATED_TABLES+=("${table}")

    echo "--- ${suffix}: values=${values}${split:+ (one row per chunk)}"
    ${CLICKHOUSE_CLIENT} --query "
        CREATE TABLE ${table} (f32 Nullable(Float32), f64 Nullable(Float64))
        ENGINE = IcebergLocal('${ROOT}/${suffix}/', 'Parquet')
    "
    if [ -n "${split}" ]; then
        local num_rows
        num_rows=$(grep -o '(' <<< "${values}" | wc -l)
        ${CLICKHOUSE_CLIENT} --allow_insert_into_iceberg=1 --query "
            INSERT INTO ${table}
            WITH [${values}] AS rows
            SELECT rows[number + 1].1, rows[number + 1].2 FROM numbers(${num_rows})
            SETTINGS max_block_size = 1, max_threads = 1"
    else
        ${CLICKHOUSE_CLIENT} --allow_insert_into_iceberg=1 --query "INSERT INTO ${table} VALUES ${values}"
    fi

    for manifest in $(find "${ROOT}/${suffix}/metadata" -maxdepth 1 -name '*.avro' \
            -not -name 'snap-*.avro' -type f | sort); do
        ${CLICKHOUSE_CLIENT} --query "
            SELECT
                'lower_ids=' || toString(arraySort(arrayMap(x -> x.1, tupleElement(data_file, 'lower_bounds')))),
                'upper_ids=' || toString(arraySort(arrayMap(x -> x.1, tupleElement(data_file, 'upper_bounds')))),
                'f32_lower=' || toString(arrayMap(x -> reinterpretAsFloat32(x.2),
                    arrayFilter(x -> x.1 = 1, tupleElement(data_file, 'lower_bounds')))),
                'f32_upper=' || toString(arrayMap(x -> reinterpretAsFloat32(x.2),
                    arrayFilter(x -> x.1 = 1, tupleElement(data_file, 'upper_bounds')))),
                'f64_lower=' || toString(arrayMap(x -> reinterpretAsFloat64(x.2),
                    arrayFilter(x -> x.1 = 2, tupleElement(data_file, 'lower_bounds')))),
                'f64_upper=' || toString(arrayMap(x -> reinterpretAsFloat64(x.2),
                    arrayFilter(x -> x.1 = 2, tupleElement(data_file, 'upper_bounds'))))
            FROM file('${manifest}', Avro)
            ORDER BY 1, 2, 3, 4
        "
    done
}

# Case A: the whole column is NaN for both widths, so the bound is unknown and must be omitted.
run_case A '(nan, nan)'

# Case B: no NaN in both columns, the bound is the plain min/max.
run_case B '(1.5, 1.5), (3.5, 3.5)'

# Case C: NaN mixed with real values, the bound must exclude NaN and reflect only the real ones.
run_case C '(1.5, 1.5), (nan, nan), (-5.5, -5.5)'

# Case D: same values as C, but one row per chunk, so the all-NaN chunk's range is merged by
# `uniteRanges`, where `accurateLess` ranks NaN above every real value. NaN must not win the bound.
run_case D '(1.5, 1.5), (nan, nan), (-5.5, -5.5)' split

# Case E: NULL mixed with real values, the bound must exclude NULL and still be published.
run_case E '(1.5, 1.5), (NULL, NULL), (-5.5, -5.5)'

# Case F: Iceberg orders -0.0 before +0.0 (spec: "Bounds for Float and Double"), unlike IEEE754
# comparison, where they're equal. lower_bound must be -0.0, not +0.0, even though both occur.
# hex() proves the sign bit, since toString() may not render it. All in one chunk (no
# max_block_size): this is the within-chunk case (`getExtremeRangeFromColumn`/`ColumnVector::getExtremes`).
run_case F '(nan, nan), (0.0, 0.0), (-0.0, -0.0), (5.5, 5.5)'

# Case G: like F, but one row per chunk, so 0.0 and -0.0 land in separate chunks and get merged
# via `uniteRanges` - the cross-chunk case, distinct from F's within-chunk one.
run_case G '(nan, nan), (0.0, 0.0), (-0.0, -0.0)' split

# Case H: same as G but with 0.0/-0.0 in the opposite order - `uniteRanges`'s zero-sign tie-break
# is order-dependent, so G and H together are needed to catch a regression on either bound.
run_case H '(nan, nan), (-0.0, -0.0), (0.0, 0.0)' split

for suffix in F G H; do
    for manifest in $(find "${ROOT}/${suffix}/metadata" -maxdepth 1 -name '*.avro' -not -name 'snap-*.avro' -type f | sort); do
        ${CLICKHOUSE_CLIENT} --query "
            SELECT
                '${suffix}_f32_lower_hex=' || toString(arrayMap(x -> hex(x.2), arrayFilter(x -> x.1 = 1, tupleElement(data_file, 'lower_bounds')))),
                '${suffix}_f32_upper_hex=' || toString(arrayMap(x -> hex(x.2), arrayFilter(x -> x.1 = 1, tupleElement(data_file, 'upper_bounds')))),
                '${suffix}_f64_lower_hex=' || toString(arrayMap(x -> hex(x.2), arrayFilter(x -> x.1 = 2, tupleElement(data_file, 'lower_bounds')))),
                '${suffix}_f64_upper_hex=' || toString(arrayMap(x -> hex(x.2), arrayFilter(x -> x.1 = 2, tupleElement(data_file, 'upper_bounds'))))
            FROM file('${manifest}', Avro)
            ORDER BY 1, 2, 3, 4
        "
    done
done

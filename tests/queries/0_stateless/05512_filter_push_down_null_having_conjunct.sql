DROP TABLE IF EXISTS t_05512;
DROP TABLE IF EXISTS l_05512;
DROP TABLE IF EXISTS r_05512;

CREATE TABLE t_05512 (c0 Int32) ENGINE = MergeTree ORDER BY c0;
INSERT INTO t_05512 SELECT number FROM numbers(1000);

SELECT count() FROM (SELECT 7 AND (max(c0) + NULL) AND 65535 AS h, -c0 AS g FROM t_05512 GROUP BY g HAVING h);
SELECT count() FROM (SELECT toLowCardinality(toUInt8(1)) AND 1 AND (max(c0) + NULL) AS h, -c0 AS g FROM t_05512 GROUP BY g HAVING h);
SELECT count() FROM (SELECT 7 AND (max(c0) > 997) AND 65535 AS h, -c0 AS g FROM t_05512 GROUP BY g HAVING h);

CREATE TABLE l_05512 (a Int32, b Int32) ENGINE = MergeTree ORDER BY a;
CREATE TABLE r_05512 (a Int32, b Int32) ENGINE = MergeTree ORDER BY a;
INSERT INTO l_05512 VALUES (1, 10), (2, 20), (3, 30);
INSERT INTO r_05512 VALUES (1, 100), (2, 200), (3, 300);

SELECT 'join';
SELECT l.a, 7 AND (l.b + r.b + NULL) AND 65535 AS w FROM l_05512 AS l INNER JOIN r_05512 AS r ON l.a = r.a WHERE w ORDER BY l.a;


-- Actions after a bare source that ends with a nested `EXPLAIN TEXT` without actions of its own
-- could belong to either statement, so the query is rejected.
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 ONELINE FORMAT JSONEachRow'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 ONELINE, MULTILINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 LIMIT 5 MODIFY LIMIT 2'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT (SELECT 1) ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 SETTINGS max_threads = 1 ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 FORMAT TSV ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXECUTE AS default EXPLAIN TEXT SELECT 1 FORMAT TSV ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT EXPLAIN TEXT SELECT 1 ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT (EXPLAIN TEXT EXPLAIN TEXT SELECT 1 ONELINE)'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN AST EXPLAIN TEXT SELECT 1 ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT EXECUTE AS default EXPLAIN TEXT SELECT 1 ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT SELECT 1 PARALLEL WITH EXPLAIN TEXT SELECT 2 ONELINE'); -- { serverError SYNTAX_ERROR }
SELECT formatQuerySingleLine('EXPLAIN TEXT CREATE HANDLER h URL ''/x'' AS EXPLAIN TEXT SELECT 1 ONELINE'); -- { serverError SYNTAX_ERROR }
EXPLAIN TEXT EXPLAIN TEXT SELECT 1 ONELINE FORMAT JSONEachRow; -- { clientError SYNTAX_ERROR }


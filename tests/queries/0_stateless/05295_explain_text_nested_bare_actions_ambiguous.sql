-- Only one statement can take the actions.
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN AST SELECT 1 ONELINE');
SELECT formatQuerySingleLine('EXPLAIN AST EXPLAIN TEXT SELECT 1 ONELINE');

-- Without actions nothing is ambiguous.
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1');
SELECT formatQuerySingleLine('EXPLAIN TEXT EXPLAIN TEXT SELECT 1 FORMAT TSV');

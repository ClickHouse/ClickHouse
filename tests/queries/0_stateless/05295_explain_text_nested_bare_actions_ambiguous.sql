SELECT formatQuerySingleLine('EXPLAIN TEXT (EXPLAIN AST EXPLAIN TEXT SELECT 1 ONELINE)');
SELECT formatQuerySingleLine('EXPLAIN TEXT (EXPLAIN AST EXPLAIN TEXT SELECT 1) ONELINE');
SELECT formatQuerySingleLine('EXPLAIN TEXT (EXECUTE AS default EXPLAIN TEXT SELECT 1 ONELINE)');
SELECT formatQuerySingleLine('EXPLAIN TEXT (EXECUTE AS default EXPLAIN TEXT SELECT 1) ONELINE');
SELECT formatQuerySingleLine('EXPLAIN TEXT (CREATE HANDLER h URL ''/x'' AS EXPLAIN TEXT SELECT 1 ONELINE)');
SELECT formatQuerySingleLine('EXPLAIN TEXT (CREATE HANDLER h URL ''/x'' AS EXPLAIN TEXT SELECT 1) ONELINE');
EXPLAIN TEXT (EXPLAIN TEXT SELECT 1 ONELINE) FORMAT JSONEachRow;

-- A refreshable materialized view is filled by its first refresh, so POPULATE is rejected
-- (EMPTY is the way to skip the initial refresh).

DROP TABLE IF EXISTS src_04645;
DROP TABLE IF EXISTS dst_04645;

CREATE TABLE src_04645 (x UInt64) ENGINE = MergeTree ORDER BY x;
CREATE TABLE dst_04645 (x UInt64) ENGINE = MergeTree ORDER BY x;

CREATE MATERIALIZED VIEW mv_04645 REFRESH EVERY 1 HOUR TO dst_04645 POPULATE AS SELECT x FROM src_04645; -- { clientError SYNTAX_ERROR }
CREATE MATERIALIZED VIEW mv_04645 REFRESH EVERY 1 HOUR APPEND TO dst_04645 POPULATE AS SELECT x FROM src_04645; -- { clientError SYNTAX_ERROR }
CREATE MATERIALIZED VIEW mv_04645 REFRESH EVERY 1 HOUR ENGINE = MergeTree ORDER BY x POPULATE AS SELECT x FROM src_04645; -- { clientError SYNTAX_ERROR }
CREATE MATERIALIZED VIEW mv_04645 REFRESH EVERY 1 HOUR TO dst_04645 COMMENT 'c' POPULATE AS SELECT x FROM src_04645; -- { clientError SYNTAX_ERROR }

DROP TABLE src_04645;
DROP TABLE dst_04645;

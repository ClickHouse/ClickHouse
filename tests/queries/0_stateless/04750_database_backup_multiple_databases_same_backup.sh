#!/usr/bin/env bash
# Tags: no-encrypted-storage

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CUR_DIR"/../shell_config.sh

SOURCE_DATABASE_NAME=${CLICKHOUSE_TEST_UNIQUE_NAME}_source
FIRST_DATABASE_NAME=${CLICKHOUSE_TEST_UNIQUE_NAME}_first
SECOND_DATABASE_NAME=${CLICKHOUSE_TEST_UNIQUE_NAME}_second
BACKUP_PATH=${CLICKHOUSE_TEST_UNIQUE_NAME}_backup

$CLICKHOUSE_CLIENT -q """
DROP DATABASE IF EXISTS $SOURCE_DATABASE_NAME;
CREATE DATABASE $SOURCE_DATABASE_NAME;

CREATE TABLE $SOURCE_DATABASE_NAME.test_table (id UInt64, value String) ENGINE = MergeTree ORDER BY id;
INSERT INTO $SOURCE_DATABASE_NAME.test_table SELECT number, number FROM numbers(1000);

BACKUP DATABASE $SOURCE_DATABASE_NAME TO Disk('backups', '$BACKUP_PATH') FORMAT Null;

SELECT 'two databases from one backup';

DROP DATABASE IF EXISTS $FIRST_DATABASE_NAME;
DROP DATABASE IF EXISTS $SECOND_DATABASE_NAME;
CREATE DATABASE $FIRST_DATABASE_NAME ENGINE = Backup('$SOURCE_DATABASE_NAME', Disk('backups', '$BACKUP_PATH'));
CREATE DATABASE $SECOND_DATABASE_NAME ENGINE = Backup('$SOURCE_DATABASE_NAME', Disk('backups', '$BACKUP_PATH'));

SELECT count(), sum(id) FROM $FIRST_DATABASE_NAME.test_table;
SELECT count(), sum(id) FROM $SECOND_DATABASE_NAME.test_table;

DROP DATABASE $SECOND_DATABASE_NAME;
DROP DATABASE $FIRST_DATABASE_NAME;

SELECT '--';
SELECT 'recreated under the same name';

CREATE DATABASE $FIRST_DATABASE_NAME ENGINE = Backup('$SOURCE_DATABASE_NAME', Disk('backups', '$BACKUP_PATH'));
SELECT count(), sum(id) FROM $FIRST_DATABASE_NAME.test_table;
DROP DATABASE $FIRST_DATABASE_NAME;
CREATE DATABASE $FIRST_DATABASE_NAME ENGINE = Backup('$SOURCE_DATABASE_NAME', Disk('backups', '$BACKUP_PATH'));
SELECT count(), sum(id) FROM $FIRST_DATABASE_NAME.test_table;

SELECT '--';
SELECT 'recreated under a different name';

DROP DATABASE $FIRST_DATABASE_NAME;
CREATE DATABASE $SECOND_DATABASE_NAME ENGINE = Backup('$SOURCE_DATABASE_NAME', Disk('backups', '$BACKUP_PATH'));
SELECT count(), sum(id) FROM $SECOND_DATABASE_NAME.test_table;
"""

echo '--'
echo 'rename is not supported'
$CLICKHOUSE_CLIENT -q "RENAME DATABASE $SECOND_DATABASE_NAME TO ${SECOND_DATABASE_NAME}_renamed" 2>&1 \
    | grep -oF 'Backup: RENAME DATABASE is not supported. (NOT_IMPLEMENTED)' | head -n 1

$CLICKHOUSE_CLIENT -q """
DROP DATABASE $SECOND_DATABASE_NAME;
DROP DATABASE $SOURCE_DATABASE_NAME;
"""

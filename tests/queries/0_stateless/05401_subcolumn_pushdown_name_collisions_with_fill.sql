-- `optimize_push_subcolumns_into_subqueries` must not change the result of a query.

SET enable_analyzer = 1;
SET optimize_push_subcolumns_into_subqueries = 1;

-- A declared column has the same name as a subcolumn of another column.
DROP TABLE IF EXISTS t_subcolumn_pushdown_declared;
CREATE TABLE t_subcolumn_pushdown_declared (n Nullable(Int32), `n.null` UInt8) ENGINE = MergeTree ORDER BY tuple();
INSERT INTO t_subcolumn_pushdown_declared VALUES (NULL, 42), (7, 43);
SELECT getSubcolumn(n, 'null') FROM (SELECT n FROM t_subcolumn_pushdown_declared) ORDER BY ALL;
SELECT getSubcolumn(n, 'null') FROM (SELECT n FROM t_subcolumn_pushdown_declared) ORDER BY ALL SETTINGS optimize_push_subcolumns_into_subqueries = 0;
DROP TABLE t_subcolumn_pushdown_declared;

-- Rows generated by `WITH FILL` have the default value of the column, not of its subcolumn.
DROP TABLE IF EXISTS t_subcolumn_pushdown_fill;
CREATE TABLE t_subcolumn_pushdown_fill (k UInt64, n Nullable(Int32)) ENGINE = MergeTree ORDER BY k;
INSERT INTO t_subcolumn_pushdown_fill VALUES (1, 7), (3, 8);
SELECT k, n.null FROM (SELECT k, n FROM t_subcolumn_pushdown_fill ORDER BY k WITH FILL);
SELECT k, n.null FROM (SELECT k, n FROM t_subcolumn_pushdown_fill ORDER BY k WITH FILL) SETTINGS optimize_push_subcolumns_into_subqueries = 0;
DROP TABLE t_subcolumn_pushdown_fill;

-- Different subcolumns of different columns have the same flattened name.
DROP TABLE IF EXISTS t_subcolumn_pushdown_flattened;
CREATE TABLE t_subcolumn_pushdown_flattened (x Tuple(a Tuple(b String)), y Tuple(b String), z Tuple(b UInt32)) ENGINE = MergeTree ORDER BY tuple();
INSERT INTO t_subcolumn_pushdown_flattened VALUES ((('first')), ('second'), (3));
SELECT getSubcolumn(p, 'a.b'), getSubcolumn(`p.a`, 'b') FROM (SELECT x AS p, y AS `p.a` FROM t_subcolumn_pushdown_flattened);
SELECT getSubcolumn(p, 'a.b'), getSubcolumn(`p.a`, 'b') FROM (SELECT x AS p, z AS `p.a` FROM t_subcolumn_pushdown_flattened);
SELECT getSubcolumn(p, 'a.b'), getSubcolumn(`p.a`, 'b') FROM (SELECT x AS p, y AS `p.a` FROM t_subcolumn_pushdown_flattened) SETTINGS optimize_push_subcolumns_into_subqueries = 0;
DROP TABLE t_subcolumn_pushdown_flattened;

#!/usr/bin/env bash
# Tags: no-fasttest
#       ^ no Parquet support in fasttest

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=../shell_config.sh
. "$CUR_DIR"/../shell_config.sh

# Regression test: `extractSpatialPredicateNodeBbox`'s `accept_input` callback in
# `extractSpatialFilters` (src/Processors/Formats/Impl/Parquet/GeoFilter.cpp) already rejects
# `Variant`/`Dynamic`-typed (mixed-kind) GeoParquet geometry columns (see 04886), but a GeoParquet
# column declared with a single `geometry_types` entry is exposed as a CONCRETE type (e.g. `Point`,
# not `Geometry`/`Variant`) and used to sail straight through. `IFunctionBase::rejectsConstGeometryKind`
# was only ever consulted for CONSTANT predicate arguments, never for the column itself, so a
# concretely `Point`-typed column that `polygonsIntersectCartesian`/`polygonsWithinCartesian` is
# guaranteed to reject could still have its row group's `covering.bbox` statistics trusted to prune
# using only the constant query polygon -- silently returning 0 instead of raising
# `ILLEGAL_TYPE_OF_ARGUMENT` once evaluated.
#
# The fixture (generated by a throwaway pyarrow script, not checked into the repo) has a single row
# group on column `geometry` (concrete `Point` type, geometry_types = ["Point"]), 4 rows near
# (500..503, 500..503), far from the query polygon near the origin, with `covering.bbox` statistics
# columns `bbox_xmin`/`bbox_ymin`/`bbox_xmax`/`bbox_ymax`.

FILE="$CUR_DIR/data_parquet/04888_geo_concrete_point_column_pruning.parquet"

echo "=== toTypeName(geometry) is Point -- concrete, single-kind GeoParquet column ==="
$CLICKHOUSE_LOCAL -q "SELECT DISTINCT toTypeName(geometry) FROM file('$FILE', Parquet)"

# polygonsIntersectCartesian rejects Point at every argument position. The row group is far from
# the query polygon near the origin, so the buggy pruning path would derive a bbox from the query
# polygon alone and prune the row group away, returning 0 instead of raising.
echo "=== polygonsIntersectCartesian: the Point row group must still raise, not be pruned away ==="
$CLICKHOUSE_LOCAL -q "
SELECT count() FROM file('$FILE', Parquet)
WHERE polygonsIntersectCartesian(geometry, [[(0., 0.), (2., 0.), (2., 2.), (0., 2.), (0., 0.)]])
" 2>&1 | grep -o "must not be Point"

# Sanity: pointInPolygon's first argument legitimately accepts a Point-typed column -- this fix
# must not regress ordinary pruning/evaluation of that case.
echo "=== sanity: pointInPolygon still prunes/evaluates a concrete Point column correctly ==="
$CLICKHOUSE_LOCAL -q "
SELECT count() FROM file('$FILE', Parquet)
WHERE pointInPolygon(geometry, [(499., 499.), (505., 499.), (505., 505.), (499., 505.)])
"

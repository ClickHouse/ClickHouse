/** Nimbus-owned bootstrap for the ClickHouse Kapa Ask AI widget. */

declare global {
  interface Window {
    kapaSettings?: { user: { uniqueClientId?: string } };
    Kapa?: { open: (options: { mode: "ai" }) => void };
  }
}

const SCRIPT_ID = "kapa-widget-script";
const SCRIPT_URL = "https://widget.kapa.ai/kapa-widget.bundle.js";
let pendingOpen = false;

function cookie(name: string): string | undefined {
  const prefix = `${name}=`;
  for (const value of decodeURIComponent(document.cookie).split(";")) {
    const trimmed = value.trim();
    if (trimmed.startsWith(prefix)) return trimmed.slice(prefix.length);
  }
  return undefined;
}

function googleAnalyticsUserId(): string | undefined {
  const parts = cookie("_ga")?.split(".").slice(-2);
  return parts?.length === 2 ? parts.join("-") : undefined;
}

function isUnsupportedIos(): boolean {
  if (!/iPad|iPhone/.test(navigator.userAgent)) return false;
  const match = navigator.userAgent.match(/OS (\d+)(?:_(\d+))?/);
  if (!match) return true;
  const major = Number.parseInt(match[1], 10);
  const minor = Number.parseInt(match[2] ?? "0", 10);
  return major < 16 || (major === 16 && minor <= 4);
}

function boot(): void {
  if (document.getElementById(SCRIPT_ID) || isUnsupportedIos()) return;

  window.kapaSettings = { user: { uniqueClientId: googleAnalyticsUserId() } };
  const script = document.createElement("script");
  script.id = SCRIPT_ID;
  script.src = SCRIPT_URL;
  script.async = true;
  script.defer = true;
  script.onload = () => {
    if (pendingOpen) openKapa();
  };
  for (const [name, value] of Object.entries({
    "data-website-id": "5df6cc2b-732e-44e4-b789-aec81b70fe46",
    "data-project-name": "ClickHouse",
    "data-project-color": "#151515",
    "data-project-logo":
      "https://avatars.githubusercontent.com/u/54801242?s=200&v=4",
    "data-modal-disclaimer":
      "This is a custom LLM for ClickHouse with access to all developer documentation, open GitHub Issues, YouTube videos, and resolved StackOverflow posts. Please note that answers are generated by AI and may not be fully accurate, so please use your best judgement.",
    "data-modal-example-questions":
      "How to speed up queries?,How to use materialized views?",
    "data-mcp-enabled": "false",
    "data-launcher-button-hidden": "true",
  })) {
    script.setAttribute(name, value);
  }
  document.head.appendChild(script);
}

function openKapa(): void {
  if (!window.Kapa) {
    pendingOpen = true;
    return;
  }
  pendingOpen = false;
  window.Kapa.open({ mode: "ai" });
}

document.addEventListener("click", (event) => {
  if (!(event.target as Element | null)?.closest("[data-kapa-trigger]")) return;
  event.preventDefault();
  openKapa();
});

if (document.readyState === "loading")
  document.addEventListener("DOMContentLoaded", boot, { once: true });
else boot();

// Generates Astro island wrappers for the interactive snippet React
// components listed in src/compat/interactive-components.json. The Vite
// plugin routes `/snippets/components/<Name>/<Name>.jsx` imports to the
// generated `.ts` module, whose default and named exports are the wrapper.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const list = JSON.parse(fs.readFileSync(path.join(root, "src/compat/interactive-components.json"), "utf8")).components as string[];
const outRoot = path.join(root, "src/generated/compat-wrappers");
fs.rmSync(outRoot, { recursive: true, force: true });

// English components live in snippets/components; each translated tree has
// its own copies in snippets/<locale>/components (GT translates UI strings).
const localeDirs = fs
  .readdirSync(path.join(root, "snippets"), { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(root, "snippets", d.name, "components")))
  .map((d) => d.name);
const variants: Array<{ locale: string | null; snippetsRel: string; outDir: string; upDirs: string }> = [
  { locale: null, snippetsRel: "snippets/components", outDir: outRoot, upDirs: "../../.." },
  ...localeDirs.map((l) => ({ locale: l, snippetsRel: `snippets/${l}/components`, outDir: path.join(outRoot, l), upDirs: "../../../.." })),
];

let count = 0;
for (const v of variants) for (const name of list) {
  const source = path.join(root, v.snippetsRel, name, `${name}.jsx`);
  if (!fs.existsSync(source)) {
    if (v.locale === null) throw new Error(`gen-compat-wrappers: ${source} not found`);
    continue;
  }
  const outDir = v.outDir;
  fs.mkdirSync(outDir, { recursive: true });
  const code = fs.readFileSync(source, "utf8");
  const hasNamed = new RegExp(`export\\s+(?:const|function)\\s+${name}\\b`).test(code);
  const rel = `${v.upDirs}/${v.snippetsRel}/${name}/${name}.jsx?clickhouse-react-island`;
  const clientModule = `./${name}.client`;
  count++;
  // The browser-facing island must not use the original `/snippets/**`
  // specifier. That public specifier is intentionally redirected back to the
  // Astro wrapper for MDX imports; exposing it as the island component URL
  // would make hydration try to render an Astro component through React.
  fs.writeFileSync(
    path.join(outDir, `${name}.client.ts`),
    hasNamed
      ? `// Generated by bin/gen-compat-wrappers.ts. Browser entry for the React island.\nexport { ${name} as default } from "${rel}";\n`
      : `// Generated by bin/gen-compat-wrappers.ts. Browser entry for the React island.\nexport { default } from "${rel}";\n`,
  );
  fs.writeFileSync(
    path.join(outDir, `${name}.astro`),
    `---
// Generated by bin/gen-compat-wrappers.ts. Hydrates the snippet React component as an island.
import Inner from "${clientModule}";
const props = Astro.props;
---

<Inner client:visible {...props}><slot /></Inner>
`,
  );
  fs.writeFileSync(
    path.join(outDir, `${name}.ts`),
    `// Generated by bin/gen-compat-wrappers.ts.
import ${name} from "./${name}.astro";
export { ${name} };
export default ${name};
`,
  );
}
console.log(`gen-compat-wrappers: ${count} wrappers (${variants.length} trees) in src/generated/compat-wrappers`);

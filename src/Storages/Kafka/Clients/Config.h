#pragma once

#include <Common/Logger.h>
#include <base/types.h>

#include <chrono>
#include <functional>
#include <optional>
#include <variant>
#include <vector>

namespace Kafka
{

/// Mirrors librdkafka's `security.protocol` values.
enum class SecurityProtocol : UInt8
{
    Plaintext,
    Ssl,
    SaslPlaintext,
    SaslSsl,
};

const char * securityProtocolName(SecurityProtocol protocol) noexcept;

/// True when the protocol wraps the connection in TLS.
constexpr bool usesTls(SecurityProtocol protocol)
{
    return protocol == SecurityProtocol::Ssl || protocol == SecurityProtocol::SaslSsl;
}

/// True when the protocol authenticates with SASL.
constexpr bool usesSasl(SecurityProtocol protocol)
{
    return protocol == SecurityProtocol::SaslPlaintext || protocol == SecurityProtocol::SaslSsl;
}

struct TlsConfig
{
    /// PEM file or directory with the trusted CA certificates; empty = the
    /// system default store.
    String ca_location;
    /// Client certificate + private key (PEM) for mutual TLS; usually empty.
    String certificate_location;
    String key_location;
    String key_password;
    /// Verify the broker's certificate chain and host name.
    bool verify = true;
};

struct SaslPlainConfig
{
    String username;
    String password;
    /// Usually empty; sent as the authzid field of the PLAIN message.
    String authorization_id;
};

struct SaslScramConfig
{
    enum class Algorithm : UInt8
    {
        Sha256,
        Sha512,
    };

    Algorithm algorithm = Algorithm::Sha256;
    String username;
    String password;
};

struct OAuthToken
{
    /// The bearer token sent on the wire (for AWS MSK IAM: the SigV4 presigned
    /// payload generated by the caller).
    String value;
    /// When the token stops being valid; informational for connection reuse.
    std::chrono::system_clock::time_point expiry;
};

struct SaslOauthBearerConfig
{
    /// Called on the connecting thread every time a connection authenticates
    /// (the client owns no threads, so there is no background refresh — a
    /// caching provider is the caller's job). Throws => the connection fails.
    std::function<OAuthToken()> token_provider;
};

/// GSSAPI/Kerberos (RFC 4752). Usable only in builds with krb5 support.
/// Obtaining the ticket is the caller's job (ClickHouse runs `kerberosInit`
/// with the configured keytab/principal); the mechanism reads the default
/// credential cache.
struct SaslGssapiConfig
{
    /// The service part of the broker principal `<service>/<broker host>`
    /// (librdkafka's `sasl.kerberos.service.name`).
    String service_name = "kafka";
    /// Client principal to pick from the credential cache; empty = the cache's
    /// default principal.
    String principal;
};

using SaslConfig = std::variant<SaslPlainConfig, SaslScramConfig, SaslOauthBearerConfig, SaslGssapiConfig>;

/// Fetch isolation (KIP-98). Underlying type is not the wire type on purpose:
/// enum bases must be standard integer types, and the wire field is written
/// explicitly as Int8.
enum class IsolationLevel : UInt8
{
    ReadUncommitted = 0,
    /// Records of aborted transactions are filtered out; "latest" offsets stop
    /// at the last stable offset. librdkafka-compatible default.
    ReadCommitted = 1,
};

struct ClientConfig
{
    /// "host:port" entries used for the first metadata bootstrap.
    std::vector<String> bootstrap_brokers;
    String client_id = "ClickHouse";

    SecurityProtocol security_protocol = SecurityProtocol::Plaintext;
    /// TLS settings for Ssl/SaslSsl; nullopt = defaults (system CA store,
    /// verification on).
    std::optional<TlsConfig> tls;
    /// Required for SaslPlaintext/SaslSsl, rejected otherwise.
    std::optional<SaslConfig> sasl;

    IsolationLevel isolation_level = IsolationLevel::ReadCommitted;

    std::chrono::milliseconds connect_timeout{10'000};
    /// Default per-operation deadline when the caller passes none.
    std::chrono::milliseconds request_timeout{30'000};
    /// Cached metadata older than this refreshes on next use.
    std::chrono::milliseconds metadata_max_age{300'000};
    /// Upper bound of pooled connections per broker. Operations beyond the
    /// bound open a short-lived extra connection rather than block.
    size_t max_connections_per_broker = 3;

    /// The client never writes to stderr on its own; all messages go to this
    /// logger on the thread that runs the operation (the client owns no threads).
    LoggerPtr log = getLogger("KafkaClient");
};

}

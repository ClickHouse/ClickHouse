#!/usr/bin/env bash
# Regenerates StorageSystemChangelog.generated.cpp from the curated CHANGELOG.md at the repository
# root. Rerun after the changelog is updated for a release and commit the result, like
# StorageSystemContributors.generated.cpp.

set -e

CUR_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$CUR_DIR"

CHANGELOG_FILE=${CHANGELOG_FILE:="$CUR_DIR/../../../CHANGELOG.md"}
GENERATED_FILE=${GENERATED_FILE:="$CUR_DIR/StorageSystemChangelog.generated.cpp"}

python3 - "$CHANGELOG_FILE" "$GENERATED_FILE" <<'PYTHON'
import datetime
import re
import sys

changelog_path, generated_path = sys.argv[1], sys.argv[2]

release_re = re.compile(
    r'^### (?:<a id="[^"]*"></a>\s*)?ClickHouse release v?(\d+)\.(\d+)(?:\.(\d+))?( LTS)?, (\d{4}-\d{2}-\d{2})')
category_re = re.compile(r'^#### +(.*?) *$')
entry_re = re.compile(r'^\* +(.*)$')
pull_request_re = re.compile(r' ?\[#(\d+)\]\(https://github\.com/ClickHouse/ClickHouse/pull/\d+\)')
author_re = re.compile(r' ?\(\[([^\]#][^\]]*)\]\(https://github\.com/[^)]*\)\)')

epoch = datetime.date(1970, 1, 1)

release = None
category = None
entries = []


def flush_entry(text):
    if release is None or category is None:
        return
    pull_requests = []
    for m in pull_request_re.finditer(text):
        if m.group(1) not in pull_requests:
            pull_requests.append(m.group(1))
    authors = []
    for m in author_re.finditer(text):
        author = m.group(1).strip()
        if author and author not in authors:
            authors.append(author)
    description = pull_request_re.sub('', text)
    description = author_re.sub('', description)
    description = re.sub(r' {2,}', ' ', description)
    while '. .' in description:
        description = description.replace('. .', '.')
    description = description.strip()
    # Stripping the trailing citation tokens leaves a doubled final period behind.
    while description.endswith('..'):
        description = description[:-1]
    entries.append((release, category, description, pull_requests, authors))


current_entry = None
for line in open(changelog_path, encoding='utf-8'):
    line = line.rstrip('\n')
    m = release_re.match(line)
    if m:
        if current_entry is not None:
            flush_entry(current_entry)
            current_entry = None
        major, minor, patch, lts, date = m.groups()
        day_num = (datetime.date.fromisoformat(date) - epoch).days
        release = (int(major), int(minor), int(patch or 0), day_num, 1 if lts else 0)
        category = None
        continue
    m = category_re.match(line)
    if m:
        if current_entry is not None:
            flush_entry(current_entry)
            current_entry = None
        category = m.group(1)
        continue
    m = entry_re.match(line)
    if m:
        if current_entry is not None:
            flush_entry(current_entry)
        current_entry = m.group(1)
        continue
    if current_entry is not None:
        if line.startswith(('#', '**')) or not line.strip():
            flush_entry(current_entry)
            current_entry = None
        else:
            current_entry += ' ' + line.strip()
if current_entry is not None:
    flush_entry(current_entry)


def escape(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch in ('\n', '\r', '\t'):
            out.append(' ')
        else:
            out.append(ch)
    return ''.join(out)


with open(generated_path, 'w', encoding='utf-8') as out:
    out.write('/// Autogenerated by StorageSystemChangelog.sh from CHANGELOG.md, do not edit.\n\n')
    out.write('#include <Storages/System/StorageSystemChangelog.h>\n\n')
    out.write('namespace DB\n{\n\n')
    # Changelog text is full of quotes and backslashes; raw strings would be less readable here.
    out.write('// NOLINTBEGIN(modernize-raw-string-literal)\n')
    out.write('const AutoChangelogEntry auto_changelog[] =\n{\n')
    for (major, minor, patch, day_num, is_lts), cat, description, pull_requests, authors in entries:
        out.write('    {%d, %d, %d, %d, %d, "%s", "%s", "%s", "%s"},\n' % (
            major, minor, patch, day_num, is_lts,
            escape(cat), escape(description),
            ','.join(pull_requests), '\\t'.join(escape(a) for a in authors)))
    out.write('};\n\n')
    out.write('// NOLINTEND(modernize-raw-string-literal)\n')
    out.write('const size_t auto_changelog_size = sizeof(auto_changelog) / sizeof(auto_changelog[0]);\n')
    out.write('\n}\n')

print('generated %d entries into %s' % (len(entries), generated_path))
PYTHON

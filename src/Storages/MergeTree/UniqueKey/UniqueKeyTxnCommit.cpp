/// Base implementation of a single write, inherited by INSERT/DELETE/MERGE.
class UniqueKeyCommitBase : public IUniqueKeyCommit
{
public:
    explicit UniqueKeyCommitBase(DeleteBitmapStore & delete_bitmap_store_)
        : delete_bitmap_store(delete_bitmap_store_)
        , log(getLogger("UniqueKeyTxnCommit"))
    {
    }

    /// 1. Resolve conflicts for each write operation
    /// 2. Stage bitmaps generated by this write, which is durable but not visible to others
    std::optional<StagedWrite> stage(const PartitionWriteGuard &) final
    {
        if (!resolveConflicts())
        {
            LOG_TRACE(log, "UNIQUE KEY {} (partition {}): conflict resolution left nothing to commit",
                writeKind(), partitionId());
            return {};
        }

        auto kills = ownKills();
        auto carried = selectCarriedBitmaps();

        /// Before the first deref of `own_part`: a write that stages anything must publish the part
        /// that resolves it, and `own_kills` is a bitmap for that part itself.
        if (!own_part && (own_kills || !kills.empty() || !carried.empty()))
            throw Exception(
                ErrorCodes::LOGICAL_ERROR,
                "UNIQUE KEY write staged {} bitmap(s) but publishes no part to resolve them against",
                kills.size() + carried.size() + (own_kills ? 1 : 0));

        if (own_kills && !kills.emplace(own_part->info, own_kills).second)
            throw Exception(ErrorCodes::LOGICAL_ERROR,
                "UNIQUE KEY write has both a delta and its own bitmap for part {}", own_part->name);

        StagedWrite staged;
        MergeTreeDataPartChecksums written;

        for (const auto & [target, bitmap] : kills)
        {
            /// The name is the file's, not the index's: the store is keyed by info
            const DeleteBitmapFileOps::BitmapFile file{0, target.getPartNameV1()};
            written.files[file.fileName()]
                = DeleteBitmapFileOps::stageBitmap(own_part->getDataPartStorage(), file, *bitmap);
            staged.targets.push_back(target);

            LOG_TRACE(log, "UNIQUE KEY {} (partition {}): staged a {}-row delete bitmap for part {} in {}",
                writeKind(), partitionId(), bitmap->cardinality(), target.getPartNameV1(), own_part->name);
        }

        /// One file per version, never folded into one.
        staged.carried.reserve(carried.size());
        for (const auto & [link, held_in, file] : carried)
        {
            /// The version travels with the bytes: this part did not create the kills and its own
            /// csn says nothing about when they apply.
            const DeleteBitmapFileOps::BitmapFile in_result{link.csn, link.target.getPartNameV1()};
            written.files[in_result.fileName()] = DeleteBitmapFileOps::carryBitmap(
                held_in->getDataPartStorage(), file, own_part->getDataPartStorage(), in_result);
            staged.carried.push_back(link);

            LOG_TRACE(log, "UNIQUE KEY {} (partition {}): carried the delete bitmap of part {} "
                "at csn {} from {} into {}",
                writeKind(), partitionId(), link.target.getPartNameV1(), link.csn,
                held_in->name, own_part->name);
        }

        recordBitmapChecksums(written);

        return staged;
    }

protected:

    using KillsByPart = std::map<MergeTreePartInfo, ConstDeleteBitmapPtr>;

    /// Resolve conflicts with concurrent writes and fill the members below; `stage` writes
    /// what this leaves behind. False means there is nothing to commit.
    virtual bool resolveConflicts() = 0;

    /// What this write has to copy in rather than originate -- see
    /// `DeleteBitmapStore::selectCarriedBitmaps`. Only a merge has any.
    virtual std::vector<DeleteBitmapStore::CarriedBitmap> selectCarriedBitmaps() { return {}; }

    void recordBitmapChecksums(const MergeTreeDataPartChecksums & written)
    {
        if (written.files.empty())
            return;

        auto & storage = own_part->getDataPartStorage();
        for (const auto & [name, checksum] : written.files)
            own_part->checksums.files[name] = checksum;

        {
            auto out = storage.writeFile("checksums.txt", 4096, {});
            own_part->checksums.write(*out);
            out->sync();
            out->finalize();
        }

        own_part->setBytesOnDisk(own_part->checksums.getTotalSizeOnDisk());
    }

    KillsByPart ownKills()
    {
        KillsByPart prepared;

        for (const auto & [part_info, kill] : kills_per_part)
            if (kill && !kill->empty())
                prepared.emplace(part_info, kill);

        return prepared;
    }

    DeleteBitmapStore & delete_bitmap_store;
    LoggerPtr log;

    /// The part generated by this write
    MergeTreeMutableDataPartPtr own_part;
    /// The rows this write kills in the part it publishes, if any (a merge's late kills)
    DeleteBitmapPtr own_kills;
    /// The rows this write kills in parts OTHER than `own_part`, one delta per target
    std::map<MergeTreePartInfo, ConstDeleteBitmapPtr> kills_per_part;
};

/// Rename `part` and make it active, but not visible to other transactions.
static void addPartToActiveSet(MergeTreeData & storage, MergeTreeMutableDataPartPtr & part, const MergeTreeTransactionPtr & txn)
{
    /// Created outside the parts lock: on an exceptional path its destructor re-acquires it.
    MergeTreeData::Transaction transaction(storage, txn.get());
    {
        auto parts_lock = storage.lockParts();
        storage.renameTempPartAndAdd(part, transaction, parts_lock, /*rename_in_transaction=*/false);
        transaction.commit(parts_lock);
    }
}

class UniqueKeyTxnCommit::InsertCommit : public UniqueKeyCommitBase
{
public:
    explicit InsertCommit(InsertRequest & request)
        : UniqueKeyCommitBase(request.storage.uniqueKeyTxnManager().deleteBitmapStore())
        , sink(request.sink)
        , storage(request.storage)
        , metadata_snapshot(request.metadata_snapshot)
        , context(request.context)
        , temp_part(request.temp_part)
        , block(request.block)
        , transaction(request.transaction)
        , deduplication_hashes(request.deduplication_hashes)
    {
        own_part = request.temp_part->part;
    }

    String partitionId() const override { return own_part->info.getPartitionId(); }
    std::string_view writeKind() const override { return "INSERT"; }

    const IMergeTreeDataPart & publish(
        const PartitionWriteGuard &, const MergeTreeTransactionPtr & txn, const StagedWrite &) override
    {
        addPartToActiveSet(storage, own_part, txn);

        /// The window a read sees the part Active before its commit point, otherwise too narrow to hit.
        FailPointInjection::pauseFailPoint(FailPoints::unique_key_insert_pause_before_commit);
        return *own_part;
    }

    std::vector<std::string> run();

    bool partDiscarded() const { return part_discarded; }

protected:
    bool resolveConflicts() override;

private:
    ProbeTargetPartPtr makeSSTProbeTarget(const MergeTreeDataPartPtr & target);

    std::vector<ProbeResult> probeActiveParts(const String & partition_id, const Settings & query_settings);

    const Block & incomingBlock() const { return *block; }

    /// Rewrite the part without the conflicting rows.
    /// Return false (with `part_discarded`) when nothing survives the filter or the rewrite.
    bool rewritePartIgnoreConflicts(const IColumn::Filter & keep);

    MergeTreeSink & sink;
    MergeTreeData & storage;
    StorageMetadataPtr metadata_snapshot;
    ContextPtr context;
    MergeTreeTemporaryPartPtr & temp_part;
    std::shared_ptr<const Block> block;
    MergeTreeTransactionHolder & transaction;

    /// Block deduplication. `resolveConflicts` allocates the block number and registers it in the
    /// dedup log, and `publish` adds the part. Both run under the partition guard, so a partition has
    /// at most one block number outstanding and no merge can select over a gap a later publish fills.
    const std::vector<DeduplicationHash> & deduplication_hashes;
    std::unique_ptr<BlockAllocation> allocation;

    /// The whole part is discarded after IGNORE
    bool part_discarded = false;
};

ProbeTargetPartPtr UniqueKeyTxnCommit::InsertCommit::makeSSTProbeTarget(const MergeTreeDataPartPtr & target)
{
    if (target->rows_count == 0)
        return nullptr;
    auto sst_path = target->getDenseIndexBackingPath();
    if (!sst_path)
        throw Exception(
            ErrorCodes::LOGICAL_ERROR,
            "UNIQUE KEY part {} has {} rows but no dense index; cannot probe for duplicates",
            target->name, target->rows_count);
#if USE_ROCKSDB
    return std::make_shared<SSTProbeTargetPart>(
        target.get(),
        delete_bitmap_store.readLatestBitmap(target->info),
        openSSTReaderFromStorage(target->getDataPartStoragePtr(), SSTIndexWriter::FILE_NAME, context->getReadSettings()));
#else
    throw Exception(ErrorCodes::SUPPORT_IS_DISABLED,
        "UNIQUE KEY duplicate probing requires RocksDB support (USE_ROCKSDB=1)");
#endif
}

static Block filterBlockByMask(const Block & block, const IColumn::Filter & keep)
{
    /// Throws rather than asserts: `chassert` is compiled out in Release and `IColumn::filter`
    /// reads `keep` positionally, so a mismatch there is an out-of-bounds read, not a wrong answer.
    /// `keep` is sized from the probe results and the block is re-read here, a function apart.
    if (keep.size() != block.rows())
        throw Exception(ErrorCodes::LOGICAL_ERROR,
            "UNIQUE KEY filter mask has {} entries for a block of {} rows", keep.size(), block.rows());
    const size_t kept = countBytesInFilter(keep);

    Block result = block.cloneWithoutColumns();
    auto columns = block.getColumns();
    for (auto & col : columns)
        col = col->filter(keep, kept);
    result.setColumns(columns);
    return result;
}

bool UniqueKeyTxnCommit::InsertCommit::rewritePartIgnoreConflicts(const IColumn::Filter & keep)
{
    Block filtered = filterBlockByMask(incomingBlock(), keep);
    if (filtered.rows() == 0)
    {
        part_discarded = true;
        return false;
    }

    /// From the part, not the sink's block: writing the part moved the partition value into it.
    BlockWithPartition filtered_with_partition(std::make_shared<Block>(std::move(filtered)), own_part->partition.value);
    auto rewritten = sink.writeNewTempPart(filtered_with_partition, transaction.getTransaction());
    /// `optimize_on_insert` can collapse every surviving row, and then no part is written.
    if (!rewritten->part)
    {
        part_discarded = true;
        return false;
    }

    rewritten->finalize();
    temp_part = std::move(rewritten);
    own_part = temp_part->part;
    /// The dedup log registered the allocated block number, so the rewritten part takes it over
    /// rather than the fresh one the writer assigns.
    allocation->assignTo(*own_part);
    return true;
}

/// Newest-first, so the probe resolves a key to its most recent live occurrence and stops there.
static void sortNewestFirst(std::vector<MergeTreeDataPartPtr> & parts)
{
    /// Read CSN once
    std::vector<std::pair<CSN, MergeTreeDataPartPtr>> keyed;
    keyed.reserve(parts.size());
    for (auto & part : parts)
    {
        /// The reserved csns are not commit timestamps and must not be ordered as if they were:
        /// `RolledBackCSN` is the `UInt64` max and would sort ahead of every real commit, and a
        /// non-transactional part -- an attached one -- shares csn 1 with all the others. Those
        /// fall back to the tiebreaker together.
        const CSN csn = part->version->getInfo().creation_csn;
        const bool committed = csn > Tx::MaxReservedCSN && csn <= Tx::MaxCommittedCSN;
        keyed.emplace_back(committed ? csn : 0, std::move(part));
    }

    std::sort(keyed.begin(), keyed.end(), [](const auto & a, const auto & b)
    {
        if (a.first != b.first)
            return a.first > b.first;
        return a.second->info.min_block > b.second->info.min_block;
    });

    for (size_t i = 0; i < keyed.size(); ++i)
        parts[i] = std::move(keyed[i].second);
}

std::vector<ProbeResult> UniqueKeyTxnCommit::InsertCommit::probeActiveParts(const String & partition_id, const Settings & query_settings)
{
    /// The latest parts and not a snapshot: the partition lock excludes concurrent writes
    std::vector<MergeTreeDataPartPtr> active_parts;
    {
        auto parts_lock = storage.readLockParts();
        active_parts = storage.getDataPartsVectorInPartitionForInternalUsage(
            MergeTreeData::DataPartState::Active, partition_id, parts_lock);
    }

    sortNewestFirst(active_parts);

    /// The new part is still staged, so it cannot appear in the active list.
    ProbeTargetsSnapshot targets;
    targets.reserve(active_parts.size());
    for (const auto & part : active_parts)
    {
        /// Rolled back after the part list was read.
        if (part->version->getInfo().creation_csn == Tx::RolledBackCSN)
            continue;
        if (auto probe_target = makeSSTProbeTarget(part))
            targets.push_back(std::move(probe_target));
    }

    auto columns = metadata_snapshot->getUniqueKeyColumns();
    auto probe = makeUniqueKeyProbe(
        query_settings[Setting::unique_key_probe_implementation],
        [&targets](const String &) { return targets; },
        columns,
        query_settings[Setting::unique_key_max_encoded_size]);
    auto results = probe->probeBatch(incomingBlock(), partition_id);

    ProfileEvents::increment(ProfileEvents::UniqueKeyDedupProbes, results.size());

    LOG_TRACE(log, "UNIQUE KEY INSERT (partition {}): probed {} row(s) against {} active part(s)",
        partition_id, results.size(), targets.size());

    return results;
}

bool UniqueKeyTxnCommit::InsertCommit::resolveConflicts()
{
    allocation = sink.allocateBlock(own_part, deduplication_hashes);
    if (!allocation->dedupConflicts().empty())
        return false;

    /// TODO(unique-key): split the probe into two stages to shrink the lock scope
    const auto & partition_id = own_part->info.getPartitionId();
    const auto & query_settings = context->getSettingsRef();
    auto results = probeActiveParts(partition_id, query_settings);

    std::vector<size_t> conflict_rows;
    for (size_t i = 0; i < results.size(); ++i)
        if (results[i].outcome == ProbeOutcome::FOUND_LIVE && results[i].part)
            conflict_rows.push_back(i);

    if (!conflict_rows.empty())
    {
        const auto conflict_action = (*storage.getSettings())[MergeTreeSetting::unique_key_conflict_action].value;

        LOG_DEBUG(log, "UNIQUE KEY INSERT (partition {}): {} of {} row(s) conflict, applying {}",
            partitionId(), conflict_rows.size(), results.size(), conflict_action);

        switch (conflict_action)
        {
        case UniqueKeyConflictAction::Abort:
        {
            /// TODO(unique-key): abort is per-part, not atomic across a multi-part INSERT
            const ProbeResult & first = results[conflict_rows.front()];
            throw Exception(
                ErrorCodes::VIOLATED_CONSTRAINT,
                "UNIQUE KEY constraint violated: key already exists in part {} (row {})",
                first.part->name, first.row_number);
        }

        case UniqueKeyConflictAction::Ignore:
        {
            /// Existing rows win: drop the conflicting incoming rows, publish the rest, and
            /// touch no old part. Nothing left to publish means nothing to commit.
            IColumn::Filter keep(results.size(), 1);
            for (size_t row : conflict_rows)
                keep[row] = 0;

            ProfileEvents::increment(ProfileEvents::UniqueKeyConflictIgnoredRows, conflict_rows.size());
            if (!rewritePartIgnoreConflicts(keep))
                return false;
            break;
        }
        case UniqueKeyConflictAction::Overwrite:
        {
            /// `kills_per_part` holds const bitmaps; build the kills mutable here, then hand them over.
            std::map<MergeTreePartInfo, DeleteBitmapPtr> kills_by_target;
            for (size_t row : conflict_rows)
            {
                const auto & part = results[row].part->info;
                auto & bm = kills_by_target[part];
                if (!bm)
                    bm = std::make_shared<DeleteBitmap>();
                bm->add(results[row].row_number);
            }

            ProfileEvents::increment(ProfileEvents::UniqueKeyConflictOverwriteRows, conflict_rows.size());
            kills_per_part.insert(kills_by_target.begin(), kills_by_target.end());
            break;
        }
        }
    }

    return true;
}

std::vector<std::string> UniqueKeyTxnCommit::InsertCommit::run()
{
    const CSN csn = storage.uniqueKeyTxnManager().commitTransaction(transaction, *this);
    if (csn != INVALID_CSN)
        allocation->commit();

    return allocation->dedupConflicts();
}

UniqueKeyInsertOutcome UniqueKeyTxnCommit::insert(InsertRequest request)
{
    InsertCommit op(request);
    auto conflicts = op.run();

    LOG_DEBUG(getLogger("UniqueKeyTxnCommit"),
        "UNIQUE KEY INSERT (partition {}): done, {} conflicting block(s), part {}",
        op.partitionId(), conflicts.size(), op.partDiscarded() ? "discarded" : "published");

    return {.conflicting_blocks = std::move(conflicts), .part_discarded = op.partDiscarded()};
}

class UniqueKeyTxnCommit::MergeCommit : public UniqueKeyCommitBase
{
public:
    MergeCommit(StorageMergeTree & storage_, const MergeRequest & request_)
        : UniqueKeyCommitBase(storage_.uniqueKeyTxnManager().deleteBitmapStore())
        , storage(storage_)
        , request(request_)
    {
    }

    String partitionId() const override { return request.merged_part->info.getPartitionId(); }
    std::string_view writeKind() const override { return "MERGE"; }

    const DeleteBitmapPtr & lateKills() const { return own_kills; }

protected:
    std::vector<DeleteBitmapStore::CarriedBitmap> selectCarriedBitmaps() override
    {
        std::vector<MergeTreePartInfo> sources;
        sources.reserve(request.source_parts.size());
        for (const auto & source : request.source_parts)
            sources.push_back(source->info);

        return delete_bitmap_store.selectCarriedBitmaps(sources);
    }

    bool resolveConflicts() override
    {
        own_kills = computeMergeLateKills();
        own_part = request.merged_part;

        return true;
    }

    const IMergeTreeDataPart & publish(
        const PartitionWriteGuard &, const MergeTreeTransactionPtr & commit_txn, const StagedWrite &) override
    {
        MergeTreeData::Transaction transaction(storage, commit_txn.get());
        storage.merger_mutator.renameMergedTemporaryPart(
            own_part, request.source_parts, commit_txn, transaction);
        transaction.commit();

        return *own_part;
    }

private:

    DeleteBitmapPtr computeMergeLateKills();

    StorageMergeTree & storage;
    const MergeRequest & request;
};

/// A late kill is a source row killed after the merge's snapshot: the merged part still holds it
/// live, so it has to be killed there, at the row `UniqueKeyMergeRowMap::toMergedRow` maps it to.
DeleteBitmapPtr UniqueKeyTxnCommit::MergeCommit::computeMergeLateKills()
{
    const auto & sources = request.source_parts;
    const auto & snapshot_bitmaps = request.snapshot_bitmaps;
    const auto & offsets = request.merged_part_offsets;
    const IMergeTreeDataPart & merged_part = *request.merged_part;

    if (merged_part.rows_count == 0)
        return nullptr;

    if (!offsets.isFinalized())
        throw Exception(ErrorCodes::LOGICAL_ERROR,
            "UNIQUE KEY merge into {}: the row mapping is not finalized at the commit", merged_part.name);

    const UniqueKeyMergeRowMap row_map(sources, snapshot_bitmaps, offsets);
    if (!offsets.isMappingEnabled() && row_map.mergedRowsCount() != merged_part.rows_count)
        throw Exception(ErrorCodes::LOGICAL_ERROR,
            "UNIQUE KEY merge into {}: {} row(s) of the sources were live at the snapshot, but the merged part has {}",
            merged_part.name, row_map.mergedRowsCount(), merged_part.rows_count);

    auto late_kills = std::make_shared<DeleteBitmap>();

    for (size_t i = 0; i < sources.size(); ++i)
    {
        DeleteBitmap newly_dead;
        newly_dead.merge(*delete_bitmap_store.readLatestBitmap(sources[i]->info));
        newly_dead.subtract(*snapshot_bitmaps[i]);

        for (const UInt64 source_offset : newly_dead.toVector())
        {
            const auto merged_row = row_map.toMergedRow(i, source_offset);
            if (!merged_row)
                throw Exception(ErrorCodes::LOGICAL_ERROR,
                    "UNIQUE KEY merge into {}: late-killed row {} of {} has no merged row",
                    merged_part.name, source_offset, sources[i]->name);
            late_kills->add(*merged_row);
        }
    }

    return late_kills->empty() ? nullptr : late_kills;
}

void UniqueKeyTxnCommit::merge(StorageMergeTree & storage, MergeRequest request)
{
    MergeCommit op(storage, request);
    storage.uniqueKeyTxnManager().commitTransaction(request.transaction, op, request.cancelled);

    const String & partition_id = request.merged_part->info.getPartitionId();

    LOG_DEBUG(getLogger("UniqueKeyTxnCommit"),
        "UNIQUE KEY MERGE (partition {}): done, merged part {} from {} source part(s)",
        partition_id, request.merged_part->name, request.source_parts.size());

    if (op.lateKills())
        LOG_DEBUG(getLogger("UniqueKeyTxnCommit"),
            "UNIQUE KEY merge (partition {}): reconciled {} late kill(s) into the merged part {}",
            partition_id, op.lateKills()->cardinality(), request.merged_part->name);
}

class UniqueKeyTxnCommit::DeleteCommit : public UniqueKeyCommitBase
{
public:
    DeleteCommit(StorageMergeTree & storage_, DeleteRequest & request_)
        : UniqueKeyCommitBase(storage_.uniqueKeyTxnManager().deleteBitmapStore())
        , storage(storage_)
        , request(request_)
    {
    }

    String partitionId() const override { return request.partition_id; }
    std::string_view writeKind() const override { return "DELETE"; }

    size_t committedRows() const
    {
        size_t rows = 0;
        for (const auto & t : target_parts)
            if (t.kills)
                rows += t.kills->cardinality();
        return rows;
    }

protected:
    bool resolveConflicts() override;

    const IMergeTreeDataPart & publish(
        const PartitionWriteGuard &, const MergeTreeTransactionPtr & commit_txn, const StagedWrite &) override;

private:
    /// A matched part resolved to a live `DataPartPtr`, with the rows this DELETE kills in it.
    struct ResolvedTarget
    {
        MergeTreeData::DataPartPtr part;
        DeleteBitmapPtr kills;
    };

    /// A concurrent operation can drop the part directly, so double-check
    void checkPartExistence();

    /// Create a marker part to carry this commit's csn, and stage the bitmaps for all the target parts.
    void stageOwnerMarkerPart();

    StorageMergeTree & storage;
    DeleteRequest & request;

    std::unique_ptr<PlainCommittingBlockHolder> marker_block_holder;
    scope_guard marker_tmp_dir_holder;

    std::vector<ResolvedTarget> target_parts;
};

bool UniqueKeyTxnCommit::DeleteCommit::resolveConflicts()
{
    checkPartExistence();
    if (target_parts.empty())
        return false;

    stageOwnerMarkerPart();

    for (const auto & t : target_parts)
        /// The row finder groups by part, so a repeat means the request was built wrong --
        /// and silently dropping one of the two would under-delete.
        if (!kills_per_part.emplace(t.part->info, t.kills).second)
            throw Exception(ErrorCodes::LOGICAL_ERROR,
                "UNIQUE KEY DELETE has two row sets for part {}", t.part->name);

    return true;
}

const IMergeTreeDataPart & UniqueKeyTxnCommit::DeleteCommit::publish(
    const PartitionWriteGuard &, const MergeTreeTransactionPtr & commit_txn, const StagedWrite &)
{
    addPartToActiveSet(storage, own_part, commit_txn);
    return *own_part;
}

void UniqueKeyTxnCommit::DeleteCommit::checkPartExistence()
{
    const auto & parts_in_partition = request.rows_by_part;
    target_parts.reserve(parts_in_partition.size());

    LOG_TRACE(log, "UNIQUE KEY DELETE (partition {}): resolving {} target part(s)",
        partitionId(), parts_in_partition.size());

    auto parts_lock = storage.readLockParts();
    for (const auto & entry : parts_in_partition)
    {
        auto target = storage.getActiveContainingPart(entry.part_name, parts_lock);
        if (!target || target->name != entry.part_name)
            throw Exception(ErrorCodes::ABORTED,
                "UNIQUE KEY DELETE conflicts with other operation on part {}, rerun the DELETE",
                entry.part_name);

        target_parts.push_back({std::move(target), entry.rows});
    }
}

void UniqueKeyTxnCommit::DeleteCommit::stageOwnerMarkerPart()
{
    marker_block_holder = storage.allocateBlockNumber(CommittingBlock::Op::NewPart);
    const Int64 block_number = marker_block_holder->block.number;
    chassert(block_number >= 0);

    MergeTreePartInfo new_part_info{request.partition_id, block_number, block_number, /*level=*/0};
    String new_part_name = new_part_info.getPartNameAndCheckFormat(storage.format_version);
    auto metadata_snapshot = storage.getInMemoryMetadataPtr(storage.getContext(), /*bypass_metadata_cache=*/false);

    std::tie(own_part, marker_tmp_dir_holder) = storage.createEmptyPart(
        new_part_info, target_parts.front().part->partition, new_part_name, metadata_snapshot,
        request.transaction.getTransaction(), /*patch_part_index=*/std::nullopt);

    LOG_TRACE(log, "UNIQUE KEY DELETE (partition {}): staged the 0-row marker part {} at block {}",
        request.partition_id, own_part->name, block_number);
}


size_t UniqueKeyTxnCommit::deleteRows(StorageMergeTree & storage, DeleteRequest request)
{
    DeleteCommit op(storage, request);
    if (storage.uniqueKeyTxnManager().commitTransaction(request.transaction, op) == INVALID_CSN)
        return 0;  /// nothing was staged, so nothing committed

    const size_t rows = op.committedRows();

    LOG_DEBUG(getLogger("UniqueKeyTxnCommit"),
        "UNIQUE KEY DELETE (partition {}): done, killed {} row(s) across {} part(s)",
        request.partition_id, rows, request.rows_by_part.size());

    return rows;
}


/// Skips separators inside a row and deliberately stops at a line break: skipping `\n`/`\r`
/// here would let a row that ends with a trailing delimiter silently continue on the next
/// physical line, stitching two rows into one.
static inline void skipWhitespacesAndDelimiters(ReadBuffer & in)
{
    while (!in.eof() && (isWhitespaceASCIIOneLine(*in.position()) || *in.position() == ',' || *in.position() == ':'))
        ++in.position();
}

/// A row ends at the end of the data or at a line break.
static inline bool atRowEnd(ReadBuffer & in)
{
    return in.eof() || *in.position() == '\n' || *in.position() == '\r';
}

// Returns the score of the given type. This doesn't take nullable into account.
// Possible return values (increasing by power of 5):
// - 1: String
// - 5: Decimal, Float
// - 25: Map, Array, Tuple
// - 125: Date, DateTime,
static unsigned scoreForType(const DataTypePtr & type)
{
    WhichDataType which(type);

    if (which.isNullable())
    {
        const auto * nullable_type = assert_cast<const DataTypeNullable *>(type.get());
        return scoreForType(nullable_type->getNestedType());
    }

    if (which.isDateOrDate32() || which.isDateTimeOrDateTime64())
        return 125;

    if (which.isMap() || which.isArray() || which.isTuple())
        return 25;

    if (which.isDecimal() || which.isFloat() || which.isInt() || which.isUInt())
        return 5;

    return 1;
}

static unsigned scoreForRule(FormatSettings::EscapingRule rule)
{
    switch (rule)
    {
        case FormatSettings::EscapingRule::JSON:
            return 4;
        case FormatSettings::EscapingRule::CSV:
            [[fallthrough]];
        case FormatSettings::EscapingRule::Quoted:
            return 2;
        case FormatSettings::EscapingRule::Escaped:
            [[fallthrough]];
        case FormatSettings::EscapingRule::Raw:
            return 1;
        default:
            return 0;
    }
    UNREACHABLE();
}

static unsigned scoreForField(FormatSettings::EscapingRule rule, const DataTypePtr & type)
{
    return scoreForRule(rule) * scoreForType(type);
}

/// The names of the inferred columns as the schema reader reports them: the names from the data (a key
/// of a root JSON object, or an autogenerated `cN`), unless `column_names_for_schema_inference` replaces them.
static Names getColumnNames(const NamesAndTypes & inferred, const FormatSettings & settings)
{
    if (settings.column_names_for_schema_inference.empty())
    {
        Names names;
        for (const auto & column : inferred)
            names.push_back(column.name);
        return names;
    }

    auto names = splitColumnNames(settings.column_names_for_schema_inference);
    if (names.size() != inferred.size())
        throw Exception(
            ErrorCodes::INCORRECT_DATA,
            "The number of column names {} differs with the number of inferred columns {}",
            names.size(),
            inferred.size());

    std::unordered_set<std::string_view> names_set;
    for (const auto & name : names)
        if (!names_set.insert(name).second)
            throw Exception(ErrorCodes::INCORRECT_DATA, "Duplicate column name found while schema inference: \"{}\"", name);

    return names;
}

static FieldMatcher::Result makeFailedResult()
{
    return {
        .names_and_types = {},
        .fields = {},
        .score = 0,
        .type_score = 0,
        .offset = 0,
        .ok = false,
        .parse_till_newline_as_one_string = false,
    };
}

FieldMatcher::Result FieldMatcher::generateResult(NamesAndFields & fields, size_t offset)
{
    if (fields.empty())
        return makeFailedResult();

    NamesAndTypesList names_and_types;
    std::vector<String> values;
    unsigned type_score = 0;
    unsigned score = 0;
    for (auto & [col, field] : fields)
    {
        /// An empty field or a field consisting of a single delimiter is a sign that the matcher
        /// consumed a separator, not data. Only the actual delimiter set is rejected here: other
        /// one-character punctuation tokens (a `-` placeholder in Apache or syslog logs) are data.
        if (field.empty() || (field.size() == 1 && (field[0] == ',' || field[0] == ':' || isWhitespaceASCII(field[0]))))
            return makeFailedResult();

        auto type = getDataTypeFromField(field);
        if (!type)
            return makeFailedResult();

        names_and_types.emplace_back(col, type);
        values.emplace_back(field);
        score += scoreForField(getEscapingRule(), type);
        type_score += scoreForType(type);
    }

    return {
        .names_and_types = names_and_types,
        .fields = values,
        .score = score,
        .type_score = type_score,
        .offset = offset,
        .ok = true,
        .parse_till_newline_as_one_string = (fields.rbegin()->second.ends_with(':') && getName() == "RawByWhitespaceFieldMatcher"),
    };
}

template <bool with_offset>
FieldMatcher::Result FieldMatcher::parseField(PeekableReadBuffer & in, unsigned index)
{
    try
    {
        /// The buffer may be exhausted here: trailing whitespace and delimiters are consumed
        /// before a matcher is tried. Dereferencing the position of an exhausted buffer would
        /// read uninitialized memory beyond the last byte of the data. A matcher invoked at a
        /// line break must likewise fail: a field never continues past the end of the row.
        if (atRowEnd(in))
            return makeFailedResult();

        auto fields = readFieldsByEscapingRule(in, index);

        /// A matcher has to consume the whole field: if it stopped in the middle of a token
        /// (as a JSON matcher does on `2022.11.17`, reading it as the number `2022.11`),
        /// the rest of the row would be parsed at a shifted position.
        if (!in.eof() && !isWhitespaceASCII(*in.position()) && *in.position() != ',' && *in.position() != ':')
            return makeFailedResult();

        if constexpr (with_offset)
            return generateResult(fields, in.offsetFromCheckpoint()); // offset is not needed if this is called in parseRow()

        return generateResult(fields, 0);
    }
    catch (Exception & e)
    {
        /// Only a genuine parse miss means that the matcher does not fit the field. A failure of the
        /// underlying buffer (a socket, a truncated HTTP body, an object storage read) is a failure
        /// of the input, and `ReadBuffer::next` cancels the buffer before rethrowing: reporting it
        /// as a mismatch would lose the real error and go on retrying other matchers on a canceled stream.
        if (!isParseError(e.code()) || in.isCanceled())
            throw;

        LOG_DEBUG(&Poco::Logger::get("FreeformFieldMatcher"), "Error while parsing: {}", e.message());
        return makeFailedResult();
    }
}

FieldMatcher::NamesAndFields JSONFieldMatcher::readFieldsByEscapingRule(PeekableReadBuffer & in, unsigned index) const
{
    // If there's no opening bracket, read the field as a json field with the column name as c{index}
    if (*in.position() != '{')
    {
        String field;
        readJSONField(field, in, settings.json);
        return {{fmt::format("c{}", index), field}};
    }

    // Else, attempt to parse each JSON fields of the root object as separate columns.

    ++in.position();

    skipWhitespacesAndDelimiters(in);
    NamesAndFields cols_and_fields;
    while (true)
    {
        /// The object may be truncated by the end of the data, and the position of an exhausted
        /// buffer must not be dereferenced.
        if (in.eof())
            throw Exception(ErrorCodes::CANNOT_READ_ALL_DATA, "Unexpected end of stream while parsing a JSON object");

        if (*in.position() == '}')
            break;

        String col = JSONUtils::readFieldName(in, settings.json);
        String field;

        if (!in.eof() && *in.position() == '{')
            readJSONObjectPossiblyInvalid(field, in);
        else
            readJSONField(field, in, settings.json);

        cols_and_fields.emplace_back(col, field);
        skipWhitespacesAndDelimiters(in);
    }

    ++in.position();

    return cols_and_fields;
}

FieldMatcher::NamesAndFields CSVFieldMatcher::readFieldsByEscapingRule(PeekableReadBuffer & in, unsigned index) const
{
    String field;
    readCSVField(field, in, settings.csv);
    return {{fmt::format("c{}", index), field}};
}

FieldMatcher::NamesAndFields QuotedFieldMatcher::readFieldsByEscapingRule(PeekableReadBuffer & in, unsigned index) const
{
    String field;
    readQuotedField(field, in);
    return {{fmt::format("c{}", index), field}};
}

FieldMatcher::NamesAndFields EscapedFieldMatcher::readFieldsByEscapingRule(PeekableReadBuffer & in, unsigned index) const
{
    /// The field is kept as it is in the data, escape sequences included: it is inferred from
    /// and later deserialized as an `Escaped` field, and decoding it here would make the final
    /// `deserializeTextEscaped` decode it a second time (`\N` would stop being the null token, and
    /// an escaped tab would split the field).
    String field;
    readTSVField(field, in);
    return {{fmt::format("c{}", index), field}};
}

FieldMatcher::NamesAndFields RawByWhitespaceFieldMatcher::readFieldsByEscapingRule(PeekableReadBuffer & in, unsigned index) const
{
    String field;
    readStringUntilWhitespaceDelimiter(field, in);
    return {{fmt::format("c{}", index), field}};
}

FieldMatcher::NamesAndFields RestOfLineFieldMatcher::readFieldsByEscapingRule(PeekableReadBuffer & in, unsigned index) const
{
    String field;
    while (!in.eof())
    {
        char * end = find_first_symbols<'\n', '\r'>(in.position(), in.buffer().end());
        field.append(in.position(), static_cast<size_t>(end - in.position()));
        in.position() = end;
        if (in.hasPendingData())
            break;
    }

    return {{fmt::format("c{}", index), field}};
}

DataTypePtr RestOfLineFieldMatcher::getDataTypeFromField(const String &)
{
    /// The remainder of a line is a message, and a message is text whatever it happens to look like
    /// in the first rows: `42` in one row and `restarted` in the next must not invalidate the solution.
    return std::make_shared<DataTypeString>();
}

FreeformFieldMatcher::FreeformFieldMatcher(PeekableReadBuffer & in_, const FormatSettings & settings_)
    : in(in_)
{
    setLimits(settings_.max_rows_to_read_for_schema_inference, settings_.max_bytes_to_read_for_schema_inference);

    // matchers are pushed in the order of priority, this helps with exiting early and reducing the search tree.
    matchers.emplace_back(std::make_unique<JSONFieldMatcher>(FormatSettings::EscapingRule::JSON, settings_));
    matchers.emplace_back(std::make_unique<CSVFieldMatcher>(FormatSettings::EscapingRule::CSV, settings_));
    matchers.emplace_back(std::make_unique<RawByWhitespaceFieldMatcher>(FormatSettings::EscapingRule::Raw, settings_));
    matchers.emplace_back(std::make_unique<QuotedFieldMatcher>(FormatSettings::EscapingRule::Quoted, settings_));
    matchers.emplace_back(std::make_unique<EscapedFieldMatcher>(FormatSettings::EscapingRule::Escaped, settings_));
    /// Must stay last: `readNextFields` tries it only where the previous field ends with `:`.
    matchers.emplace_back(std::make_unique<RestOfLineFieldMatcher>(FormatSettings::EscapingRule::Raw, settings_));
}

void FreeformFieldMatcher::setLimits(size_t max_rows, size_t max_bytes)
{
    max_rows_to_check = std::min<size_t>(100, max_rows);
    max_bytes_to_check = max_bytes;
}

void FreeformFieldMatcher::seekInRow(size_t offset) const
{
    /// A single checkpoint is kept at the beginning of the row, and every position inside the row is
    /// addressed by its offset from it. Nested checkpoints are deliberately not used here: the search
    /// rewinds the buffer over and over, and a single checkpoint keeps the bookkeeping trivial.
    in.rollbackToCheckpoint();
    in.ignore(offset);
}

std::vector<FreeformFieldMatcher::Fields>
FreeformFieldMatcher::readNextFields(bool parse_till_newline_as_one_string, unsigned index, size_t offset) const
{
    std::vector<Fields> next_fields;
    if (parse_till_newline_as_one_string)
    {
        auto result = matchers.back()->parseField<true>(in, index);
        if (result.ok)
            next_fields.emplace_back(result, matchers.size() - 1);

        return next_fields;
    }

    size_t best_score = 0;
    /// The last matcher reads the rest of the line and is only tried above.
    for (uint8_t i = 0; i + 1 < matchers.size(); ++i)
    {
        const auto & matcher = matchers[i];
        auto result = matcher->parseField<true>(in, index);
        if (result.ok)
        {
            // best_score <= 1 means that we've only found strings so far, in that case it's best to include all of the fields
            if (best_score <= 1 || result.type_score > best_score)
            {
                best_score = result.type_score;
                next_fields.emplace_back(result, i);
            }
        }

        seekInRow(offset);
    }

    return next_fields;
}

void FreeformFieldMatcher::buildSolutions(
    Solution current_solution, std::vector<Solution> & solutions, bool parse_till_newline_as_one_string, size_t offset) const
{
    seekInRow(offset);
    skipWhitespacesAndDelimiters(in);

    /// Trailing delimiters before a line break end the row too: delimiter runs are collapsed
    /// by design, and the alternative of walking into the next physical line would stitch
    /// two rows into one.
    if (atRowEnd(in))
    {
        solutions.push_back(current_solution);
        return;
    }

    const size_t offset_after_delimiters = in.offsetFromCheckpoint();

    const auto next_fields = readNextFields(parse_till_newline_as_one_string, current_solution.size, offset_after_delimiters);
    for (const auto & fields : next_fields)
    {
        auto next = current_solution;
        next.matchers_order.push_back(fields.matcher_index);
        next.first_columns.push_back(current_solution.size);
        for (const auto & name_and_type : fields.parse_result.names_and_types)
            next.columns.push_back(name_and_type);

        next.score += fields.parse_result.score;
        next.size += fields.parse_result.names_and_types.size();

        buildSolutions(next, solutions, fields.parse_result.parse_till_newline_as_one_string, fields.parse_result.offset);
    }
}

template <typename OnField>
void FreeformFieldMatcher::readRowBySolution(
    const Solution & solution, const std::unordered_map<String, unsigned> & column_index, OnField && on_field)
{
    /// Every column is filled by the field of the solution it was inferred from, and only once: counting the
    /// matched names instead would let a JSON key named like the autogenerated name of a later field (`c1` in
    /// `{"c1":0,"a":1} 2` for the solution `a, c1`) stand in for that field, and the real one would be dropped.
    std::vector<bool> filled(solution.columns.size(), false);
    for (size_t step = 0; step < solution.matchers_order.size(); ++step)
    {
        const auto matcher_index = solution.matchers_order[step];
        const auto & matcher = matchers[matcher_index];
        const size_t begin = solution.first_columns[step];
        const size_t end = step + 1 < solution.first_columns.size() ? solution.first_columns[step + 1] : solution.columns.size();

        skipWhitespacesAndDelimiters(in);
        auto result = matcher->parseField<false>(in, static_cast<unsigned>(begin));
        if (!result.ok)
            throw Exception(
                ErrorCodes::CANNOT_READ_ALL_DATA, "Row does not match the inferred solution: cannot parse a field with {}", matcher->getName());

        size_t j = 0;
        for (const auto & [name, type] : result.names_and_types)
        {
            const auto & field = result.fields[j++];

            /// A key not seen in the first row (an extra key of a JSON object) is skipped: otherwise
            /// whether a row matches would depend on the order of the keys.
            auto it = column_index.find(name);
            if (it == column_index.end())
                continue;

            const size_t column = it->second;
            if (column < begin || column >= end)
                throw Exception(
                    ErrorCodes::CANNOT_READ_ALL_DATA,
                    "Field '{}' of the row belongs to another field of the inferred solution",
                    name);

            if (filled[column])
                throw Exception(ErrorCodes::CANNOT_READ_ALL_DATA, "Field '{}' occurs twice in the row", name);

            filled[column] = true;
            on_field(column, matcher_index, type, field);
        }
    }

    for (size_t column = 0; column < filled.size(); ++column)
        if (!filled[column])
            throw Exception(
                ErrorCodes::CANNOT_READ_ALL_DATA,
                "Row has no value for the field '{}' of the inferred solution",
                solution.columns[column].name);

    skipWhitespacesAndDelimiters(in);
    if (!atRowEnd(in))
        throw Exception(ErrorCodes::CANNOT_READ_ALL_DATA, "Row does not end at a newline after all fields of the inferred solution");
}

bool FreeformFieldMatcher::validateSolution(Solution & solution)
{
    try
    {
        // A map mapping column name to an index. This allows transforming multiple rows in one columns into one type.
        std::unordered_map<String, unsigned> column_index;
        for (unsigned i = 0; const auto & [name, _] : solution.columns)
        {
            /// A duplicate name (a root JSON key colliding with an autogenerated `cN` name, or a
            /// duplicate key) would make two columns share one index, so one of them would silently
            /// take the values of the other.
            if (column_index.contains(name))
                throw Exception(ErrorCodes::CANNOT_READ_ALL_DATA, "Duplicate column name '{}' in the inferred solution", name);

            column_index[name] = i++;
        }

        for (size_t row = 0; row < max_rows_to_check; ++row)
        {
            // For each iteration, we try to parse fields and find the type union of the current row and the previously parsed rows. If it doesn't exist,
            // the solution is invalid.

            /// Blank lines are not rows, exactly as in `parseRow`: inference and reading must agree
            /// on what a row is, or a file would be rejected by inference and accepted by the reader.
            skipWhitespaceIfAny(in);
            if (in.eof())
                break;

            /// The first row is always checked: the solution was built from it.
            if (row > 0 && in.offsetFromCheckpoint() >= max_bytes_to_check)
                break;

            rows_checked = row + 1;

            readRowBySolution(
                solution,
                column_index,
                [&](size_t column, uint8_t matcher_index, const DataTypePtr & field_type, const String &)
                {
                    if (!field_type)
                        throw Exception(
                            ErrorCodes::CANNOT_READ_ALL_DATA, "Cannot infer the type of field '{}'", solution.columns[column].name);

                    auto type = field_type;
                    matchers[matcher_index]->transformTypesIfPossible(solution.columns[column].type, type);
                    if (!solution.columns[column].type->equals(*type))
                        throw Exception(ErrorCodes::CANNOT_READ_ALL_DATA, "Received unexpected type after transform attempt");
                });

            skipToNextLineOrEOF(in);
        }

        in.rollbackToCheckpoint();
        return true;
    }
    catch (Exception & e)
    {
        /// See `FieldMatcher::parseField`: a failure of the buffer itself is not a failed candidate.
        if (!isParseError(e.code()) || in.isCanceled())
            throw;

        LOG_DEBUG(&Poco::Logger::get("FreeformFieldMatcher"), "Solution fails: {}", e.message());
    }

    in.rollbackToCheckpoint();
    return false;
}

void FreeformFieldMatcher::setFinalSolution(const Solution & solution)
{
    final_solution = solution;

    field_name_to_index.clear();
    rules.assign(final_solution.size, FormatSettings::EscapingRule::None);
    whole_line.assign(final_solution.size, false);
    for (unsigned i = 0; const auto & [name, _] : final_solution.columns)
        field_name_to_index[name] = i++;

    for (size_t step = 0; step < final_solution.matchers_order.size(); ++step)
    {
        const auto & matcher = matchers[final_solution.matchers_order[step]];
        const size_t end = step + 1 < final_solution.first_columns.size() ? final_solution.first_columns[step + 1] : final_solution.size;
        for (size_t column = final_solution.first_columns[step]; column < end; ++column)
        {
            rules[column] = matcher->getEscapingRule();
            whole_line[column] = matcher->readsWholeLine();
        }
    }
}

bool FreeformFieldMatcher::buildSolutionsAndPickBest()
{
    if (!final_solution.matchers_order.empty())
        // if a solution is found already, we could return immediately
        // this is useful in the case of readRow
        //
        // temporary solution until we could reuse the solution generated in readSchema,
        // possibly by making use of the SchemaCache
        return true;

    skipBOMIfExists(in);
    /// Leading blank lines are not rows (see `parseRow`), and an input with no rows has no solution.
    skipWhitespaceIfAny(in);
    if (in.eof())
        return false;

    in.setCheckpoint();

    std::vector<Solution> solutions;
    buildSolutions(Solution{.columns = {}, .matchers_order = {}, .first_columns = {}, .score = 0, .size = 0}, solutions, false, 0);
    in.rollbackToCheckpoint();
    if (solutions.empty())
    {
        in.rollbackToCheckpoint(true);
        throw Exception(ErrorCodes::BAD_ARGUMENTS, "Empty solutions set");
    }

    ::sort(
        solutions.begin(),
        solutions.end(),
        [](const Solution & first, const Solution & second)
        { return std::tie(first.score, first.matchers_order) > std::tie(second.score, second.matchers_order); });

    // after finding and ranking the solutions, we now run them through the max_rows_to_check rows and pick the first one that works for all of them.
    // Validation also widens the types of the solution to the union of the types seen in the checked rows (the first row alone
    // does not tell whether a column of integers is nullable), so the validated solution is the one that becomes final.
    for (auto & solution : solutions)
        if (validateSolution(solution))
        {
            setFinalSolution(solution);
            in.rollbackToCheckpoint(true);
            LOG_DEBUG(&Poco::Logger::get("FreeformFieldMatcher"), "Found solution");
            return true;
        }

    in.rollbackToCheckpoint(true);
    throw Exception(ErrorCodes::BAD_ARGUMENTS, "None of the {} candidate solutions parses every checked row", solutions.size());
}

bool FreeformFieldMatcher::parseRow()
{
    /// Blank lines and whitespace at the end of the data are not rows, but a delimiter here
    /// would belong to a row, so only whitespace is skipped.
    skipWhitespaceIfAny(in);
    if (in.eof() || final_solution.matchers_order.empty())
        return false;

    /// Every field is reassigned below; a row that stops matching the solution must fail
    /// instead of silently reusing the previous row's values.
    matched_fields.assign(final_solution.size, {});

    readRowBySolution(
        final_solution,
        field_name_to_index,
        [&](size_t column, uint8_t, const DataTypePtr &, const String & field) { matched_fields[column] = field; });

    skipToNextLineOrEOF(in);
    return true;
}

FreeformRowInputFormat::FreeformRowInputFormat(
    ReadBuffer & in_, SharedHeader header_, Params params_, const FormatSettings & format_settings_)
    : FreeformRowInputFormat(std::make_unique<PeekableReadBuffer>(in_), header_, params_, format_settings_)
{
}

FreeformRowInputFormat::FreeformRowInputFormat(
    std::unique_ptr<PeekableReadBuffer> buf_, SharedHeader header_, Params params_, const FormatSettings & format_settings_)
    : IRowInputFormat(header_, *buf_, params_)
    , format_settings(format_settings_)
    , buf(std::move(buf_))
    , matcher(std::make_unique<FreeformFieldMatcher>(*buf, format_settings))
{
}

void FreeformRowInputFormat::setReadBuffer(ReadBuffer & in_)
{
    /// The solution inferred from the previous stream is not carried over: the structure of this
    /// format is inferred from the data, and this is another piece of data.
    matcher.reset();
    header_positions.clear();
    buf = std::make_unique<PeekableReadBuffer>(in_);
    matcher = std::make_unique<FreeformFieldMatcher>(*buf, format_settings);
    IRowInputFormat::setReadBuffer(*buf);
}

void FreeformRowInputFormat::resetReadBuffer()
{
    matcher.reset();
    header_positions.clear();
    buf.reset();
    IRowInputFormat::resetReadBuffer();
}

void FreeformRowInputFormat::buildHeaderPositions()
{
    /// `columns` and `serializations` are built from the header the caller provided (an explicit
    /// structure of `file(...)` or the table of `INSERT ... FORMAT Freeform`), and the inferred
    /// solution is not obliged to fit it. A field named by the data (a key of a root JSON object)
    /// is read into the column of the same name; a field with an autogenerated `cN` name that the
    /// header does not have is read into the N-th column. Anything else is a mismatch, and so are
    /// two fields mapped onto one column.
    /// The names are the ones schema inference reports, so that `column_names_for_schema_inference` renames
    /// the fields for reading exactly as it renames them in the inferred structure.
    const auto & header = getPort().getHeader();
    const auto & inferred = matcher->getNamesAndTypes();
    const auto names = getColumnNames(inferred, format_settings);

    if (inferred.size() != header.columns())
        throw Exception(
            ErrorCodes::INCORRECT_NUMBER_OF_COLUMNS,
            "The inferred solution has {} fields per row, while {} columns are expected",
            inferred.size(),
            header.columns());

    header_positions.assign(inferred.size(), 0);
    std::vector<bool> is_column_mapped(header.columns(), false);
    for (size_t i = 0; i < inferred.size(); ++i)
    {
        const auto & name = names[i];
        size_t target = 0;
        if (header.has(name))
            target = header.getPositionByName(name);
        else if (inferred[i].name == fmt::format("c{}", i))
            target = i;
        else
            throw Exception(
                ErrorCodes::INCORRECT_DATA,
                "Field '{}' inferred from the data is not among the expected columns: {}",
                name,
                header.dumpNames());

        if (is_column_mapped[target])
        {
            throw Exception(
                ErrorCodes::INCORRECT_DATA,
                "Two fields of the inferred solution ({}) would be read into the column '{}'",
                fmt::join(names, ", "),
                header.getByPosition(target).name);
        }

        is_column_mapped[target] = true;
        header_positions[i] = target;
    }
}

bool FreeformRowInputFormat::readField(unsigned index, MutableColumns & columns)
{
    /// The field is deserialized as the column of the header, not as the inferred type: the header
    /// is what the caller asked for, and the two may legitimately differ (a number read into a
    /// `String`, a value read into a `Nullable` column).
    const size_t target = header_positions[index];
    const auto & type = getPort().getHeader().getByPosition(target).type;
    const auto rule = matcher->getRule(index);
    const auto & field = matcher->getField(index);
    ReadBufferFromString field_buf(field);

    try
    {
        bool read = true;
        if (matcher->readsWholeLine(index))
        {
            /// The remainder of a line was taken verbatim, so it is read as a whole text: a `Raw`
            /// reader would stop at a tab, and an `Escaped` one would decode escape sequences that
            /// were never meant as such.
            if (format_settings.null_as_default && !isNullableOrLowCardinalityNullable(type))
                read = SerializationNullable::deserializeNullAsDefaultOrNestedWholeText(*columns[target], field_buf, format_settings, serializations[target]);
            else
                serializations[target]->deserializeWholeText(*columns[target], field_buf, format_settings);
        }
        else
        {
            read = deserializeFieldByEscapingRule(type, serializations[target], *columns[target], field_buf, rule, format_settings);

            /// The matcher has isolated the whole field, so the value has to consume it entirely: a
            /// number reader stops at the first byte it cannot use (`1x` would be read as `1`), and no
            /// delimiter follows here to reject the leftover. The `CSV` and `JSON` rules permit
            /// whitespace after a value.
            if (rule == FormatSettings::EscapingRule::CSV)
            {
                if (!format_settings.csv.allow_whitespace_or_tab_as_delimiter)
                    while (!field_buf.eof() && (*field_buf.position() == ' ' || *field_buf.position() == '\t'))
                        ++field_buf.position();
            }
            else if (rule == FormatSettings::EscapingRule::JSON)
                skipWhitespaceIfAny(field_buf);
        }

        if (!field_buf.eof())
            throw Exception(
                ErrorCodes::INCORRECT_DATA,
                "Unexpected data '{}' after parsed value in the field '{}'",
                String(field_buf.position(), field_buf.available()),
                field);

        return read;
    }
    catch (Exception & e)
    {
        e.addMessage("(while reading the value of column " + getPort().getHeader().getByPosition(target).name + ")");
        throw;
    }
}

bool FreeformRowInputFormat::readRow(MutableColumns & columns, RowReadExtension & ext)
{
    /// `buildSolutionsAndPickBest` returns false only for empty input (any other failure throws
    /// there), and the caller has already provided the structure, so an empty input is simply
    /// zero rows, as in every other input format. Only schema inference has to fail on it.
    if (!matcher->buildSolutionsAndPickBest())
        return false;

    if (header_positions.empty())
        buildHeaderPositions();

    if (matcher->parseRow())
    {
        ext.read_columns.assign(columns.size(), false);
        for (unsigned index = 0; index < header_positions.size(); ++index)
            ext.read_columns[header_positions[index]] = readField(index, columns);
    }

    return !in->eof();
}


NamesAndTypesList FreeformSchemaReader::readSchema()
{
    /// The structure is inferred from the whole sample at once rather than row by row, so the post-processing
    /// of `IRowSchemaReader::readSchema` (the limits of the sample, the column names and the type hints from the
    /// settings, the nullability of the inferred types) is applied here.
    if (max_rows_to_read == 0 || max_bytes_to_read == 0)
        throw Exception(
            ErrorCodes::BAD_ARGUMENTS,
            "Cannot read rows to determine the schema, the maximum number of rows (or bytes) to read is set to 0. "
            "Most likely setting input_format_max_rows_to_read_for_schema_inference or input_format_max_bytes_to_read_for_schema_inference is set to 0");

    matcher.setLimits(max_rows_to_read, max_bytes_to_read);
    if (!matcher.buildSolutionsAndPickBest())
        throw Exception(ErrorCodes::BAD_ARGUMENTS, "Unable to parse freeform text, no solutions found");

    rows_read = matcher.getRowsChecked();

    const auto & columns = matcher.getNamesAndTypes();
    const auto names = getColumnNames(columns, format_settings);
    NamesAndTypesList ret;
    for (size_t i = 0; i < columns.size(); ++i)
    {
        auto type = columns[i].type;
        if (auto hint = hints.find(names[i]); hint != hints.end())
            type = hint->second;

        /// A column whose every checked value is null (`\N` in an `Escaped` field) has no complete type.
        if (!checkIfTypeIsComplete(type))
            throw Exception(
                ErrorCodes::ONLY_NULLS_WHILE_READING_SCHEMA,
                "Cannot determine type for column '{}' by first {} rows of data, most likely this column contains only Nulls. "
                "You can specify the type for this column using setting schema_inference_hints{}",
                names[i],
                rows_read,
                hints_parsing_error.empty() ? "" : ". Column types from setting schema_inference_hints couldn't be parsed because of error: " + hints_parsing_error);

        /// The matchers see the nulls of the sample, so a type is `Nullable` exactly where a null was seen, as
        /// with `schema_inference_make_columns_nullable = 'auto'`. The two explicit choices are honored.
        if (format_settings.schema_inference_make_columns_nullable == 0)
            type = removeNullableRecursively(type, format_settings);
        else if (format_settings.schema_inference_make_columns_nullable == 1)
            type = makeNullableRecursively(type, format_settings);

        ret.emplace_back(names[i], type);
    }

    return ret;
}


#include <Core/Types.h>
#include <Interpreters/Context_fwd.h>
#include <Interpreters/StorageID.h>
#include <Parsers/IAST_fwd.h>

#include <optional>
#include <string_view>

namespace DB
{

class ASTCreateQuery;

/** The union system log tables (`system.all_query_log` and friends, see `create_union_system_log_tables`)
  * are data-free proxies over the `merge` / `clusterAllReplicas` table function which `SystemLog::prepareUnionTable`
  * generates and replaces whenever their definition is outdated. Users may create tables of their own on
  * these names - `system.all_query_log` is exactly the name a hand-rolled union of the rotated logs takes -
  * and such a table must never be replaced, because that drops it with its data.
  *
  * A generated table is recognized by its definition alone: it reads from the log table it was generated
  * for through one of the generated shapes, and its comment ends with the marker below. Neither part alone
  * is enough, since a user may write a proxy over the same table function, or copy the comment onto a proxy
  * over something else. Deciding from the definition alone, rather than from who issued the query, is what
  * lets `CREATE OR REPLACE` enforce the rule wherever the query runs, including a database that replays its
  * DDL from the query text on the DDL worker.
  */

/// Ends the comment of every generated union table. Changing this text would make the tables generated by
/// older versions look like user tables, so they would be kept with their stale definition.
inline constexpr std::string_view SYSTEM_LOG_UNION_TABLE_COMMENT_MARKER
    = "It is safe to drop this table at any time: it will be recreated automatically.";

/// The pattern of the `merge` table function of a union table: the log table and its rotated
/// versions (`query_log`, `query_log_0`, `query_log_1`, ...), but not the union table itself.
String getRotatedLogTablesRegexp(const StorageID & log_table_id);

/// The system log table whose union table `create_query` defines, if it is a definition that
/// `SystemLog::prepareUnionTable` generates: a proxy over one of the generated table functions carrying the
/// comment marker. The name of the cluster and the choice between the generated shapes come from the server
/// configuration, which may well have changed since the table was generated, so they are not pinned.
///
/// The names in the definition may be spelled as literals, identifiers, or (with `context`) any constant
/// expression, the same way the table functions themselves accept them: `merge(currentDatabase(), ...)` is
/// the same definition as `merge('system', ...)` when `system` is the current database. A definition being
/// created has to be read that way, because a table function nested into `clusterAllReplicas` keeps its
/// arguments as written; a stored definition is read without a context, as the server wrote it.
std::optional<StorageID> getSystemLogOfGeneratedUnionTable(const ASTCreateQuery & create_query, ContextPtr context = nullptr);

/// Whether `create_query_ast` is a definition that `SystemLog::prepareUnionTable` generated for `log_table_id`,
/// and therefore a table that it may replace.
bool isGeneratedUnionTable(const ASTPtr & create_query_ast, const StorageID & log_table_id);

}

/// See the declaration for the meaning of `generated`.
[[noreturn]] void throwTooManyAddresses(
    const RemoteDescriptionCaller & caller, size_t max_addresses, std::optional<size_t> generated)
{
    /// Unlike the object storage table functions, `url` has no way to enumerate the existing files:
    /// HTTP has no listing, so a pattern is a generator of addresses rather than a filter over them.
    /// This is the difference that makes the very same pattern work for `s3` and fail here.
    const String hint = caller.listing_alternative.empty()
        ? ""
        : fmt::format(
            ". Note that every address generated by the pattern has to be read, because HTTP provides no way to"
            " list the existing files. Use {} if the pattern is meant to be matched against the list of existing"
            " objects instead",
            caller.listing_alternative);

    if (generated)
        throw Exception(
            ErrorCodes::BAD_ARGUMENTS,
            "{}: first argument generates too many result addresses: {}, while at most {} are allowed"
            " (see the '{}' setting){}",
            caller.description,
            *generated,
            max_addresses,
            caller.max_addresses_setting,
            hint);

    throw Exception(
        ErrorCodes::BAD_ARGUMENTS,
        "{}: first argument generates too many result addresses, while at most {} are allowed"
        " (see the '{}' setting){}",
        caller.description,
        max_addresses,
        caller.max_addresses_setting,
        hint);
}


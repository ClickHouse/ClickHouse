"""Render the license inventory using declared source files."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__, fromfile_prefix_chars="@")
    parser.add_argument("manifest", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("paths", nargs="*")
    parser.add_argument("--cmake-metadata", type=Path)
    args = parser.parse_args()
    rows = json.loads(args.manifest.read_text())
    paths = dict(zip(args.paths[0::2], args.paths[1::2], strict=True))
    if args.cmake_metadata:
        # The recorded Linux CMake build used an awk without GNU IGNORECASE.
        # Preserve that inventory only for --//bazel:cmake_metadata. Normal
        # Bazel builds keep all entries from license_manifest.json.
        substitutions = json.loads(args.cmake_metadata.read_text())
        selected = []
        for name, license_type, source in rows:
            if source in substitutions:
                replacement = substitutions.pop(source)
                if replacement is None:
                    continue
                license_type, source = replacement
            selected.append((name, license_type, source))
        if substitutions:
            raise ValueError(f"CMake licenses absent from the default inventory: {substitutions}")
        rows = selected
    result = ['// autogenerated from utils/list-licenses/list-licenses.sh\n',
              'const char * library_licenses[] = {\n']
    for name, license_type, source in rows:
        # Match shell command substitution in StorageSystemLicenses.sh:
        # trailing newlines are removed, other license bytes are preserved.
        text = Path(paths[source.lstrip('/')]).read_bytes().decode('utf-8').rstrip('\n')
        result.append(f'"{name}", "{license_type}", "{source}", R"heredoc({text})heredoc",\n\n')
    result.append('nullptr\n};\n')
    args.output.write_bytes(''.join(result).encode('utf-8'))


if __name__ == '__main__':
    main()

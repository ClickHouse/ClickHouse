"""Generate ClickHouse's timezone table from the pinned cctz zoneinfo files."""

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('files', nargs='+')
    args = parser.parse_args()
    zones = sorted((path.split('/testdata/zoneinfo/', 1)[1], Path(path)) for path in args.files)
    text = '// autogenerated by ClickHouse/contrib/cctz-cmake/CMakeLists.txt\n'
    for index, (_, path) in enumerate(zones, 1):
        values = ','.join(map(str, path.read_bytes()))
        text += f'constexpr unsigned char resource_timezone{index}[] = {{\n{values}\n}};\n'
    text += 'const char * auto_time_zones[] {\n'
    text += ''.join(f'    "{name}",\n' for name, _ in zones)
    text += '    nullptr\n};\n\n#include <string_view>\n\n'
    text += 'std::string_view getTimeZone(std::string_view name)\n{\n'
    for index, (name, _) in enumerate(zones, 1):
        text += (f'    if (std::string_view("{name}") == name) return {{ reinterpret_cast<const char *>(resource_timezone{index}), '
                 f'std::size(resource_timezone{index}) }};\n')
    text += '    return {};\n}\n'
    args.output.write_text(text)


if __name__ == '__main__':
    main()

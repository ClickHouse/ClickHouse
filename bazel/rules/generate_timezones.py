"""Generate ClickHouse's timezone table from the pinned cctz zoneinfo files."""

import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('files', nargs='+')
    args = parser.parse_args()
    prefix = 'contrib/cctz/testdata/zoneinfo/'
    names = sorted(path.split('/testdata/zoneinfo/', 1)[1] for path in args.files)
    text = '// autogenerated by ClickHouse/contrib/cctz-cmake/CMakeLists.txt\n'
    for index, name in enumerate(names, 1):
        text += f'constexpr unsigned char resource_timezone{index}[] = {{\n#embed "{prefix}{name}"\n}};\n'
    text += 'const char * auto_time_zones[] {\n'
    text += ''.join(f'    "{name}",\n' for name in names)
    text += '    nullptr\n};\n\n#include <string_view>\n\n'
    text += 'std::string_view getTimeZone(std::string_view name)\n{\n'
    for index, name in enumerate(names, 1):
        text += (f'    if (std::string_view("{name}") == name) return {{ reinterpret_cast<const char *>(resource_timezone{index}), '
                 f'std::size(resource_timezone{index}) }};\n')
    text += '    return {};\n}\n'
    args.output.write_text(text)


if __name__ == '__main__':
    main()

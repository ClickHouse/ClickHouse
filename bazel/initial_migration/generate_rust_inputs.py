#!/usr/bin/env python3
"""Resolve the two imported Cargo packages with ClickHouse's exact features."""

import argparse
import os
from pathlib import Path
import re
import subprocess
import tomllib


def generate(root, cargo):
    temporary = root / 'tmp/rust-resolution'
    temporary.mkdir(parents=True, exist_ok=True)
    config = (root / 'contrib/corrosion-cmake/config.toml.in').read_text()
    config = config[config.index('[source.vendored-sources]'):]
    config = config.replace('@RUST_VENDOR_DIR@', str(root / 'contrib/rust_vendor'))
    config_path = temporary / 'config.toml'
    config_path.write_text(config)
    for name, crate in [('delta-kernel-rs', 'delta_kernel_ffi'), ('chdig', 'chdig')]:
        cmake = (root / 'contrib' / (name + '-cmake') / 'CMakeLists.txt').read_text()
        invocation = re.search(r'clickhouse_import_crate\((.*?)\)', cmake, re.DOTALL).group(1)
        features = re.search(r'FEATURES\s+("[^"]+"|[^\s)]+)', invocation).group(1).strip('"')
        features = [f.strip() for f in features.split(',')]
        path = '../../../contrib/' + name + ('/ffi' if name == 'delta-kernel-rs' else '')
        directory = root / 'bazel/rust' / name
        directory.mkdir(parents=True, exist_ok=True)
        # A dependency-only workspace prevents other vendored workspace members
        # and their default features from changing the imported package closure.
        (directory / 'Cargo.toml').write_text(
            '# Generated by bazel/initial_migration/generate_rust_inputs.py.\n'
            '[workspace]\n\n[package]\nname = "clickhouse-' + name + '-dependencies"\n'
            'version = "0.0.0"\nedition = "2021"\npublish = false\n\n'
            '[lib]\npath = "empty.rs"\n\n[dependencies]\n' + crate
            + ' = { path = "' + path + '", default-features = false, features = ['
            + ', '.join('"' + f + '"' for f in features) + '] }\n')
        (directory / 'empty.rs').write_text('// Cargo dependency-resolution root; never compiled.\n')
        # Let Cargo retain upstream pins while pruning unused workspace members
        # and recording the synthetic root's feature-selection edge.
        lock = (root / 'contrib' / name / 'Cargo.lock').read_text()
        (directory / 'Cargo.lock').write_text(lock)
        subprocess.run([str(cargo), 'metadata', '--offline', '--format-version=1',
                        '--manifest-path', str(directory / 'Cargo.toml'), '--config', str(config_path)],
                       env=os.environ | {'RUSTC': str(cargo.parent / 'rustc')},
                       stdout=subprocess.DEVNULL, check=True)
        upstream = {(p['name'], p['version'], p.get('source'), p.get('checksum'))
                    for p in tomllib.loads(lock)['package']}
        resolved = tomllib.loads((directory / 'Cargo.lock').read_text())['package']
        for package in resolved:
            if package['name'] == 'clickhouse-' + name + '-dependencies':
                continue
            identity = (package['name'], package['version'], package.get('source'), package.get('checksum'))
            if identity not in upstream:
                raise ValueError('Cargo changed an upstream package pin: ' + repr(identity))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cargo', type=Path, required=True)
    args = parser.parse_args()
    generate(Path(__file__).resolve().parents[2], args.cargo.resolve())

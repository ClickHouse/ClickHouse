#!/usr/bin/env python3
"""Refresh --//bazel:cmake_metadata from one configured CMake architecture."""

import argparse
import ast
import copy
import difflib
import gzip
import json
from pathlib import Path
import re
import struct
import sys
import tarfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from initial_migration.build_file import starlark
from initial_migration.codegen import non_vendor_license_paths, render_license
from initial_migration.cmake_metadata import read_metadata, write_metadata
from initial_migration.compact_build import Source
from initial_migration.configured_external_outputs import ChooseCpu
from initial_migration.generate_build import ARCHES, BUILD_OPTIONS_OUTPUT, LICENSES_OUTPUT, ROOT, cmake_build_options
from initial_migration.repository_inputs import source_label

GIT_HASH_OUTPUT = 'base/base/GitHash.generated.cpp'
LLVM_CONFIG = 'contrib/llvm-project/llvm/include/llvm/Config/'
RESOURCE_DIRS = {
    'ClickStack': ('contrib/clickstack-cmake', 'clickstack_compressed'),
    'SQLConsole': ('contrib/sql-console-cmake', 'sql_console_compressed'),
}


def _codegen_records(source):
    records = [
        statement.value for statement in ast.parse(source).body
        if isinstance(statement, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == 'CODEGEN_RULES'
                for target in statement.targets)
    ]
    if len(records) != 1 or not isinstance(records[0], ast.Dict):
        raise ValueError('Expected one generated CODEGEN_RULES dictionary')
    return {ast.literal_eval(k): v for k, v in zip(records[0].keys, records[0].values)}


def _literal_fields(record):
    return {ast.literal_eval(k): v for k, v in zip(record.keys, record.values)}


def _license_inputs(source):
    return ast.literal_eval(next(
        statement.value for statement in ast.parse(source).body
        if isinstance(statement, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == '_LICENSE_INPUTS'
                for target in statement.targets)
    ))


def _license_fields(record, license_inputs, arch):
    fields = _literal_fields(record)
    common = {
        'source_paths': ('list(_LICENSE_INPUTS)', list(license_inputs)),
        'srcs': ('list(_LICENSE_INPUTS.values())', list(license_inputs.values())),
    }
    result = {}
    for key, field in fields.items():
        if key not in common:
            continue
        field = ChooseCpu(arch).visit(copy.deepcopy(field))
        if key in common and ast.dump(field) == ast.dump(ast.parse(common[key][0], mode='eval').body):
            result[key] = common[key][1]
        else:
            result[key] = ast.literal_eval(field)
    return result


def _license_substitutions(root, reference):
    prefix, marker, body = reference.partition(b'const char * library_licenses[] = {\n')
    if not marker or not prefix.startswith(b'// autogenerated '):
        raise ValueError('Unrecognized CMake license header')
    body = body.decode('utf-8')
    row = re.compile(r'"([^"\n]+)", "([^"\n]+)", "([^"\n]+)", R"heredoc\((.*?)\)heredoc",\n\n', re.DOTALL)
    actual = []
    offset = 0
    while found := row.match(body, offset):
        actual.append(found.group(1, 2, 3))
        offset = found.end()
    if body[offset:] != 'nullptr\n};\n':
        raise ValueError('Unparsed CMake license bytes after row ' + str(len(actual)))
    expected = [tuple(row) for row in json.loads((root / 'bazel/rules/license_manifest.json').read_text())]
    substitutions = {}
    for kind, start, end, rstart, rend in difflib.SequenceMatcher(
            a=expected, b=actual, autojunk=False).get_opcodes():
        if kind == 'equal':
            continue
        if kind == 'delete':
            replacements = [None] * (end - start)
        elif kind == 'replace' and end - start == rend - rstart and all(
                a[0] == b[0] for a, b in zip(expected[start:end], actual[rstart:rend])):
            replacements = [list(row[1:]) for row in actual[rstart:rend]]
        else:
            raise ValueError(f'CMake licenses cannot be represented as ordered substitutions: '
                             f'{kind} {expected[start:end]} -> {actual[rstart:rend]}')
        for old, replacement in zip(expected[start:end], replacements):
            source = old[2]
            if source in substitutions and substitutions[source] != replacement:
                raise ValueError('Conflicting CMake license substitutions for ' + source)
            substitutions[source] = replacement
    replay = []
    for name, license_type, source in expected:
        if source in substitutions:
            value = substitutions[source]
            if value is None:
                continue
            license_type, source = value
        replay.append((name, license_type, source))
    if replay != actual:
        raise ValueError('CMake license substitutions do not reproduce every row in order')
    return substitutions, len(actual)


def _resource_mtimes(build, arch, records):
    observed = json.loads((build / 'resource-gzip-headers.json').read_text())
    if set(observed) != set(RESOURCE_DIRS):
        raise ValueError('Expected resource gzip records for ClickStack and SQLConsole')
    mtimes = {}
    for namespace, (directory, compressed) in RESOURCE_DIRS.items():
        fields = _literal_fields(records['generate_native_' + namespace])
        outs = ast.literal_eval(fields['outs'])
        prefix = 'gen/' + directory + '/' + compressed + '/'
        paths = [out.removeprefix(prefix) for out in outs[1:]]
        if any(not out.startswith(prefix) for out in outs[1:]):
            raise ValueError('Unexpected recorded gzip outputs for ' + namespace)
        entries = observed[namespace]
        if paths != [entry['file'] for entry in entries]:
            raise ValueError('CMake resource gzip files differ from codegen outputs for ' + namespace)
        values = {entry['mtime'] for entry in entries}
        if len(values) != 1:
            raise ValueError(f'{namespace} contains {len(values)} mtimes; '
                             'embed_resources.py needs per-file CMake metadata')
        mtimes[namespace] = values.pop()
        for entry in entries:
            basename = Path(entry['file']).name.removesuffix('.gz')
            header = struct.pack('<4sIBB', b'\x1f\x8b\x08\x08', mtimes[namespace], 0, 3)
            header += basename.encode('utf-8') + b'\0'
            if entry['basename'] != basename or bytes(entry['header']) != header:
                raise ValueError('CMake gzip header differs from GNU gzip default: ' + entry['file'])
            if not re.fullmatch('[0-9a-f]{64}', entry['sha256']) or entry['bytes'] < len(header) + 8:
                raise ValueError('Invalid CMake gzip record: ' + entry['file'])
        generated = build / directory / (namespace + 'Resources.generated.h')
        if not generated.is_file():
            raise ValueError('CMake resource table missing: ' + str(generated))
    return mtimes


def _llvm_reference(root, build, arch):
    planned = {}
    overlay = root / 'bazel/dependencies/clickhouse_llvm_project.BUILD.bazel'
    for statement in ast.parse(overlay.read_text()).body:
        if not isinstance(statement, ast.Expr) or not isinstance(statement.value, ast.Call):
            continue
        call = statement.value
        if not isinstance(call.func, ast.Name) or call.func.id not in ('expand_template', 'write_file'):
            continue
        fields = {keyword.arg: keyword.value for keyword in call.keywords}
        out = ast.literal_eval(fields['out'])
        prefix = 'gen/llvm/include/llvm/Config/'
        if not out.startswith(prefix):
            continue
        if call.func.id == 'expand_template':
            template = ast.literal_eval(fields['template'])
            if not template.startswith('@clickhouse//') or ':' not in template:
                raise ValueError('Unexpected LLVM template ' + template)
            package, name = template.removeprefix('@clickhouse//').split(':', 1)
            content = (root / package / name).read_text()
            for key, value in ast.literal_eval(ChooseCpu(arch).visit(fields['substitutions'])).items():
                content = content.replace(key, value)
        else:
            content = '\n'.join(ast.literal_eval(ChooseCpu(arch).visit(fields['content'])))
        planned[LLVM_CONFIG + out.removeprefix(prefix)] = content.encode()
    if len(planned) != 9:
        raise ValueError(f'Expected 9 LLVM Config outputs, found {len(planned)}')
    actual = {}
    with tarfile.open(build / 'llvm-config-headers.tar.gz') as archive:
        for member in archive.getmembers():
            if member.isfile() and member.name in planned:
                actual[member.name] = archive.extractfile(member).read()
    if actual.keys() != planned.keys():
        raise ValueError('LLVM Config archive is missing: ' + str(sorted(planned.keys() - actual.keys())))
    return actual, {name: value for name, value in actual.items() if value != planned[name]}


def _full_reference(root, build, arch, metadata, check):
    codegen_file = root / 'bazel/rules/codegen_rules.bzl'
    codegen = codegen_file.read_text()
    records = _codegen_records(codegen)
    with gzip.open(build / (LICENSES_OUTPUT + '.gz'), 'rb') as source:
        substitutions, license_rows = _license_substitutions(root, source.read())
    mtimes = _resource_mtimes(build, arch, records)
    _, differences = _llvm_reference(root, build, arch)
    if differences:
        raise ValueError('LLVM generated Config headers differ from CMake: '
                         + ', '.join(sorted(differences)))

    licenses = 'generate_native_licenses'
    license_inputs = _license_inputs(codegen)
    before = _license_fields(records[licenses], license_inputs, arch)
    current = dict(zip(before['source_paths'], before['srcs'], strict=True))
    manifest = json.loads((root / 'bazel/rules/license_manifest.json').read_text())
    inputs = {source: current.get(source) or source_label(source)
              for source in non_vendor_license_paths(manifest, substitutions)}
    license_name = 'license_substitutions_' + arch + '.json'
    shared_license_name = 'license_substitutions_x86_64.json'
    shared_license_file = root / 'bazel/initial_migration' / shared_license_name
    reuse_licenses = shared_license_file.is_file() and json.loads(shared_license_file.read_text()) == substitutions
    if reuse_licenses:
        license_name = shared_license_name
    license_file = root / 'bazel/initial_migration' / license_name
    attrs = {
        'source_paths': sorted(inputs),
        'srcs': [inputs[source] for source in sorted(inputs)],
    }
    source = Source(codegen)
    updates = []
    if attrs != before:
        # Only refreshing one CMake reference. Preserve the other CPU's exact
        # inputs if this reference adds a license file.
        rendered = _literal_fields(ast.parse(render_license(attrs, license_inputs), mode='eval').body)
        fields = _literal_fields(records[licenses])
        for key in ('srcs', 'source_paths'):
            if attrs[key] == before[key]:
                continue
            branches = []
            for cpu in ARCHES:
                node = (rendered[key] if cpu == arch else ChooseCpu(cpu).visit(copy.deepcopy(fields[key])))
                branches.append(starlark('@platforms//cpu:' + cpu) + ': (' + ast.unparse(node) + '),')
            updates.append((*source.span(fields[key]), 'select({' + ''.join(branches) + '})'))
    expected_codegen = source.rewrite(updates)
    expected_substitutions = json.dumps(substitutions, indent=2) + '\n'
    if check:
        if json.loads(license_file.read_text()) != substitutions:
            raise ValueError('Saved CMake license substitutions do not match the full reference')
        recorded_license_name = metadata[arch].get('license_substitutions', 'license_substitutions_' + arch + '.json')
        if recorded_license_name != license_name:
            raise ValueError('Saved license metadata filename does not match the full reference')
        if metadata[arch]['resource_gzip_mtimes'] != mtimes or attrs != before:
            raise ValueError('Saved codegen metadata does not match the full reference')
    else:
        metadata[arch]['resource_gzip_mtimes'] = mtimes
        if license_name != 'license_substitutions_' + arch + '.json':
            metadata[arch]['license_substitutions'] = license_name
        else:
            metadata[arch].pop('license_substitutions', None)
        if not reuse_licenses:
            license_file.write_text(expected_substitutions)
        codegen_file.write_text(expected_codegen)
    print(f'{arch}: {license_rows} CMake license rows, {len(substitutions)} substitutions, gzip mtimes {mtimes}')
    print(f'{arch}: all 9 LLVM generated Config headers match CMake')


def _verify(substitutions, template, git_hash, reference, reference_git):
    if not isinstance(substitutions, dict) or not all(
            isinstance(key, str) and isinstance(value, str) for key, value in substitutions.items()):
        raise ValueError('CMAKE_METADATA build_options must be a literal string dictionary')
    expanded = template.decode()
    for marker, value in substitutions.items():
        # ctx.actions.expand_template applies substitutions in dictionary order.
        expanded = expanded.replace(marker, value)
    if expanded.encode() != reference:
        diff = ''.join(difflib.unified_diff(
            reference.decode().splitlines(keepends=True),
            expanded.splitlines(keepends=True),
            fromfile='CMake/' + BUILD_OPTIONS_OUTPUT,
            tofile='Bazel/' + BUILD_OPTIONS_OUTPUT,
        ))
        raise ValueError('CMake build metadata differs from Bazel template expansion:\n' + diff)
    if git_hash != reference_git:
        raise ValueError('Bazel ' + GIT_HASH_OUTPUT + ' differs from the configured CMake file')
    source_hash = re.search(rb'^const char \* GIT_HASH = ("[^"]*");$', git_hash, re.MULTILINE)
    metadata_hash = re.search(rb'^    "GIT_HASH", ("[^"]*"),$', reference, re.MULTILINE)
    if not source_hash or not metadata_hash or source_hash[1] != metadata_hash[1]:
        raise ValueError('CMake GitHash.generated.cpp does not match its GIT_HASH build metadata')


def refresh(root, build, arch, check=False, full_reference=False):
    metadata = read_metadata(root)
    template_file = root / 'bazel/config' / arch / (BUILD_OPTIONS_OUTPUT + '.in')
    git_file = root / 'bazel/config' / arch / GIT_HASH_OUTPUT
    reference = (build / BUILD_OPTIONS_OUTPUT).read_bytes()
    reference_git = (build / GIT_HASH_OUTPUT).read_bytes()

    if check:
        _verify(metadata[arch]['build_options'], template_file.read_bytes(), git_file.read_bytes(),
                reference, reference_git)
    else:
        template, substitutions = cmake_build_options(reference.decode())
        # Validate before changing any record, including when markers inside a
        # CMake value would be expanded again by Bazel's expand_template.
        _verify(substitutions, template.encode(), reference_git, reference, reference_git)
    if full_reference:
        _full_reference(root, build, arch, metadata, check)
    if not check:
        metadata[arch]['build_options'] = substitutions
        write_metadata(root, metadata)
        template_file.write_bytes(template.encode())
        git_file.write_bytes(reference_git)

    # Check the exact records BUILD.bazel and build_options.bzl consume, also
    # after writing. --check verifies a saved record without modifying it.
    _verify(read_metadata(root)[arch]['build_options'], template_file.read_bytes(), git_file.read_bytes(),
            reference, reference_git)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--arch', choices=ARCHES, required=True)
    parser.add_argument('--build-dir', type=Path, required=True,
                        help='Configured CMake build directory containing generated C++ metadata.')
    parser.add_argument('--check', action='store_true',
                        help='Verify the saved Bazel metadata against CMake without writing files.')
    parser.add_argument('--full-reference', action='store_true',
                        help='Also require completed license/resource/LLVM Config artifacts, '
                             'refresh their metadata and compare generated LLVM Config headers.')
    args = parser.parse_args()
    refresh(ROOT, args.build_dir, args.arch, check=args.check, full_reference=args.full_reference)
    print(f'{args.arch}: Bazel CMake metadata and GitHash.generated.cpp match {args.build_dir}')


if __name__ == '__main__':
    main()
